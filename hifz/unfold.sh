#!/usr/bin/env bash
# unfold.sh — الفكُّ: إحضارُ بايتات مصدرٍ مختومٍ من البيت المستدعى، الآنَ ولهذا
# النداء وحدَه، ثمّ تركُها حيث وُضعت. لا يُخزَّن هنا شيءٌ من البايتات.
#
# البيتُ المستدعى `Saleh1967/hamil-hala-zaman-program`، وسكربتُه **في جذره**:
#   $HAMIL_ROOT/fetch_source.sh   — ومعه $HAMIL_ROOT/sources_manifest.tsv
# ولا مجلَّدَ `SOURCES/` هناك ولم يكن. من كتبه ثانيةً أعاد خطأً سقط ثلاثًا.
#
# والنداءُ بالمعرِّف وحدَه دائمًا — لا `--all` أبدًا: فـ`--all` يجمع أحكامَ
# ستّةَ عشرَ مصدرًا في رقمٍ واحدٍ (أعلاها)، فيضيع اسمُ الساقط ويُخلَط التعذُّرُ
# بمخالفة الختم. والحكمُ لا يُعرَف إلّا مفرَدًا.
#
# الأحكامُ الأربعةُ لا «فشلٌ» واحد (عقدُ مخارج fetch_source.sh):
#   0  نجاحٌ          — البايتاتُ حاضرةٌ مطابقةُ الختم
#   1  تعذُّرُ جلبٍ    — عارضٌ (شبكةٌ أو نسخةٌ غائبة): يُعاد ويُخبَر عنه
#   2  خطأُ استعمالٍ  — خللٌ عند المستدعي: طورٌ مجهولٌ أو معرِّفٌ ليس في البيان
#   3  بيانٌ معطوبٌ   — خللٌ في البيت المستدعى: لا يُداوى بإعادةٍ
#   4  مخالفةُ ختمٍ   — البايتاتُ ليست المصدرَ: **لا يُعاد ولا يُطوى منه شيء**
#
# المخرجُ من هنا هو مخرجُ البيت المستدعى نفسُه، لا يُترجَم ولا يُجمَل. وعند
# النجاح وحدَه يُطبَع على المخرج القياسيِّ سطرٌ واحد: مسارُ البايتات الحاضرة —
# ليقرأه الطاوي ثمّ يتركَها. وما سوى ذلك فعلى مخرج الصريخ.
set -uo pipefail

HIFZ_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# HAMIL_ROOT بيتٌ كاملٌ لا ملفٌّ منفصل: السكربتُ والبيانُ متجاوران في جذره،
# فتسميتُه بالبيت أصدقُ من تسميته بالملفّ. وافتراضُه جارُ هذه الشجرة.
HAMIL_ROOT="${HAMIL_ROOT:-$(cd "$HIFZ_DIR/../.." && pwd)/hamil-hala-zaman-program}"
FETCH="$HAMIL_ROOT/fetch_source.sh"

# المخرجاتُ والذاكرةُ داخلَ Alghanem لا في بيت البايتات: لا يكتب المستدعي في
# شجرةِ من يستدعيه.
export SOURCES_DIR="${SOURCES_DIR:-$HIFZ_DIR/.sources}"
export SOURCES_CACHE="${SOURCES_CACHE:-$HIFZ_DIR/.cache}"

# البيانُ يُقرأ هنا لموضع البايتات وحدَه، لا للأختام: الأختامُ تُصادَم في البيت
# المستدعى لا تُعاد قراءتُها هنا.
MANIFEST="${SOURCES_MANIFEST:-$HAMIL_ROOT/sources_manifest.tsv}"
INBOX="${SOURCES_INBOX:-$HAMIL_ROOT/corpora/inbox}"

E_USAGE=2
HIFZ_RETRIES="${HIFZ_RETRIES:-2}"

say() { printf '%s\n' "$1" >&2; }

# ــ موضعُ البايتات يُقرأ من البيان لا يُنتزَع من سطر مطبوع ــــــــــــــــــــ
# نصُّ ما يطبعه fetch_source.sh عند النجاح زينةٌ للقارئ، وليس من العقد في شيء:
# العقدُ خمسةُ مخارجَ لا صيغةُ سطر. فانتزاعُ المسار منه يكسر عند أوّل تحسينِ
# عبارةٍ هناك. والبيانُ نفسُه مصدرُ الحقيقة، كما في قراءة المعرِّفات.
field_of() { # field_of <معرِّف> <رقمُ الحقل>
  [ -f "$MANIFEST" ] || return 1
  awk -F'\t' -v id="$1" -v n="$2" '
    /^[[:space:]]*#/ || NF < 10 { next }
    $1 == id { print $n; found = 1; exit }
    END { exit (found ? 0 : 1) }
  ' "$MANIFEST"
}

# الطرقُ ثلاثٌ وموضعُ البايتات يختلف بها:
#   البعيدُ (OpenITI) يُودِع في SOURCES_DIR/<معرِّف>.txt
#   المحلّيُّ يبقى حيث وضعه المالكُ في صندوق الوارد
#   وself يُقرأ إلى مؤقَّتٍ يمحوه البيتُ المستدعى عند خروجه، فلا بايتاتٍ تُسلَّم
bytes_path() { # bytes_path <معرِّف>
  local id="$1" repo name
  repo="$(field_of "$id" 2)" || { printf '%s/%s.txt\n' "$SOURCES_DIR" "$id"; return 0; }
  case "$repo" in
    local)
      name="$(field_of "$id" 5)"
      [ -n "$name" ] && [ "$name" != "-" ] || return 1
      printf '%s/%s\n' "$INBOX" "$name"
      ;;
    self)
      return 2
      ;;
    *)
      printf '%s/%s.txt\n' "$SOURCES_DIR" "$id"
      ;;
  esac
}

usage() {
  say "استعمالٌ: bash hifz/unfold.sh <معرِّف>   (معرِّفٌ واحدٌ لا --all)"
  say "  HAMIL_ROOT=<مسارُ بيت البايتات> إن لم يكن جارَ هذه الشجرة"
  exit "$E_USAGE"
}

[ $# -eq 1 ] || usage
case "$1" in
  --all) say "صريخ: لا يُنادى بـ--all — الحكمُ لا يُعرَف إلّا مفرَدًا"; exit "$E_USAGE" ;;
  -h|--help) usage ;;
  -*) say "صريخ: طورٌ مجهولٌ «$1» — يُنادى بالمعرِّف وحدَه"; exit "$E_USAGE" ;;
esac
id="$1"

if [ ! -f "$FETCH" ]; then
  say "صريخ: لا سكربتَ جلبٍ في $FETCH"
  say "  البيتُ المستدعى يُعلَن بـHAMIL_ROOT، وسكربتُه في جذره لا في مجلَّدٍ فرعيّ"
  exit "$E_USAGE"
fi

mkdir -p "$SOURCES_DIR" "$SOURCES_CACHE"

attempt=0
while : ; do
  attempt=$((attempt + 1))
  # المخرجُ القياسيُّ يُلتقَط ليُقرأ منه مسارُ البايتات؛ والصريخُ يمرُّ كما هو.
  out="$(bash "$FETCH" --fetch "$id")"
  rc=$?
  case "$rc" in
    0)
      printf '%s\n' "$out" >&2
      path="$(bytes_path "$id")"; pr=$?
      if [ "$pr" = "2" ]; then
        say "«$id» مطابقُ ختمِه ✓ لكنّه من طريق self: البيتُ المستدعى يقرؤه إلى"
        say "  مؤقَّتٍ يمحوه عند خروجه، فلا بايتاتٍ تُسلَّم إلى هنا فتُطوى."
        exit 1
      fi
      if [ "$pr" != "0" ] || [ -z "$path" ]; then
        say "«$id» مطابقُ ختمِه ✓ ولا موضعَ بايتاتٍ يُقرأ له في البيان"
        exit 1
      fi
      say "«$id» مفكوكٌ مطابقُ الختم ✓"
      printf '%s\n' "$path"
      exit 0
      ;;
    1)
      # تعذُّرٌ عارضٌ وحدَه يُعاد، ويُخبَر عنه في الحالين.
      if [ "$attempt" -le "$HIFZ_RETRIES" ]; then
        say "«$id» تعذَّر جلبُه (محاولةٌ $attempt) — يُعاد"
        sleep "$attempt"
        continue
      fi
      say "«$id» تعذَّر جلبُه بعدَ $attempt محاولةً — عارضٌ لا مخالفةُ ختم"
      exit 1
      ;;
    4)
      # البايتاتُ ليست المصدرَ. لا إعادةَ تنفع، ولا يُطوى منها شيء.
      say "«$id» خالف ختمَه — لا يُعاد ولا يُطوى منه شيء"
      exit 4
      ;;
    2)
      say "«$id» خطأُ استعمالٍ عند المستدعي — راجِع المعرِّفَ في البيان: bash \"$FETCH\" --list"
      exit 2
      ;;
    3)
      say "بيانُ المصادر معطوبٌ في $HAMIL_ROOT — خللٌ في البيت المستدعى لا يُداوى بإعادة"
      exit 3
      ;;
    *)
      say "«$id» مخرجٌ خارجَ العقد: $rc — العقدُ خمسةٌ لا سادسَ لها"
      exit "$rc"
      ;;
  esac
done
