def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if TARGET.read_text(encoding="utf-8") != text:
            sys.stderr.write("NABHANI_INDEX.md غيرُ مطابق؛ شغّل tools/gen_nabhani_index.py\n")
            return 1
        sys.stdout.write("NABHANI_INDEX.md مطابق\n")
        return 0
    TARGET.write_text(text, encoding="utf-8")
    sys.stdout.write("كُتب NABHANI_INDEX.md\n")
    return 0


