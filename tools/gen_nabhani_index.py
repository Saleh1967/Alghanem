def problems() -> list[str]:
    names = {m.name for m in MODULES} | set(META)
    audited = set(re.findall(r"^'([^']+)'", AXIOMS.read_text(encoding="utf-8"), re.M))
    out: list[str] = []
    for topic, _, _, units, refs, _ in ROWS:
        for u in units:
            if u not in names:
                out.append(f"UNKNOWN_UNIT:{topic}:{u}")
        for ref in refs:
            kind, _, target = ref.partition(":")
            if kind == "lean":
                if target not in audited:
                    out.append(f"UNAUDITED_THEOREM:{topic}:{target}")
            elif kind == "test":
                path, _, fn = target.partition("::")
                p = ROOT / path
                if not p.exists() or f"def {fn}(" not in p.read_text(encoding="utf-8"):
                    out.append(f"MISSING_TEST:{topic}:{target}")
            else:
                out.append(f"UNKNOWN_REF:{topic}:{ref}")
    return out


