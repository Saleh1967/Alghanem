"""مختبرُ اكتشافٍ صغير: مسألةٌ واحدة، تفسيران متنافسان، اختبارٌ يفصل بينهما.

الطلبُ كان: «لا تُطلِق اسمَ ذكاءٍ فائقٍ على واجهة محادثة؛ ابنِ مختبرًا صغيرًا
يستقبل مسألةً محدّدةً وبياناتٍ مرخَّصة، ثمّ يقترح تفسيرَين مختلفَين على الأقلّ،
ويحدّد اختبارًا يميّز بينهما، وينفّذه، ويعرض ما ثبت وما سقط وما بقي معلَّقًا».
وهذه الوحدةُ تفعل ذلك على مادّةٍ مُودَعةٍ في الشجرة، وتُسمّي ما لا تفعله::

    Protocol          != Intelligence
    Selection         != Extraction
    HeldOutAgreement  != Establishment
    RungDeclared      != RungReached

**المسألةُ محدّدةٌ ومقيسةٌ قبلَ أن تُفسَّر.** في المُودَعَين — الفاتحةُ
والفتحُ ٢٩ — مواضعُ لا تحمل علامةَ حركةٍ مكتوبة، عدّتُها مقروءةٌ من
`written_haraka_mark` لا مكتوبةٌ ههنا. والسؤال: **ما الذي يجمع هذه المواضعَ
دون غيرها؟** ولا يُسأل عن نطقٍ ولا عن سكون؛ فـ«لا علامةَ عليه» حكمٌ في الرسم،
وقد سُمِّي هناك `THE_NEGATIVE_IS_AN_ABSENT_MARK_NOT_A_SUKUN`.

**وتفسيرٌ بلا منافسٍ لا يُختبَر.** فالتفسيرُ الواحدُ يجد في كلّ نتيجةٍ ما
يوافقه، ولا يُعرَف قدرُه إلّا بما يزاحمه على المادّة نفسِها
(`AN_EXPLANATION_WITHOUT_A_RIVAL_IS_NOT_TESTED`). فههنا تفسيران:

1. **الموضعيّ**: الموضعُ عارٍ لأنّه **آخرُ كلمةٍ** — والعروُّ أثرُ موقعٍ في
   الكلمة لا أثرُ حرفٍ بعينه.
2. **البنيويّ**: الموضعُ عارٍ لأنّه **حاملُ مدٍّ** — ألفٌ بعد فتحةٍ، أو واوٌ
   بعد ضمّة، أو ياءٌ بعد كسرة — فالعروُّ أثرُ بنيةِ الحرف مع ما قبله.

**والاختبارُ يجب أن يفرّق، وإلّا فليس اختبارًا.** يُعَدُّ قبل كلّ حكمٍ عددُ
المواضع التي **يختلف عليها** التفسيران؛ فإن كان صفرًا فالمادّةُ لا تفصلهما
ولا يُقرأ من النتيجة ترجيحٌ البتّة
(`A_TEST_THAT_DOES_NOT_SEPARATE_THE_RIVALS_IS_NOT_A_TEST`).

**والمعيارُ مُسجَّلٌ قبل التنفيذ لا بعدَه.** لكلّ تفسيرٍ دعوى تكافؤٍ: «عارٍ ⟺
ينطبق عليه الوصف». فيُطلَب منه أمران معًا: **الكفاية** (لا موضعَ عارٍ خارجَه)
و**الخصوصيّة** (لا موضعَ موسومٍ داخلَه). وشاهدُ نقضٍ واحدٌ من أيّ الجهتين
يُسقط الدعوى؛ ولا تُلطَّف الدعوى بعد رؤية العدد إلى «غالبًا»
(`A_CRITERION_FIXED_AFTER_THE_COUNT_IS_NOT_A_CRITERION`).

**وما يثبت ههنا أضعفُ ممّا سقط، ويُسمّى بحدّه.** سقطت دعوى التكافؤ في
التفسيرَين جميعًا؛ وثبتت دعوى **ترتيبٍ** مُسجَّلةٌ قبل المادّة المستقلّة:
«البنيويُّ أقلُّ نقضًا من الموضعيّ». وقد صُودِمت بحذف كلّ كلمةٍ على حدةٍ من
المُودَعَين، فلم يقلبها حذفُ كلمةٍ واحدة، فليست محمولةً بصفٍّ
(`A_VERDICT_CARRIED_BY_ONE_ROW_IS_NOT_ESTABLISHED` في `lexicon_dispersion_expectation`).

**والباقي معلَّقٌ يُعَدُّ ولا يُطوى.** المواضعُ العاريةُ التي لا يشملها
تفسيرٌ منهما تُعَدُّ وتُخرَج بكلماتها، وكذلك المواضعُ الموسومةُ التي شملها
تفسيرٌ؛ فهذه مادّةُ الجولة القادمة، وطيُّها تحسينُ نتيجةٍ بحذف ما ينقضها
(`THE_RESIDUE_IS_COUNTED_AND_NOT_SWEPT`).

**والدرجاتُ الأربعُ تدرُّجٌ هندسيٌّ مُقترَح، لا مستوياتٌ معياريّةٌ معتمَدة.**
هكذا وردت في الطلب، وهكذا تُثبَت ههنا؛ ومن قرأها سلّمًا معياريًّا للذكاء
الفائق قرأ غيرَ ما كُتب (`THE_LADDER_IS_A_PROPOSED_GRADATION_NOT_A_STANDARD`).
ولكلّ درجةٍ **معيارُ نجاحٍ** و**مانعُ انتقالٍ**، وكلاهما مكتوبٌ قبل الجري.

**ومنزلةُ الدرجة تُقاس لا تُعلَن.** الدرجةُ الأولى تُبلَغ إن جرى المختبرُ على
المُودَعَين وأخرج نقضَه بنفسه. وما بعدَها مسدودٌ بموانعَ **مقيسة**: الدرجةُ
الثانيةُ تطلب قاعدةً لم تُوضَع باليد، ونصُّ التفسيرَين ههنا موجودٌ في بايتات
هذا الملفّ، فيُلتمَس فيها فيوجَد — والاختيارُ بينهما ليس استخراجًا
(`A_SELECTION_AMONG_ENACTED_RULES_IS_NOT_AN_EXTRACTION`). والثالثةُ تطلب
تراكمًا، وهذا المختبرُ عديمُ الذاكرة: لا يكتب نتيجةً ولا يقرأ سجلَّ تجاربَ
سابقة. والرابعةُ تطلب مجالَين، ومُودَعاه من جنسٍ واحد؛ فعدّةُ المجالات تُعَدُّ
ولا تُقدَّر (`A_RUNG_IS_REACHED_BY_MEASUREMENT_NOT_BY_DECLARATION`).

**وحارسُ الاسم**: هذا بروتوكولُ فحصٍ صغير، لا «ذكاءٌ فائق» ولا واجهةُ محادثة.
لا يقترح ههنا شيءٌ من تلقائه: التفسيرانِ مكتوبان، والاختبارُ مكتوب، والذي
يجري آلةُ عدٍّ تُظهِر أيَّهما ينكسر (`THE_LAB_IS_A_PROTOCOL_NOT_AN_INTELLIGENCE`).

**وحارسُ اشتراكٍ لفظيّ**: قياسُ العلامة قياسٌ على الدالّ وحدَه بمعنى الرسم،
وليس سدادًا لضلع «الدالّ وحدَه» في ثلاثيّة النبهاني الذي قِيس خلوُّه في
`dal_alone_bridge`؛ فذاك قسمةٌ منقولةٌ من مصدرٍ، وهذا عدٌّ على بايتات مُودَع
(`A_MEASUREMENT_ON_THE_SIGNIFIER_IS_NOT_THE_SOURCES_DIVISION`).

**خمولٌ سلطويّ**: لا ولادةَ ههنا ولا حكمَ ولادةٍ ولا تجميدَ `E0`، ولا استيرادَ
من `kernel/`، ولا تُرفَع بهذه الوحدة منزلةٌ محجوزة، ولا تقرأ مخرجاتِها بوّابة.

والبياناتُ مرخَّصة: متنٌ في الملك العامّ مُودَعٌ في هذه الشجرة، بحدوده
المُعلَنة في `fatiha_source_text` و`fath_ayah_source_text`.
"""

