class RungStanding(Enum):
    """منزلةُ درجةٍ عند هذه القراءة؛ تُقاس ولا تُكتَب."""

    REACHED_ON_THIS_EVIDENCE = "مبلوغةٌ_على_هذه_الشواهد"
    BLOCKED_BY_ITS_DECLARED_BLOCKER = "ممنوعةٌ_بمانعها_المُعلَن"


def _squeezed(text: str) -> str:
    """يُسقِط البياضَ وعلاماتِ الاقتباس، فلا يُخفي وصلُ السلاسل نصًّا مكتوبًا."""

    return "".join(character for character in text if character not in " \t\n\"'")


def enacted_explanations() -> tuple[str, ...]:
    """أيُّ التفاسير نصُّ دعواها موجودٌ في بايتات هذه الوحدة؟ سندُ منع الثانية.

    فما وُجد نصُّه ههنا مسنونٌ بيدٍ، ولا يُقرأ الترجيحُ بينه وبين أخيه
    استخراجًا لقاعدةٍ لم نضعها. والالتماسُ بعد إسقاط البياض والاقتباس، لئلّا
    يُقرأ وصلُ السلسلة على سطرَين غيابًا لنصِّها.
    """

    source = _squeezed(Path(__file__).resolve().read_text(encoding="utf-8"))
    return tuple(
        explanation.name
        for explanation in THE_RIVAL_EXPLANATIONS
        if _squeezed(explanation.claim) in source
    )


def _run_ledger_path() -> Path:
    """موضعُ سجلّ الجولات المنتظَر؛ وغيابُه يُقاس على القرص لا يُوصَف."""

    return Path(__file__).resolve().parents[3] / THE_RUN_LEDGER


def reads_a_prior_ledger() -> bool:
    """أيجد هذا المختبرُ سجلَّ جولاتٍ سابقةٍ مُودَعًا؟ يُلتمَس على القرص.

    ولو أُودِع غدًا لانقلب حكمُ الدرجة الثالثة من نفسه بلا تحرير حرفٍ ههنا؛
    وإيداعُه وحدَه لا يكفي حتّى تُقرأ منه جولةٌ سابقةٌ في مسألةٍ جديدة.
    """

    return _run_ledger_path().is_file()


def rung_standing() -> tuple[tuple[Rung, RungStanding, str], ...]:
    """منزلةُ كلّ درجةٍ، مشتقّةً من قياسٍ يجري الآن لا من إعلانٍ مكتوب."""

    report = run()
    domains = {deposit.domain for deposit in THE_DEPOSITS}
    enacted = enacted_explanations()
    standings: list[tuple[Rung, RungStanding, str]] = []
    for rung in THE_LADDER:
        if rung.number == 1:
            reached = bool(report.fell) and all(
                deposition.the_material_separates for deposition in report.depositions
            )
            why = (
                f"جرى على {len(report.depositions)} مُودَعَين، وأخرج "
                f"{len(report.fell)} إسقاطًا لتفسيرَيه، وعدَّ معلَّقَه."
            )
        elif rung.number == 2:
            reached = not enacted
            why = (
                f"نصُّ {len(enacted)} من {len(THE_RIVAL_EXPLANATIONS)} تفسيرًا "
                "موجودٌ في بايتات هذه الوحدة، فالترجيحُ بينها اختيار."
            )
        elif rung.number == 3:
            reached = reads_a_prior_ledger()
            why = (
                f"سجلُّ الجولات المنتظَرُ في {THE_RUN_LEDGER}: "
                f"{'موجود' if reached else 'غائب'}؛ والمختبرُ لا يكتب حصيلتَه."
            )
        else:
            reached = len(domains) > 1
            why = f"مجالاتُ المُودَعات المُعلَنة: {len(domains)}."
        standings.append(
            (
                rung,
                RungStanding.REACHED_ON_THIS_EVIDENCE
                if reached
                else RungStanding.BLOCKED_BY_ITS_DECLARED_BLOCKER,
                why,
            )
        )
    return tuple(standings)
