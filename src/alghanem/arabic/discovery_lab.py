@dataclass(frozen=True)
class MarkedPosition:
    """موضعٌ واحدٌ ومعه ما يحتاجه التفسيران: موقعُه في كلمته وما قبلَه."""

    word: str
    word_index: int
    position: Position
    is_word_final: bool
    is_madd_carrier: bool

    @property
    def is_marked(self) -> bool:
        """أعلى هذا الموضع علامةُ حركةٍ مكتوبة؟ يُقرَّر بالمحمول لا ههنا."""

        return has_written_haraka_mark(self.position)


def _positions_with_context(text: str) -> tuple[MarkedPosition, ...]:
    """يقسم المُودَعَ كلماتٍ بالبياض، ثمّ مواضعَ بخاصّية اليونيكود وحدَها.

    والقسمةُ بالبياض قاعدةٌ مسنونةٌ لا خاصّيّةٌ لغويّة، وقد سُمِّيت في
    `carrier_projection_deposit`؛ وهي ههنا شرطُ «آخرِ الكلمة» لا غير.
    """

    built: list[MarkedPosition] = []
    for word_index, word in enumerate(text.split()):
        positions = positions_of(word)
        if not positions:
            continue
        last = len(positions) - 1
        for index, position in enumerate(positions):
            carrier_haraka = MADD_CARRIERS.get(position.carrier)
            previous = positions[index - 1] if index else None
            built.append(
                MarkedPosition(
                    word=word,
                    word_index=word_index,
                    position=position,
                    is_word_final=index == last,
                    is_madd_carrier=(
                        carrier_haraka is not None
                        and previous is not None
                        and carrier_haraka in previous.haraka_marks
                    ),
                )
            )
    return tuple(built)


