_FATHA: Final[str] = "\u064e"
_DAMMA: Final[str] = "\u064f"
_KASRA: Final[str] = "\u0650"

MADD_CARRIERS: Final[dict[str, str]] = {
    "\u0627": _FATHA,  # ألفٌ بعد فتحة
    "\u0648": _DAMMA,  # واوٌ بعد ضمّة
    "\u064a": _KASRA,  # ياءٌ بعد كسرة
}
