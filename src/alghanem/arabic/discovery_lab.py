@dataclass(frozen=True)
class Rung:
    """درجةٌ من التدرُّج المُقترَح: اسمُها، وما يُعَدُّ نجاحًا، وما يمنع الانتقال."""

    number: int
    name: str
    success: str
    blocker: str
    discharge: str

    def __post_init__(self) -> None:
        if self.number < 1:
            raise DiscoveryLabError("درجةٌ برتبةٍ دون الواحدة لا تكون.")
        for value, complaint in (
            (self.name, "درجةٌ بلا اسمٍ لا تُميَّز."),
            (self.success, "درجةٌ بلا معيار نجاحٍ لا تُبلَغ ولا تُمنَع."),
            (self.blocker, "درجةٌ بلا مانعٍ مُعلَنٍ تُبلَغ بالتسامح."),
            (self.discharge, "درجةٌ بلا سدادٍ مُسمًّى مطلبٌ مفتوح."),
        ):
            if not value.strip():
                raise DiscoveryLabError(complaint)


