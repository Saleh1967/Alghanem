class ExplanationStanding(Enum):
    """منزلةُ تفسيرٍ بعد الاختبار؛ ثلاثٌ لا رابعَ لها."""

    STOOD_AS_A_BICONDITIONAL = "ثبت_تكافؤًا"
    FELL_ON_A_COUNTEREXAMPLE = "سقط_بشاهد_نقض"
    NOT_SEPARATED_BY_THIS_MATERIAL = "لم_تفصله_هذه_المادّة"


@dataclass(frozen=True)
class ExplanationReading:
    """قراءةُ تفسيرٍ على مُودَع: ما غطّاه، وما فاته، وما تجاوز إليه."""

    explanation: str
    deposit: str
    covered: int
    missed: tuple[MarkedPosition, ...]
    overreached: tuple[MarkedPosition, ...]

    @property
    def counterexamples(self) -> int:
        """شواهدُ النقض من الجهتين معًا؛ وواحدٌ منها يكفي للإسقاط."""

        return len(self.missed) + len(self.overreached)

    @property
    def standing(self) -> ExplanationStanding:
        if self.counterexamples:
            return ExplanationStanding.FELL_ON_A_COUNTEREXAMPLE
        return ExplanationStanding.STOOD_AS_A_BICONDITIONAL


def explanation_reading(
    explanation: Explanation, deposit: LabDeposit
) -> ExplanationReading:
    """يجري تفسيرًا على مُودَعٍ ويعدّ نقضَه من جهتَي الكفاية والخصوصيّة."""

    covered = 0
    missed: list[MarkedPosition] = []
    overreached: list[MarkedPosition] = []
    for reading in _positions_with_context(deposit.text):
        holds = explanation.predicate(reading)
        if reading.is_marked:
            if holds:
                overreached.append(reading)
        elif holds:
            covered += 1
        else:
            missed.append(reading)
    return ExplanationReading(
        explanation=explanation.name,
        deposit=deposit.name,
        covered=covered,
        missed=tuple(missed),
        overreached=tuple(overreached),
    )


def separating_positions(deposit: LabDeposit) -> int:
    """كم موضعًا يختلف عليه التفسيران في هذا المُودَع؟ شرطُ كون الاختبار مميِّزًا."""

    first, second = THE_RIVAL_EXPLANATIONS[0], THE_RIVAL_EXPLANATIONS[1]
    return sum(
        1
        for reading in _positions_with_context(deposit.text)
        if first.predicate(reading) != second.predicate(reading)
    )


@dataclass(frozen=True)
class DepositReading:
    """حصيلةُ مُودَعٍ واحد: قراءتا التفسيرَين، وقدرةُ المادّة على الفصل."""

    deposit: str
    separating: int
    readings: tuple[ExplanationReading, ...]

    @property
    def the_material_separates(self) -> bool:
        return self.separating > 0

    @property
    def unexplained(self) -> tuple[MarkedPosition, ...]:
        """المواضعُ العاريةُ التي فاتت التفسيرَين جميعًا؛ وهي المعلَّق الأوّل."""

        first, *rest = self.readings
        others = [
            {(item.word_index, item.position.index) for item in reading.missed}
            for reading in rest
        ]
        return tuple(
            item
            for item in first.missed
            if all((item.word_index, item.position.index) in group for group in others)
        )

    def reading_for(self, explanation: str) -> ExplanationReading:
        for reading in self.readings:
            if reading.explanation == explanation:
                return reading
        raise DiscoveryLabError(f"لا قراءةَ لتفسيرٍ باسم {explanation!r} ههنا.")


def reading_of(deposit: LabDeposit) -> DepositReading:
    """يجري التفسيرَين على مُودَعٍ، بعد عدّ ما يفترقان عليه فيه."""

    if len(THE_RIVAL_EXPLANATIONS) < 2:
        raise DiscoveryLabError(
            "تفسيرٌ واحدٌ لا يُختبَر؛ وعلّتُه في "
            "AN_EXPLANATION_WITHOUT_A_RIVAL_IS_NOT_TESTED."
        )
    return DepositReading(
        deposit=deposit.name,
        separating=separating_positions(deposit),
        readings=tuple(
            explanation_reading(explanation, deposit)
            for explanation in THE_RIVAL_EXPLANATIONS
        ),
    )


# --- الحصيلة: ما ثبت، وما سقط، وما بقي معلَّقًا ----------------------------


@dataclass(frozen=True)
class LabReport:
    """حصيلةُ الجولة على المُودَعَين، بأقسامها الثلاثة لا يُطوى منها قسم."""

    question: str
    depositions: tuple[DepositReading, ...]

    @property
    def fell(self) -> tuple[tuple[str, str, int], ...]:
        """ما سقط: تفسيرٌ في مُودَعٍ، ومعه عدّةُ شواهد نقضه."""

        return tuple(
            (reading.deposit, reading.explanation, reading.counterexamples)
            for deposition in self.depositions
            for reading in deposition.readings
            if reading.standing is ExplanationStanding.FELL_ON_A_COUNTEREXAMPLE
        )

    @property
    def stood(self) -> tuple[tuple[str, str], ...]:
        """ما ثبت: تفسيرٌ لم يُنقَض في مُودَعٍ، بدعوى التكافؤ لا بأضعفَ منها."""

        return tuple(
            (reading.deposit, reading.explanation)
            for deposition in self.depositions
            for reading in deposition.readings
            if reading.standing is ExplanationStanding.STOOD_AS_A_BICONDITIONAL
        )

    @property
    def pending(self) -> tuple[tuple[str, int, int], ...]:
        """ما بقي معلَّقًا: مواضعُ عاريةٌ لم يشملها تفسير، ومواضعُ موسومةٌ شملها."""

        pending: list[tuple[str, int, int]] = []
        for deposition in self.depositions:
            overreached = sum(
                len(reading.overreached) for reading in deposition.readings
            )
            pending.append(
                (deposition.deposit, len(deposition.unexplained), overreached)
            )
        return tuple(pending)

    @property
    def ordering_holds(self) -> bool:
        """أنقضُ البنيويِّ أقلُّ من نقضِ الموضعيِّ في المُودَعَين جميعًا؟"""

        return all(
            deposition.reading_for("البنيويّ").counterexamples
            < deposition.reading_for("الموضعيّ").counterexamples
            for deposition in self.depositions
        )

    def deposition_for(self, deposit: str) -> DepositReading:
        for deposition in self.depositions:
            if deposition.deposit == deposit:
                return deposition
        raise DiscoveryLabError(f"لا حصيلةَ لمُودَعٍ باسم {deposit!r} ههنا.")


def run() -> LabReport:
    """جولةُ المختبر: مسألةٌ واحدةٌ، تفسيران، اختبارٌ مميِّزٌ، ثمّ حصيلةٌ ثلاثيّة."""

    return LabReport(
        question=THE_QUESTION,
        depositions=tuple(reading_of(deposit) for deposit in THE_DEPOSITS),
    )


def held_out_agreement() -> tuple[str, str, bool]:
    """يُرجَّح على مُودَع الترجيح وحدَه، ثمّ يُنظَر أيثبت الترجيحُ على المحجوز.

    ويُعاد: المُرجَّحُ عند الترجيح، والمُرجَّحُ على المادّة المستقلّة، وهل
    اتّفقا. والاتّفاقُ **قرينةٌ لا استيفاءٌ للدرجة الثانية**، لأنّ المُرجَّحَ
    مختارٌ من مكتوبَين (`A_SELECTION_AMONG_ENACTED_RULES_IS_NOT_AN_EXTRACTION`).
    """

    report = run()

    def winner(deposit: str) -> str:
        deposition = report.deposition_for(deposit)
        ranked = sorted(
            deposition.readings, key=lambda reading: reading.counterexamples
        )
        if ranked[0].counterexamples == ranked[1].counterexamples:
            raise DiscoveryLabError(
                "تساوى التفسيرانِ في النقض، فلا مُرجَّحَ؛ ولا يُختار بالهوى."
            )
        return ranked[0].explanation

    fitted = winner(THE_FITTING_DEPOSIT)
    held_out = winner(THE_HELD_OUT_DEPOSIT)
    return fitted, held_out, fitted == held_out


def ordering_flips_on_leaving_one_word_out() -> tuple[tuple[str, int], ...]:
    """يحذف كلَّ كلمةٍ على حدةٍ من كلّ مُودَع: أيقلب حذفُها دعوى الترتيب؟

    فحكمٌ يقلبه صفٌّ واحدٌ محمولٌ بذلك الصفّ لا بالمادّة، ويُخرَج حاملُه
    بعينه ولا يُطوى.
    """

    flips: list[tuple[str, int]] = []
    for deposit in THE_DEPOSITS:
        words = deposit.text.split()
        for dropped in range(len(words)):
            shortened = LabDeposit(
                name=deposit.name,
                text=" ".join(words[:dropped] + words[dropped + 1 :]),
                domain=deposit.domain,
            )
            deposition = reading_of(shortened)
            if not (
                deposition.reading_for("البنيويّ").counterexamples
                < deposition.reading_for("الموضعيّ").counterexamples
            ):
                flips.append((deposit.name, dropped))
    return tuple(flips)


