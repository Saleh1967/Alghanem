class SyllableState(Enum):
    """حالاتُ النموذج المُعلَن؛ والسقوطُ حالةٌ مُسمّاةٌ لا استثناءٌ يُرفَع."""

    AWAITING_AN_ONSET = "منتظرٌ بذرةً متحرّكة"
    AFTER_A_VOWELLED_SEED = "بعد بذرةٍ متحرّكة"
    FELL_OUT_OF_THE_MODEL = "خارجَ النموذج"


@lru_cache(maxsize=1)
def _cell_index() -> frozenset[tuple[str, str]]:
    """الخاناتُ مجموعةً للفحص؛ مُشتقّةٌ من `a116_cells` لا نسخةٌ ثانيةٌ منها."""

    return frozenset(a116_cells())


def step(state: SyllableState, cell: tuple[str, str]) -> SyllableState:
    """انتقالٌ **تامٌّ** على الـ116: لكلّ حالةٍ وخانةٍ صورةٌ، ولا موضعَ بلا انتقال.

    والنموذجُ مُعلَنٌ ضيّقًا: بذرةٌ متحرّكةٌ تفتح المقطع، وساكنٌ واحدٌ يُغلِقه،
    ولا يبتدئ مقطعٌ بساكن. وخانةُ السكون في موضع البذرة سقوطٌ **يحتاج سياقًا
    يساريًّا**، لا امتناعٌ في العربيّة.
    """

    if cell not in _cell_index():
        raise A116BridgeLicenceError("خانةٌ خارجَ المئة وستَّ عشرةَ لا تُنقَل حالة.")
    if state is SyllableState.FELL_OUT_OF_THE_MODEL:
        return state
    is_sukun = cell[1] == SUKUN
    if state is SyllableState.AWAITING_AN_ONSET:
        if is_sukun:
            return SyllableState.FELL_OUT_OF_THE_MODEL
        return SyllableState.AFTER_A_VOWELLED_SEED
    if is_sukun:
        return SyllableState.AWAITING_AN_ONSET
    return SyllableState.AFTER_A_VOWELLED_SEED


def run_declared_model(cells: Sequence[tuple[str, str]]) -> SyllableState:
    """أثرُ ‎δ*‎ من حالة البدء على سلسلةِ خانات؛ دالّةٌ تامّةٌ لا ترفع استثناء."""

    state = SyllableState.AWAITING_AN_ONSET
    for cell in cells:
        state = step(state, cell)
    return state


@dataclass(frozen=True)
class FixpointReading:
    """قراءةُ الإشباع: درجاتُه، ومجموعتُه عند الاستقرار، وشهادةُ إغلاقه."""

    rungs: tuple[int, ...]
    stable_set: frozenset[SyllableState]

    @property
    def saturation_rung(self) -> int:
        """الدرجةُ التي تحقّق عندها ‎S(k+1) = S(k)‎؛ ومعدودةٌ لا مقدَّرة."""

        return len(self.rungs) - 1

    @property
    def closes_all_lengths(self) -> bool:
        """إغلاقٌ لجميع الأطوال: مجموعةٌ مغلقةٌ على كلّ خانةٍ من الـ116."""

        return all(
            step(state, cell) in self.stable_set
            for state in self.stable_set
            for cell in a116_cells()
        )


@lru_cache(maxsize=1)
def fixpoint_reading() -> FixpointReading:
    """إشباعُ المجموعة حتّى ‎S(k+1) = S(k)‎، مُشتقًّا بالتشغيل لا موصوفًا."""

    current: frozenset[SyllableState] = frozenset({SyllableState.AWAITING_AN_ONSET})
    rungs: list[int] = [len(current)]
    while True:
        grown = frozenset(current) | {
            step(state, cell) for state in current for cell in a116_cells()
        }
        if grown == current:
            break
        current = grown
        rungs.append(len(current))
    return FixpointReading(rungs=tuple(rungs), stable_set=current)


@dataclass(frozen=True)
class ModelExitReading:
    """ما خرج عن النموذج من المُودَع: عددُه، وموضعُ سقوطه، وبذرتُه."""

    projected_forms: int
    outside_forms: int
    outside_occurrences: int
    fell_at_the_first_cell: int
    named_exits: tuple[str, ...]

    @property
    def every_exit_needs_a_left_context(self) -> bool:
        """أكلُّ خارجٍ سقط عند خانته الأولى؟ فالحاجةُ حاجةُ وصلٍ لا امتناعُ صورة."""

        return self.outside_forms == self.fell_at_the_first_cell


@lru_cache(maxsize=1)
def model_exit_reading() -> ModelExitReading:
    """تعدادُ الخارجين عن النموذج المُعلَن على الصور المتمايزة المكتملِ إسقاطُها."""

    projections: dict[str, tuple[tuple[str, str], ...]] = {}
    occurrences: dict[str, int] = {}
    for word in deposited_words():
        cells = projected_cells(word)
        if cells is None:
            continue
        projections[word] = cells
        occurrences[word] = occurrences.get(word, 0) + 1
    outside = [
        form
        for form, cells in projections.items()
        if run_declared_model(cells) is SyllableState.FELL_OUT_OF_THE_MODEL
    ]
    first_cell_exits = sum(
        1
        for form in outside
        if step(SyllableState.AWAITING_AN_ONSET, projections[form][0])
        is SyllableState.FELL_OUT_OF_THE_MODEL
    )
    return ModelExitReading(
        projected_forms=len(projections),
        outside_forms=len(outside),
        outside_occurrences=sum(occurrences[form] for form in outside),
        fell_at_the_first_cell=first_cell_exits,
        named_exits=tuple(sorted(outside)),
    )


