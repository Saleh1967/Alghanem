@dataclass(frozen=True)
class A116Census:
    """إحصاءُ المُودَع تحت القاعدة المُعلَنة؛ كلُّ حقلٍ مقيسٌ لا منقول."""

    words: int
    clusters: int
    attested_cells: int
    absent_cells: tuple[tuple[str, str], ...]
    complete_words: int
    bridge_words: int

    def __post_init__(self) -> None:
        if self.complete_words + self.bridge_words != self.words:
            raise A116BridgeLicenceError(
                "الكلماتُ لا تنقسم إلى مكتملٍ ومحتاجٍ للجسر، وهذا محال."
            )
        if self.attested_cells + len(self.absent_cells) != THE_HUNDRED_AND_SIXTEEN:
            raise A116BridgeLicenceError(
                "الخاناتُ المشهودةُ والخاليةُ لا تبلغان المئةَ وستَّ عشرةَ."
            )

    def value_of(self, key: str) -> int:
        """قيمةُ حقلٍ باسمه؛ والاسمُ المجهولُ يُردّ ولا يُفسَّر صفرًا."""

        if key not in {
            "words",
            "clusters",
            "attested_cells",
            "complete_words",
            "bridge_words",
        }:
            raise A116BridgeLicenceError(f"لا حقلَ مقيسٌ باسم «{key}».")
        return int(getattr(self, key))


@lru_cache(maxsize=1)
def deposited_words() -> tuple[str, ...]:
    """كلماتُ المُودَع: صفوفُ الآيات مقسومةً بالبياض، بترتيبها لا بترتيبٍ مُحدَث."""

    return tuple(
        unicodedata.normalize("NFC", word)
        for row in ayah_rows_of(THE_EXAMINED_DEPOSIT)
        for word in row.split()
    )


@lru_cache(maxsize=1)
def census() -> A116Census:
    """إحصاءُ الـ116 على البايتات المختومة، مُعادًا اشتقاقُه من القاعدة المُعلَنة."""

    words = deposited_words()
    clusters = 0
    attested: set[tuple[str, str]] = set()
    complete = 0
    for word in words:
        word_clusters = carrier_clusters(word)
        clusters += len(word_clusters)
        for cluster in word_clusters:
            cell = cluster.cell
            if cell is not None:
                attested.add(cell)
        if word_clusters and all(cluster.is_complete for cluster in word_clusters):
            complete += 1
    absent = tuple(cell for cell in a116_cells() if cell not in attested)
    return A116Census(
        words=len(words),
        clusters=clusters,
        attested_cells=len(attested),
        absent_cells=absent,
        complete_words=complete,
        bridge_words=len(words) - complete,
    )


def comparison_rows() -> tuple[tuple[TranscribedRow, int | None, RowStanding], ...]:
    """مقابلةُ المنقول بالمقيس صفًّا صفًّا؛ ولا قاعدةَ تُحرَّك لتوافقَ رقمًا."""

    measured = census()
    rows: list[tuple[TranscribedRow, int | None, RowStanding]] = []
    for row in THE_REPORT_AT_TRANSCRIPTION:
        if row.measured_key is None:
            rows.append((row, None, RowStanding.NOT_MEASURABLE_IN_THIS_TREE))
            continue
        value = measured.value_of(row.measured_key)
        standing = (
            RowStanding.AGREES_WITH_WHAT_DISK_GIVES
            if value == row.transcribed
            else RowStanding.DIVERGES_FROM_WHAT_DISK_GIVES
        )
        rows.append((row, value, standing))
    return tuple(rows)


