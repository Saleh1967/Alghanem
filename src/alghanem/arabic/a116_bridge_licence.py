@dataclass(frozen=True)
class CarrierCluster:
    """عنقودٌ كتابيّ: حاملٌ مطويٌّ وما لحقه من علاماتٍ بترتيب المُودَع."""

    carrier: str
    marks: tuple[str, ...]

    @property
    def harakat(self) -> tuple[str, ...]:
        """ما كان من علاماته من الأربع المُعلَنة؛ وما سواها بقيّةٌ تُسمّى."""

        return tuple(mark for mark in self.marks if mark in THE_HARAKAT)

    @property
    def residue(self) -> tuple[str, ...]:
        """البقيّةُ: شدّةٌ أو تنوينٌ أو خنجريّةٌ أو تطويل؛ وهي موضعُ الجسر."""

        return tuple(mark for mark in self.marks if mark not in THE_HARAKAT)

    @property
    def cell(self) -> tuple[str, str] | None:
        """خانتُه من ‎A₁₁₆‎ إن كان حاملًا مُعلَنًا عليه حركةٌ واحدةٌ لا غير."""

        if self.carrier not in LETTER_VOCABULARY:
            return None
        harakat = self.harakat
        if len(harakat) != 1:
            return None
        return (self.carrier, harakat[0])

    @property
    def is_complete(self) -> bool:
        """أاكتمل إسقاطُه بلا بقيّة؟ فالخانةُ وحدَها لا تكفي إن بقيت علامة."""

        return self.cell is not None and not self.residue


