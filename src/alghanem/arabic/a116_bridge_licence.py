class MaterialStanding(Enum):
    """مقامُ المادّة، **مُشتَقًّا من القرص** لا مُعلَنًا في حقلٍ يُكتَب باليد."""

    DEPOSITED_AND_SEALED = "مُودَعةٌ مطابقةٌ لطولها وبصمتها"
