    PRESENT_WITHOUT_A_DECLARED_SEAL = "حاضرةٌ بلا ختمٍ مُعلَن"
    PRESENT_BUT_BREAKS_ITS_SEAL = "حاضرةٌ مخالفةٌ لختمها"

