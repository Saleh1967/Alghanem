@dataclass(frozen=True)
class CollisionReading:
    """قراءةُ التصادم في الحالتين: بالجسر وبغيره، والزوجُ المُسمّى معهما."""

    groups_with_the_bridge: int
    groups_without_the_bridge: int
    named_pair_collides_with_the_bridge: bool
    named_pair_collides_without_the_bridge: bool

    @property
    def groups_the_bridge_removes(self) -> int:
        """ما أزاله الجسرُ من مجموعات؛ وهو فرقٌ مقيسٌ لا دعوى إزالةٍ عامّة."""

        return self.groups_without_the_bridge - self.groups_with_the_bridge

    @property
    def the_bridge_moves_the_named_pair(self) -> bool:
        """أانتقل الزوجُ المُسمّى بالجسر من تصادمٍ إلى تمايز؟"""

        return (
            self.named_pair_collides_without_the_bridge
            and not self.named_pair_collides_with_the_bridge
        )

    @property
    def retrieval_rests_on_the_original_log(self) -> bool:
        """أبقيت مجموعاتُ تصادمٍ بعد الجسر؟ فالاسترجاعُ مثبَّتٌ بسجلّ الأصل."""

        return self.groups_with_the_bridge > 0


def _collision_groups(keep_bare_alif: bool) -> int:
    buckets: dict[str, set[str]] = {}
    for word in deposited_words():
        key = atomic_projection(word, keep_bare_alif=keep_bare_alif)
        buckets.setdefault(key, set()).add(word)
    return sum(1 for forms in buckets.values() if len(forms) > 1)


@lru_cache(maxsize=1)
def collision_reading() -> CollisionReading:
    """أثرُ الجسر مقيسًا: عددُ المجموعتين، ومنزلةُ «مَلِكِ/مَالِكِ» في كلٍّ."""

    _assert_the_named_pair_is_attested()
    first, second = THE_NAMED_COLLIDING_PAIR
    return CollisionReading(
        groups_with_the_bridge=_collision_groups(True),
        groups_without_the_bridge=_collision_groups(False),
        named_pair_collides_with_the_bridge=(
            atomic_projection(first) == atomic_projection(second)
        ),
        named_pair_collides_without_the_bridge=(
            atomic_projection(first, keep_bare_alif=False)
            == atomic_projection(second, keep_bare_alif=False)
        ),
    )


def _assert_the_named_pair_is_attested() -> None:
    """لا يُقاس زوجٌ مُسمًّى إلّا وهو مشهودٌ في المُودَع بصورته."""

    attested = set(deposited_words())
    for form in THE_NAMED_COLLIDING_PAIR:
        if form not in attested:
            raise A116BridgeLicenceError(
                f"«{form}» غيرُ مشهودةٍ في المُودَع؛ لا يُقاس بها جسر."
            )


