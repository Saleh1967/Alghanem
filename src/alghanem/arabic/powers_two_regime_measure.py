@dataclass(frozen=True, slots=True)
class BandLength:
    """نطاقُ تردّدٍ واحد: حدّاه، وعددُ أنواعه، ومتوسّطُ طولها بالحروف."""

    low: int
    high: int
    types: int
    mean_length: float

    def __post_init__(self) -> None:
        if self.low < 1 or (self.high and self.high < self.low):
            raise PowersMeasureError("نطاقُ تردّدٍ مقلوبُ الحدّين لا يُودَع.")
        if self.types < 1 or self.mean_length <= 0.0:
            raise PowersMeasureError("نطاقٌ خالٍ لا يُخرِج متوسّطًا.")

    @property
    def is_a_single_specimen(self) -> bool:
        """أمتوسّطُ هذا النطاق متوسّطُ نوعٍ واحدٍ؟ فلا يُقارَن حينئذٍ."""

        return self.types == 1


@lru_cache(maxsize=len(TokenRule))
def band_lengths(rule: TokenRule = TokenRule.AS_SEALED) -> tuple[BandLength, ...]:
    """متوسّطُ الطول في كلّ نطاقٍ مُعلَن، من الأكثر تردّدًا إلى الأندر."""

    counts = _counts(rule)
    bands: list[BandLength] = []
    for low, high in THE_FREQUENCY_BANDS:
        chosen = [
            word
            for word, count in counts
            if count >= low and (not high or count <= high)
        ]
        if not chosen:
            raise PowersMeasureError("نطاقٌ مُعلَنٌ بلا لفظٍ واحدٍ لا يُقاس.")
        bands.append(
            BandLength(
                low=low,
                high=high,
                types=len(chosen),
                mean_length=sum(_drawn_length(word) for word in chosen) / len(chosen),
            )
        )
    return tuple(bands)


def the_length_ladder_is_monotone(rule: TokenRule = TokenRule.AS_SEALED) -> bool:
    """أيصعد متوسّطُ الطول في كلّ درجةٍ كما ادُّعي؟ سؤالٌ يُحسَب لا يُوصَف."""

    means = [band.mean_length for band in band_lengths(rule)]
    return all(later > earlier for earlier, later in zip(means, means[1:]))


def the_length_law_holds_between_the_extremes(
    rule: TokenRule = TokenRule.AS_SEALED,
) -> bool:
    """أالأندرُ أطولُ من الأكثر تردّدًا؟ طرفا الدعوى دون أحاديّتها."""

    bands = band_lengths(rule)
    return bands[-1].mean_length > bands[0].mean_length


def the_ladder_breaks_only_where_a_band_is_thin(
    rule: TokenRule = TokenRule.AS_SEALED,
) -> bool:
    """أكلُّ كسرٍ في السُّلَّم واقعٌ عند نطاقٍ أنواعُه أقلُّ من عشرة؟"""

    bands = band_lengths(rule)
    return all(
        earlier.types < 10 or later.mean_length > earlier.mean_length
        for earlier, later in zip(bands, bands[1:])
    )


