@dataclass(frozen=True, slots=True)
class Comparison:
    """مقابلةٌ واحدة: اسمُها، والمنقولُ، والمقيسُ، وحدُّ التسامح."""

    name: str
    quoted: float
    measured: float
    tolerance: float

    @property
    def gap(self) -> float:
        return self.measured - self.quoted

    @property
    def standing(self) -> Verdict:
        return (
            Verdict.AGREES if abs(self.gap) <= self.tolerance else Verdict.CONTRADICTS
        )


def the_quoted_figures_against_ours(
    rule: TokenRule = TokenRule.AS_SEALED,
) -> tuple[Comparison, ...]:
    """الأرقامُ المنقولةُ الثمانيةُ مقابَلةً بالمقيس، رقمًا رقمًا."""

    measured = (
        head_fit(rule, Law.ZIPF).r_squared,
        tail_fit(rule, Law.POWERS_CORRECTED).r_squared,
        tail_fit(rule, Law.ZIPF).r_squared,
    )
    rows = [
        Comparison(
            name=figure.name,
            quoted=figure.value,
            measured=value,
            tolerance=THE_R_SQUARED_TOLERANCE,
        )
        for figure, value in zip(THE_QUOTED_POWERS_FIGURES, measured)
    ]
    for index, (quoted, band) in enumerate(
        zip(THE_QUOTED_LENGTH_LADDER, band_lengths(rule))
    ):
        rows.append(
            Comparison(
                name=f"طولُ النطاق {index + 1}",
                quoted=quoted,
                measured=band.mean_length,
                tolerance=THE_LENGTH_TOLERANCE,
            )
        )
    return tuple(rows)


