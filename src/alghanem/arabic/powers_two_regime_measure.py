def _least_squares(xs: tuple[float, ...], ys: tuple[float, ...]) -> tuple[float, float]:
    count = len(xs)
    mean_x = sum(xs) / count
    mean_y = sum(ys) / count
    variance_x = sum((x - mean_x) ** 2 for x in xs)
    if variance_x <= 0.0:
        raise PowersMeasureError("مُنبئٌ بلا تباينٍ لا يُقام عليه انحدار.")
    slope = sum((x - mean_x) * (y - mean_y) for x, y in zip(xs, ys)) / variance_x
    intercept = mean_y - slope * mean_x
    residual = sum((y - (slope * x + intercept)) ** 2 for x, y in zip(xs, ys))
    total = sum((y - mean_y) ** 2 for y in ys)
    if total <= 0.0:
        raise PowersMeasureError("تردّداتٌ متساويةٌ لا تُخرِج جودةَ ربط.")
    return slope, 1.0 - residual / total


def _predictor(law: Law, rank: int) -> float:
    if law is Law.ZIPF:
        return math.log(rank)
    logarithm = math.log(rank)
    if logarithm <= 0.0:
        raise PowersMeasureError("القانونُ المصحَّح لا يُقام على رتبةٍ لوغاريتمُها صفر.")
    return math.log(rank * logarithm * logarithm)


@dataclass(frozen=True, slots=True)
class RegimeFit:
    """ملاءمةُ نظامٍ واحد: مداه بالرتب، وقانونُه، وميلُه، وجودةُ ربطه."""

    rule: TokenRule
    law: Law
    first_rank: int
    last_rank: int
    slope: float
    r_squared: float

    def __post_init__(self) -> None:
        if self.first_rank < 1 or self.last_rank <= self.first_rank:
            raise PowersMeasureError("مدًى بالرتب لا يتّسع لنقطتين لا يُلاءَم.")
        if not 0.0 <= self.r_squared <= 1.0:
            raise PowersMeasureError("جودةُ ربطٍ خارج [0، 1] لا تُقرأ.")

    @property
    def is_falling(self) -> bool:
        return self.slope < 0.0


@lru_cache(maxsize=len(TokenRule) * len(Law) * 2)
def _fit(rule: TokenRule, law: Law, first_rank: int, last_rank: int) -> RegimeFit:
    frequencies = _frequencies(rule)
    if last_rank > len(frequencies):
        last_rank = len(frequencies)
    ranks = tuple(range(first_rank, last_rank + 1))
    xs = tuple(_predictor(law, rank) for rank in ranks)
    ys = tuple(math.log(frequencies[rank - 1]) for rank in ranks)
    slope, r_squared = _least_squares(xs, ys)
    return RegimeFit(
        rule=rule,
        law=law,
        first_rank=first_rank,
        last_rank=ranks[-1],
        slope=slope,
        r_squared=r_squared,
    )


def head_fit(rule: TokenRule = TokenRule.AS_SEALED, law: Law = Law.ZIPF) -> RegimeFit:
    """ملاءمةُ الرأس على النافذة المُعلَنة ‎10–99‎."""

    return _fit(rule, law, THE_HEAD_WINDOW[0], THE_HEAD_WINDOW[1])


def tail_fit(
    rule: TokenRule = TokenRule.AS_SEALED, law: Law = Law.POWERS_CORRECTED
) -> RegimeFit:
    """ملاءمةُ الذيل من الرتبة المُعلَنة ‎100‎ إلى آخر رتبةٍ في المقام."""

    return _fit(rule, law, THE_TAIL_FLOOR, len(_frequencies(rule)))


def the_tail_prefers_the_corrected_law(
    rule: TokenRule = TokenRule.AS_SEALED,
) -> bool:
    """أيغلب القانونُ المصحَّحُ زِبفَ في الذيل، كما تنبّأت الورقة؟"""

    return (
        tail_fit(rule, Law.POWERS_CORRECTED).r_squared
        > tail_fit(rule, Law.ZIPF).r_squared
    )


def the_head_prefers_plain_zipf(rule: TokenRule = TokenRule.AS_SEALED) -> bool:
    """أيغلب زِبفُ الخامُ المصحَّحَ في الرأس؟ الوجهُ الآخرُ من النظامين."""

    return (
        head_fit(rule, Law.ZIPF).r_squared
        > head_fit(rule, Law.POWERS_CORRECTED).r_squared
    )


