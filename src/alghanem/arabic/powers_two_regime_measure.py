"""ورقةُ Powers مقروءةً شاهدًا لا حكمًا: نظامان مقيسان، وقانونُ طولٍ يُكسَر عند رأسه.

رُفعت ورقةٌ (Powers, 1998) وقيل إنّها ترفع تحليلَنا «من زِبف خامٍ إلى زِبف
مصحَّح»، وأُعلن أنّ ثلاثةً منها قِيست فصدقت: رأسٌ يطيع زِبف بـ**R² = 0.9805**،
وذيلٌ يطيع `1/(r·log²r)` بـ**R² = 0.9508** متفوّقًا على زِبف **0.9476**،
وقانونُ طولٍ يصعد أحاديًّا **3.20 → 3.84 → 5.05 → 5.62 → 5.99**. وهذه الوحدةُ
تُجري الثلاثةَ على بايتاتنا المختومة وحدَها، فيفترق ههنا أربعةٌ كانت تُقرأ
«انتفاعًا بالورقة» واحدًا::

    APredictedOrdering  != AQuotedMagnitude
    ATokenOfTheLanguage != ATokenOfThePublisher
    AMonotoneLadder     != ALadderWithATopRungBreak
    ADeclaredPendingLaw != AMeasuredOne

**أوّلًا: النظامان موجودان، وترتيبُ الورقة يصمد، ومقاديرُها تسقط.** الرأسُ
(الرتب 10–99) يطيع زِبف بـ**R² = 0.9924**، والذيلُ (الرتبة 100 فصاعدًا) يطيع
`1/(r·log²r)` بـ**R² = 0.9417** متفوّقًا على زِبف في الذيل نفسِه
(**0.9376**). فالذي تنبّأت به الورقةُ — أن يغلب القانونُ المصحَّحُ زِبفَ في
الذيل — **يصمد على بايتاتنا**. وأمّا الأرقامُ المنقولةُ فتنقسم بحدّ تسامحٍ
مُعلَنٍ قبل المقابلة (**0.01**): رقما الذيل يوافقان (فارقُهما 0.0091 و0.0100)،
ورقمُ الرأس يخالف (فارقُه **0.0119** والمقيسُ عندنا **أعلى** من المنقول لا
أدنى). فيُسجَّل **الترتيبُ صامدًا والمقدارُ منقسمًا**، ولا يُقرأ أحدُهما بالآخر
(`A_PREDICTED_ORDERING_THAT_HOLDS_IS_NOT_A_QUOTED_MAGNITUDE_THAT_MATCHES`).

**وثانيًا: ورتبتُنا الأولى ليست لفظًا عربيًّا أصلًا.** أكثرُ التوكنات ورودًا
في بايتاتنا `<sel>` — **4,287 وقوعًا** — وهي علامةُ ناشرٍ لا كلمة. فرأسُ
منحنانا كان يتصدّره مِرماز، وهذا يُسمّى ولا يُطوى: تُقاس الأرقامُ على
مفتاحَي توكنٍ مُعلَنَين، أحدُهما يُسقط علاماتِ الناشر المشتقّةَ بنمطها لا
المسرودةَ بأسمائها. وإسقاطُها يُخرِج **78,245** توكنًا — وهو بعينه العددُ
المنقولُ في نثر `quran_corpus_word_total` عن أسرة «simple». وهذا **توافقُ رقمٍ
لا تصديقُ تنفيذ**: بايتاتُنا المُودَعةُ بلا فواصل حقولٍ، فقاعدةُ حقل الآية في
تلك الوحدة تُخرِج عليها **صفرًا** ولا تُنتِج 78,245 بنفسها؛ فيُسمّى التوافقُ
توافقًا ويُفحَص صمتُ القاعدة بدالّةٍ لا بعبارة
(`THE_FIRST_RANK_IS_A_PUBLISHER_MARK_NOT_A_WORD`).

**وثالثًا: قانونُ الطول يصعد أربعًا ويُكسَر عند الخامسة.** متوسّطُ طول اللفظ
بالحروف المرسومة عبر نطاقات التردّد المُعلَنة:
**3.500 · 3.345 · 4.456 · 5.080 · 5.408**. فالطرفان يقولان ما قالته الورقةُ
بلا لبس — الأندرُ أطولُ من الأكثر بنحو حرفين — **لكنّ الصعودَ ليس أحاديًّا**:
يُكسَر بين النطاق الأعلى والذي يليه. وسببُه مقيسٌ لا مُخمَّن: النطاقُ الأعلى
فيه **نوعان اثنان** فقط على المفتاح المختوم و**واحدٌ** بعد إسقاط علامة
الناشر، فمتوسّطُ نطاقٍ من واحدٍ ليس متوسّطًا يُقارَن. فالدعوى تُقبَل في
طرفيها وتُردّ في أحاديّتها
(`A_LADDER_THAT_BREAKS_AT_ITS_TOP_RUNG_IS_NOT_A_MONOTONE_LAW`).

**ورابعًا: وبندان من الورقة مُعلَنان لا مقيسان، وسجنُهما مُسمًّى.** قانونُ
تعدُّد المعاني `m ∝ √f` يحتاج جردَ معانٍ، **ولا معجمَ معانٍ مُودَعًا في هذه
الشجرة**؛ وقياسُ وفورات الترميز الرتبيّ `L(r)` يحتاج ترميزًا مُودَعًا يُقابَل
به. فيُودَعان **بندين ينتظران مادّتَهما**، ولا يُقرأ واحدٌ منهما موافقةً ولا
مناقضة (`A_DECLARED_PENDING_LAW_IS_NEITHER_CONFIRMED_NOR_REFUTED`).

**وخامسًا: ولا يُقرأ من هذه الوحدة مدحٌ لورقةٍ ولا ذمٌّ لها.** ما صمد منها
سُجِّل بمقداره المقيس عندنا لا بمقداره المنشور عندها، وما سقط سُجِّل باسمه؛
ولا تُخرِج هذه الوحدةُ لفظَ «تصحيح» حكمًا على أدواتنا: القانونُ المصحَّحُ
يغلب زِبفَ **في الذيل وحدَه**، ويغلبه زِبفُ في الرأس.

**خمولٌ سلطويّ**: لا ولادةَ هنا ولا حكمَ ولادةٍ ولا تجميدَ `E0`، ولا استيرادَ
من `kernel/` ولا من `program/`، ولا تزحزح هذه الوحدةُ بوّابةَ ماركوف عمّا
كانت عليه.
"""

