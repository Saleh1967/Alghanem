@lru_cache(maxsize=1)
def _sealed_tokens() -> tuple[str, ...]:
    return tuple(read_quran_corpus_bytes().decode("utf-8").split())


@lru_cache(maxsize=len(TokenRule))
def _counts(rule: TokenRule) -> tuple[tuple[str, int], ...]:
    tokens = _sealed_tokens()
    if rule is TokenRule.PUBLISHER_MARKUP_DROPPED:
        tokens = tuple(
            token for token in tokens if not THE_MARKUP_PATTERN.fullmatch(token)
        )
    counts = Counter(tokens)
    return tuple(sorted(counts.items(), key=lambda item: (-item[1], item[0])))


def _frequencies(rule: TokenRule) -> tuple[int, ...]:
    return tuple(count for _, count in _counts(rule))


def _drawn_length(word: str) -> int:
    """طولُ اللفظ بالحروف المرسومة؛ العلاماتُ لا تُعَدّ حرفًا."""

    return sum(1 for character in word if character not in THE_ARABIC_COMBINING_MARKS)


@dataclass(frozen=True, slots=True)
class MarkupCensus:
    """إحصاءُ علامات الناشر: صورُها، ووقوعاتُها، ورتبةُ أكثرها."""

    forms: tuple[str, ...]
    occurrences: int
    top_rank: int

    def __post_init__(self) -> None:
        if not self.forms or self.occurrences < 1 or self.top_rank < 1:
            raise PowersMeasureError("إحصاءُ مِرمازٍ خالٍ لا يُودَع.")


def the_publisher_markup_census() -> MarkupCensus:
    """ما في بايتاتنا من علامات الناشر، مشتقًّا بالنمط لا مسرودًا بالاسم."""

    counts = _counts(TokenRule.AS_SEALED)
    marks = [
        (index + 1, token, count)
        for index, (token, count) in enumerate(counts)
        if THE_MARKUP_PATTERN.fullmatch(token)
    ]
    if not marks:
        raise PowersMeasureError("لا علامةَ ناشرٍ في هذه البايتات؛ والنمطُ مُعلَن.")
    return MarkupCensus(
        forms=tuple(token for _, token, _ in marks),
        occurrences=sum(count for _, _, count in marks),
        top_rank=min(rank for rank, _, _ in marks),
    )


@dataclass(frozen=True, slots=True)
class TokenCensus:
    """مقامُ القياس على قاعدة توكنٍ مُعلَنة."""

    rule: TokenRule
    tokens: int
    types: int

    def __post_init__(self) -> None:
        if self.types < 1 or self.tokens < self.types:
            raise PowersMeasureError("مقامٌ لا يستقيم ترتيبُ أعداده لا يُودَع.")


def token_census(rule: TokenRule = TokenRule.AS_SEALED) -> TokenCensus:
    """كلماتُ البايتات ومفرداتُها على قاعدةٍ مُعلَنة."""

    frequencies = _frequencies(rule)
    return TokenCensus(rule=rule, tokens=sum(frequencies), types=len(frequencies))


