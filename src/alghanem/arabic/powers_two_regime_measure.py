_PLACES: Final[int] = 4


def the_measured_figures_have_drifted() -> bool:
    """أانزاح شيءٌ ممّا جُمِّد في هذا النثر عمّا يقيسه القرصُ الآن؟"""

    census = token_census()
    dropped = token_census(TokenRule.PUBLISHER_MARKUP_DROPPED)
    markup = the_publisher_markup_census()
    if (census.tokens, dropped.tokens, markup.occurrences) != THE_TOKENS_AT_MEASUREMENT:
        return True
    regimes = (
        round(head_fit(TokenRule.AS_SEALED, Law.ZIPF).r_squared, _PLACES),
        round(tail_fit(TokenRule.AS_SEALED, Law.ZIPF).r_squared, _PLACES),
        round(tail_fit(TokenRule.AS_SEALED, Law.POWERS_CORRECTED).r_squared, _PLACES),
        round(
            head_fit(TokenRule.PUBLISHER_MARKUP_DROPPED, Law.ZIPF).r_squared, _PLACES
        ),
    )
    if regimes != THE_REGIMES_AT_MEASUREMENT:
        return True
    lengths = tuple(round(band.mean_length, _PLACES) for band in band_lengths())
    return lengths != THE_LENGTHS_AT_MEASUREMENT


