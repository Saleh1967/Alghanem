"""سجلُّ علاقات المجاز: أحدَ عشرَ نوعًا تُشتَقُّ من بايتاتٍ مختومة لا تُنقَل باليد.

كانت فجوةٌ في هذه الشجرة **مُعلَنةً قبل أن تُسَدّ**: وحدةُ
`lafz_madlul_relation_formal` أخرجت أقسامَ العلاقة المجازيّة (مشابهة، مجاورة،
سببيّة...) من نطاقها بالتصريح، وقالت إنّ إدخالها بلا شواهدَ «ادّعاءُ نطاقٍ غير
مبرهَن»؛ وفي الوقت نفسِه كان `MajazRequiresLicensedRelation` في
`signifier_signified_relation` يطلب **مرجعَ علاقةٍ مُرخَّصة** ولا سجلَّ في
الشجرة يُرجَع إليه، فكان كلُّ نصٍّ غيرِ فارغٍ يمرُّ مرجعًا. وقد أُودعت بايتاتُ
الجزء الثالث بختمها وتفويض مالكها، وفيها حصرُ الأنواع منصوصًا، فسُدَّت الفجوةُ
من المتن لا من الذاكرة.

**والسجلُّ مُشتَقٌّ لا منقول**: لا يُكتَب في هذا الملفّ اسمُ نوعٍ ولا رتبتُه
ولا رقمُ سطره؛ تُفتَح الوديعةُ، ويُقاس ختمُها، ثمّ تُستخرَج الأنواعُ من
حدودِها الكتابيّة. وما نُقل ههنا حرفًا — أسماءُ الأنواع في
`THE_TRANSCRIBED_NAMES` — **منقولٌ ليُصادَم لا ليُصدَّق**، فيسقط إن انزاح عمّا
يولّده القرص.

ويحرس هذا السجلُّ أربعةَ فروقٍ قاسها القرصُ ولم تُفترَض:

**أوّلًا: الحادي عشرَ لا يلبس علامةَ العشرة**
(`THE_ELEVENTH_WEARS_NEITHER_MARKER_OF_THE_TEN`).
فالأنواعُ العشرةُ الأولى مُصدَّرةٌ بلفظ «النوع»، والحادي عشرَ مُصدَّرٌ برتبته
مجرّدةً. فمسطرةُ «النوع» — وهي المسطرةُ البديهيّةُ — تُخرِج **عشرةً**، والعشرةُ
ليست غلطًا في العدّ بل أثرٌ من المسطرة نفسِها. ومن قرأ مخرجَها حصرًا فقد أسقط
نوعًا كاملًا بسبب علامةِ ناشرٍ لا بسبب المتن.

**وثانيًا: التطويلُ شكلٌ لا حرف** (`A_KASHIDA_IS_A_SHAPE_NOT_A_LETTER`).
فرتبةُ الحادي عشرَ مكتوبةٌ في هذه الوديعة بتطويلٍ داخلَها، فلا تطابق نصًّا
مكتوبًا بلا تطويل. والوديعةُ فيها أكثرُ من ألفِ تطويل، فهذا ليس شذوذَ سطرٍ
واحد. فمن قابل باللفظ الخام دون إسقاط التطويل لم يجد الحادي عشرَ ألبتّة —
وسقوطُه عندئذٍ سقوطُ مسطرةٍ لا غيابُ نصّ.

**وثالثًا: الرتبةُ المجرّدةُ ليست علامةَ فصلٍ** (`A_BARE_ORDINAL_IS_NOT_A_SECTION_MARKER`).
فلو عُوِّض عن مسطرة «النوع» بمسطرةِ الرتبِ المجرّدة طلبًا للحادي عشر، لانفتح
البابُ على المتن كلِّه: الرتبُ المجرّدةُ تقع في مواضعَ كثيرةٍ لا علاقةَ لها
بالمجاز، وفيها «حادي عشرَ» آخرُ في بابٍ آخر. فالنطاقُ يُشتَقُّ من **جِوارِ**
الأنواع العشرة لا من صيغةِ الرتبة وحدَها، والحصرُ يُقاس بأن الذي يلي الحادي
عشرَ ليس رتبةً أصلًا.

**ورابعًا: عدُّ الأقسام ليس عدَّ الأنواع** (`COUNTING_SUBDIVISIONS_IS_NOT_COUNTING_TYPES`).
فنوعان من الأحدَ عشرَ يُصرِّحان بأقسامٍ تحتهما، فمجموعُ الأقسام المصرَّح بها
ليس عددَ الأنواع ولا زيادةً عليه، وهما عددان لا يُجمَعان ولا يُبدَّل أحدُهما
بالآخر.

**وخامسًا: المُرخَّصُ عضوٌ في سجلّ لا مشابهةٌ مستشعَرة**
(`A_LICENSED_RELATION_IS_A_REGISTER_MEMBER_NOT_A_FELT_RESEMBLANCE`). فهذه
الوحدةُ تُجيب سؤالًا واحدًا: أهذا المرجعُ اسمُ نوعٍ في السجلِّ المُشتَقّ، أم
لا؟ ولا تحكم بأنّ وقوعًا بعينه مجازٌ، ولا تُصنِّف نصًّا، ولا تُرخِّص علاقةً لم
تُستخرَج من الوديعة.

**خمولٌ سلطويّ**: لا استيرادَ من `kernel/`، ولا ولادةَ ولا حكمَ ولادة، ولا
تغييرَ في السباعيّة ولا في شرط `MajazRequiresLicensedRelation` نفسِه: هذا
سجلٌّ يُرجَع إليه، وليس بوّابةً تُلزِم أحدًا بالرجوع. تسجيلٌ لا سلطة.
"""

