class MarkerGenus(Enum):
    """بأيّ علامةٍ كتابيّةٍ صُدِّر النوع؟ وهي مُشتقّةٌ من السطر لا مكتوبةٌ فيه."""

    PREFIXED_BY_NAW = "مُصدَّرٌ بلفظ «النوع»"
    BARE_ORDINAL = "رتبةٌ مجرّدةٌ بلا «النوع»"


@dataclass(frozen=True)
class MajazRelationEntry:
    """نوعٌ واحدٌ كما استُخرج من الوديعة؛ لا يُبنى إلّا من سطرٍ مقروء."""

    ordinal: str
    name: str
    line_number: int
    marker: MarkerGenus
    declared_subdivisions: int | None

    def __post_init__(self) -> None:
        if self.ordinal not in THE_ORDINALS:
            raise MajazRelationRegisterError(
                f"رتبةٌ خارجَ الأحدَ عشرَ: «{self.ordinal}»."
            )
        if not self.name.strip():
            raise MajazRelationRegisterError("نوعٌ بلا اسمٍ لا يُسجَّل.")
        if self.line_number <= 0:
            raise MajazRelationRegisterError(
                f"رقمُ سطرٍ غيرُ موجبٍ لنوع «{self.name}»."
            )
        if self.declared_subdivisions is not None and (
            self.declared_subdivisions <= 1
        ):
            raise MajazRelationRegisterError(
                f"أقسامٌ مصرَّحٌ بها دونَ اثنين في «{self.name}»."
            )

    @property
    def rank(self) -> int:
        """رتبةُ النوع عددًا، مشتقّةٌ من موضعه في الرتب لا مكتوبةٌ في حقل."""

        return THE_ORDINALS.index(self.ordinal) + 1

    @property
    def is_subdivided(self) -> bool:
        return self.declared_subdivisions is not None


def _repository_root() -> Path:
    return Path(__file__).resolve().parents[3]


def matn_deposit() -> SealedDeposit:
    """وديعةُ المتن كما سُجِّلت في الإيداع المأذون؛ ولا يُكرَّر ختمُها هنا."""

    for deposit in THE_DEPOSITS:
        if deposit.path == THE_MATN_PATH:
            return deposit
    raise MajazRelationRegisterError(
        f"لا وديعةَ باسم {THE_MATN_PATH} في الإيداع المأذون."
    )


def _without_kashida(line: str) -> str:
    return line.replace(THE_KASHIDA, "")


def _matn_lines() -> tuple[str, ...]:
    """لا يُقرأ حرفٌ من وديعةٍ لم يوافق ختمُها ولم يُسمِّها التفويض."""

    deposit = matn_deposit()
    standing = standing_of(deposit)
    if standing is not DepositStanding.SIGNED_AND_SEALED:
        raise MajazRelationRegisterError(
            f"وديعةُ المتن قائمتُها «{standing.value}»، فلا يُشتَقُّ منها سجلّ."
        )
    payload = (_repository_root() / deposit.path).read_text(encoding="utf-8")
    return tuple(payload.split("\n"))


def _declared_subdivisions(line: str) -> int | None:
    found = _SUBDIVISION.search(line)
    if found is None:
        return None
    return _SPELLED_NUMBERS[found.group(1)]


def _name_of(line: str) -> str:
    _, colon, rest = line.partition(":")
    if not colon:
        raise MajazRelationRegisterError("سطرُ نوعٍ بلا نقطتَين لا يُقرأ.")
    return rest.split("-")[0].strip()


def _the_prefixed_run(lines: tuple[str, ...]) -> tuple[int, ...]:
    """الشوطُ الوحيدُ المتّصلُ الصاعدُ من «النوع الأول» إلى «النوع العاشر»."""

    runs: list[list[int]] = []
    for index, raw in enumerate(lines):
        found = _PREFIXED.match(_without_kashida(raw))
        if found is None:
            continue
        expected_rank = 0 if not runs or runs[-1][-1] != index - 1 else len(
            runs[-1]
        )
        if found.group(1) != THE_ORDINALS[expected_rank]:
            continue
        if expected_rank == 0:
            runs.append([index])
        else:
            runs[-1].append(index)
    complete = [one for one in runs if len(one) == 10]
    if len(complete) != 1:
        raise MajazRelationRegisterError(
            "لم يوجد في الوديعة شوطٌ واحدٌ متّصلٌ من عشرةِ أنواعٍ مُصدَّرةٍ "
            f"بلفظ «{_THE_NAW_WORD}»، بل {len(complete)}؛ "
            + A_BARE_ORDINAL_IS_NOT_A_SECTION_MARKER
        )
    return tuple(complete[0])


def derive_register() -> tuple[MajazRelationEntry, ...]:
    """السجلُّ كلُّه مُشتَقٌّ من البايتات الآن: أحدَ عشرَ نوعًا أو رفضٌ مُسمًّى."""

    lines = _matn_lines()
    run = _the_prefixed_run(lines)
    entries: list[MajazRelationEntry] = []
    for rank, index in enumerate(run):
        bare = _without_kashida(lines[index])
        entries.append(
            MajazRelationEntry(
                ordinal=THE_ORDINALS[rank],
                name=_name_of(bare),
                line_number=index + 1,
                marker=MarkerGenus.PREFIXED_BY_NAW,
                declared_subdivisions=_declared_subdivisions(bare),
            )
        )
    eleventh_index = run[-1] + 1
    if eleventh_index >= len(lines):
        raise MajazRelationRegisterError(
            "انقطعت الوديعةُ دونَ الحادي عشرَ؛ "
            + THE_ELEVENTH_WEARS_NEITHER_MARKER_OF_THE_TEN
        )
    eleventh = _without_kashida(lines[eleventh_index])
    found = _BARE.match(eleventh)
    if found is None or found.group(1) != THE_ORDINALS[10]:
        raise MajazRelationRegisterError(
            "لم يلِ الأنواعَ العشرةَ رتبةُ الحادي عشرَ مجرّدةً؛ "
            + THE_ELEVENTH_WEARS_NEITHER_MARKER_OF_THE_TEN
        )
    entries.append(
        MajazRelationEntry(
            ordinal=THE_ORDINALS[10],
            name=_name_of(eleventh),
            line_number=eleventh_index + 1,
            marker=MarkerGenus.BARE_ORDINAL,
            declared_subdivisions=_declared_subdivisions(eleventh),
        )
    )
    closing = eleventh_index + 1
    if closing < len(lines) and _ANY_ORDINAL_HEAD.match(
        _without_kashida(lines[closing])
    ):
        raise MajazRelationRegisterError(
            "تلا الحادي عشرَ رتبةٌ أخرى، فالحصرُ غيرُ مقيسٍ على هذه الوديعة."
        )
    return tuple(entries)


def entries_wearing(marker: MarkerGenus) -> tuple[MajazRelationEntry, ...]:
    """من لبس علامةً بعينها؛ والقسمةُ مقيسةٌ لا مفترَضة."""

    if not isinstance(marker, MarkerGenus):
        raise MajazRelationRegisterError("العلامةُ عضوٌ في `MarkerGenus`.")
    return tuple(one for one in derive_register() if one.marker is marker)


def naw_ruler_yield() -> int:
    """ما تُخرِجه مسطرةُ «النوع» وحدَها على الوديعة كلِّها — لا ما في المتن."""

    return sum(
        1
        for line in _matn_lines()
        if _PREFIXED.match(_without_kashida(line)) is not None
    )


def kashida_blind_eleventh_lines() -> tuple[int, ...]:
    """أين يجد «الحادي عشرَ» قارئٌ لا يُسقِط التطويل؟ تُعرَض أسطرُه لا عددُه.

    فالعددُ وحدَه يخدع: قد يكون غيرَ صفرٍ ثمّ لا يكون فيه سطرُ المجاز ألبتّة،
    وهو ما تقوله هذه الوديعة. فتُعرَض المواضعُ لتُقابَل بموضع النوع الحادي عشر.
    """

    target = THE_ORDINALS[10]
    return tuple(
        index + 1
        for index, line in enumerate(_matn_lines())
        if (found := _BARE.match(line)) is not None and found.group(1) == target
    )


def bare_ordinal_hits_in_the_whole_matn() -> int:
    """اتّساعُ مسطرةِ الرتبِ المجرّدة لو جُعلت حدًّا للنطاق."""

    return sum(
        1
        for line in _matn_lines()
        if _BARE.match(_without_kashida(line)) is not None
    )


def subdividing_entries() -> tuple[MajazRelationEntry, ...]:
    """الأنواعُ التي يُصرِّح المتنُ بأقسامٍ تحتها."""

    return tuple(one for one in derive_register() if one.is_subdivided)


def declared_subdivision_total() -> int:
    """مجموعُ الأقسام المصرَّح بها؛ عددٌ يُعرَض ولا يُجمَع إلى عدد الأنواع."""

    return sum(
        one.declared_subdivisions or 0 for one in subdividing_entries()
    )


def licensed_relation_ref(entry: MajazRelationEntry) -> str:
    """المرجعُ الذي يُعلَّق به المجاز: رتبةٌ واسمٌ من الوديعة، لا وصفٌ حرّ."""

    if not isinstance(entry, MajazRelationEntry):
        raise MajazRelationRegisterError("المرجعُ يُشتَقُّ من عضوٍ في السجلّ.")
    return f"{THE_MATN_PATH}#{entry.ordinal}:{entry.name}"


def is_licensed(reference: str) -> bool:
    """أهذا المرجعُ عضوٌ في السجلِّ المُشتَقّ؟ سؤالٌ واحدٌ لا حكمَ معه."""

    if not isinstance(reference, str):
        raise MajazRelationRegisterError(
            "المرجعُ نصٌّ يُقابَل؛ "
            + A_LICENSED_RELATION_IS_A_REGISTER_MEMBER_NOT_A_FELT_RESEMBLANCE
        )
    candidate = _without_kashida(reference).strip()
    if not candidate:
        return False
    return candidate in {
        licensed_relation_ref(one) for one in derive_register()
    }
