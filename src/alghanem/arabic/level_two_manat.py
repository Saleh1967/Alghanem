def tadmin_taqyid_certificate_is_constructible() -> bool:
    """`False` بحاله: هذه الوحدةُ لا تُغيّر موقفَ المرحلة المُجمَّدة بحرف."""

    registration = COMPOUND_LAYER_PREREGISTRATION.registration_for(
        CompoundStage.TADMIN_TAQYID
    )
    if registration.stage is not CompoundStage.TADMIN_TAQYID:  # pragma: no cover
        raise RuntimeError(LEVEL_TWO_LINK_IS_NOT_THE_TADMIN_TAQYID_CERTIFICATE_NOTE)
    return COMPOUND_LAYER_PREREGISTRATION.certificate_is_constructible


def _texts(payload: Any) -> tuple[str, ...]:
    """كلُّ نصوص البطاقة، مفاتيحَ وقيَمًا، مسرودةً بلا تأويل."""

    if isinstance(payload, str):
        return (payload,)
    if isinstance(payload, Mapping):
        collected: list[str] = []
        for key, value in payload.items():
            collected.extend(_texts(key))
            collected.extend(_texts(value))
        return tuple(collected)
    if isinstance(payload, list | tuple):
        gathered: list[str] = []
        for item in payload:
            gathered.extend(_texts(item))
        return tuple(gathered)
    return ()


def _require_text(value: Any, label: str) -> str:
    if not isinstance(value, str) or not value.strip():
        raise LevelTwoManatError(f"{label} نصٌّ غير فارغ")
    return value


def _refuse_written_outcome(card: Mapping[str, Any], label: str) -> None:
    """يرفض بطاقةً تكتب درجةَ نقلٍ أو حالَ إغلاقٍ بدل أن تُشتَقّ من حاملها."""

    for text in _texts(card):
        key = comparison_key(text)
        if any(written == key for written in _WRITTEN_STANDING_KEYS):
            raise LevelTwoManatError(
                f"{label} تكتب درجةَ النقل نصًّا، والدرجةُ تُشتَقّ من طريق "
                f"النقل لا تُقرأ مكتوبة: {DERIVED_NOT_WRITTEN_NOTE}"
            )
        if any(written == key for written in _WRITTEN_STATUS_KEYS):
            raise LevelTwoManatError(
                f"{label} تكتب حالَ إغلاقٍ نصًّا، والحالُ تُقرأ من البوّابة "
                f"وحدها: {LEVEL_ONE_CLOSURE_IS_READ_NOT_REPEATED_NOTE}"
            )


def read_declared_composition_relation(
    card: Mapping[str, Any],
) -> tuple[CompositionGenus, str]:
    """يقرأ نوعَ النسبة ومصدرَه المُسمّى من بطاقة التركيب، بلا تأويل.

    وبطاقةٌ لم تُعلِن النسبةَ أصلًا لا يُقرأ سكوتُها جنسًا: تُنتج
    `غير_محسوم` بمصدرٍ فارغ. وجنسٌ مُعلَنٌ بلا مصدرٍ مُسمًّى يُرفَض، فالجنسُ
    مقروءٌ في مصدر التركيب لا مكتوبٌ في البطاقة ابتداءً.
    """

    if not isinstance(card, Mapping):
        raise LevelTwoManatError("بطاقةُ التركيب كائنٌ يُقرأ بمفاتيحه")
    raw = card.get(CARD_COMPOSITION_RELATION_KEY)
    if raw is None:
        return (CompositionGenus.غير_محسوم, "")
    if not isinstance(raw, Mapping):
        raise LevelTwoManatError(f"{CARD_COMPOSITION_RELATION_KEY} كائنٌ لا نصّ")
    allowed = {comparison_key(name) for name in ALLOWED_COMPOSITION_RELATION_KEYS}
    if {comparison_key(str(key)) for key in raw} - allowed:
        raise LevelTwoManatError(
            f"{CARD_COMPOSITION_RELATION_KEY} لا يقبل إلا: "
            + "، ".join(ALLOWED_COMPOSITION_RELATION_KEYS)
        )
    declared = _require_text(raw.get("نوع_النسبة"), "نسبة_التركيب.نوع_النسبة")
    genus = _GENUS_BY_KEY.get(comparison_key(declared))
    if genus is None:
        raise LevelTwoManatError(
            "نسبة_التركيب.نوع_النسبة يجب أن يكون أحد: "
            + "، ".join(member.value for member in CompositionGenus)
        )
    if genus is CompositionGenus.غير_محسوم:
        return (genus, "")
    named_source = _require_text(raw.get("المصدر_المُسمّى"), "نسبة_التركيب.المصدر_المُسمّى")
    return (genus, named_source)


def derive_composition_genus(card: Mapping[str, Any]) -> CompositionGenus:
    """جنسُ التركيب مُشتقًّا من نوع النسبة المُعلَن في مصدر التركيب وحده."""

    return read_declared_composition_relation(card)[0]


def derive_qayd_signification(
    descriptor: LexicalTransmissionDescriptor,
) -> QaydSignification:
    """يشتقّ دلالةَ القيد من نصوص إسنادات طريقه، لا من تصنيفٍ مُمرَّر.

    ولا يُقرأ غيابُ التصريح طرديّةً ولا تخصيصًا: العضوُ الثالث موضعُ من لم
    يُنقَل عنه واحدٌ منهما (`SPECIFICATION_IS_A_KIND_NOT_A_DEGREE_NOTE`).
    """

    if not isinstance(descriptor, LexicalTransmissionDescriptor):
        raise LevelTwoManatError("دلالةُ القيد تُشتَقّ من واصف طريق نقله")
    excerpts = tuple(
        comparison_key(attribution.verbatim_excerpt)
        for attribution in descriptor.attributions
    )
    specifying = any(
        marker in excerpt for excerpt in excerpts for marker in _SPECIFYING_KEYS
    )
    tardi = any(marker in excerpt for excerpt in excerpts for marker in _TARDI_KEYS)
    if specifying and tardi:
        raise LevelTwoManatError(
            "طريقٌ واحدٌ يَنقُل التخصيصَ والطرديّة معًا في قيدٍ واحد: "
            "التعارضُ يُرفَض ولا يُحمَل على أحد الطرفين"
        )
    if specifying:
        return QaydSignification.قيد_مخصص
    if tardi:
        return QaydSignification.وصف_طردي
    return QaydSignification.دلالة_القيد_غير_محسومة


@dataclass(frozen=True, slots=True)
class ClosedLevelOneCard:
    """بطاقةُ مستوًى أوّلٍ مُغلَقة، تُقرأ من حال إغلاقها لا من نصّها الخام.

    والإغلاقُ هنا واقعةٌ لا دعوى: `EvidenceApplicabilityAssessment` لا تُنشَأ
    إلا من بوّابة `G0.EA.1` نفسها، ونطاقُها يُقابَل بنطاق البطاقة فلا يُستعار
    إغلاقُ بطاقةٍ لأخرى.
    """

    role: CompositionRole
    card: Mapping[str, Any]
    assessment: EvidenceApplicabilityAssessment | None

    def __post_init__(self) -> None:
        if not isinstance(self.role, CompositionRole):
            raise LevelTwoManatError("موضعُ البطاقة من مفردته المغلقة")
        if not isinstance(self.card, Mapping):
            raise LevelTwoManatError("بطاقةُ المستوى الأول كائنٌ يُقرأ بمفاتيحه")
        if self.assessment is None:
            raise LevelTwoManatError(
                "بطاقةٌ لم تُغلَق لا تدخل المستوى الثاني: "
                + LEVEL_ONE_CLOSURE_IS_READ_NOT_REPEATED_NOTE
            )
        if type(self.assessment) is not EvidenceApplicabilityAssessment:
            raise LevelTwoManatError(
                "حالُ الإغلاق من بوّابة G0.EA.1 وحدها: "
                + LEVEL_ONE_CLOSURE_IS_READ_NOT_REPEATED_NOTE
            )
        if self.assessment.scope != manat_claim_scope(self.card):
            raise LevelTwoManatError(
                "حالُ الإغلاق صادرةٌ في نطاقٍ غير نطاق هذه البطاقة، "
                "واستعارتُها تنقل إغلاقَ موضعٍ إلى موضعٍ آخر"
            )
        _refuse_written_outcome(self.card, "بطاقةُ المستوى الأول")

    @property
    def status(self) -> ApplicabilityAssessmentStatus:
        """حالُ الإغلاق كما أصدرتها البوّابة، لا تُلطَّف ولا تُشدَّد."""

        assessment = self.assessment
        if assessment is None:  # pragma: no cover - refused at construction
            raise LevelTwoManatError(LEVEL_ONE_CLOSURE_IS_READ_NOT_REPEATED_NOTE)
        return assessment.status

    @property
    def scope_reference(self) -> str:
        """موضعُ البطاقة كما اشتُقّ من نطاق دعواها."""

        return manat_claim_scope(self.card).reference


@dataclass(frozen=True, slots=True)
class LevelTwoCompositionInput:
    """مدخلُ المستوى الثاني: بطاقتان مُغلَقتان وبطاقةُ تركيبٍ تُقرأ منها النسبة."""

    described: ClosedLevelOneCard
    descriptor: ClosedLevelOneCard
    composition_card: Mapping[str, Any]
    declared_genus: CompositionGenus

    def __post_init__(self) -> None:
        for part, expected, label in (
            (self.described, CompositionRole.موصوف, "الموصوف"),
            (self.descriptor, CompositionRole.صفة, "الصفة"),
        ):
            if not isinstance(part, ClosedLevelOneCard):
                raise LevelTwoManatError(f"{label} بطاقةُ مستوًى أوّلٍ مُغلَقة")
            if part.role is not expected:
                raise LevelTwoManatError(
                    f"{label} يشغل موضعَ {expected.value} لا موضعًا آخر"
                )
        if self.described.scope_reference == self.descriptor.scope_reference:
            raise LevelTwoManatError(
                "الموصوفُ والصفةُ موضعان متمايزان؛ وبطاقةٌ واحدةٌ في الموضعين "
                "تصنع تركيبًا من طرفٍ واحد"
            )
        if not isinstance(self.composition_card, Mapping):
            raise LevelTwoManatError("بطاقةُ التركيب كائنٌ يُقرأ بمفاتيحه")
        _refuse_written_outcome(self.composition_card, "بطاقةُ التركيب")
        if not isinstance(self.declared_genus, CompositionGenus):
            raise LevelTwoManatError("جنسُ التركيب من مفردته المغلقة")
        if self.declared_genus is not self.genus:
            raise LevelTwoManatError(
                "جنسُ التركيب المكتوبُ يخالف المُشتَقّ من مصدره: " + DERIVED_NOT_WRITTEN_NOTE
            )

    @property
    def genus(self) -> CompositionGenus:
        """جنسُ التركيب مُشتقًّا من بطاقة التركيب وحدها."""

        return derive_composition_genus(self.composition_card)

    @property
    def named_relation_source(self) -> str:
        """مصدرُ النسبة المُسمّى، وهو فارغٌ حين لا جنسَ محسومًا."""

        return read_declared_composition_relation(self.composition_card)[1]

    @property
    def citation_structure(self) -> LexicalCitationStructure:
        """بنيةُ استشهاد طريق نقل القيد بعينه، لا طريقِ أحد طرفيه."""

        return card_lexical_citation_structure(self.composition_card)

    @property
    def unconstructibility_genus(self) -> UnconstructibilityGenus:
        """جنسُ امتناع الدرجة على هذا الطريق، مُشتقًّا من بنيته."""

        transmission = read_lexical_transmission(self.composition_card)
        if transmission is None:
            return UnconstructibilityGenus.GENUS_NOT_SETTLED
        return lexical_unconstructibility_genus(transmission)

    @property
    def transmission_standing(self) -> TransmissionStanding | None:
        """درجةُ نقل القيد المُشتَقّة، أو لا شيءَ حين لا طريقَ له."""

        return card_transmission_standing(self.composition_card)

    @property
    def qayd_signification(self) -> QaydSignification:
        """دلالةُ القيد مُشتقّةً من نصوص إسناداته، أو غيرَ محسومةٍ بلا طريق."""

        transmission = read_lexical_transmission(self.composition_card)
        if transmission is None:
            return QaydSignification.دلالة_القيد_غير_محسومة
        return derive_qayd_signification(transmission)


@dataclass(frozen=True, slots=True)
class TaqyeedLinkAttempt:
    """محاولةُ الرابط الموازي على مدخلٍ واحد: أقام، أم وقف ولأيّ جنسٍ مُسمًّى."""

    label: str
    module_relative_path: str
    stood_up: bool
    missing_declaration: str
    stop_genus: LevelTwoStopGenus
    qayd_signification: QaydSignification
    standing: TransmissionStanding | None

    def __post_init__(self) -> None:
        if not isinstance(self.stop_genus, LevelTwoStopGenus):
            raise LevelTwoManatError("جنسُ الموقف من مفردته المغلقة")
        if not isinstance(self.qayd_signification, QaydSignification):
            raise LevelTwoManatError("دلالةُ القيد من مفردتها المغلقة")
        standing_declared = self.stop_genus is LevelTwoStopGenus.الرابط_قائم
        if standing_declared != self.stood_up:
            raise LevelTwoManatError(
                "قيامُ الرابط وجنسُ موقفه وجهان لحالٍ واحدة، فلا يفترقان"
            )
        if self.stood_up and self.missing_declaration:
            raise LevelTwoManatError("رابطٌ قائمٌ لا إعلانَ غائبًا يُكتَب له")
        if not self.stood_up and not self.missing_declaration.strip():
            raise LevelTwoManatError("وقوفُ الرابط يُعلَّل بنصّه لا بصمته")


class TaqyeedManatGate:
    """الرابطُ الموازي للرابط الرابع، على القيد لا على الكلمة.

    ومعيارُ قيامه واحدٌ لا ثانيَ له: أن يُشتَقّ من **طريق نقل هذا القيد بعينه**
    عضوٌ من `TransmissionStanding`، وأن يكون المنقولُ فيه تخصيصًا لا وصفًا
    طرديًّا. وما دون ذلك وقوفٌ بجنسٍ مُسمّى، لا سكوت.
    """

    @staticmethod
    def assess(composition: LevelTwoCompositionInput) -> TaqyeedLinkAttempt:
        """يقرأ المدخل ويُصدر محاولةَ الرابط كما اشتُقّت، بلا تلطيفٍ ولا تشديد."""

        if not isinstance(composition, LevelTwoCompositionInput):
            raise LevelTwoManatError("الرابطُ يقوم على مدخل مستوًى ثانٍ مُصاغ")

        genus = composition.genus
        if genus is not CompositionGenus.تقييدية:
            return TaqyeedLinkAttempt(
                label=TAQYEED_LINK_LABEL,
                module_relative_path="level_two_manat.py",
                stood_up=False,
                missing_declaration=(
                    "هذا الرابط موضوعٌ للتركيب التقييديّ، وجنسُ التركيب "
                    f"المُشتَقّ `{genus.value}`؛ فالآلةُ لم تُختبَر على هذا "
                    f"المدخل أصلًا. {INPUT_STOP_IS_NOT_A_MECHANISM_FAILURE_NOTE}"
                ),
                stop_genus=LevelTwoStopGenus.وقوف_مدخل_قبل_اختبار_الآلة,
                qayd_signification=composition.qayd_signification,
                standing=None,
            )

        standing = composition.transmission_standing
        if standing is None:
            return TaqyeedLinkAttempt(
                label=TAQYEED_LINK_LABEL,
                module_relative_path="level_two_manat.py",
                stood_up=False,
                missing_declaration=(
                    "درجةُ النقل من `TransmissionStanding` لا تُشتَقّ من طريق "
                    "نقل هذا القيد: بنيةُ استشهاده "
                    f"`{composition.citation_structure.value}`، وجنسُ امتناعه "
                    f"`{composition.unconstructibility_genus.value}`؛ ولا "
                    "يُستعاض عنه بطريق الموصوف ولا بطريق الصفة منفردَين."
                ),
                stop_genus=LevelTwoStopGenus.وقوف_آلة_لانقطاع_نقل_القيد,
                qayd_signification=composition.qayd_signification,
                standing=None,
            )

        signification = composition.qayd_signification
        if signification is not QaydSignification.قيد_مخصص:
            return TaqyeedLinkAttempt(
                label=TAQYEED_LINK_LABEL,
                module_relative_path="level_two_manat.py",
                stood_up=False,
                missing_declaration=(
                    "طريقُ نقل القيد قائمٌ ودرجتُه مُشتَقّة، ودلالةُ القيد فيه "
                    f"`{signification.value}` لا `{QaydSignification.قيد_مخصص.value}`؛ "
                    f"{SPECIFICATION_IS_A_KIND_NOT_A_DEGREE_NOTE}"
                ),
                stop_genus=LevelTwoStopGenus.وقوف_آلة_لغياب_تخصيص_منقول,
                qayd_signification=signification,
                standing=standing,
            )

        return TaqyeedLinkAttempt(
            label=TAQYEED_LINK_LABEL,
            module_relative_path="level_two_manat.py",
            stood_up=True,
            missing_declaration="",
            stop_genus=LevelTwoStopGenus.الرابط_قائم,
            qayd_signification=signification,
            standing=standing,
        )


def _bears_marker(name: str, marker: str) -> bool:
    """أيحمل اسمُ الحقل هذه العلامةَ كلمةً قائمةً لا جزءًا من كلمةٍ أخرى؟

    والفحصُ على حدود الكلمات لا بمجرّد الاحتواء، وإلّا رُدَّ `declaration`
    لأن فيه حروف `ratio` — وذلك ردٌّ بلفظٍ عارضٍ لا بحقلٍ محظور.
    """

    return marker in name.split("_")


def _assert_no_fields_matching(markers: tuple[str, ...]) -> None:
    for declaring_type in (
        ClosedLevelOneCard,
        LevelTwoCompositionInput,
        TaqyeedLinkAttempt,
    ):
        for field in fields(declaring_type):
            for marker in markers:
                if _bears_marker(field.name, marker):  # pragma: no cover - guard
                    raise RuntimeError(
                        f"{declaring_type.__name__} يحمل حقلاً محظورًا: {field.name}"
                    )


_assert_no_fields_matching(_FORBIDDEN_FIELD_MARKERS)
