"""مناطُ المستوى الثاني: رابطٌ موازٍ للرابط الرابع، على القيد لا على الكلمة.

**تسجيلٌ مسبقٌ مكتوبٌ قبل أيّ قراءة**، على منهج `probe_preregistration.py` و
`compound_layer_preregistration.py`: المفرداتُ المغلقة وأعدادُها، ومعيارُ قيام
الرابط، والرفوضاتُ المُسمّاة — كلُّها مُجمَّدةٌ في هذا الرأس وفي ثوابت `_NOTE`
قبل أن تُقرأ بطاقةٌ واحدة.

**لماذا تركيبٌ تقييديّ من مفردتين غيرِ مُجمَلتين؟** بطاقاتُ المستوى الأول
القائمة (قُروء، أنّى، مَلِك، عسعس) مُجمَلةٌ لغويًّا بذاتها، فأيُّ وقوفٍ في مستوًى
ثانٍ مبنيٍّ عليها لا يُعزى بثقة: أفشلت آلةُ التركيب، أم تسرّب غموضُ المستوى
الأول صعودًا؟ وهذا خلطُ متغيّرين في تجربةٍ واحدة. فمدخلُ هذه الوحدة موصوفٌ
وصفةٌ **لا خلافَ معجميًّا في معناهما**، ليُعزى ما يقع هنا إلى آلة التركيب وحدها.

**وشاهدُ «الغنم السائمة» شاهدٌ جديدٌ في هذه الشجرة لا مثالٌ مُثبَتٌ فيها**:
`mantuq_mafhum_ifada.py` يملك `SignifiedAspect` (`نوع_الحكم` / `قيد_جانبي`)
بتقسيمه المجرَّد، **ولا مثالَ منصوصًا فيه** — لا «غنم» ولا «سائمة» في شيءٍ من
الشجرة قبل هذه الوحدة. فالبناءُ هنا إدخالُ شاهدٍ نصّيٍّ لأوّل مرّة، يُسمّى
بنصّه ولا يُقرأ استمرارًا لما سبق (`NEW_WITNESS_IS_NOT_AN_ESTABLISHED_EXAMPLE_NOTE`).

**وليست هذه شهادةَ مرحلة «التضمين والتقييد»**: تلك مرحلةٌ مُجمَّدة في
`compound_layer_preregistration.py` بمخرجاتٍ مغلقة وموقفِ إسنادٍ `مصدر_غير_مُقدَّم`
و`certificate_is_constructible == False`، وما زالت تنتظر نصَّها المصدريّ. وهذه
الوحدةُ لا تُقدّم ذلك النصّ ولا تُوسّع تلك المفردة ولا تُبدّل موقفَ إسنادها؛
ورفضان مُسمَّيان يحرسان الفارق: `LevelTwoLinkIsNotTheTadminTaqyidCertificate` و
`CompositionGenusIsNotAFrozenStageOutcome`.

**معيارُ قيام الرابط هو معيارُ المستوى الأول حرفًا بحرف**: اشتقاقٌ لا تصريح.
الدرجةُ تُشتَقّ من **طريق نقل هذا القيد بعينه** — لا من طريق الموصوف ولا الصفة
منفردَين — بإعادة استعمال `lexical_transmission` و`transmission_standing` كما
هما، بلا حرفٍ يُعدَّل فيهما. ومتى لم يقم طريقٌ فالوقوفُ مُعلَّلٌ ببنية الاستشهاد
وبجنس امتناعٍ مُسمًّى من `UnconstructibilityGenus`، لا بغياب كلمةٍ مكتوبة.

**وجنسُ الوقوف يُميَّز حتى لا يعود خلطُ المتغيّرين من بابٍ آخر**: وقوفٌ لأن
**المدخل** لم يُحسَم (جنسُ التركيب غيرُ محسوم، أو ليس تقييدًا أصلًا) شيءٌ،
ووقوفٌ لأن **الآلة** لم تجد نقلًا لهذا القيد أو لم تجد فيه تخصيصًا منقولًا شيءٌ
آخر؛ ولكلٍّ عضوٌ في `LevelTwoStopGenus` لا رسالةٌ نثرية.

**والتخصيصُ نوعٌ لا درجة**، بنفس صرامة `ELIMINATION_IS_A_KIND_NOT_A_DEGREE`:
لا يقوم القيدُ مُخصِّصًا إلا بنقلٍ مُسنَدٍ يُصرّح بإخراج ما عداه؛ والاستنباطُ
الحديث لا يقوم مقامه، وغيابُ التصريح يُقرأ `دلالة_القيد_غير_محسومة` لا
`وصف_طرديّ`.

**ولا حكمَ فركتاليًّا هنا (Φ)**: هذه الوحدةُ تُسجّل موضعَها ونتيجتَها وحسب،
ومقارنةُ التوازي مع الرابط الرابع تُترَك لقراءةٍ خارجها؛ فكتابتُها هنا تجعل
الوحدةَ خصمًا وحكمًا (`FRACTAL_VERDICT_IS_NOT_ISSUED_HERE_NOTE`).

**ومفردةُ جنس البيان لم تتغيّر بحرف**: النصُّ الحديثيُّ المُسنَد قولٌ منصوص،
فيقع في `BayanKind.QAWL` بمعناه الضيّق المُصرَّح به في `manat_verification.py`؛
ولمّا كان جنسُ مصدره مختلفًا عن البطاقات القرآنية القائمة، وُضِعت بطاقاتُه في
موضعٍ مستقلّ يُصرّح بذلك (`examples/level_two_manat/`) ولم تُدَسّ بينها
(`HADITH_SOURCE_DOES_NOT_WIDEN_THE_BAYAN_VOCABULARY_NOTE`).

**خمولٌ سلطويّ**: لا ولادةَ هنا ولا حكمَ ولادة ولا تجميد ولا `E0`، ولا تقرأ
هذه المخرجاتِ بوّابةٌ في `kernel/`، ولا تدخل `BirthExperimentSpecification`.
"""

