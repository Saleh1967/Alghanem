"""جدولُ تغطية عقد الدال بالتراث: إحصاؤه يُعاد ولا يُصدَّق، ومعيارُه غائب.

رُفع جدولُ تغطيةٍ يقابل «عقد الدال» بعقدٍ من التراث النحويّ والعَروضيّ
والتجويديّ، وأُعلنت ترويستُه **«28 مغطاة · 4 غياب معلن»** على **«عقد الدال
الثلاث والثلاثين»**. وهذا الجدولُ من جنسٍ يُفحَص ههنا بلا مدوّنةٍ أصلًا: فإنّ
إحصاءَه **متطابقةٌ داخل النقل نفسِه**، تُعاد بالعدّ من صفوفه وحدَها. فيفترق
ههنا أربعةٌ كانت تُقرأ واحدًا::

    ARowCount        != AQuotedTally
    AReadingOfCoverage != AMeasurementOfIt
    ATwoValuedVerdict  != AFourValuedOne
    AQuotedDenominator != ADepositedOne

**أوّلًا: للجدول ثلاثةُ مجاميعَ لا يتّفق منها اثنان.** صفوفُه المنقولةُ
**25**: منها **21** محكومٌ عليها بالتغطية و**4** بالغياب. وترويستُه تقول
**28 + 4 = 32**، وعنوانُه يقول **33** عقدة. فبين الجدول وترويسته **سبعُ
عقدٍ مغطّاةٍ لم تُسَمَّ**، وبين ترويسته وعنوانه **عقدةٌ لا يبلغها حتّى حسابُ
الترويسة نفسِه**. وهذا خرقٌ **لا يحتاج سيبويه ولا مدوّنةً ليُرى**: يُعاد بالعدّ
من البايتات المنقولة (`THE_TALLY_IS_AN_IDENTITY_INSIDE_THE_QUOTATION`).

**وثانيًا: ولا معيارَ تغطيةٍ مُعلَنًا ألبتّة.** ليس في الجدول ما يقول: متى
تُعَدّ العقدةُ التراثيّةُ مغطّيةً للعقدة المقيسة؟ أبالمصطلح؟ أم بالظاهرة؟ أم
بأن يكون في التراث ما يُنتِج العددَ نفسَه؟ فالعمودُ الأيمنُ كلُّه — واحدٌ
وعشرون صفًّا — **قراءةٌ لا قياس**: لا يُعاد اشتقاقُه ولا يُنقَض، لأنّ شرطَ
صدقه غيرُ مكتوب. وهذه الوحدةُ **لا تُصحّح صفًّا منها ولا تُخطّئه**؛ إنّما
تُسجّل أنّ 21 من 25 غيرُ قابلةٍ للفحص كما كُتبت
(`A_COVERAGE_CLAIM_WITHOUT_A_CRITERION_IS_NOT_FALSIFIABLE`).

**وثالثًا: والحكمُ في الجدول رباعيٌّ، وترويستُه تعدّه ثنائيًّا.** ليست
الألفاظُ «مغطاة» و«غياب» فحسب: فيه **«مغطاة بنيويًّا»** — تغطيةٌ مشروطةٌ
بقيدٍ لم يُفسَّر — وفيه **«لا عقدة صريحة»** مقابلَ «لا عقدة» في أخواتها
الثلاث. فصفّان من الخمسة والعشرين يحملان تحفُّظًا **يمحوه** جمعُ الترويسة إذ
يضمّهما إلى إخوتهما بلا أثر. فالتحفُّظُ يُعَدّ ولا يُطوى
(`A_HEDGED_VERDICT_IS_NOT_THE_PLAIN_ONE_IT_IS_TALLIED_WITH`).

**ورابعًا: ومقاماتُ العمود الأيسر ليست مقامًا واحدًا.** صفٌّ واحدٌ **يُعاد
اشتقاقُه من هذه الشجرة**: الذرّاتُ 112، حقلُ `letter_haraka_partition`
(28 حرفًا × 4 حركات). وسبعةُ صفوفٍ أرقامُها **ليست في الشجرة بحال**: 14,870
و71,565 و«الابتداء 2» و«الاقتصاد 43%» وأخواتُها. وستّةَ عشرَ صفًّا **بلا رقمٍ
أصلًا**، فلا مقامَ لها يُسأل عنه. ويبقى صفٌّ واحدٌ **مختلطُ المقام** هو صفُّ
الشبكة: آياتُه 6,236 تُعاد اشتقاقًا من بايتاتنا سطرًا غيرَ خالٍ، وسورُه 114
لا تُشتَقّ من أيّ الإيداعين إذ **لا حقلَ سورةٍ في بايتاتهما**، وكلماتُه 77,801
مُخرَجُ `parse_verses` في مستودعٍ آخر — وقسمةُ البياض على تلك البايتات نفسِها
تُخرِج **82,406** لا 77,801. فلا يُحمَل صفٌّ مختلطُ المقام على مقامٍ واحد،
**ولا يُقرأ رقمٌ واحدٌ منه سندًا لأخويه**.
وبايتاتُنا المختومة تُخرِج 82,532 أو 78,245 بإسقاط مِرماز الناشر — **ولا واحدٌ
منهما 77,801**. فالعمودُ الذي يُسمّى «المقيس» ليس مقيسًا عندنا في أكثره
(`A_FIGURE_MEASURED_ELSEWHERE_DOES_NOT_BECOME_OURS_BY_BEING_TABULATED`).

**وخامسًا: والغياباتُ الأربعةُ نفيٌ كلّيٌّ على تراثٍ لا بايتَ منه ههنا.**
«لا عقدة» في التراث كلِّه دعوى على سيبويه والأجروميّة وأهل العروض والتجويد،
ولا حرفَ من كتبهم مُودَعٌ في هذه الشجرة. فلا تُصدَّق ولا تُكذَّب ههنا؛ وغايةُ
ما يُقال: **هذه الشجرةُ لا تُودِع عقدةً كذلك، ولا تُودِع النصوصَ التي يُبحَث
فيها**. والفرقُ بين «ليس في التراث» و«ليس عندنا ما نبحث فيه» فرقُ جنسٍ لا
فرقُ درجة (`AN_ABSENCE_IN_AN_UNDEPOSITED_CORPUS_IS_NOT_A_MEASURED_ABSENCE`).

**وسادسًا: ولا يُقرأ من هذا ذمٌّ للجدول.** ما أُعلن غيابًا **أُعلن**، وهذا
أحسنُ من أن يُطوى؛ وإنّما يُسجَّل أنّ المُعلَن أربعةٌ والمسكوتَ عنه — بحساب
الجدول نفسِه — سبعةٌ أو ثمانية. فالغيابُ المُعلَنُ فضيلةٌ والغيابُ المحسوبُ
دَينٌ، ولا يُقاسان بمكيالٍ واحد.

**خمولٌ سلطويّ**: لا ولادةَ هنا ولا حكمَ ولادةٍ ولا تجميدَ `E0`، ولا استيرادَ
من `kernel/` ولا من `program/`، ولا تزحزح هذه الوحدةُ بوّابةَ ماركوف عمّا
كانت عليه.
"""

