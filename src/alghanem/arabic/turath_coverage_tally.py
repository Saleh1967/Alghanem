class TurathCoverageError(ValueError):
    """رُفض مدخلٌ خارج مفردات هذه الوحدة؛ ولا يُحمَل على أقرب حالة."""


class Mark(Enum):
    """ألفاظُ الحكم في الجدول المنقول، على أربعتها لا على ثنائيّتها."""

    COVERED = "مغطاة"
    COVERED_STRUCTURALLY = "مغطاة بنيويًّا"
    ABSENT = "غياب معلن — لا عقدة"
    ABSENT_NO_EXPLICIT_NODE = "غياب معلن — لا عقدة صريحة"

    @property
    def is_counted_covered_by_the_header(self) -> bool:
        """أيضمّه جمعُ الترويسة إلى «المغطّاة»؟ وهو جمعٌ ثنائيٌّ لا رباعيّ."""

        return self in (Mark.COVERED, Mark.COVERED_STRUCTURALLY)

    @property
    def is_hedged(self) -> bool:
        """أيحمل هذا الحكمُ تحفُّظًا يمحوه الجمعُ الثنائيّ؟"""

        return self in (Mark.COVERED_STRUCTURALLY, Mark.ABSENT_NO_EXPLICIT_NODE)


