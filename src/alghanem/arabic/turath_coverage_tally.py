@dataclass(frozen=True, slots=True)
class QuotedHeader:
    """ترويسةُ الجدول كما نُقلت: مغطّاةٌ وغيابٌ، ومجموعُهما يُشتَقّ."""

    covered: int
    absent: int

    def __post_init__(self) -> None:
        if self.covered < 0 or self.absent < 0:
            raise TurathCoverageError("ترويسةٌ بعددٍ سالبٍ لا تُودَع.")

    @property
    def total(self) -> int:
        return self.covered + self.absent


THE_QUOTED_HEADER: Final[QuotedHeader] = QuotedHeader(covered=28, absent=4)
"""«النتيجة: 28 مغطاة · 4 غياب معلن» — منقولةٌ بنصّها لتُصادَم بعدّ الصفوف."""

THE_QUOTED_NODE_COUNT: Final[int] = 33
"""«عقد الدال الثلاث والثلاثين» — منقولٌ من عنوان الجدول لا من صفوفه."""


@dataclass(frozen=True, slots=True)
class Tally:
    """إحصاءُ الجدول مُعادًا من صفوفه: لا يُكتَب حقلًا بل يُشتَقّ عدًّا."""

    rows: int
    covered: int
    absent: int
    hedged: int

    def __post_init__(self) -> None:
        if self.covered + self.absent != self.rows:
            raise TurathCoverageError("إحصاءٌ لا يجمع صفوفَه لا يُودَع.")


@lru_cache(maxsize=1)
def tally() -> Tally:
    """عدُّ الصفوف وأحكامِها؛ متطابقةٌ داخل النقل لا تحتاج مدوّنةً لتُفحَص."""

    covered = sum(1 for row in THE_ROWS if row.mark.is_counted_covered_by_the_header)
    return Tally(
        rows=len(THE_ROWS),
        covered=covered,
        absent=len(THE_ROWS) - covered,
        hedged=sum(1 for row in THE_ROWS if row.mark.is_hedged),
    )


def the_header_overstates_the_covered_rows_by() -> int:
    """كم عقدةً مغطّاةً تدّعيها الترويسةُ ولا يسمّيها الجدول؟"""

    return THE_QUOTED_HEADER.covered - tally().covered


def unnamed_nodes() -> int:
    """كم عقدةً من الثلاث والثلاثين لا صفَّ لها في الجدول ألبتّة؟"""

    return THE_QUOTED_NODE_COUNT - tally().rows


def the_title_is_unreached_even_by_the_header() -> int:
    """كم تنقص الترويسةُ عن عنوانها؟ خرقٌ ثانٍ داخل النقل وحدَه."""

    return THE_QUOTED_NODE_COUNT - THE_QUOTED_HEADER.total


def hedged_rows() -> tuple[CoverageRow, ...]:
    """الصفوفُ التي تحمل تحفُّظًا يمحوه الجمعُ الثنائيّ في الترويسة."""

    return tuple(row for row in THE_ROWS if row.mark.is_hedged)


def mark_census() -> dict[Mark, int]:
    """توزيعُ الأحكام على أربعتها، لا على ثنائيّة الترويسة."""

    return {mark: sum(1 for row in THE_ROWS if row.mark is mark) for mark in Mark}


def rows_by_ground(ground: Ground) -> tuple[CoverageRow, ...]:
    """صفوفُ مقامٍ واحد من مقامات العمود الأيسر الأربعة."""

    return tuple(row for row in THE_ROWS if row.ground is ground)


def ground_census() -> dict[Ground, int]:
    """كم صفًّا في كلّ مقام؟ تصنيفٌ عن البايتات لا عن الدعوى."""

    return {ground: len(rows_by_ground(ground)) for ground in Ground}


