@dataclass(frozen=True, slots=True)
class CoverageRow:
    """صفٌّ واحدٌ من الجدول المنقول، بنصّه وحكمه ومقام رقمه."""

    measured_node: str
    turath_node: str
    mark: Mark
    ground: Ground

    def __post_init__(self) -> None:
        if not self.measured_node.strip() or not self.turath_node.strip():
            raise TurathCoverageError("صفٌّ بعمودٍ خالٍ لا يُودَع.")

    @property
    def is_falsifiable_here(self) -> bool:
        """أيمكن فحصُ دعوى هذا الصفّ ههنا؟ لا — ما دام المعيارُ غائبًا."""

        return False


