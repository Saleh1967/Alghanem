def locked_dispersions_have_drifted() -> tuple[str, ...]:
    """أسماءُ ما انزاح من المقاييس المقفلة؛ وفراغُها شهادةُ ثباتٍ لا دعواه."""

    drifted: list[str] = []
    for verdict in dispersion_verdicts():
        locked = THE_LOCKED_SCALED_DISPERSIONS[verdict.measure.name]
        if (verdict.scaled_lexical, verdict.scaled_textual) != locked:
            drifted.append(verdict.measure.name)
    return tuple(drifted)


def _assert_the_criterion_is_written_before_any_figure() -> None:
    """حارسُ المعيار: لا مقياسَ بلا صيغة، ولا حدَّ فصلٍ بلا نصّ."""

    if len(_MEASURE_FUNCTIONS) != len(DispersionMeasure):
        raise DispersionExpectationError(
            "مقياسٌ مسمًّى بلا صيغةٍ تحسبه؛ فالمعيارُ ناقصٌ لا يُقاس به."
        )
    if not THE_SEPARATION_RULE.strip():
        raise DispersionExpectationError("حدُّ فصلٍ بلا نصٍّ لا يفصل شيئًا.")


def _assert_the_mirror_is_not_the_named_lexicon() -> None:
    """حارسُ المرآة: المعجمُ المقيسُ غيرُ المعجم المحجوب، والاسمان لا يختلطان."""

    if THE_MIRRORED_LEXICON == THE_WITHHELD_LEXICON:
        raise DispersionExpectationError(
            "المرآةُ سُمّيت باسم المعجم المحجوب؛ وذلك استبدالٌ لا تقوية."
        )


def _assert_the_mirror_is_narrower_than_the_closed_list() -> None:
    """حارسُ التعداد: صفوفُ المرآة دون العشرين، وخروجُ «قرأ» مقيسٌ لا مُغفَل."""

    rows = mirror_rows()
    if len(rows) >= len(THE_TWENTY_MATERIALS):
        raise DispersionExpectationError(
            "صفوفُ المرآةِ بلغت القائمةَ المغلقة؛ فالنثرُ عن خروج «قرأ» بائد."
        )
    if len({row.material for row in rows}) != len(rows):
        raise DispersionExpectationError("مادّةٌ مكرّرةٌ في المرآة؛ فالتعدادُ كاذب.")


_assert_the_criterion_is_written_before_any_figure()
_assert_the_mirror_is_not_the_named_lexicon()
_assert_the_mirror_is_narrower_than_the_closed_list()
