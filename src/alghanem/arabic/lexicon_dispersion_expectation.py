"""البندُ المتوقَّع في جسر المعجم: يُقيَّد بمعيارٍ قبل نزول بايتاته، ثمّ تُقاس مرآتُه.

**ما جاءت إليه هذه الوحدة**: خلَّف `lexicon_bridge` بندًا متوقَّعًا بحروفه —
«العشرون المادّةُ أعلاها شواهدَ في لسان العرب ستتباين في ورودها النصّيّ تباينًا
يفوق التباينَ المعجميّ، يُقاس حين تُرفع النسخة». وهذا البندُ كما وُرِد **لا
يسقط**: لا مقياسَ تشتّتٍ مسمًّى فيه، ولا حدَّ فصلٍ، ولا جهةَ قياس. فأيُّ خارجٍ
يخرج غدًا يُقرأ موافقًا إن شئنا ومخالفًا إن شئنا، وذلك ليس توقُّعًا بل رخصةٌ
مؤجَّلة. وبابُ هذه الوحدة: أن يُقيَّد **الآن** بما يجعله قابلًا للسقوط، قبل أن
تنزل البايتاتُ التي يُحكَم عليها بها.

`AN_EXPECTATION_WITHOUT_A_CRITERION_CANNOT_FAIL_SO_IT_IS_NOT_ONE`: توقُّعٌ لا
يُعرَف ما يكذّبه ليس توقُّعًا. فسُمِّيت ههنا ثلاثةُ مقاييسَ للتشتّت بأسمائها
وصيغِها، وسُنَّ حدُّ الفصل — «تفوق» تعني الزيادةَ الصريحة لا التساوي — وعُيِّنت
جهتا القياس: معجميٌّ من خانةِ شواهدَ في جدولٍ مُودَع، ونصّيٌّ من ورودٍ مقيسٍ في
المدوّنة. وكلُّ ذلك مكتوبٌ قبل الرقم لا بعده.

`THE_THREE_MEASURES_LEAVE_TOGETHER_OR_NONE_DOES`: المقاييسُ الثلاثةُ تخرج معًا
في مخرَجٍ واحدٍ لا يُنتقى منه. وإنّما سُنَّت ثلاثةً لأنّ مقياسًا واحدًا يُختار
بعد رؤية الأرقام يكون **مفصَّلًا على مقاسها**؛ فإذا اتّفقت الثلاثةُ فالاتّفاقُ
خبرٌ، وإذا اختلفت فالاختلافُ خبرٌ أنفسُ منه — ولا يُكتَم أحدُهما.

`A_MIRROR_IS_A_CORROBORATION_NOT_A_SUBSTITUTE`: المعجمُ المذكورُ في البند هو
«لسان العرب»، ولا بايتَ منه في هذه الشجرة. والذي يُقاس ههنا جدولُ «مقاييس
اللغة» المُودَع — معجمٌ آخرُ لمؤلّفٍ آخرَ بمنهجٍ آخر. فخارجُ هذه الوحدة **مرآةٌ**
لا بديل: يُقوّي التوقُّعَ أو يُضعِفه، ولا يفصل فيه. وحكمُ البند على لسان العرب
باقٍ محجوبًا، ومحجوبيّتُه مكتوبةٌ في `THE_VERDICT_ON_THE_NAMED_LEXICON_IS_HELD`.

`THE_LEXICAL_TALLY_IS_A_PRODUCERS_SEPARATOR_NOT_A_LEXICOGRAPHERS_COUNT`: الجانبُ
المعجميُّ مقيسٌ بعدّ مقاطعِ خانةِ الشواهد تحت قاعدة الفصل المكتوبة في
`maqayis_witness_census`. وذلك يعدّ **ما فصله ناشرُ الجدول**، لا ما عدّه
لغويٌّ شاهدًا. فمجموعُ الجانب المعجميّ كلِّه أربعون مقطعًا على تسع عشرة مادّة،
وهو عددٌ صغيرٌ تتحرّك نسبُه بمقطعٍ واحد؛ ومَن قرأه «غزارةَ المادّة في المعجم»
قرأ غيرَ ما قيس.

`A_VERDICT_CARRIED_BY_ONE_ROW_IS_NOT_ESTABLISHED`: الحكمُ ههنا لا يُنشَر حتّى
يُعرَف حاملُه. فتُحذَف كلُّ مادّةٍ على حدةٍ ويُعاد القياسُ تسعَ عشرةَ مرّة
(`leave_one_out_flips`)، فيُرى أيُّ مادّةٍ إذا غابت انقلب الحكم. وحكمٌ تقلبه
مادّةٌ واحدةٌ من تسع عشرة حكمٌ موافقٌ ضعيفُ الحمل، فيُخرَج باسمه ذاك لا باسم
«ثبت».

`THE_MIRROR_MEASURES_NINETEEN_NOT_TWENTY`: «قرأ» لا مدخلَ لها في الجدول المُودَع
عند المقام المُصرَّح به — وذلك مقيسٌ سلفًا في `entry_leg_census` — فلا جانبَ
معجميًّا لها ههنا، فتخرج من المرآة. فالمقيسُ تسعَ عشرةَ مادّةً لا عشرين، والعددُ
مُعلَنٌ في المخرَج كيلا يُقرأ عشرين.

`AN_ABSENCE_IS_CLAIMED_ONLY_AFTER_A_POSITIVE_WITNESS`: خروجُ «قرأ» نفيٌ، ولا
يُذكَر إلّا بعد شاهدٍ موجِب: ثماني عشرةَ مادّةً تُطابَق في الجدول نفسِه فتوجد،
ومقاطعُ شواهدِه بالآلاف فتُعَدّ — فالأداةُ تقرأ، وغيابُ «قرأ» غيابٌ في البايتات.

ولا ولادةَ في هذه الوحدة ولا حكمَ ولادة ولا تجميدَ E0، ولا استيرادَ من `kernel/`.
"""

