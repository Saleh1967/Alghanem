class DispersionMeasure(Enum):
    """مقاييسُ التشتّت الثلاثةُ، مسمّاةً قبل أن يُقاس بها رقمٌ واحد."""

    COEFFICIENT_OF_VARIATION = "معامِلُ الاختلاف"
    GINI = "معامِلُ جيني"
    ENTROPY_CONCENTRATION = "تركُّزُ الإنتروبيا"


class MirrorStanding(Enum):
    """منزلةُ البند في المرآة؛ ثلاثٌ لا اثنتان، والوسطى ليست تفصيلًا."""

    MIRRORED_AND_FIRMLY_CARRIED = "موافقٌ في المرآة وحملُه غيرُ منفرد"
    MIRRORED_BUT_CARRIED_BY_ONE_ROW = "موافقٌ في المرآة وحملُه صفٌّ واحد"
    NOT_MIRRORED = "مخالفٌ في المرآة"


@dataclass(frozen=True)
class MirrorRow:
    """صفُّ مادّةٍ في المرآة: جانبُها المعجميُّ وجانبُها النصّيّ، كلاهما مقيس."""

    material: str
    lexical_segments: int
    textual_occurrences: int

    def __post_init__(self) -> None:
        if self.lexical_segments < 0 or self.textual_occurrences < 0:
            raise DispersionExpectationError("عددٌ سالبٌ لا يخرج من عدٍّ؛ قاعدةٌ منكسرة.")


@dataclass(frozen=True)
class DispersionVerdict:
    """حكمُ مقياسٍ واحد: جانباه مقفلين أعدادًا صحيحة، ومنزلتُه مشتقّةٌ منهما."""

    measure: DispersionMeasure
    scaled_lexical: int
    scaled_textual: int
    rows: int
    flipping_materials: tuple[str, ...]

    @property
    def the_textual_side_disperses_more(self) -> bool:
        """أيفوق التشتُّتُ النصّيُّ المعجميَّ؟ أكبريّةٌ صارمةٌ لا تساوي."""

        return self.scaled_textual > self.scaled_lexical

    @property
    def standing(self) -> MirrorStanding:
        """المنزلةُ تُشتَقّ: موافقةٌ وحدَها لا تكفي حتّى يُعرَف حاملُها."""

        if not self.the_textual_side_disperses_more:
            return MirrorStanding.NOT_MIRRORED
        if len(self.flipping_materials) == 1:
            return MirrorStanding.MIRRORED_BUT_CARRIED_BY_ONE_ROW
        return MirrorStanding.MIRRORED_AND_FIRMLY_CARRIED


def _coefficient_of_variation(values: tuple[int, ...]) -> float:
    return statistics.pstdev(values) / statistics.fmean(values)


def _gini(values: tuple[int, ...]) -> float:
    ordered = sorted(values)
    count = len(ordered)
    total = sum(ordered)
    return sum(
        (2 * index - count + 1) * value for index, value in enumerate(ordered)
    ) / (count * total)


def _entropy_concentration(values: tuple[int, ...]) -> float:
    total = sum(values)
    shares = [value / total for value in values if value > 0]
    entropy = -sum(share * math.log(share) for share in shares)
    return 1.0 - entropy / math.log(len(values))


_MEASURE_FUNCTIONS: Final[
    dict[DispersionMeasure, Callable[[tuple[int, ...]], float]]
] = {
    DispersionMeasure.COEFFICIENT_OF_VARIATION: _coefficient_of_variation,
    DispersionMeasure.GINI: _gini,
    DispersionMeasure.ENTROPY_CONCENTRATION: _entropy_concentration,
}


def dispersion_of(measure: DispersionMeasure, values: tuple[int, ...]) -> int:
    """تشتُّتُ سلسلةٍ بمقياسٍ مسمًّى، مقفلًا عددًا صحيحًا على `SCALE`.

    والمقياسُ وسيطٌ إلزاميٌّ لا افتراضيّ: لا تختار هذه الوحدةُ مقياسًا نيابةً
    عن قارئها، فاختيارُ المقياس بعد رؤية الأرقام هو بابُ التفصيل على المقاس.
    """

    if not isinstance(measure, DispersionMeasure):
        raise DispersionExpectationError("المقياسُ وسيطٌ إلزاميٌّ من `DispersionMeasure`.")
    if len(values) < 2:
        raise DispersionExpectationError("لا تشتُّتَ في سلسلةٍ دون صفَّين.")
    if sum(values) <= 0:
        raise DispersionExpectationError("سلسلةٌ مجموعُها صفرٌ لا تُقسَم عليها نسبة.")
    function = _MEASURE_FUNCTIONS[measure]
    return round(function(values) * SCALE)


@lru_cache(maxsize=1)
def mirror_rows() -> tuple[MirrorRow, ...]:
    """صفوفُ المرآة: كلُّ مادّةٍ لها مدخلٌ في الجدول المُودَع، بجانبَيها.

    ومَن لا مدخلَ لها تخرج ولا تُحمَل على صفر: صفرُ الشواهد خانةٌ خاليةٌ في
    صفٍّ موجود، وانعدامُ الصفّ شيءٌ آخرُ لا يُطوى فيه.
    """

    rules = _stage_rules(THE_MATCHING_STAGE)
    segments_by_entry: dict[str, int] = {}
    for row in root_table_rows():
        key = _normalised(row[THE_ENTRY_COLUMN], rules)
        segments_by_entry[key] = segments_by_entry.get(key, 0) + len(
            split_witness_segments(row["poetry_evidence"])
        )
    rows: list[MirrorRow] = []
    for reading in material_readings():
        key = _normalised(reading.material, rules)
        if key not in segments_by_entry:
            continue
        rows.append(
            MirrorRow(
                material=reading.material,
                lexical_segments=segments_by_entry[key],
                textual_occurrences=reading.occurrences,
            )
        )
    return tuple(rows)


def _sides(rows: tuple[MirrorRow, ...]) -> tuple[tuple[int, ...], tuple[int, ...]]:
    return (
        tuple(row.lexical_segments for row in rows),
        tuple(row.textual_occurrences for row in rows),
    )


def leave_one_out_flips(measure: DispersionMeasure) -> tuple[str, ...]:
    """أسماءُ الموادّ التي إذا حُذِفت انقلب حكمُ المقياس؛ وفراغُها حملٌ موزَّع."""

    rows = mirror_rows()
    lexical, textual = _sides(rows)
    standing = dispersion_of(measure, textual) > dispersion_of(measure, lexical)
    flipping: list[str] = []
    for index, row in enumerate(rows):
        trimmed_lexical = lexical[:index] + lexical[index + 1 :]
        trimmed_textual = textual[:index] + textual[index + 1 :]
        without = dispersion_of(measure, trimmed_textual) > dispersion_of(
            measure, trimmed_lexical
        )
        if without != standing:
            flipping.append(row.material)
    return tuple(flipping)


def dispersion_verdicts() -> tuple[DispersionVerdict, ...]:
    """الأحكامُ الثلاثةُ معًا؛ ولا يُنتقى منها واحدٌ ولا يُكتَم مخالف."""

    rows = mirror_rows()
    lexical, textual = _sides(rows)
    return tuple(
        DispersionVerdict(
            measure=measure,
            scaled_lexical=dispersion_of(measure, lexical),
            scaled_textual=dispersion_of(measure, textual),
            rows=len(rows),
            flipping_materials=leave_one_out_flips(measure),
        )
        for measure in DispersionMeasure
    )


