ANCHOR_ROOT: Final[str] = "كتب"
FARD_SEGMENT_OPENING: Final[str] = "ومن الباب الكِتَابُ وهو الفَرْضُ"
_AYAH_QUOTATION: Final[re.Pattern[str]] = re.compile("\ufd3f([^\ufd3e]*)\ufd3e")
"""قوسا الآية المزخرفان؛ وما بينهما اقتباسٌ يُؤخَذ كما ورد."""

THE_TECHNICAL_ABSENCE_MARKS: Final[frozenset[str]] = frozenset(
    {"", "none", "(null)", "null", "nan"}
)


@dataclass(frozen=True, slots=True)
class AyahAddress:
    """عنوانُ الآية، ورقمُ سطرها في المُودَع مُشتقٌّ لا مكتوبٌ في الحكم."""

    sura: int
    ayah: int
    line_number: int

    def __post_init__(self) -> None:
        if self.sura < 1 or self.ayah < 1 or self.line_number < 1:
            raise FardSenseLinkError("عنوانُ آيةٍ لا يكون صفرًا ولا سالبًا.")


THE_ANCHOR_AYAH: Final[AyahAddress] = AyahAddress(sura=2, ayah=183, line_number=190)
"""البقرة ١٨٣، وسطرُها في `corpora/quran-simple-enhanced.txt` سطرًا بآية."""


@dataclass(frozen=True, slots=True)
class Premise:
    """مقدّمةٌ واحدة: جنسُها، ومصدرُها، وموضعُ دليلها، وهل هي حاضرة."""

    name: PremiseName
    genus: PremiseGenus
    source: str
    locus: str
    is_satisfied: bool
    pending_material: str | None = None

    def __post_init__(self) -> None:
        if self.is_satisfied and self.pending_material is not None:
            raise FardSenseLinkError("مقدّمةٌ حاضرةٌ لا تُعلَّق على مادّةٍ منتظَرة.")
        if not self.is_satisfied and not self.pending_material:
            raise FardSenseLinkError(
                "مقدّمةٌ غائبةٌ تُسمّى مادّتُها المنتظَرة، ولا تُترَك بلا اسم."
            )


@dataclass(frozen=True, slots=True)
class Claim:
    """دعوى: ما تقوله، وما تقوم عليه، وحدُّها، وهل تُفتَح بالأدلّة أصلًا."""

    name: str
    statement: str
    requires: tuple[PremiseName, ...]
    bound: str
    is_barred: bool = False
    barring_reason: str | None = None

    def __post_init__(self) -> None:
        if self.is_barred and not self.barring_reason:
            raise FardSenseLinkError("المنعُ يُعلَّل، ولا يُطلَق بلا سبب.")
        if self.is_barred and self.requires:
            raise FardSenseLinkError(
                "الممنوعُ لا يُعلَّق على مقدّماتٍ، وإلّا صار معلَّقًا ينتظرها."
            )

    def verdict_under(self, satisfied: frozenset[PremiseName]) -> ClaimVerdict:
        """منزلةُ الدعوى تحت مجموعةِ المقدّمات الحاضرة؛ دالّةٌ خالصةٌ تُختبَر."""

        if self.is_barred:
            return ClaimVerdict.ممنوع
        if all(premise in satisfied for premise in self.requires):
            return ClaimVerdict.نافذ
        return ClaimVerdict.معلق

    def missing_under(
        self, satisfied: frozenset[PremiseName]
    ) -> tuple[PremiseName, ...]:
        """ما نقص من مقدّماتها بعينه، فلا يُقال «ناقصة» بلا تسمية."""

        return tuple(premise for premise in self.requires if premise not in satisfied)


def _repository_root() -> Path:
    return Path(__file__).resolve().parents[3]


@lru_cache(maxsize=1)
def _anchor_row() -> tuple[int, dict[str, str]]:
    for index, row in enumerate(root_table_rows()):
        if row["root_full"].strip() == ANCHOR_ROOT:
            return index, row
    raise FardSenseLinkError(f"لا صفَّ للمادّة «{ANCHOR_ROOT}» في المُودَع.")


@lru_cache(maxsize=1)
def fard_segment() -> tuple[int, int, str]:
    """مقطعُ معنى الفرض: مطلعُه ومنتهاه ونصُّه، مُشتقّةً من المتن لا مكتوبة."""

    _, row = _anchor_row()
    body = row["body_text"]
    start = body.find(FARD_SEGMENT_OPENING)
    if start == -1:
        raise FardSenseLinkError(
            "لم يُوجَد مطلعُ مقطع الفرض في متن المادّة؛ فلا يُفترَض موضعُه."
        )
    end = body.find("\n", start)
    if end == -1:
        end = len(body)
    return start, end, body[start:end]


@lru_cache(maxsize=1)
def lexical_quotation() -> str:
    """الآيةُ مقتبسةً داخل مقطع الفرض، بين قوسَي الآية، كما وردت بلا تحرير."""

    _, _, segment = fard_segment()
    quoted = _AYAH_QUOTATION.search(segment)
    if quoted is None:
        raise FardSenseLinkError("لا اقتباسَ بين قوسَي آيةٍ في مقطع الفرض.")
    return quoted.group(1)


@lru_cache(maxsize=1)
def anchor_ayah_text() -> str:
    """نصُّ الآية من المُودَع القرآنيّ، مقروءًا بسطره لا منسوخًا في الشفرة."""

    path = _repository_root() / "corpora" / "quran-simple-enhanced.txt"
    if not path.is_file():
        raise FardSenseLinkError(f"المُودَعُ القرآنيُّ غائبٌ عن {path}.")
    lines = path.read_text(encoding="utf-8").split("\n")
    index = THE_ANCHOR_AYAH.line_number - 1
    if index >= len(lines):
        raise FardSenseLinkError("رقمُ السطر خارج المُودَع؛ فلا تُقرأ آيةٌ منه.")
    return lines[index]


def quotation_is_in_the_deposited_ayah() -> bool:
    """أيطابق اقتباسُ ابن فارس المتنَ المُودَع بعد الطيّ المُعلَن؟ مقيسًا."""

    return fold_for_comparison(lexical_quotation()) in fold_for_comparison(
        anchor_ayah_text()
    )


def absent_value_genus(value: str | None) -> AbsentValueGenus | None:
    """صنفُ الخانة الخالية، أو لا شيءَ إن كانت ناطقة؛ ولا تُحوَّل حروفًا أبدًا."""

    if value is None:
        return AbsentValueGenus.علامة_تقنية
    folded = value.strip().casefold()
    if folded in THE_TECHNICAL_ABSENCE_MARKS:
        return (
            AbsentValueGenus.قيمة_مفقودة
            if folded == ""
            else AbsentValueGenus.علامة_تقنية
        )
    return None


def masaq_key_uniqueness() -> tuple[int, int] | None:
    """فرادةُ `(ID, Word_No)` على النسخة الحاضرة: (عددُ الصفوف، المفاتيحُ المتميّزة).

    ولا شيءَ إن لم تنزل البايتات؛ فالفرادةُ خاصّةُ نسخةٍ لا خاصّةُ مخطَّط.
    """

    from .masaq_corpus_deposit import (
        SEGMENT_INDEX_COLUMN,
        masaq_bytes_are_resolvable,
        masaq_records,
        read_masaq_bytes,
    )

    if not masaq_bytes_are_resolvable():
        return None
    records = masaq_records(read_masaq_bytes())
    keys = {(record.get("ID"), record.get(SEGMENT_INDEX_COLUMN)) for record in records}
    return len(records), len(keys)


