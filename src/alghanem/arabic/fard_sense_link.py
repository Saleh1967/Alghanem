"""وصلةٌ واحدةٌ تعمل: «كُتِبَ عَلَيْكُمُ الصِّيَامُ» من المعجم إلى المتن.

هذه الوحدةُ ليست دفترَ موانع. إنّها **منفِّذٌ يستقبل بايتاتٍ ويُخرِج حكمًا ذا
شهادة**، وقرارُه يتغيّر بإضافة دليلٍ لازمٍ أو حذفه. وما لا تكفي له الأدلّةُ
الحاضرةُ يُعلَّق **بدعواه لا بملفّه**، فلا يُوقِف غيابُ مصدرٍ ما لا يتوقّف عليه.

`THE_LINK_RUNS_ON_THE_EVIDENCE_THAT_IS_HERE`: ثلاثةُ أرباع المسار قائمةٌ اليوم
على بايتاتٍ مختومةٍ في الشجرة. فمادّةُ «كتب» في مقاييس اللغة تقول نصًّا: «ومن
الباب الكِتَابُ وهو الفَرْضُ. قال اللّه تعالى: ﴿كُتِبَ عَلَيْكُمُ اَلصِّيامُ﴾»،
والمتنُ القرآنيُّ المُودَع يحمل الآيةَ في موضعها. فالرابطُ المعجميُّ إلى الشاهد
**مقروءٌ من النصّ لا مُخمَّنٌ من أصل الجذر**، وهو أقوى من أيّ استنباطٍ من
«جمع شيء إلى شيء».

`A_CLAIM_IS_SUSPENDED_BY_ITS_OWN_PREMISE_NOT_BY_A_FILENAME`: التعليقُ يقع على
**الدعوى** لا على الوحدة. فغيابُ MASAQ يُعلّق دعوى البناء للمجهول ودعوى نائب
الفاعل، ولا يُعلّق دعوى وقوع اللفظ في موضعه ولا دعوى إسناد المعنى؛ وغيابُ
مغني اللبيب يُعلّق دعوى تعلّق الجار والمجرور وحدَها. فمن أوقف المسارَ كلَّه
لغياب مصدرٍ أوقف ما لا يتوقّف عليه.

`A_SUSPENDED_CLAIM_AND_A_BARRED_CLAIM_ARE_NOT_THE_SAME`: وهذا فرقٌ لا يُطوى.
فالمعلَّقُ ينتظر دليلًا من **جنسٍ معلوم**: لو نزلت بايتاتُ MASAQ انفتح. وأمّا
«وقع الصيامُ من المخاطبين» فليس معلَّقًا ينتظر MASAQ ولا مغني اللبيب: **لا
يُخرِجه دليلٌ معجميٌّ ولا صرفيٌّ ولا نحويٌّ ألبتّة**، لأنّ فرضَ الفعل غيرُ
وقوعه. فهو **ممنوعٌ بنيويًّا**، وإضافةُ كلّ أدلّة هذه الوحدة لا تفتحه. ومن
عدَّه معلَّقًا وعد بفتحه يومًا، وذلك وعدٌ كاذب.

`WHAT_IS_TRANSMITTED_IS_NEVER_COUNTED_AS_DERIVED`: لكلّ مقدّمةٍ جنسٌ مُعلَن:
`مُشتقٌّ_من_بايتات` لما يُعاد اشتقاقُه هنا من مودَعٍ مختوم، و`منقولٌ_عن_مصدر`
لما يؤخذ تحليلًا جاهزًا من غيرنا، و`مستنبطٌ_من_الـ116` لما يُشتقّ من الوحدات
الأساسيّة وحدَها. **ولا تحمل هذه الوحدةُ مقدّمةً واحدةً من الجنس الثالث**،
فليست شهادتُها شهادةَ استنباطٍ من الـ١١٦ ولا تُقرأ كذلك. فإدخالُ وَسْمِ
«مبنيٌّ للمجهول» من MASAQ ثمّ إخراجُه استعمالٌ لمعرفةٍ سابقة، لا اكتشافٌ.

`THE_QUOTATION_IS_MATCHED_AFTER_A_DECLARED_FOLD`: اقتباسُ ابن فارس مضبوطٌ برسمٍ
غيرِ رسم المُودَع — فيه ألفُ وصلٍ محرَّكةٌ «اَلصِّيام» وقوسا آيةٍ — فلا تصحّ
المقابلةُ حرفًا بحرف. والطيُّ مُعلَنٌ في `fold_for_comparison` ومحدودٌ:
إسقاطُ العلامات الجامعة وتوحيدُ صور الهمزة والألف والياء والتاء. **والطيُّ
يُثبِت تطابقَ الملفوظ لا تطابقَ الرسم**، ومن قرأه تطابقًا في الرسم زاد على
المقيس.

`THE_UNIQUENESS_OF_A_KEY_IS_A_PROPERTY_OF_A_COPY_NOT_OF_A_SCHEMA`: مفتاحُ
`(ID, Word_No)` يُفحَص على النسخة الحاضرة في كلّ تشغيل ولا يُورَث عن نسخةٍ
أخرى. وفرادتُه — إن ثبتت — تُثبِت أنّ الصفوف متمايزةٌ ولا تُثبِت أنّ التجزئةَ
صحيحة: تلك دعوى لغويّةٌ تحتاج توثيقًا مستقلًّا.

`AN_ABSENT_VALUE_IS_NOT_A_SILENT_LETTER`: `None` و`(null)` في خاناتِ MASAQ
**لا تُحوَّل حروفًا** عند التفكيك إلى الـ١١٦، ولا تُسمّى عنصرًا مقدَّرًا بغير
دليل. فتُفرَز ثلاثًا: قيمةٌ مفقودة، وعلامةٌ تقنيّةٌ من الناشر، وعنصرٌ مقدَّرٌ
موثَّق؛ ولا يُنتقَل من الأولى إلى الثالثة إلّا بشاهد.

وهذه الوحدة تسجيلٌ لا سلطة: لا ولادةَ فيها، ولا تجميدَ `E0`، ولا تستورد من
`kernel/` شيئًا.
"""

