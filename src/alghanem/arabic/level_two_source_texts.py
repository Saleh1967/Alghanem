def require_attested_fath_bari_excerpt(excerpt: str) -> str:
    """اقبلْ مقطعًا بشرط احتوائه اسمَ سلطته المُسنَدة نصًّا، وإلّا فاردُدْه.

    وهو حدُّ `LexicalAttribution` عينُه مُطبَّقًا هنا: من نقل مقطعًا لا يقع فيه
    اسمُ قائله فقد نقل متنًا بلا سلطةٍ مُسمّاة داخله.
    """

    _require_text(excerpt, "المقطعُ المنقول")
    key = comparison_key(excerpt)
    for authority in QAYD_ATTRIBUTION_SCAN.qualifying_attributions:
        if comparison_key(authority) in key:
            return excerpt
    raise SourceTextError(
        "لا يقع في هذا المقطع اسمُ سلطةٍ من الإسنادات المُحتسَبة؛ "
        + SECOND_ATTRIBUTION_MAY_NOT_BE_MANUFACTURED_NOTE
    )


