class SourceExhaustionStanding(Enum):
    """موقفُ المصدر من عتبة التعاقب؛ ثلاثيٌّ مغلق، ولا يُقرأ أحدُ طرفيه من نفي الآخر.

    أوّلُها حالُ من لم يُمسَح مصدرُه أصلًا، فوقوفُه محتملٌ أن يرفعه تفريغٌ أتمّ.
    وثانيها حالُ من مُسِح كاملُه فلم يبلغ العتبة، فوقوفُه نهائيٌّ **عليه**.
    وثالثها حالُ من مُسِح كاملُه فبلغها. وغيابُ المسح ليس استنفادًا، والاستنفادُ
    ليس بلوغًا.
    """

    المصدر_لم_يُمسَح = "المصدر_لم_يُمسَح"
    مستنفد_دون_عتبة_التعاقب = "مستنفد_دون_عتبة_التعاقب"
    مستنفد_ببلوغ_عتبة_التعاقب = "مستنفد_ببلوغ_عتبة_التعاقب"


