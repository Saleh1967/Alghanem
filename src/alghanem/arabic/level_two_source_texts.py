"""نصُّ بطاقة «سائمة الغنم» مُقابَلًا بشاهدٍ رقميٍّ مُسمّى، ومسحٌ **أُجري** على كامل مصدره.

`qayd_marker_preregistration` سجّل جبهةً مفتوحةً واحدةً
(`LEXICAL_PATH_FRONT_IS_REGISTERED_NOT_OPENED`) وعلّق فتحَها بشرطٍ صريح: «لا
يُشغَّل عليه شيءٌ **قبل أن تُغلَق تجربةُ سائمة الغنم الجارية بنتيجةٍ واحدةٍ
كاملة**». وهذه الوحدةُ موضعُ تلك النتيجة، وهي **نتيجةٌ سالبةٌ تامّة** لا فتحٌ
لجبهةٍ ولا ترقيةُ موقف.

**والسؤالُ الذي أُغلِق هو سؤالُ البطاقة نفسِه**: وقفت آلةُ المستوى الثاني عند
`وقوف_آلة_لانقطاع_نقل_القيد` بجنس امتناعٍ `REFUSED_BY_STRUCTURAL_CATEGORY_MISMATCH`،
وعلّتُه أثرُ عتبةٍ مُسمّاة: `LEXICAL_CHAIN_MINIMUM_ATTRIBUTIONS == 2` والمنقولُ
إسنادٌ واحد. وبقي مُعلَّقًا: **أهذا نقصُ نقلٍ يرفعه تفريغٌ أتمّ، أم استنفادٌ
للمصدر نفسِه؟** فمُسِح كاملُ «فتح الباري» — لا بابُ الزكاة وحده — فلم يقع فيه
إلّا إسنادٌ واحدٌ في مادّة قيد السوم. فالوقوفُ **نهائيٌّ على هذا المصدر**، ولا
يرفعه تفريغٌ ولا إعادةُ قراءة.

**واستنفادُ مصدرٍ ليس استنفادًا للمسألة** (`ExhaustedSourceIsNotAnExhaustedWorld`):
المقيسُ كتابٌ واحدٌ سمّته البطاقةُ في حقل `المصدر`، ومن قرأ هذا حكمًا بأنّ
الشرّاح لم يزيدوا على الزين بن المنير فقد حمل قيدَ الأداة نصًّا في العالم.

**ولا يُبلَغ التعاقبُ بصناعة إسنادٍ ثانٍ** (`SecondAttributionMayNotBeManufactured`):
بلوغُ العتبة بكتابة «قال ابن حجر» قبل ترجيحه يُنشئ لفظًا لم يقع في النصّ،
والبطاقةُ نفسُها ردّت ذلك في `بيان_الإسناد_الواحد` قبل هذا المسح؛ فالمسحُ يؤكّد
ردَّها ولا يُنشئه.

**والمسحُ لفظيٌّ لا معنويّ** (`ScanIsLexicalNotSemantic`): يقرأ حروفًا مُعدَّدةً
لا جهةَ قولٍ ولا موضوعَ بحث، وهو القيدُ عينُه الذي سمّاه
`SCAN_IS_BLIND_TO_NEGATION_AND_STANCE` هناك. ولذلك تُسمّى المواقعُ المُستبعَدةُ
بأعيانها وبعلّةِ استبعادها، ولا تُطوى في رقمٍ مُجمَل.

**وما وقع من تحقُّقٍ إيجابيٍّ يُسجَّل كما يُسجَّل ما لم يقع**: مقطعُ البطاقة
المنقولُ «من خارج هذه الشجرة» قُوبِل حرفًا بحرف بهذا الشاهد فطابقه، وهذا أوّلُ
تحقُّقٍ خارجيٍّ لمقطعٍ في هذه الشجرة. والمقابلةُ على الحروف المجرَّدة من الشكل
والترقيم، لأنّ الشاهدَ الرقميَّ مجرَّدٌ منهما أصلًا؛ فهي مطابقةُ حروفٍ لا
مطابقةُ رسمٍ تامّ، وتُسمّى بحدِّها لا بأوسعَ منه.

**وموضعُ الطبعة مرفوعٌ بعضًا لا كلًّا، والخلافُ فيه لا يُطوى**: البطاقةُ تكتب
«[ص: ٣٧٢]» بلا مجلَّد، وهذا الشاهدُ يُرقّم على «دار المعرفة - بيروت، ١٣٧٩»
بثلاثة عشر مجلَّدًا، ويقع المقطعُ بين علامتَي `PageV03P317` و`PageV03P318`.
فالمجلَّدُ **الثالث** ثابتٌ بعلامتَي الطرفين معًا، وأمّا رقمُ الصفحة فيتوقّف على
عُرفٍ لم يُتحقَّق منه هنا: أتقع العلامةُ في آخر صفحتها أم في أوّلها؟ فيُكتَب
الرقمُ **مترجِّحًا بين ٣١٧ و٣١٨** ولا يُحسَم بالظنّ
(`PAGE_MILESTONE_CONVENTION_NOT_VERIFIED`). ورقمُ البطاقة **لم يُمسَح ولم
يُستبدَل** بهذا، لأنّ الطبعتين غيرُ متطابقتين وإبدالُ موضعٍ مُعلَنٍ بعد رؤية
شاهدٍ جديدٍ هو عينُ ما رُفِض في «المقام» (`CARD_LOCUS_IS_NOT_OVERWRITTEN`).

**ولا تُرقّى بهذه الوحدة مرتبةُ موضعٍ إلى أعلاها**: `مقابل_بنسخة_ورقية_محققة`
يبقى عضوًا **بلا مدخلٍ** هنا أيضًا، فلم تُقابَل هذه الحروفُ بورقٍ في اليد.

**وإغلاقُ الشرط ليس فتحًا للمشروط** (`ClosureIsNotTheOpeningOfWhatItUnblocks`):
تحقُّقُ شرط `LEXICAL_PATH_FRONT_IS_REGISTERED_NOT_OPENED` يُثبِت أنّ المانعَ
التسلسليَّ ارتفع، ولا يُنشئ أداةً ولا مفردةً ولا عضوًا في تعدادٍ قائم لطريق
النقل المعجميّ؛ وفتحُ الجبهة في الخطوة التي تُغلِق شرطَها يجمع المستويين معًا،
وهو ما يمنعه `NoRicherStructureBeforeLowerOpenResidualClosure` بعينه.

**والمسحُ قياسٌ مُجمَّدٌ لا اشتقاقٌ يُعاد في كلّ تشغيل**
(`ScanIsAFrozenMeasurementNotAVendoredCorpus`): الكوربصُ غيرُ منقولٍ في هذه
الشجرة، فأرقامُ المسح مُثبَتةٌ هنا مع بصمة الملفّ المقيس وحجمِه ليُعادَ
اشتقاقُها على نسخةٍ مُطابقة، على منوال `docs/reference/`.

**ولا سلطةَ لهذه الوحدة**: لا ولادةَ، ولا حكمَ ولادةٍ، ولا تجميد، ولا `E0`، ولا
تقرؤها بوّابةٌ في `kernel/`، ولا تدخل في `BirthExperimentSpecification`، ولا
يتغيّر بها حرفٌ في `qayd_marker_preregistration` ولا في `level_two_manat`.
"""

