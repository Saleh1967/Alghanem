def _repository_root() -> Path:
    return Path(__file__).resolve().parents[3]


def matn_deposit() -> SealedDeposit:
    """وديعةُ المتن كما سُجِّلت في الإيداع المأذون؛ ولا يُكرَّر ختمُها هنا."""

    for deposit in THE_DEPOSITS:
        if deposit.path == THE_MATN_PATH:
            return deposit
    raise BridgeError(f"لا وديعةَ باسم {THE_MATN_PATH} في الإيداع المأذون.")


def _matn_lines() -> tuple[str, ...]:
    """الشرطُ الأول: لا قراءةَ قبل ختم؛ ولا حرفَ من وديعةٍ لم توافق ختمَها."""

    deposit = matn_deposit()
    standing = standing_of(deposit)
    if standing is not DepositStanding.SIGNED_AND_SEALED:
        raise BridgeError(
            f"وديعةُ المتن قائمتُها «{standing.value}»، فلا يُقرأ منها حرف."
        )
    payload = (_repository_root() / deposit.path).read_text(encoding="utf-8")
    return tuple(line.replace(THE_KASHIDA, "") for line in payload.split("\n"))


def _line_bearing(anchor: str) -> str:
    """السطرُ الذي تقع فيه المرساةُ؛ ويُرفَض الغياب والتعدُّد كلاهما."""

    bearing = [line for line in _matn_lines() if anchor in line]
    if not bearing:
        raise BridgeError(
            f"المرساةُ «{anchor}» غائبةٌ عن الوديعة، فلا دليلَ حرفيًّا لها."
        )
    if len(bearing) > 1:
        raise BridgeError(
            f"المرساةُ «{anchor}» تقع في {len(bearing)} أسطر، فليست مرساةً."
        )
    return bearing[0]


def _the_condition_is_in_the_deposit() -> bool:
    """أفي البايتات نصُّ «شرطٌ وليس بموجِب»؟ يُقاس ولا يُفترَض."""

    return any(
        THE_ILTIZAM_CONDITION_ANCHOR in line for line in _matn_lines()
    )


def class_of_dal(dal: str) -> MadlulClass:
    """وسمُ الدالّ بقسمٍ من الخمسة، ولا وسمَ إلّا بقرينةٍ منصوصةٍ في الوديعة."""

    if not isinstance(dal, str):
        raise BridgeError("الدالُّ نصٌّ يُقابَل بالوديعة.")
    for named, klass, anchor in THE_CLASS_ANCHORS:
        if named == dal:
            _line_bearing(anchor)
            return klass
    return MadlulClass.UNTAGGED_FOR_WANT_OF_EVIDENCE


def derive_pairs() -> tuple[BridgePair, ...]:
    """أزواجُ الجسر، مُشتقّةً من البايتات عند كلّ نداء لا منقولةً في حقل."""

    if not _the_condition_is_in_the_deposit():
        raise BridgeError(
            "نصُّ «شرطٌ وليس بموجِب» غائبٌ عن الوديعة؛ "
            + THE_CONDITION_IS_QUOTED_FROM_THE_DEPOSIT_NOT_ASSERTED
        )
    source = f"{THE_MATN_PATH}#{matn_deposit().transcribed_sha256}"
    pairs: list[BridgePair] = []
    for dal, channel, madlul, anchor in THE_PAIR_ANCHORS:
        pairs.append(
            BridgePair(
                dal=dal,
                channel=channel,
                madlul=madlul,
                madlul_class=class_of_dal(dal),
                literal_evidence=_line_bearing(anchor),
                sealed_source=source,
                iltizam=(
                    IltizamStanding.CONDITION_NOT_CAUSE
                    if channel is DalalaChannel.ILTIZAM
                    else IltizamStanding.NOT_ASKED
                ),
            )
        )
    return tuple(pairs)


def pairs_in(channel: DalalaChannel) -> tuple[BridgePair, ...]:
    """أزواجُ قناةٍ بعينها؛ والفراغُ يُعرَض فراغًا."""

    if not isinstance(channel, DalalaChannel):
        raise BridgeError("القناةُ عضوٌ في الثلاث.")
    return tuple(one for one in derive_pairs() if one.channel is channel)


def pending_dawal() -> tuple[PendingDal, ...]:
    """المعلَّقُ محفوظًا بنصّ سببه؛ صنفٌ أوّلٌ لا بقيّةٌ تُطرَح."""

    return THE_PENDING_DAWAL


def unopened_channels() -> tuple[tuple[str, str], ...]:
    """قنواتٌ طلبها العقدُ ولم تُفتَح، ومعها سببُ امتناعِ كلٍّ منها."""

    return THE_UNOPENED_CHANNELS


def coverage() -> tuple[int, int]:
    """التغطية خامًا: دوالٌّ لها مدلولُ مطابقةٍ واحدٌ على الأقلّ، من كلّ دالّ.

    والمقامُ يضمّ المعلَّقَ؛ فحذفُه كان سيرفع النسبةَ بحذف ما يخالفها.
    """

    pairs = derive_pairs()
    matched = {
        one.dal for one in pairs if one.channel is DalalaChannel.MUTABAQA
    }
    every = {one.dal for one in pairs} | {
        one.dal for one in pending_dawal()
    }
    return len(matched), len(every)


def pairs_joining_both_sides() -> tuple[BridgePair, ...]:
    """حدُّ العقد مقيسًا: أيُّ زوجٍ حمل الطرفَين كائنًا واحدًا؟

    ويُقاس بأمرين معًا: ألّا يكون في الزوج حقلٌ يجمع الطرفَين نصًّا، وألّا
    يحمل وسمًا من السباعيّة المؤجَّلة. وكلاهما مُشتَقٌّ لا موعودٌ في نثر.
    """

    seven = {
        "منفرد",
        "متباين",
        "مترادف",
        "مشترك",
        "منقول",
        "حقيقة",
        "مجاز",
    }
    joined: list[BridgePair] = []
    for one in derive_pairs():
        fused = f"{one.dal} {one.madlul}"
        if fused in (one.madlul_class.value, one.channel.value):
            joined.append(one)
        elif one.madlul_class.value in seven or one.channel.value in seven:
            joined.append(one)
    return tuple(joined)


def separation_count() -> int:
    """رقمُ الانفصال؛ واحدٌ فيه يُسقِط المهمّة، فيُعاد اشتقاقُه لا يُوعَد."""

    return len(pairs_joining_both_sides())
