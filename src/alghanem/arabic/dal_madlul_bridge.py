"""جسرُ الدالِّ بالمدلول: أزواجٌ تُشتَقُّ من بايتاتٍ مختومة، ومعلَّقٌ يُحفَظ.

العقدُ كان: قابِل كلَّ دالٍّ بمدلوله عبر قنواتِ الدلالة الثلاث، وسِمْ كلَّ
مدلولٍ بقسمٍ من الأقسام الخمسة، وائتِ لكلِّ زوجٍ بدليلٍ حرفيٍّ من مادّةٍ
مختومة، **ولا تجمع الطرفَين في مفهوم**. وهذه الوحدةُ تفعل ذلك، وتُسمّي —
بنفس الانضباط — **أين ينكسر العقدُ على نفسه**.

فالضلعان مبنيّان قبل اليوم: الدلالاتُ الثلاث في `dalalat_thalath`، والأقسامُ
الخمسة في `madlul_alone_formal`؛ والناقصُ كان الجسرَ بينهما. وهذه الوحدةُ
جسرٌ لا مفهوم: تُخرِج الزوجَ ذا الأركان الستّة، ولا تُركِّب منه كائنًا ثالثًا
يحمل الطرفَين معًا.

**أوّلًا: صورةُ المدلول ليست جنسَه** (`THE_SHAPE_OF_A_GLOSS_IS_NOT_THE_GENUS_OF_A_MADLUL`).
هذا أخطرُ ما في العقد، وهو عطبٌ في العقد لا في تنفيذه. فالأقسامُ الخمسةُ
تُقسِّم **الدالَّ** بجنسِ مدلوله: أمعنًى هو أم لفظ؟ وإن كان لفظًا فمفردٌ أم
مركّب، مستعمَلٌ أم مهمَل؟ والمتنُ يُصرِّح أنّ القسم الأول «أن يكون المدلول
معنًى، **أي شيئًا ليس بلفظ**»، ويضرب لأقسامه الأربعة الباقية أمثلةً كلَّها
ألفاظٌ **واصفةٌ للغة**: الكلمة، وحروف الهجاء، والخبر، والهذيان. فمدلولُ
«الإنسان» معنًى — قسمٌ أوّلٌ — وإن كُتِب ذلك المعنى بلفظَين. ومن وسَم
المخرَجَ «الحيوان الناطق» بأنّه «لفظٌ مركّبٌ مستعمَل» لأنّه كلمتان، فقد وسَم
**الحبرَ الذي رُسم به المعنى** بوسمٍ موضوعُه جنسُ المدلول، فأخرج قسمًا رابعًا
من حيث لا قسمَ رابع. وهذا بعينه ما يمنعه العقدُ في بنده الأخير: قراءةُ صورة
اللفظ حكمًا على المدلول هي **جمعُ الطرفَين** في موضعٍ واحد، أي المفهومُ
المؤجَّل يتسلّل من باب الوسم. فههنا لا يُوسَم مدلولٌ بقسمٍ إلّا إذا كان
دالُّه من الدوالّ التي **نصَّ المتنُ على قسمها بعينها**، وما عداه يُترَك
`غيرُ_موسومٍ_بقرينة` ولا يُخمَّن.

**وثانيًا: الاقترانُ الإحصائيُّ ليس لزومًا ذهنيًّا**
(`A_COOCCURRENCE_WINDOW_IS_NOT_A_TRANSFER_OF_THE_MIND`). طلب العقدُ أن
يُقاس الالتزامُ باقترانٍ إحصائيٍّ بنافذةٍ مسمّاة. والمتنُ يقول إنّ المعتبَر
«**اللزومُ الذهنيّ**، وهو الذي ينتقل الذهنُ إليه عند سماع اللفظ»، ثمّ يفصل
بينه وبين اللازم الخارجيّ بمثالَين: ما هو لازمٌ في الخارج أيضًا، وما ليس
بلازمٍ في الخارج ألبتّة. ونافذةُ الجوار لا ترى هذا الفصلَ أصلًا: هي تقيس
تجاورًا في نصٍّ، والتجاورُ أثرُ موضوعِ الكتاب وأسلوبِ مؤلّفه. فتسميةُ
مخرَجِها «التزامًا» بصمةٌ تُقاس صحيحةً ثمّ تُسمَّى باسم ظاهرةٍ ليست هي. فلا
تُفتَح ههنا قناةُ التزامٍ بالجوار ألبتّة، وما يُخرَج في هذه القناة منصوصٌ
مثالُه في المتن لا مستخرَجٌ بنافذة.

**وثالثًا: اللزومُ شرطٌ لا موجِب** — ونصُّه في هذه الوديعة بحروفه: «وهذا
اللزومُ شرطٌ وليس بموجِب... بل السببُ هو إطلاقُ اللفظ، واللزومُ شرط»
(`THE_CONDITION_IS_QUOTED_FROM_THE_DEPOSIT_NOT_ASSERTED`). فكلُّ زوجٍ في
قناة الالتزام يخرج موسومًا «شرط» **مشتقًّا من حضور هذا النصّ في البايتات**،
لا مكتوبًا في حقلٍ باليد؛ فلو غاب النصُّ سقط الوسمُ ولم يُكتَب.

**ورابعًا: المحورُ الدلاليُّ ليس تمامَ المسمّى**
(`A_SEMANTIC_AXIS_IS_NOT_THE_WHOLE_OF_A_DEFINIENDUM`). طلب العقدُ أن تمرّ
قناةُ التضمّن بأصلٍ معجميٍّ مصرَّحٍ به، وسمّى مقاييسَ ابن فارس. والمقاييسُ
تُعطي **محورَ الجذر** («حدّةٌ في الشيء ونفاذ»)، وهو ليس حدًّا ذا جنسٍ وفصل.
والتضمّنُ في المتن «دلالةُ اللفظ على **جزء المسمّى**»، وجزءُ المسمّى لا
يُعرَف إلّا بعد أن يُعرَف تمامُه — «الحيوانُ الناطق» جنسٌ وفصل، فالحيوانُ
جزءٌ والناطقُ جزء. فلا يُشتَقُّ من محورٍ دلاليٍّ جزءُ مسمًّى، ولا تُفتَح
قناةُ التضمّن من المقاييس. والمقاييسُ **مختومةٌ حاضرةٌ في هذه الشجرة**،
فامتناعُ الاشتقاق امتناعُ جنسٍ لا غيابُ بايتات، وهذا أصدقُ من تمريره.

**وخامسًا: الفراغُ يُعرَض فراغًا** (`AN_EMPTY_CHANNEL_IS_REPORTED_NOT_FILLED`).
ما لم تُفتَح قناتُه يخرج عددُه صفرًا معروضًا، والدالُّ الذي لا يُعرَف مدلولُه
يُحفَظ `معلَّقًا` بنصِّ سبب تعليقه. ولا تُستكمَل قناةٌ بتخمين، ولا يُحذَف
معلَّقٌ ليجمُل رقمُ التغطية.

**وسادسًا: الانفصالُ حدُّ العقد، فيُقاس لا يُوعَد**
(`NO_PAIR_CARRIES_BOTH_SIDES_AS_ONE_OBJECT`). لا تُركَّب في هذه الوحدةِ بنيةٌ
تحمل الدالَّ والمدلولَ بوصفهما كائنًا واحدًا، ولا تُقرأ السباعيّةُ
(منفرد/متباين/مترادف/مشترك/منقول/حقيقة/مجاز) ولا تُستورَد وحدتُها؛ ويُعرَض
هذا عددًا صفرًا يُعاد اشتقاقُه، لا سطرًا في تقرير.

**خمولٌ سلطويّ**: لا استيرادَ من `kernel/`، ولا ولادةَ ولا حكمَ ولادة، ولا
بوّابةَ تقرأ مخرجَ هذا الجسر حكمًا. تسجيلٌ لا سلطة.
"""

