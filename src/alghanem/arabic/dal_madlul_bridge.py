@dataclass(frozen=True, slots=True)
class ChannelGate:
    """بابُ قناةٍ: دلالتُها، وجملةُ تعريفها المطلوبةُ في البايتات، ومادّتُها."""

    kind: DalalaKind
    defining_phrase: str
    material_key: str
    what_it_yields: str

    def __post_init__(self) -> None:
        if not isinstance(self.kind, DalalaKind):
            raise DalMadlulBridgeError("قناةُ الجسر عضوٌ من `DalalaKind` لا اسمٌ حرّ.")
        for field_name in ("defining_phrase", "material_key", "what_it_yields"):
            if not str(getattr(self, field_name)).strip():
                raise DalMadlulBridgeError("بابُ القناة بحقولٍ غيرِ فارغة.")


