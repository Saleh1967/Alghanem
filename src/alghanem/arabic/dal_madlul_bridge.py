"""جسرُ الدالِّ وحدَه بالمدلول وحدَه: قنواتٌ ثلاثٌ مُقفَلةٌ بختمٍ غائب.

الطلبُ كان: «ابنِ جسرًا آليًّا يقابل كلَّ دالٍّ بمدلوله — الدالُّ وحدَه من
جهة، والمدلولُ وحدَه من جهةٍ أخرى، والجسرُ بينهما — دون بناء المفهوم».
وشرطُه الأوّلُ: **الختمُ قبل القراءة**؛ فلا عملَ على مادّةٍ لم تُختَم بايتاتُها.
وهذه الوحدةُ تُنفِّذ الشرطَ الأوّلَ حرفيًّا، فيقع ما يقع:

    SealedBytes      != TranscribedExcerpt
    ClosedChannel    != EmptyResult
    VacantZero       != DisciplinedZero
    RequestQuotation != SealedWitness

**أوّلًا: المادّةُ الحاكمةُ غائبةٌ عن هذه الشجرة، وغيابُها مقيسٌ لا مقول.**
المرجعُ الضابطُ في الطلب ملفٌّ مُسمًّى بطولِ بايتاته (٦٧٣٬٥٣٧) وبختمه
(`360f7653…`)، ولا بايتةَ منه ههنا. فيُقاس الغيابُ بمحاولة فتح المسار
واشتقاقِ الختم، لا بقولٍ «ليس عندنا»
(`AN_ABSENCE_IS_MEASURED_BY_OPENING_THE_PATH_NOT_BY_SAYING_SO`).

**وثانيًا: ونقلُ النصّ في الشجرة ليس بايتاتِه المختومة.** في
`sentence_card_source_texts` نقلٌ بحروفه عن الجزء الثالث حالُ موضعه
«موضع_غير_متحقق»، وعليه تقوم `dalalat_thalath`. فذلك **نقلٌ مقروءٌ** لا
**بايتاتٌ مختومة**؛ ومن عدَّه ختمًا خلط رتبتين: رتبةَ القول المرويّ برتبة
البايتات التي تُفتَح
(`A_TRANSCRIPTION_IN_THE_TREE_IS_NOT_SEALED_BYTES`).

**وثالثًا: والاقتباسُ في الطلب نفسِه ليس شاهدًا.** نصوصُ القسمة في الطلب
منقولةٌ في الطلب، والطلبُ ليس حاويةً مختومة. فلو فُتِحت بها القنواتُ لكانت
الدعوى شاهدةً لنفسها، وهو عينُ ما يمنعه الشرطُ الرابع: «كلُّ زوجٍ بدليلٍ
حرفيٍّ من الحاوية المختومة»
(`A_QUOTATION_IN_THE_REQUEST_IS_NOT_A_SEALED_WITNESS`).

**ورابعًا: فالقنواتُ الثلاثُ مُقفَلةٌ، والإقفالُ غيرُ الخلوّ.** المقفلُ بابٌ
يُسمّى شرطُه ويُعرَف مفتاحُه: بايتاتُ ج٣ بختمها المُعلَن. فإذا وصلت انفتحت
القنواتُ بلا تعديل سطرٍ واحدٍ ههنا؛ وما دامت غائبةً فلا زوجَ يُخرَج
(`A_CLOSED_CHANNEL_IS_NOT_AN_EMPTY_RESULT`).

**وخامسًا: وكلُّ دالٍّ فحصَه الجسرُ يخرج «معلَّقًا» — والمعلَّقُ صنفٌ أوّل.**
لا يُستكمَل بتخمينٍ ولا يُحذَف: يُكتَب اسمُه، ودرجتُه غيرُ المستوفاة باسمها،
وشاهدٌ حرفيٌّ من مادّةٍ **مختومةٍ حاضرة** يُثبت أنّ الآلةَ قرأته
(`A_SUSPENDED_SIGNIFIER_IS_A_FIRST_CLASS_ROW_NOT_A_DROPPED_ONE`).

**وسادسًا: وفحصُ السمع يسبق الأرقام.** الدوالُّ المعلَّقةُ تُنتزَع من بايتات
مقاييس اللغة المختومة (`2c6000bd…`)، ومعها سطرُها الذي وُجدت فيه. فعدمُ
إخراجِ زوجٍ ليس عمى الآلة: هي تقرأ، وتُخرِج ما قرأت، وتقف عند البابٍ المقفل
(`THE_INSTRUMENT_IS_SHOWN_SIGHTED_BEFORE_ITS_ZERO_IS_READ`).

**وسابعًا: وصفرُ الانفصال بلغه الخلوُّ لا الانضباط.** «صفرُ زوجٍ جُمع فيه
الدالُّ والمدلولُ مفهومًا» متحقّقٌ ههنا، ولكن لأنّه لا زوجَ أصلًا. فيُعرَض
الرقمُ ومعه ما بلغه به، ولا يُقرأ ظفرًا بضبطٍ لم يُمتحَن
(`A_ZERO_REACHED_BY_VACANCY_IS_NOT_A_ZERO_EARNED`).

**وثامنًا: والخمسةُ ههنا غيرُ خمسة الطلب في الخامس.** القسمةُ المُبرهَنةُ في
`madlul_alone_formal` خامسُها «هذيان»، وخامسُ الطلب «لفظٌ مركّبٌ مهمَل».
والفصلُ بينهما لا يكون إلّا ببايتات ج٣، وهي غائبة؛ فيُسجَّل الخلافُ ولا
تُعاد التسميةُ صامتةً على وحدةٍ مُبرهَنة
(`THE_FIFTH_SECTION_IS_CONTESTED_AND_UNADJUDICABLE_HERE`).

**وتاسعًا: والمفهومُ لم يُبنَ.** لا نوعَ ههنا يجمع دالًّا ومدلولًا في كيانٍ
واحد، ولا تُستورَد قسمةُ «الدالّ والمدلول معًا» السباعيّة ولا يُستعمَل
حكمُها. والسطرُ مكتوبٌ صريحًا في `THE_DEFERRED_LINE`.

ولا سلطةَ لهذه الوحدة: لا ولادةَ، ولا حكمَ ولادةٍ، ولا تجميدَ `E0`، ولا
استيرادَ من `kernel/`، ولا تقرأ مخرجاتِها بوّابة.

المصدرُ المنهجيّ: «الشخصية الإسلامية» الجزء الثالث، تقي الدين النبهاني —
مُودَعٌ في `methodological_sources` بابًا ومنزلة؛ والإسنادُ إليه شرطُ نقلٍ لا
لطفَ عبارة.
"""

