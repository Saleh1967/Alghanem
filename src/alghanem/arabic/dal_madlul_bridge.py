"""القنواتُ الثلاثُ وأبوابُها؛ وكلُّها مشروطةٌ ببايتات المادّة الحاكمة.

وجملةُ التعريف **تُلتمَس في البايتات** ولا يُكتفى بحضور الملفّ: مادّةٌ حاضرةٌ
مختومةٌ لا تقع فيها جملةُ القناة لا تفتحها، فالختمُ يُثبت أيَّ بايتاتٍ هذه لا
ماذا فيها.
"""


@dataclass(frozen=True, slots=True)
class ChannelReading:
    """قراءةُ بابٍ: حالُه، وسببُ حاله، وما يُفتَح به إن أُغلِق."""

    gate: ChannelGate
    standing: ChannelStanding
    unmet_condition: str | None
    key_that_would_open_it: str

    @property
    def is_open(self) -> bool:
        return self.standing is ChannelStanding.OPEN


A_SEALED_CONTAINER_IS_READ_THROUGH_ITS_FORMAT_NOT_AS_RAW_BYTES: Final[str] = (
    "الختمُ يقع على بايتات الملفّ كما أُودِع، والقراءةُ تقع على نصّه: فملفُّ "
    "‎.docx‎ حاويةُ ZIP مضغوطة، وفكُّ بايتاتها الخام UTF-8 لا يُخرِج جملةً "
    "واحدةً من متنه — فتبقى القناةُ مقفلةً والمادّةُ حاضرةٌ مختومة. فيُقرأ "
    "‎word/document.xml‎ وتُنزَع وسومُه، ولا يُمسّ الختم."
)


def _sealed_material_text(path: Path) -> str:
    """نصُّ مادّةٍ مختومة: حاويةُ ‎.docx‎ تُفَكّ إلى متنها، وما سواها UTF-8."""

    data = path.read_bytes()
    if data[:2] == b"PK" and zipfile.is_zipfile(path):
        with zipfile.ZipFile(path) as archive:
            xml = archive.read("word/document.xml").decode("utf-8")
        return re.sub(r"<[^>]+>", "", xml)
    return data.decode("utf-8", errors="ignore")


def channel_readings(root: Path | None = None) -> tuple[ChannelReading, ...]:
    """حالُ القنوات الثلاث، مُشتقًّا من أختام المواد لا مكتوبًا في نثر."""

    readings_by_key = {reading.material.key: reading for reading in seal_readings(root)}
    channels: list[ChannelReading] = []
    for gate in THE_CHANNEL_GATES:
        seal = readings_by_key.get(gate.material_key)
        opened = False
        unmet: str | None = None
        if seal is None:
            unmet = f"لا مادّةَ مُعلَنةً بالمفتاح {gate.material_key}"
        elif not seal.is_readable:
            unmet = (
                f"{seal.material.title}: {seal.standing.value} — "
                f"فلا تُقرأ فيها جملةُ «{gate.defining_phrase}»"
            )
        else:
            text = _sealed_material_text(
                (root or _repository_root()) / seal.material.relative_path
            )
            opened = gate.defining_phrase in text
            if not opened:
                unmet = (
                    f"البايتاتُ مختومةٌ حاضرةٌ ولا تقع فيها جملةُ "
                    f"«{gate.defining_phrase}»"
                )
        channels.append(
            ChannelReading(
                gate=gate,
                standing=(
                    ChannelStanding.OPEN
                    if opened
                    else ChannelStanding.CLOSED_FOR_AN_UNSEALED_SOURCE
                ),
                unmet_condition=unmet,
                key_that_would_open_it=(
                    f"بايتاتُ «{gate.material_key}» بختمها المُعلَن، "
                    "تقع فيها جملةُ التعريف بحروفها"
                ),
            )
        )
    return tuple(channels)


def transcription_is_not_a_seal(
    root: Path | None = None,
) -> tuple[tuple[str, bool], ...]:
    """أتقع جملُ التعريف الثلاثُ في نقلِ الشجرة؟ وهل يرفع وقوعُها الإقفال؟

    تُلتمَس كلُّ جملةٍ في بايتات `sentence_card_source_texts` — وهي موضعُ
    النقل بحروفه — فيخرج عددٌ خام: ما وقع منها وما لم يقع. ووقوعُها **لا
    يفتح قناةً**، لأنّ ذلك النقلَ حالُ موضعه «موضع_غير_متحقق» فهو قولٌ
    مرويٌّ لا بايتاتٌ مختومة.
    """

    path = (
        (root or _repository_root())
        / "src"
        / "alghanem"
        / "arabic"
        / "sentence_card_source_texts.py"
    )
    if not path.is_file():
        raise DalMadlulBridgeError(
            "موضعُ النقل بحروفه غائبٌ عن الشجرة، فلا يُنقَل عنه نفيٌ ولا إثبات."
        )
    text = path.read_text(encoding="utf-8")
    return tuple(
        (gate.defining_phrase, gate.defining_phrase in text)
        for gate in THE_CHANNEL_GATES
    )


