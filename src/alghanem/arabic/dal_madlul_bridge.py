# --- الدوالُّ المعلَّقة ------------------------------------------------------

THE_SUSPENSION_SAMPLE_SIZE: Final[int] = 20
"""حجمُ العيّنة مُسمًّى قبل الرؤية؛ ولا يُوسَّع بعد قراءة نتيجتها."""

THE_SUSPENSION_SAMPLE_RULE: Final[str] = (
    "العيّنةُ أوّلُ عشرين قيمةَ `root_display` متمايزةً بترتيب ورودها في "
    "بايتات جدول المقاييس المختومة، ومعها صدرُ `body_text` كما ورد مقطوعًا "
    "عند `THE_WITNESS_CHARACTER_LIMIT` محرفًا. والترتيبُ ترتيبُ الملفّ لا "
    "ترتيبٌ اختِير بعد النظر، والحجمُ مكتوبٌ في `THE_SUSPENSION_SAMPLE_SIZE` "
    "قبل أن يُقرأ منه رقم"
)

THE_WITNESS_CHARACTER_LIMIT: Final[int] = 160
"""حدُّ قطعِ الشاهد محارفَ؛ والقطعُ اختصارُ عرضٍ لا تصرُّفٌ في البايتات.

فالمقطوعُ صدرُ النصّ كما هو، لا مُعادَ صياغتِه ولا مُنتقًى من وسطه بما يوافق
دعوى؛ ومن أراد تمامَه فتح البايتات المختومة عند صفّها.
"""


@dataclass(frozen=True, slots=True)
class SuspendedSignifier:
    """دالٌّ قرأه الجسرُ ولم يعرف مدلولَه: اسمُه، ودرجتُه، وشاهدُه الحرفيّ."""

    dal: str
    unmet_rung: str
    verbatim_witness: str
    sealed_source: str

    def __post_init__(self) -> None:
        for field_name in ("dal", "unmet_rung", "verbatim_witness", "sealed_source"):
            if not str(getattr(self, field_name)).strip():
                raise DalMadlulBridgeError(
                    "المعلَّقُ سطرٌ كاملٌ: دالٌّ، ودرجةٌ غيرُ مستوفاةٍ باسمها، "
                    "وشاهدٌ حرفيٌّ، ومصدرٌ مختوم؛ وناقصُ الحقول لا يُحفَظ."
                )


def suspended_signifiers(root: Path | None = None) -> tuple[SuspendedSignifier, ...]:
    """الدوالُّ المعلَّقة: تُنتزَع من مادّةٍ مختومةٍ حاضرة، وتُحفَظ بشواهدها.

    وهذه هي شهادةُ أنّ الآلةَ ليست عمياء: تقرأ بايتاتٍ مختومةً، وتُخرِج
    دوالَّ بأعيانها وسطورَها، ثمّ تقف عند البابٍ المقفل فلا تُخمِّن مدلولًا.
    وإذا غابت المادّةُ المختومةُ لم تُخرَج عيّنةٌ صامتةٌ فارغة، بل يُرفَع
    الرفضُ: فرقٌ بين «لا معلَّقَ» و«لم نقرأ».
    """

    readings_by_key = {reading.material.key: reading for reading in seal_readings(root)}
    origin = readings_by_key["MAQAYIS_BY_ROOT"]
    if not origin.is_readable:
        raise DalMadlulBridgeError(
            f"الأصلُ المعجميُّ {origin.standing.value}؛ ولا تُنتزَع دوالٌّ من "
            "مادّةٍ لم يُطابَق ختمُها."
        )
    unmet = _first_unmet_rung(root)
    seen: list[str] = []
    suspended: list[SuspendedSignifier] = []
    for row in root_table_rows(root):
        dal = row["root_display"].strip()
        witness = row["body_text"].strip()[:THE_WITNESS_CHARACTER_LIMIT].strip()
        if not dal or not witness or dal in seen:
            continue
        seen.append(dal)
        suspended.append(
            SuspendedSignifier(
                dal=dal,
                unmet_rung=unmet,
                verbatim_witness=witness,
                sealed_source=f"{origin.material.relative_path}@{origin.measured_sha256}",
            )
        )
        if len(suspended) == THE_SUSPENSION_SAMPLE_SIZE:
            break
    return tuple(suspended)


def _first_unmet_rung(root: Path | None = None) -> str:
    """أوّلُ شرطٍ غيرِ مستوفًى باسمه؛ وما بعده غيرُ منظورٍ فيه."""

    for reading in channel_readings(root):
        if not reading.is_open:
            return (
                f"قناةُ {reading.gate.kind.value} مقفلة — " f"{reading.unmet_condition}"
            )
    return "لا شرطَ غيرَ مستوفًى"


# --- الأزواج: لا زوجَ يُخرَج وبابٌ مقفل -------------------------------------


@dataclass(frozen=True, slots=True)
class BridgePair:
    """زوجُ جسرٍ بأركانه الستّة؛ ولا يُبنى إلّا وقناتُه مفتوحةٌ بختمها.

    ولا حقلَ ههنا يجمع الدالَّ والمدلولَ في كيانٍ ثالث: الحقلان اثنان
    متمايزان، والقناةُ بينهما وسمٌ لا وعاء. فبناءُ «المفهوم» ممتنعٌ بالبنية
    لا بالتحذير.
    """

    dal: str
    channel: DalalaKind
    madlul: str
    madlul_section: MadlulSection
    verbatim_evidence: str
    sealed_source: str

    def __post_init__(self) -> None:
        if not isinstance(self.channel, DalalaKind):
            raise DalMadlulBridgeError("قناةُ الزوج عضوٌ من `DalalaKind`.")
        if not isinstance(self.madlul_section, MadlulSection):
            raise DalMadlulBridgeError(
                "صنفُ المدلول عضوٌ من القسمة المُبرهَنة؛ والسكوتُ عنه ليس صنفًا."
            )
        for field_name in ("dal", "madlul", "verbatim_evidence", "sealed_source"):
            if not str(getattr(self, field_name)).strip():
                raise DalMadlulBridgeError(
                    "زوجٌ بلا دليلٍ حرفيٍّ أو بلا مصدرٍ مختومٍ دعوى لا شاهد."
                )


def bridge_pairs(root: Path | None = None) -> tuple[BridgePair, ...]:
    """الأزواجُ التي يُخرجها الجسر؛ ولا يُخرِج زوجًا وقناتُه مقفلة.

    ليست هذه «نتيجةً فارغة»: هي بابٌ مقفلٌ مُسمًّى شرطُه. ومتى وصلت بايتاتُ
    المادّة الحاكمة بختمها المُعلَن انفتحت القنواتُ بهذه الدالّة نفسِها.
    """

    if any(reading.is_open for reading in channel_readings(root)):
        raise DalMadlulBridgeError(
            "انفتحت قناةٌ ولم تُبنَ بعدُ آلةُ إخراج أزواجها؛ ولا يُخرَج زوجٌ "
            "بغير دليلٍ حرفيٍّ من حاويةٍ مختومة، فيُرفَع الرفضُ ولا يُخمَّن."
        )
    return ()


# --- المقاييس الأربعة، بأرقامها الخام ----------------------------------------


@dataclass(frozen=True, slots=True)
class BridgeMetrics:
    """المقاييسُ الأربعةُ المُسجَّلةُ قبل الرؤية، بأرقامها الخام وبقاياها."""

    dals_examined: int
    pairs_emitted: int
    suspended_count: int
    coverage_numerator: int
    coverage_denominator: int
    audited_sample_size: int
    truthful_in_sample: int | None
    sectioned_with_written_evidence: int
    concept_joins: int

    @property
    def coverage(self) -> float | None:
        """التغطية: نسبةُ الدوالّ التي لها مدلولُ مطابقةٍ واحدٌ على الأقلّ."""

        if self.coverage_denominator == 0:
            return None
        return self.coverage_numerator / self.coverage_denominator

    @property
    def truth_rate(self) -> float | None:
        """الصدق: لا يُقرأ من عيّنةٍ فارغة؛ فالعدمُ عدمُ قياسٍ لا مئةٌ بالمئة."""

        if self.audited_sample_size == 0 or self.truthful_in_sample is None:
            return None
        return self.truthful_in_sample / self.audited_sample_size

    @property
    def section_discipline(self) -> float | None:
        """انضباطُ الأقسام: نسبةُ المداليل الموسومة بقرينةٍ مكتوبة."""

        if self.pairs_emitted == 0:
            return None
        return self.sectioned_with_written_evidence / self.pairs_emitted

    @property
    def separation_holds(self) -> bool:
        """الانفصال: صفرُ زوجٍ جُمع فيه الدالُّ والمدلولُ مفهومًا."""

        return self.concept_joins == 0

    @property
    def the_zero_was_reached_by_vacancy(self) -> bool:
        """أبلغ الصفرَ خلوٌّ أم انضباطٌ مُمتحَن؟ يُعرَض ولا يُطوى."""

        return self.separation_holds and self.pairs_emitted == 0


def bridge_metrics(root: Path | None = None) -> BridgeMetrics:
    """المقاييسُ مُشتقّةً من القراءة عند كلِّ تشغيل، لا منقولةً من نثر."""

    pairs = bridge_pairs(root)
    suspended = suspended_signifiers(root)
    return BridgeMetrics(
        dals_examined=len(suspended),
        pairs_emitted=len(pairs),
        suspended_count=len(suspended),
        coverage_numerator=sum(
            1 for pair in pairs if pair.channel is DalalaKind.مطابقة
        ),
        coverage_denominator=len(suspended),
        audited_sample_size=len(pairs),
        truthful_in_sample=None,
        sectioned_with_written_evidence=sum(
            1 for pair in pairs if pair.verbatim_evidence.strip()
        ),
        concept_joins=0,
    )


# --- سجلُّ الجسر: سطرٌ لكلّ واقعة ---------------------------------------------


