@dataclass(frozen=True)
class DecisionAxis:
    """محورُ قرارٍ في برهانٍ مبنيّ، بنصّه وحمولته المسنونة."""

    module: str
    label: str
    question: str
    load: AxisLoad
    why: str

    def __post_init__(self) -> None:
        for value, complaint in (
            (self.module, "محورٌ بلا وحدةٍ لا يُقابَل ببايتات."),
            (self.label, "محورٌ بلا وسمٍ لا يُميَّز عن أخيه."),
            (self.question, "محورٌ بلا نصِّ سؤالٍ نقلٌ مبهَم."),
            (self.why, "حمولةٌ بلا تعليلٍ حكمٌ بلا فاتورة."),
        ):
            if not value.strip():
                raise DalAloneBridgeError(complaint)


