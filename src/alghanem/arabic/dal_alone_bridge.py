def _arabic_package() -> Path:
    return Path(__file__).resolve().parent


def _module_bytes(module: str) -> str | None:
    path = _arabic_package() / f"{module}.py"
    if not path.is_file():
        return None
    return path.read_text(encoding="utf-8")


@dataclass(frozen=True)
class SidesReading:
    """قراءةُ الأضلاع الثلاثة عن القرص: المبنيُّ منها والخالي."""

    built: tuple[str, ...]
    vacant: tuple[str, ...]

    @property
    def standings(self) -> tuple[tuple[str, SideStanding], ...]:
        return tuple(
            (side.name, SideStanding.BUILT_AS_A_FORMAL_PROOF)
            if side.name in self.built
            else (side.name, SideStanding.VACANT_IN_THIS_TREE)
            for side in THE_SIDES
        )


def sides_reading() -> SidesReading:
    """أيُّ أضلاع الثلاثيّة مبنيٌّ وأيُّها خالٍ؟ يُلتمَس ملفُّ كلٍّ منها.

    والالتماسُ لا يكتفي بوجود ملفٍّ باسمه: يُشترَط أن تحمل بايتاتُه حدَّ
    البرهان بحروفه، فملفٌّ باسم الضلع بلا برهانٍ فيه لا يسدّ الضلع.
    """

    built: list[str] = []
    vacant: list[str] = []
    seal = THE_SHAPE_INVARIANTS[0][1]
    for side in THE_SIDES:
        text = _module_bytes(side.module)
        if text is not None and seal in text:
            built.append(side.name)
        else:
            vacant.append(side.name)
    return SidesReading(built=tuple(built), vacant=tuple(vacant))


def axis_transcription_drift() -> tuple[DecisionAxis, ...]:
    """المحاورُ التي لا يوجد نصُّ سؤالها في بايتات وحدتها؛ سندُ القاعدة المسنونة."""

    drifted: list[DecisionAxis] = []
    for axis in THE_TRANSCRIBED_AXES:
        text = _module_bytes(axis.module)
        if text is None or axis.question not in text:
            drifted.append(axis)
    return tuple(drifted)


def load_census() -> tuple[tuple[str, int, int], ...]:
    """لكلِّ برهانٍ ذي محاورَ مُعلَنة: كم محورًا له، وكم منها من الدالّ وحدَه.

    وهذا هو حملُ الجسر: إن كان الثاني لا يفصل فروعَ الأوّل، لم يكن ضلعُ
    الدالّ إسقاطًا لما بُني، بل مادّةً تُطلَب.
    """

    modules: list[str] = []
    for axis in THE_TRANSCRIBED_AXES:
        if axis.module not in modules:
            modules.append(axis.module)
    census: list[tuple[str, int, int]] = []
    for module in modules:
        axes = [axis for axis in THE_TRANSCRIBED_AXES if axis.module == module]
        alone = [
            axis for axis in axes if axis.load is AxisLoad.FROM_THE_SIGNIFIER_ALONE
        ]
        census.append((module, len(axes), len(alone)))
    return tuple(census)


@dataclass(frozen=True)
class InvariantCensus:
    """لازمُ شكلٍ وحاملوه من البراهين المبنيّة، بأعيانهم لا بعددهم وحدَه."""

    name: str
    marker: str
    carriers: tuple[str, ...]

    @property
    def is_carried_by_every_built_proof(self) -> bool:
        return set(self.carriers) == set(THE_BUILT_PROOFS)


def invariant_census() -> tuple[InvariantCensus, ...]:
    """أيُّ لوازم الشكل حملتها البراهينُ كلُّها، وأيُّها حملَه بعضُها؟"""

    readings: list[InvariantCensus] = []
    for name, marker in THE_SHAPE_INVARIANTS:
        carriers = tuple(
            module
            for module in THE_BUILT_PROOFS
            if (text := _module_bytes(module)) is not None and marker in text
        )
        readings.append(InvariantCensus(name=name, marker=marker, carriers=carriers))
    return tuple(readings)


def the_seven_are_by_both() -> bool:
    """أجملةُ الحصر السبعيّة بالطرفين معًا؟ تُقرأ من بايتات وحدتها لا تُنقَل.

    ولو نُقِلت الجملةُ ههنا لصارت الدعوى شاهدةً لنفسها؛ فتُقرأ هناك.
    """

    text = _module_bytes("lafz_madlul_relation_formal")
    if text is None:
        raise DalAloneBridgeError("وحدةُ جملة الحصر غائبةٌ، فلا تُقرأ منها الجملة.")
    opening = "ينقسم اللفظ باعتبار الدال"
    index = text.find(opening)
    if index < 0:
        raise DalAloneBridgeError("جملةُ الحصر غائبةٌ عن بايتات وحدتها.")
    return "والمدلول" in text[index : index + len(opening) + 12]


@dataclass(frozen=True)
class MaterialScan:
    """نتيجةُ مسحِ الكتاب الحاضر عن مادّة الضلع الخالي، بانحيازها مُعلَنًا."""

    book: str
    extracted_arabic_runs: int
    marker_hits: tuple[tuple[str, int], ...]
    near_miss_hits: int

    @property
    def the_extractor_is_not_blind(self) -> bool:
        """الشاهدُ الموجِب: أخرجت الآلةُ عربيّةً كثيرةً ووجدت الاقتراب."""

        return self.extracted_arabic_runs > 1000 and self.near_miss_hits > 0

    @property
    def carries_the_division(self) -> bool:
        return any(count for _, count in self.marker_hits)


def _scanned_book_path() -> Path:
    return _arabic_package().parents[2] / THE_SCANNED_BOOK


def material_scan() -> MaterialScan:
    """أيحمل الكتابُ الحاضرُ قسمةَ الدالّ وحدَه؟ يُمسَح ولا يُفترَض.

    والاستخراجُ خشنٌ مُعلَنُ الخشونة، فيُخرَج معه شاهدُه الموجِب: عددُ ما
    استُخرج من كلمٍ عربيّ، وعددُ مواضع اللفظ القريب. فبهما يُعلَم أنّ عدمَ
    وجدان القسمة عدمُ وجودٍ في المستخرَج لا عجزٌ عن القراءة.
    """

    path = _scanned_book_path()
    if not path.is_file():
        raise DalAloneBridgeError(
            "الكتابُ المُعلَن مسحُه غائبٌ عن موضعه، فلا يُنقَل عنه نفيٌ ولا إثبات."
        )
    text = path.read_bytes().decode("utf-16-le", errors="ignore")
    runs = len(re.findall(r"[\u0621-\u064a]{3,}", text))
    hits = tuple((marker, text.count(marker)) for marker in THE_DIVISION_MARKERS)
    return MaterialScan(
        book=THE_SCANNED_BOOK,
        extracted_arabic_runs=runs,
        marker_hits=hits,
        near_miss_hits=text.count(THE_NEAR_MISS),
    )
