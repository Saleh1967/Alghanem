"""جسرٌ بين البرهان الصوريّ والدالّ وحدَه، وموصولٌ بجسر المدلول وحدَه.

الطلبُ كان: «ابنِ جسرًا بين البرهان والدالّ وحدَه كما بنيناه وفق قواعد
النبهاني، واربطه بجسر المدلول وحدَه». وهذه الوحدة تفعل منه ما تكفيه بايتاتُ
هذه الشجرة، وتُسمّي ما لا تكفيه::

    BuiltSide        != DeclaredSide
    AxisLoad         != AxisAnswer
    ShapeOnTwo       != ShapeOfTheGenus
    SignifierChapter != SignifierSide

**ثلاثيّةُ النبهاني ثلاثةُ أضلاع، والمبنيُّ منها ضلعان.** في «الشخصية
الإسلامية» يُقسَم اللفظ باعتبار المدلول وحدَه، وباعتبار الدالّ والمدلول معًا،
وهذان مبنيّان في هذه الشجرة برهانَين صوريَّين شاملَين على نطاقٍ محدود. أمّا
الضلعُ الثالث — الدالُّ وحدَه — فليس في الشجرة وحدةٌ تحمله، وخلوُّه **يُقاس**
بوجود ملفَّي الضلعَين وغياب ملفِّه، لا يُقال قولًا
(`THE_THIRD_SIDE_IS_VACANT_AND_ITS_VACANCY_IS_MEASURED`).

**وجملةُ الحصر السبعيّة ليست في الدالّ وحدَه.** جملةُ المصدر المنقولةُ في
`lafz_madlul_relation_formal` تجعل القسمةَ «باعتبار الدالّ **والمدلول**»،
فالأقسامُ المحصورةُ هناك قسمةٌ بالطرفين معًا، ومن حسبها قسمةَ الدالّ وحدَه نسب
إلى المصدر ما لم يقله. ولا تُنقَل تلك الجملةُ ههنا حرفًا — فنقلُها يجعل الدعوى
شاهدةً لنفسها — بل تُقرأ من بايتات وحدتها ويُلتمَس فيها لفظُ المدلول
(`THE_SEVEN_ARE_BY_BOTH_NOT_BY_THE_SIGNIFIER_ALONE`).

**والجسرُ يقيس حمولةَ المحاور لا يُصدِر برهانًا.** لكلِّ برهانٍ مبنيٍّ محاورُ
قرارٍ مُعلَنةٌ بنصّها، ولكلِّ محورٍ **حمولةٌ**: أيُجاب عنه من الدالّ وحدَه، أم
لا يُجاب إلّا بمدلول، أم يحتاجهما معًا؟ فإن كانت المحاورُ المُجابةُ من الدالّ
وحدَه لا تكفي لفصل فروع برهانٍ قائم، لم يكن ضلعُ الدالّ إسقاطًا لبرهانٍ مبنيٍّ
بل مادّةً جديدةً تُطلَب
(`A_PROJECTION_OF_A_BUILT_PROOF_IS_NOT_A_NEW_PROOF`).

**وتصنيفُ الحمولة قاعدةٌ تُسَنُّ ههنا لا خاصّيّةٌ تُقرأ**، على منوال
`NORMALISATION_IS_A_RULE_ENACTED_NOT_A_FACT_READ` في جسر رسم الجذور. فهي
مكتوبةٌ بيدٍ، ولذلك لا يمرّ محورٌ بلا **نصِّ سؤاله بحروفه**، ويُقابَل ذلك النصُّ
ببايتات وحدته على القرص؛ فإن نزاح النقلُ سقط الجسرُ ولم يمضِ صامتًا
(`AN_AXIS_CLASSIFICATION_IS_ENACTED_HERE_NOT_READ`).

**ولوازمُ الشكل تُقاس على البراهين ولا تُشترَط عليها.** يُلتمَس كلُّ لازمٍ في
بايتات البراهين الأربعة فيُعلَم حاملُه من غيرِ حامله. وثلاثةٌ منها حملتها
الأربعةُ جميعًا، وواحدٌ حملَه اثنان لا غير — فهذا الأخيرُ شكلُ وحدتَين لا شكلُ
الجنس، ومن عمّمه على البرهان اشترط على الضلع الثالث ما لم يلتزمه نصفُ ما قبله
(`A_SHAPE_CARRIED_BY_SOME_IS_NOT_A_SHAPE_OF_THE_GENUS`).

**وحارسُ اشتراكٍ لفظيّ**: في هذه الشجرة وحدةٌ اسمها `dal_alone_gloss` وعنوانُها
«الدالُّ وحدَه»، وليست هذه الضلعَ ولا طرفًا منه: تلك وسمُ **بابِ حرف الدال** في
مقاييس اللغة، جنسُها مدخلُ جذرٍ في معجم؛ وهذه قسمةُ **الطرف الدالّ** من طرفَي
الدلالة. واتّحادُ اللفظين لا يُوحِّد الجنسين، وهو عينُ ما تقرّر هناك بـ
`A_SURFACE_SEGMENT_IS_NOT_A_ROOT_ENTRY`، وعينُ قاعدة القياس المقيَّد بالجنس
الواحد (`THE_DAL_CHAPTER_GLOSS_IS_A_HOMONYM_NOT_THIS_SIDE`).

**والخلوُّ مسحٌ جرى لا بحثٌ غاب.** لا يكفي أن يُقال «ليس في الشجرة ملفُّ
الضلع»: طُلِبت مادّتُه فيما بين أيدينا من بايتات النبهاني، فكانت الحجّةُ
ساقَين. الأولى: **الكتابُ الحاملُ للقسمة غائبٌ عن هذه الشجرة أصلًا** — القسمةُ
في «الشخصية الإسلامية» الجزء الثالث، ولا بايتَ منه ههنا، وإنّما فيها كتابٌ
آخرُ له. والثانية: ذلك الكتابُ الحاضرُ **مُسِح** فلم يقع فيه لفظُ القسمة ولا
جملةُ حصرها (`THE_VACANCY_SURVIVED_A_SCAN_AND_IS_NOT_A_SILENCE`).

**والمسحُ مُنحازٌ إلى عدم الوجدان، فيُعلَن انحيازُه ويُضبَط.** استخراجُ النصّ
من مستندٍ مُركَّبٍ استخراجٌ خشن: ما فاته من البايتات يُقرأ عدمَ وجدانٍ وهو عدمُ
قراءة، فالانحيازُ إلى تقوية النفي لا إلى تضعيفه
(`A_CRUDE_EXTRACTION_BIASES_A_NEGATIVE_TOWARD_ITSELF`). ولذلك لا يُعتمَد النفيُ
حتّى يجتاز **شاهدًا موجِبًا**: يُعَدُّ ما استُخرج من كلمٍ عربيٍّ فيكون كثيرًا،
ويُلتمَس فيه لفظٌ قريبٌ من المطلوب فيوجد. فالآلةُ ليست عمياء، وعدمُ وجدانها
القسمةَ عدمُ وجودٍ في المستخرَج لا عجزٌ عن القراءة.

**والاقترابُ يُسمّى ولا يُعَدُّ وجدانًا**: في الكتاب الحاضر مواضعُ فيها لفظُ
المدلول، وهي في سياق تصوُّر واقع الفكرة لا في قسمة اللفظ؛ وعددُها يُخرجه
`material_scan` ولا يُنقَل ههنا رقمًا. فلا تُحسَب مادّةً للضلع، ولا تُطوى
فيُقال «لا ذكرَ للمدلول فيه»
(`A_NEAR_MISS_IS_NAMED_AND_NOT_COUNTED_AS_A_FINDING`).

**وما يُخرجه هذا الجسر أعدادٌ عن هذه الشجرة لا عن اللغة**: عددُ المحاور،
وحاملُ اللازم، وحضورُ ملفٍّ وغيابُه. فليس فيه رقمٌ عن عربيّةٍ ولا عن مدوّنة،
ولا يُقرأ منه حكمٌ على لفظٍ واحد
(`THIS_BRIDGE_MEASURES_THE_TREE_NOT_THE_LANGUAGE`).

**خمولٌ سلطويّ**: لا ولادةَ هنا ولا حكمَ ولادةٍ ولا تجميدَ `E0`، ولا استيرادَ
من `kernel/`، ولا تُرفَع بهذه الوحدة منزلةٌ محجوزة، ولا تقرأ مخرجاتِها بوّابةٌ.

المصدر المنهجيّ: «الشخصية الإسلامية» الجزء الثالث، تقي الدين النبهاني —
مُودَعٌ في `methodological_sources` بابًا ومنزلة؛ والإسنادُ إليه شرطُ نقلٍ لا
لطفَ عبارة.
"""

