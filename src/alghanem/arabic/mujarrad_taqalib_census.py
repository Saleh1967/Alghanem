class ForbiddingRule(Enum):
    """قواعدُ الامتناع المُعلَنة، وكلتاهما حسّاسةٌ للترتيب فتُفرِّق داخلَ المدار."""

    FA_EQUALS_AYN = "لا تتماثل الفاءُ والعين"
    ADJACENT_SHARED_MAKHRAJ = "لا يتجاور حرفان مختلفان من مخرجٍ واحد"


def _forbids(rule: ForbiddingRule, form: str) -> bool:
    if rule is ForbiddingRule.FA_EQUALS_AYN:
        return len(form) >= 2 and form[0] == form[1]
    return any(
        form[index] != form[index + 1]
        and CLASSICAL_ORDINAL.get(form[index]) is not None
        and CLASSICAL_ORDINAL.get(form[index]) == CLASSICAL_ORDINAL.get(form[index + 1])
        for index in range(len(form) - 1)
    )


def forbidding_rules_against(form: str) -> tuple[ForbiddingRule, ...]:
    """أيُّ القواعد المُعلَنة تمنع هذه الصورة؟ تُسمّى كلُّها ولا تُدمَج في حكم."""

    if not form:
        raise MujarradTaqalibError("صورةٌ فارغةٌ لا تُفحَص.")
    return tuple(rule for rule in ForbiddingRule if _forbids(rule, form))


class UsageWarrant(Enum):
    """مُستنَدُ الاستعمال. والقياسُ مرفوضٌ ههنا لغياب إيداعِ قاعدةٍ تُرخِّصه."""

    SAMA_IN_THE_SEALED_LEXICON = "سماعٌ: واقعٌ في الجرد المختوم"
    QIYAS_REFUSED_FOR_ABSENT_RULE_DEPOSIT = "قياسٌ مرفوض: لا قاعدةَ مُودَعةٌ ترخّصه"


class CellStanding(Enum):
    """منزلةُ خليّةِ تقليبٍ واحدة. والمهملُ بقيّةٌ بعد الممنوع لا صنفٌ بقاعدة."""

    USED_UNFORBIDDEN = "مستعملٌ لا تمنعه قاعدة"
    USED_THOUGH_FORBIDDEN = "مستعملٌ تمنعه قاعدةٌ فتنتقض القاعدة"
    FORBIDDEN_AND_UNUSED = "ممنوعٌ بقاعدةٍ ولم يُستعمل"
    MUHMAL = "مهملٌ: لا قاعدةَ تمنعه ولم يُستعمل"


def classify_cell(form: str, used: bool) -> CellStanding:
    """منزلةُ الخليّة مُشتقّةٌ من القواعد ومن الاستعمال معًا، لا تُملى باليد."""

    forbidden = bool(forbidding_rules_against(form))
    if used:
        return (
            CellStanding.USED_THOUGH_FORBIDDEN
            if forbidden
            else CellStanding.USED_UNFORBIDDEN
        )
    return CellStanding.FORBIDDEN_AND_UNUSED if forbidden else CellStanding.MUHMAL


def _used_forms(class_names: tuple[str, ...], root: Path | None) -> frozenset[str]:
    return frozenset(
        fold_root(row["root_full"])
        for row in root_table_rows(root)
        if row["root_type"] in class_names and row["root_full"]
    )


@dataclass(frozen=True, slots=True)
class OrbitReading:
    """مدارٌ واحد: حروفُه مرتَّبةً، وفضاؤه، ومنزلةُ كلِّ خليّةٍ فيه."""

    letters: str
    space: int
    used: tuple[str, ...]
    standings: MappingProxyType[str, CellStanding]

    def __post_init__(self) -> None:
        if self.space != len(self.standings):
            raise MujarradTaqalibError("فضاءُ المدار لا يطابق عددَ خلاياه المُصنَّفة.")
        if len(self.used) > self.space:
            raise MujarradTaqalibError("المستعملُ لا يزيد على فضاء مداره.")

    @property
    def unused(self) -> int:
        """الخالي من خلايا المدار؛ وهو ممنوعٌ ومهملٌ معًا لا مهملٌ وحدَه."""

        return self.space - len(self.used)


def orbit_readings(
    class_names: tuple[str, ...] = THE_LETTER_CLASSES_READ_HERE,
    root: Path | None = None,
) -> tuple[OrbitReading, ...]:
    """مداراتُ الجرد المختوم، مرتَّبةً بحروفها، وكلُّ خليّةٍ بمنزلتها."""

    used = _used_forms(class_names, root)
    orbits: dict[str, set[str]] = {}
    for form in used:
        orbits.setdefault("".join(sorted(form)), set()).add(form)
    readings = []
    for letters in sorted(orbits):
        cells = {"".join(order) for order in permutations(letters)}
        occupied = orbits[letters]
        readings.append(
            OrbitReading(
                letters=letters,
                space=multiset_permutation_count(letters),
                used=tuple(sorted(occupied)),
                standings=MappingProxyType(
                    {
                        cell: classify_cell(cell, cell in occupied)
                        for cell in sorted(cells)
                    }
                ),
            )
        )
    return tuple(readings)


@dataclass(frozen=True, slots=True)
class TaqalibCensus:
    """جملةُ محور المقلوب: مداراتٌ وفضاءٌ وتقسيمُ المنازل الأربع."""

    orbits: int
    space: int
    used_unforbidden: int
    used_though_forbidden: int
    forbidden_and_unused: int
    muhmal: int

    def __post_init__(self) -> None:
        parts = (
            self.used_unforbidden,
            self.used_though_forbidden,
            self.forbidden_and_unused,
            self.muhmal,
        )
        for value in (self.orbits, self.space, *parts):
            if isinstance(value, bool) or not isinstance(value, int) or value < 0:
                raise MujarradTaqalibError("عددٌ في الإحصاء صحيحٌ غيرُ سالب.")
        if sum(parts) != self.space:
            raise MujarradTaqalibError(
                "المنازلُ الأربعُ لا تستوفي الفضاء؛ وإحصاءٌ لا يُجمَع ليس قسمة."
            )

    @property
    def used(self) -> int:
        """جملةُ المستعمل: الممنوعُ منه محسوبٌ معه، فلا يسقط نقضُ القاعدة."""

        return self.used_unforbidden + self.used_though_forbidden


def taqalib_census(
    class_names: tuple[str, ...] = THE_LETTER_CLASSES_READ_HERE,
    root: Path | None = None,
) -> TaqalibCensus:
    """إحصاءُ المقلوب على البايتات المختومة، مُعادَ الاشتقاق في كلِّ نداء."""

    tally: Counter[CellStanding] = Counter()
    readings = orbit_readings(class_names, root)
    for reading in readings:
        tally.update(reading.standings.values())
    return TaqalibCensus(
        orbits=len(readings),
        space=sum(reading.space for reading in readings),
        used_unforbidden=tally[CellStanding.USED_UNFORBIDDEN],
        used_though_forbidden=tally[CellStanding.USED_THOUGH_FORBIDDEN],
        forbidden_and_unused=tally[CellStanding.FORBIDDEN_AND_UNUSED],
        muhmal=tally[CellStanding.MUHMAL],
    )


@dataclass(frozen=True, slots=True)
class RulePrice:
    """ثمنُ قاعدةِ امتناعٍ مقيسًا: خلاياها، ومستعملُها، ونسبتا الاستعمال."""

    rule: ForbiddingRule
    cells: int
    used_inside: int
    cells_outside: int
    used_outside: int

    def __post_init__(self) -> None:
        if self.cells < 1 or self.cells_outside < 1:
            raise MujarradTaqalibError("قاعدةٌ بلا خلايا داخلَها أو خارجَها لا تُسعَّر.")
        if self.used_inside > self.cells or self.used_outside > self.cells_outside:
            raise MujarradTaqalibError("المستعملُ لا يزيد على خلاياه.")

    @property
    def is_refuted_as_an_impossibility(self) -> bool:
        """امتناعٌ وقع فيه مستعملٌ واحدٌ منقوضٌ امتناعًا؛ والميلُ يبقى بنسبته."""

        return self.used_inside > 0

    @property
    def usage_rate_inside(self) -> float:
        """نسبةُ الاستعمال داخلَ خلايا القاعدة؛ تُخرَج معها نسبةُ الخارج دائمًا."""

        return self.used_inside / self.cells

    @property
    def usage_rate_outside(self) -> float:
        """نسبةُ الاستعمال خارجَها؛ وبدونها لا تُقرأ نسبةُ الداخل شيئًا."""

        return self.used_outside / self.cells_outside

    @property
    def warrant_of_the_used(self) -> UsageWarrant:
        """مُستنَدُ المستعمل داخلَ الممنوع: سماعٌ ههنا، ولا قياسَ يُمنَح."""

        if self.used_inside == 0:
            return UsageWarrant.QIYAS_REFUSED_FOR_ABSENT_RULE_DEPOSIT
        return UsageWarrant.SAMA_IN_THE_SEALED_LEXICON


def rule_prices(
    class_names: tuple[str, ...] = THE_LETTER_CLASSES_READ_HERE,
    root: Path | None = None,
) -> tuple[RulePrice, ...]:
    """ثمنُ كلِّ قاعدةٍ على حدةٍ، مقيسًا على الفضاء كلِّه لا على عيّنة."""

    readings = orbit_readings(class_names, root)
    prices = []
    for rule in ForbiddingRule:
        inside = used_inside = outside = used_outside = 0
        for reading in readings:
            occupied = set(reading.used)
            for cell in reading.standings:
                if _forbids(rule, cell):
                    inside += 1
                    used_inside += cell in occupied
                else:
                    outside += 1
                    used_outside += cell in occupied
        prices.append(
            RulePrice(
                rule=rule,
                cells=inside,
                used_inside=used_inside,
                cells_outside=outside,
                used_outside=used_outside,
            )
        )
    return tuple(prices)


@dataclass(frozen=True, slots=True)
class ClassCollision:
    """صورةٌ مطويّةٌ يدّعيها أكثرُ من صنف، أو أكثرُ من صورةٍ داخلَ صنفٍ واحد."""

    folded_form: str
    classes: tuple[str, ...]
    written_forms: tuple[str, ...]

    def __post_init__(self) -> None:
        if not self.folded_form:
            raise MujarradTaqalibError("تصادمٌ بلا صورةٍ مطويّةٍ ليس تصادمًا.")

    @property
    def crosses_two_classes(self) -> bool:
        """هل خالف الشرطَ المطلوب؟ الشرطُ على الأصناف لا على الصور المكتوبة."""

        return len(self.classes) > 1


def class_collisions(root: Path | None = None) -> tuple[ClassCollision, ...]:
    """تصادماتُ الطيّ: عبرَ الأصناف وداخلَها معًا، فيُقرأ صفرُ العبور خلوًّا."""

    seen: dict[str, tuple[set[str], set[str]]] = {}
    for row in root_table_rows(root):
        written = row["root_full"]
        if not written or row["root_type"] not in (
            *THE_LETTER_CLASSES_READ_HERE,
            THE_QUADRILATERAL_CLASS,
        ):
            continue
        classes, forms = seen.setdefault(fold_root(written), (set(), set()))
        classes.add(row["root_type"])
        forms.add(written)
    return tuple(
        ClassCollision(
            folded_form=folded,
            classes=tuple(sorted(classes)),
            written_forms=tuple(sorted(forms)),
        )
        for folded, (classes, forms) in sorted(seen.items())
        if len(classes) > 1 or len(forms) > 1
    )


def quadrilateral_readings(root: Path | None = None) -> tuple[OrbitReading, ...]:
    """مداراتُ الرباعيّ في الجرد؛ تُخرَج ولو خلت، ولا يُحذَف صفُّها."""

    return orbit_readings((THE_QUADRILATERAL_CLASS,), root)


