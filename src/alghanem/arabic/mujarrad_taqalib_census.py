def fold_root(root: str) -> str:
    """صورةُ الجذر بعد الطيّ المُعلَن؛ والطيُّ بنودٌ مكتوبةٌ لا عادةُ قارئ."""

    if not root:
        raise MujarradTaqalibError("جذرٌ فارغٌ لا يُطوى ولا يُعَدّ.")
    return "".join(THE_DECLARED_FOLD.get(letter, letter) for letter in root)


def multiset_permutation_count(letters: str) -> int:
    """فضاءُ تقاليب الحروف: `n! / ∏ mᵢ!`، فالمكرَّرُ لا يُعَدّ مرّتين.

    والتباديلُ دون تكرارٍ تُسقِط أبنيةً هنا: جذرٌ حرفاه متماثلان فضاؤه ثلاثةٌ
    لا ستّة، ومن عدّه ستّةً عدَّ صورةً واحدةً مرّتين.
    """

    if not letters:
        raise MujarradTaqalibError("فضاءُ تقاليبِ لا شيءَ ليس عددًا.")
    space = math.factorial(len(letters))
    for repetition in Counter(letters).values():
        space //= math.factorial(repetition)
    return space


class RungWarrant(Enum):
    """منزلةُ القيد الذي قطع الدرجة؛ والمنقولُ لا يُقرأ مقيسًا."""

    DERIVED_BY_COUNTING = "قيدٌ حسابيٌّ يُعاد اشتقاقُه"
    TRANSCRIBED_NOT_MEASURED = "قيدٌ منقولٌ من التقسيم المشهور لا مقيسٌ ههنا"


@dataclass(frozen=True, slots=True)
class WaznRung:
    """درجةٌ من سُلَّم التخصّص: سعتُها، وقيدُها، ومنزلةُ القيد."""

    name: str
    cells: int
    constraint: str
    warrant: RungWarrant

    def __post_init__(self) -> None:
        if not self.name.strip() or not self.constraint.strip():
            raise MujarradTaqalibError("درجةٌ بلا اسمٍ أو بلا قيدٍ مكتوبٍ ليست درجة.")
        if isinstance(self.cells, bool) or not isinstance(self.cells, int):
            raise MujarradTaqalibError("سعةُ الدرجة عددٌ صحيح.")
        if self.cells < 1:
            raise MujarradTaqalibError("سعةٌ غيرُ موجبةٍ ليست سعة.")
        if not isinstance(self.warrant, RungWarrant):
            raise MujarradTaqalibError("منزلةُ القيد عضوٌ في `RungWarrant` المغلقة.")


