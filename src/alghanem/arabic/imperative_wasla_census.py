"""قياسُ همزة الوصل في الأمر المجرَّد على البايتات المُبصَّمة، تحت القواعد الأربع.

هذا تشغيلُ `imperative_wasla_specification` لا تعديلٌ له: لا قاعدةَ حُذفت، ولا
بذرةَ بُدِّلت، ولا محرفَ أُضيف إلى قراءة همزة الوصل. وكلُّ رقمٍ هنا مربوطٌ
ببصمةِ تلك المواصفة، ومنزلتُها `مُصاغة_بعد_الرقم` مُعلَنةٌ لا مطويّة.

**والثابتُ تحت القواعد الأربع جميعًا شيئان، وهما خبرٌ عن البايتات**: الأجوفُ
لا تدخله همزةُ وصلٍ واحدةٌ البتّة (صفرٌ من ٤٢٥ إلى ٤٤٥ مقطعًا بحسب القاعدة)،
والمثالُ كذلك (صفرٌ من ٣٨ إلى ٩٩، إلّا موضعًا واحدًا يظهر حين تُعَدُّ الهمزةُ
علّةً). وهذان الصفران **لا يتبدّلان بتبدّل القاعدة**، فهما أقوى ما في الباب.

**والمتبدِّلُ نسبةُ السالم، وتبدُّلها هو النتيجة لا حاشيتها**: ٨٤٫٤٪ حين
تُقصَر العلّةُ على الواو والياء، و١٠٠٪ حين تُعَدُّ الهمزةُ علّةً ويُفرَد
المضاعف. **فالرقمُ الوارد (٩٦٫٩٪) لا يخرج إلّا بمُصادَرةٍ تخلط المهموزَ
بالمعتلّ**، وهي مُصادَرةٌ مُعلَنةٌ في المواصفة لا مدسوسةٌ في العدّ. ومن نقل
رقمًا واحدًا من هذا الجدول بلا اسم قاعدته نقل نصفَ الخبر.

`THE_SOUND_EXCEPTIONS_WERE_ALL_ONE_THING`: الاستثناءاتُ الأربعةَ عشرَ في
السالم — تحت قاعدة «علّة وهمزة» — **كلُّها مضاعفةٌ بلا واحدةٍ خارجة**: رُدُّوا،
كُفُّوا، لُمَّ، هُزِّي، قَرِّي، قُصِّي، صُبُّوا، شُدُّوا، فِرُّوا، غُلُّوا. فليست
أخطاءَ تصنيفٍ ولا شذوذًا، بل بابٌ واحدٌ لم يُفرَد. وإفرادُه يُخرِج السالمَ إلى
**٤٩٣ من ٤٩٣ بلا استثناءٍ واحد**.

`THE_MECHANISM_WAS_TESTED_INSIDE_ONE_CLASS_NOT_BETWEEN_TWO`: وهذا أقوى ما في
القياس. الآليّةُ المدّعاةُ أنّ همزةَ الوصل تُجلَب لتعذّر الابتداء بساكن، فمتى
تحرّك أوّلُ الصيغة انتفى موجبُها. والمضاعفُ **يقع على الوجهين داخل صنفٍ واحد**:
فإذا أُدغِم تحرّك أوّلُه (رُدُّوا) وإذا فُكَّ سكن (ٱشْدُدْ). فاختُبِر الشرطُ
على الإدغام وحدَه: **من اثنين وعشرين موضعًا أصاب واحدٌ وعشرون** — حيث الشدّةُ
حاضرةٌ فلا همزةَ وصل (١٣ من ١٣)، وحيث فُكَّ الإدغامُ فهمزةُ الوصل حاضرةٌ (٨ من
٨). وهذا اختبارُ آليّةٍ داخلَ صنفٍ واحدٍ لا ارتباطٌ بين صنفين، فلا يُعتَرض عليه
بأنّ الصنفين اختُلِفا في أشياءَ أخرى.

`THE_ONE_DOUBLED_RESIDUAL_IS_THE_CONTESTED_FORM_ITSELF`: والموضعُ الثاني
والعشرون «وَقَرْنَ» (٣٣:٣٣) — لا شدّةَ فيه ولا همزةَ وصل، فيُخالف الشرطَ
وحدَه. وهو بعينه الموضعُ الذي اختُلِف في أصله عند أهل اللغة قديمًا، ووَسْمُ
المدوَّنة نفسُه مضطربٌ فيه: تُثبِت له `LEM:taqar~a` وهو وزنٌ مزيد، وتَسِمه
مجرَّدًا. فلا يُصحَّح ولا يُحذَف؛ يُسمّى ويُترَك خارجَ الحساب المُصحَّح.

`ONE_QAC_TAG_CARRIES_THE_WHOLE_NAQIS_EXCEPTION`: واستثناءُ الناقص الوحيدُ
«دَعَانِ» (٢:١٨٦) تَسِمه المدوَّنةُ أمرًا للمثنّى، وقراءتُه الشائعةُ ماضٍ
وفاعلُه مفردٌ ونونُ وقاية. **ولسنا حَكَمًا على وَسْم المدوَّنة**: يُعَدُّ كما
وُسِم، ويُسجَّل الخلافُ باسمه، ولا يُطرَح ليستقيم الرقم. فمن طرَحه بلغ
بالناقص مئةً بالمئة، وليس ذلك رقمَ المدوَّنة بل رقمَ من عدّلها.

`THE_IMPERFECT_AS_A_PRECONDITION_WAS_NOT_SETTLED`: من ١٤٩ جذرًا له أمرٌ مجرَّد،
١١٦ له مضارعٌ مجرَّدٌ في المدوَّنة و٣٣ لا مضارعَ مجرَّدَ له (٢٢٫١٪)، ومنها ٢٥
لا مضارعَ لها في أيِّ وزن. وهذا **غيابُ دليلٍ لا دليلُ غياب**؛ فالدعوى لا
تُفنَّد به ولا تثبت، وتبقى خارجَ ما تحسمه هذه المدوَّنة.

`SHA_256_ORDERS_NOTHING`: ولا يُتتبَّع في هذا القياس ولا في غيره «صعودٌ ونزولٌ
في البصمات». دالّةُ `SHA-256` لا خاصيّةَ حفظِ ترتيبٍ فيها البتّة، ومدخلان
متجاوران يُخرِجان بصمتين لا علاقةَ بينهما. فالبصمةُ تُثبِت هويّةَ الملفّ ولا
تُرتِّب شيئًا، والترتيبُ المقيسُ في هذه الشجرة ترتيبُ نقاط يونيكود لا ترتيبُ
بصمات.

وهذه الوحدة تسجيلٌ لا سلطة: لا ولادةَ فيها، ولا حكمَ ولادة، ولا تجميدَ `E0`،
ولا تستورد من `kernel/` شيئًا، ولا تقرؤها وحدةٌ فيه. وبايتاتُ المدوَّنة غيرُ
منسوخةٍ إلى الشجرة؛ والشاهدُ مُودَعٌ في `irab_corpus_witness`.
"""

