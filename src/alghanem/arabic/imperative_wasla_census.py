@dataclass(frozen=True, slots=True)
class ImperativeReading:
    """قراءةُ مقطعِ أمرٍ واحد: جذرُه، وتجرّدُه، وحضورُ همزة الوصل، والإدغام."""

    root: str
    is_bare: bool
    has_wasla: bool
    has_shadda: bool

    def __post_init__(self) -> None:
        if not isinstance(self.root, str) or not self.root.strip():
            raise ImperativeWaslaCensusError("جذرُ المقطع نصٌّ غير فارغ.")
        for value, label in (
            (self.is_bare, "التجرّد"),
            (self.has_wasla, "حضورُ همزة الوصل"),
            (self.has_shadda, "حضورُ الشدّة"),
        ):
            if not isinstance(value, bool):
                raise ImperativeWaslaCensusError(f"{label} قيمةٌ ثنائيةٌ مقروءة.")


def read_imperative(record: SegmentRecord) -> ImperativeReading | None:
    """يقرأ مقطعًا فيُرجِع قراءتَه إن كان أمرًا بجذرٍ ثلاثيّ، وإلّا فلا شيء.

    `THE_ABSENT_TAG_IS_THE_SIGNAL`: التجرّدُ يُقرأ من **غياب** وسوم الأوزان
    المزيدة، إذ لا تَسِم هذه المدوَّنةُ الوزنَ الأوّل بشيء. فمن اشترط حضورَ
    `(I)` خرج بصفرٍ من مدوَّنةٍ فيها ألفُ أمرٍ مجرَّد.
    """
    features = record.features.split("|")
    if "IMPV" not in features:
        return None
    root = root_of_features(record.features)
    if not root or len(root) != 3:
        return None
    return ImperativeReading(
        root=root,
        is_bare=not (AUGMENTED_FORM_TAGS & set(features)),
        has_wasla=record.form.startswith(WASL_CHARACTER),
        has_shadda=SHADDA in record.form,
    )


def classify_root(root: str, rule: WeaknessRule) -> RootShape:
    """يصنّف جذرًا ثلاثيًّا تحت قاعدةٍ بعينها؛ ولا يصنّف تحت «القاعدة» مطلقةً.

    `A_SHAPE_WITHOUT_ITS_RULE_IS_NOT_A_READING`: الصنفُ تابعٌ للقاعدة، فلا
    يُطلَب صنفُ جذرٍ بلا تسميةِ القاعدة التي صُنِّف تحتها؛ ومن أطلقه أوهَم أنّ
    الصنفَ في البايتات وهو في القاعدة.
    """
    if not isinstance(root, str) or len(root) != 3:
        raise ImperativeWaslaCensusError("يُصنَّف الجذرُ الثلاثيُّ وحدَه في هذا القياس.")
    if not isinstance(rule, WeaknessRule):
        raise ImperativeWaslaCensusError(
            "لا يُصنَّف جذرٌ بلا قاعدةٍ مُسمّاةٍ من `WEAKNESS_RULES`."
        )
    if rule.separates_the_doubled_root and root[1] == root[2]:
        return RootShape.MUDAAF
    positions = [
        index for index, letter in enumerate(root) if letter in rule.weak_letters
    ]
    if not positions:
        return RootShape.SALIM
    if len(positions) > 1:
        return RootShape.LAFIF
    return (RootShape.MITHAL, RootShape.AJWAF, RootShape.NAQIS)[positions[0]]


@dataclass(frozen=True, slots=True)
class ShapeCount:
    """عدُّ صنفٍ واحدٍ تحت قاعدةٍ واحدة: كم مقطعًا، وكم منها بهمزة وصل."""

    rule_name: str
    shape: RootShape
    with_wasla: int
    segments: int

    def __post_init__(self) -> None:
        if self.segments < 0 or self.with_wasla < 0:
            raise ImperativeWaslaCensusError("العدّان صحيحان غيرُ سالبين.")
        if self.with_wasla > self.segments:
            raise ImperativeWaslaCensusError(
                "ما بهمزة الوصل لا يفوق جملةَ المقاطع؛ وعدٌّ يفوق وعاءَه خطأُ قراءة."
            )

    @property
    def percentage(self) -> float:
        """النسبةُ مُقرَّبةً إلى منزلتين؛ والصنفُ الخالي لا نسبةَ له فيُرجَع صفر."""
        if self.segments == 0:
            return 0.0
        return round(100 * self.with_wasla / self.segments, 2)


def shape_table(
    readings: tuple[ImperativeReading, ...], rule: WeaknessRule
) -> tuple[ShapeCount, ...]:
    """يبني جدولَ الأصناف تحت قاعدةٍ واحدة، مرتَّبًا بترتيب `RootShape` الثابت."""
    with_wasla: dict[RootShape, int] = {shape: 0 for shape in RootShape}
    segments: dict[RootShape, int] = {shape: 0 for shape in RootShape}
    for reading in readings:
        if not reading.is_bare:
            continue
        shape = classify_root(reading.root, rule)
        segments[shape] += 1
        if reading.has_wasla:
            with_wasla[shape] += 1
    return tuple(
        ShapeCount(
            rule_name=rule.name,
            shape=shape,
            with_wasla=with_wasla[shape],
            segments=segments[shape],
        )
        for shape in RootShape
        if segments[shape] > 0
    )


@dataclass(frozen=True, slots=True)
class PermutationOutcome:
    """نتيجةُ اختبار تبديلٍ واحد، بفارقه واحتماله وأقصى فارقٍ عدميّ."""

    label: str
    first_size: int
    second_size: int
    gap_points: float
    at_least_as_extreme: int
    p_value: float
    maximum_null_gap: float

    def __post_init__(self) -> None:
        if self.first_size < 1 or self.second_size < 1:
            raise ImperativeWaslaCensusError("لا يُبدَّل بين مجموعتين إحداهما خالية.")
        floor = 1 / (1 + PERMUTATION_PROTOCOL.permutations)
        if self.p_value < floor:
            raise ImperativeWaslaCensusError(
                f"احتمالٌ دون أرضيّة البروتوكول {floor}؛ و`0.0000` لا يقع منه."
            )


def permutation_test(
    label: str, first: list[bool], second: list[bool]
) -> PermutationOutcome:
    """يُبدِّل بين مجموعتين بالبذرة المُجمَّدة، فيُخرِج الفارقَ واحتمالَه.

    `THE_MAXIMUM_NULL_GAP_IS_NOT_THE_P_VALUE`: أقصى فارقٍ عدميٍّ يُعرَض لأنّه
    وارِدٌ في النصّ، ولا يُحكَم به: قد يقع الفارقُ المرصود دونه ويكون دالًّا.
    فالحُكمُ للاحتمال وحدَه.
    """
    if not first or not second:
        raise ImperativeWaslaCensusError("لا يُبدَّل بين مجموعتين إحداهما خالية.")
    observed = abs(sum(first) / len(first) - sum(second) / len(second))
    pool = list(first) + list(second)
    generator = random.Random(PERMUTATION_PROTOCOL.seed)
    size = len(first)
    extreme = 0
    maximum = 0.0
    for _ in range(PERMUTATION_PROTOCOL.permutations):
        generator.shuffle(pool)
        gap = abs(sum(pool[:size]) / size - sum(pool[size:]) / (len(pool) - size))
        maximum = max(maximum, gap)
        if gap >= observed - 1e-12:
            extreme += 1
    return PermutationOutcome(
        label=label,
        first_size=len(first),
        second_size=len(second),
        gap_points=round(100 * observed, 2),
        at_least_as_extreme=extreme,
        p_value=round((1 + extreme) / (1 + PERMUTATION_PROTOCOL.permutations), 6),
        maximum_null_gap=round(100 * maximum, 2),
    )


@dataclass(frozen=True, slots=True)
class IdghamAgreement:
    """اتّفاقُ الشرط داخل المضاعف: الشدّةُ تنفي همزةَ الوصل وفكُّها يُثبِتها."""

    assimilated_without_wasla: int
    broken_with_wasla: int
    disagreeing: int

    @property
    def total(self) -> int:
        return (
            self.assimilated_without_wasla + self.broken_with_wasla + self.disagreeing
        )

    @property
    def agreeing(self) -> int:
        return self.assimilated_without_wasla + self.broken_with_wasla


def idgham_agreement(readings: tuple[ImperativeReading, ...]) -> IdghamAgreement:
    """يختبر الآليّةَ داخل المضاعف وحدَه: هل الشدّةُ تُلازِم غيابَ همزة الوصل؟"""
    assimilated = 0
    broken = 0
    disagreeing = 0
    for reading in readings:
        if not reading.is_bare or reading.root[1] != reading.root[2]:
            continue
        if reading.has_shadda and not reading.has_wasla:
            assimilated += 1
        elif not reading.has_shadda and reading.has_wasla:
            broken += 1
        else:
            disagreeing += 1
    return IdghamAgreement(
        assimilated_without_wasla=assimilated,
        broken_with_wasla=broken,
        disagreeing=disagreeing,
    )


@dataclass(frozen=True, slots=True)
class ImperfectCoexistence:
    """عدُّ الجذور التي لها أمرٌ مجرَّد، وكم منها له مضارعٌ في المدوَّنة."""

    imperative_roots: int
    with_bare_imperfect: int
    with_imperfect_in_any_form: int

    @property
    def without_bare_imperfect(self) -> int:
        return self.imperative_roots - self.with_bare_imperfect

    @property
    def without_any_imperfect(self) -> int:
        return self.imperative_roots - self.with_imperfect_in_any_form


def imperfect_coexistence(
    records: list[SegmentRecord],
) -> ImperfectCoexistence:
    """يعُدّ تعايشَ الأمر والمضارع بالجذر، لا يحكم على إمكانِ ما لم يرد."""
    imperative: set[str] = set()
    bare_imperfect: set[str] = set()
    any_imperfect: set[str] = set()
    for record in records:
        features = record.features.split("|")
        root = root_of_features(record.features)
        if not root:
            continue
        bare = not (AUGMENTED_FORM_TAGS & set(features))
        if "IMPV" in features and bare:
            imperative.add(root)
        if "IMPF" in features:
            any_imperfect.add(root)
            if bare:
                bare_imperfect.add(root)
    return ImperfectCoexistence(
        imperative_roots=len(imperative),
        with_bare_imperfect=len(imperative & bare_imperfect),
        with_imperfect_in_any_form=len(imperative & any_imperfect),
    )


