"""الوزن: الميزانُ الصرفيُّ قالبًا على الخانات — مرآةُ `formal/Slge/Wazn.lean`.

الوزنُ قالبٌ: تتابعُ رموزٍ كلُّ رمزٍ إمّا **زائدٌ** (خانةٌ بعينها: حامل + حالة) وإمّا **أصل**
(موضعُ الفاء أو العين أو اللام + حالتُه). وملءُ القالب بأصلٍ ثلاثيّ (`fill`) يعطي الكلمةَ خاناتٍ،
والاستخراجُ (`root_of`) يعيد الأصلَ بعينه (مبرهَن `Slge.Wazn.rootOf_fill`). والميزانُ الصرفيُّ
هو ملءُ القالب بالأصل (ف، ع، ل) نفسِه (`mizan`).

**القانونُ المبرهَن** (`licensed_fill_indep`): ترخيصُ الكلمة لا يتوقّف على الأصل، بل على القالب
وحدَه؛ فالوزنُ يُرخَّص **مرّةً واحدةً** لكلّ الأصول. وبه كلُّ وزنٍ في `AWZAN` مرخَّصٌ لكلّ أصلٍ
(`awzan_licensed`). والشدّةُ خانتان (ساكنٌ فمتحرّك) كما في الـ116؛ والتاءُ المربوطة تاء، والألفُ
المقصورة ألف، وهمزةُ الوصل همزةٌ بحركتها (ألفُها بقيّةُ رسمٍ: `A116.Residue` WASL)، كما تُخرجها البوّابة.

**ما لا يدّعيه الجدول:** الأوزانُ المودَعة من كتب الصرف (معلن)، وهياكلُها مقيسةٌ على أبنية سيبويه
(`tests/test_wazn.py`)، وحركاتُها ليست مقيسةً على مرجعٍ محجوب بعد. مصدرُ الثلاثيّ سماعيٌّ فالمودَع
أغلبُ أوزانه القياسيّة؛ الرباعيُّ وجموعُه خارج الأصل الثلاثيّ: دَينٌ مسمًّى؛ «المفعول المطلق»
إعرابٌ لا وزن؛ و«الجامد» قيدٌ معجميّ لا وزن. والإعلالُ لا يُطبَّق هنا (في الغانم `gate/ilal.py`).
"""

