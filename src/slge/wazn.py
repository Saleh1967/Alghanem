SUKUN: Final[str] = STATES[3]
_MARK: Final[dict[str, str]] = {"َ": STATES[0], "ِ": STATES[1], "ُ": STATES[2],
                                "ْ": SUKUN}
_SHADDA: Final[str] = "ّ"
_SLOT: Final[dict[str, int]] = {"ف": 0, "ع": 1, "ل": 2}
_FOLD: Final[dict[str, str]] = {"ة": "ت", "ى": "ا", "آ": "ءا", "أ": "ء", "إ": "ء", "ؤ": "ء",
                                "ئ": "ء"}
FAL: Final[tuple[str, str, str]] = ("ف", "ع", "ل")


@dataclass(frozen=True, slots=True)
class Sym:
    """رمزُ القالب: `slot` موضعُ أصلٍ (0 ف، 1 ع، 2 ل) أو `None` لزائدٍ حاملُه `carrier`؛ وحالتُه."""

    slot: int | None
    carrier: str | None
    state: str


Template = tuple[Sym, ...]


@dataclass(frozen=True, slots=True)
class Wazn:
    """وزنٌ مسمًّى: بابُه (فعل/مصدر/مشتق/جمع/تأنيث)، ميزانُه نصًّا، وقالبُه."""

    name: str
    bab: str
    template: Template
    note: str = ""


def parse(mizan_text: str) -> Template:
    """من الميزان المشكول إلى القالب: ف/ع/ل أصول، وغيرُها زوائد؛ الشدّةُ تضعّف الخانة."""

    out: list[Sym] = []
    text = "".join(_FOLD.get(ch, ch) for ch in mizan_text)
    i = 0
    while i < len(text):
        ch = text[i]
        if ch not in ALPHABET and ch not in _SLOT:
            raise ValueError(f"NOT_A_CARRIER:{ch}")
        i += 1
        shadda, state = False, ""
        while i < len(text) and (text[i] == _SHADDA or text[i] in _MARK):
            if text[i] == _SHADDA:
                shadda = True
            else:
                state = _MARK[text[i]]
            i += 1
        if ch == "ا" and state:
            ch = "ء"  # همزةُ الوصل: حاملُها الهمزة، وألفُها بقيّةُ رسم
        elif ch == "ا" or (ch in "وي" and not state):
            state = SUKUN  # حرفُ المدّ ساكنٌ كما تُخرجه البوّابة
        elif not state:
            raise ValueError(f"UNVOCALIZED_SYMBOL:{ch}")
        slot, carrier = (_SLOT[ch], None) if ch in _SLOT else (None, ch)
        if shadda:
            out.append(Sym(slot, carrier, SUKUN))
        out.append(Sym(slot, carrier, state))
    return tuple(out)


def fill(t: Template, root: Sequence[str]) -> tuple[Cell, ...]:
    """ملءُ القالب بالأصل."""

    if len(root) != 3 or any(r not in ALPHABET for r in root):
        raise ValueError("ROOT_MUST_BE_THREE_CARRIERS")
    return tuple((root[s.slot] if s.slot is not None else s.carrier or "", s.state) for s in t)


def root_of(t: Template, word: Sequence[Cell]) -> tuple[str, str, str] | None:
    """الأصلُ من الكلمة بالقالب: أوّلُ ظهورٍ لكلّ موضع؛ `None` إن اختلف الطولُ أو غاب موضع."""

    if len(word) != len(t):
        return None
    found: dict[int, str] = {}
    for s, (carrier, _) in zip(t, word, strict=True):
        if s.slot is not None:
            found.setdefault(s.slot, carrier)
    if set(found) != {0, 1, 2}:
        return None
    return found[0], found[1], found[2]


def states_of(t: Template) -> tuple[str, ...]:
    """حالاتُ القالب: لا تتوقّف على الأصل."""

    return tuple(s.state for s in t)


def mizan(t: Template) -> tuple[Cell, ...]:
    """الميزانُ الصرفيّ: القالبُ مملوءًا بـ(ف، ع، ل)."""

    return fill(t, FAL)


def skeleton(t: Template) -> str:
    """هيكلُ الوزن حروفًا بلا حركات (للمقابلة بأبنية سيبويه)؛ الشدّةُ حرفٌ واحد."""

    cells = mizan(t)
    out: list[str] = []
    for i, (c, s) in enumerate(cells):
        if s == SUKUN and i + 1 < len(cells) and cells[i + 1][0] == c and c != "ا":
            continue
        out.append(c)
    return "".join(out)


def _w(name: str, bab: str, text: str, note: str = "") -> Wazn:
    return Wazn(name, bab, parse(text), note)


