"""SLGE-صفات: الصفاتُ الصوتيّة والمخارج — بياناتٌ تراثيّةٌ معلنة [D].

الحرفُ عند هذه الطبقة تركيبُ صفات، فهي لا تستورد الأبجديّة من `cells`: تُعلن حروفها
بنفسها، ويفحص الاختبارُ أنها هي الـ29 بعينها. والتجربةُ الصوتيّة القياسيّة (طيفٌ
وزمنٌ على عيّنات نطق) مؤجّلةٌ بقرارٍ معلن: لا عتادَ ولا بياناتِ نطقٍ هنا.
"""

from __future__ import annotations

from typing import Final

__all__ = ["BETWEEN", "LETTERS", "MAHRAJ", "PAIRS", "PLACES", "features"]

LETTERS: Final[tuple[str, ...]] = tuple("ءابتثجحخدذرزسشصضطظعغفقكلمنهوي")


def _not(s: str) -> list[str]:
    return [c for c in LETTERS if c not in s]


PAIRS: Final[tuple[tuple[str, str, tuple[str, ...], tuple[str, ...]], ...]] = tuple(
    (name, opp, tuple(pos), tuple(bet))
    for name, opp, pos, bet in [
        ("جهر", "همس", _not("فحثهشخسكت"), []),
        ("همس", "جهر", list("فحثهشخسكت"), []),
        ("شدة", "رخاوة", list("بجدطعقكء"), []),
        ("رخاوة", "شدة", _not("بجدطعقكء"), []),
        ("استعلاء", "استفال", list("خصضغطقظ"), ["ل"]),
        ("استفال", "استعلاء", _not("خصضغطقظل"), []),
        ("إطباق", "انفتاح", list("صضطظق"), []),
        ("انفتاح", "إطباق", _not("صضطظق"), []),
        ("ذلاقة", "إصمات", list("فبمولنر"), []),
        ("إصمات", "ذلاقة", _not("فبمولنر"), []),
        ("غنة", "لين", list("نم"), []),
        ("لين", "غنة", ["و", "ي"], ["و", "ي"]),
        ("تفشي", "جمعة", ["ش"], []),
        ("جمعة", "تفشي", _not("ش"), []),
        ("اصطرار", "انحراف", ["ر"], []),
        ("انحراف", "اصطرار", ["ل"], []),
    ]
)
"""(الصفة، ضدّها، حملتُها، بينيّاتُها) كما أعلنها `slge_phon.py`."""

BETWEEN: Final[dict[str, str]] = {"ل": "استعلاء/استفال بيني", "و": "لين/توسط", "ي": "لين/توسط"}

PLACES: Final[tuple[str, ...]] = ("الجوف", "الحلق", "اللسان", "الشفتان", "الخيشوم")

MAHRAJ: Final[dict[str, tuple[str, str]]] = {
    "ا": ("الجوف", "مدّ الفتح"), "و": ("الجوف", "مدّ الضم"), "ي": ("الجوف", "مدّ الكسر"),
    "ء": ("الحلق", "أقصى"), "ه": ("الحلق", "أدنى"), "ع": ("الحلق", "وسط"),
    "ح": ("الحلق", "وسط"), "غ": ("الحلق", "أدنى"), "خ": ("الحلق", "أدنى"),
    "ق": ("اللسان", "أقصى ما يلي الحلق"), "ك": ("اللسان", "أقصى ما يلي الظهر"),
    "ج": ("اللسان", "وسط فوق"), "ش": ("اللسان", "وسط فوق"),
    "ض": ("اللسان", "حافة مع أطراف الثنايا"), "ل": ("اللسان", "طرف أدناه"),
    "ر": ("اللسان", "طرف أعلاه"), "ط": ("اللسان", "أدنى مع أطراف"),
    "د": ("اللسان", "أدنى مع أطراف"), "ت": ("اللسان", "أدنى مع أطراف"),
    "ص": ("اللسان", "أدنى مع أصول"), "س": ("اللسان", "أدنى مع أصول"),
    "ز": ("اللسان", "أدنى مع أصول"), "ظ": ("اللسان", "أدنى مع وسط"),
    "ذ": ("اللسان", "عام"), "ث": ("اللسان", "عام"),
    "ف": ("الشفتان", "مخرج فم"), "ب": ("الشفتان", "مخرج فم"), "م": ("الشفتان", "مخرج فم"),
    "ن": ("الخيشوم", "غنة"),
}
"""مخرجُ كلّ حرفٍ من الـ29 كما في `slge_phon.py` بقيمته النافذة. والفرقُ تنظيفٌ لا
تصحيح: الأصلُ كتب «ن» مرّتين فنفذت الثانية (الخيشوم)، وأدخل مفتاحين ليسا حرفين
(«ي2، م2») فحُذفا. وما فيه من أسئلةٍ مفتوحة («ذ، ث» على «اللسان/عام»؛ «ي» في
الجوف وحده) مسجَّلٌ في `status.LEDGER` لا مُصحَّحٌ من الذاكرة."""


def features(letter: str) -> dict[str, str]:
    """متّجهُ صفات الحرف: لكلّ صفةٍ «+» أو «-» أو «بيني»."""

    if letter not in LETTERS:
        raise ValueError(f"ليس من الـ29: {letter!r}")
    return {
        name: "+" if letter in pos else ("بيني" if letter in bet else "-")
        for name, _opp, pos, bet in PAIRS
    }
