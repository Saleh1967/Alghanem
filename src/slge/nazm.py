def case_agree(a: Sequence[Cell], b: Sequence[Cell]) -> bool:
    """توافقُ الإعراب: حالةُ الخانة الأخيرة واحدةٌ في الكلمتين (الإعرابُ مشغّلُ الأخيرة، ONTOLOGY-4).

    هذا الشرطُ الوحيدُ من شروط الأنماط الذي له بتٌّ في SLGE؛ وما سواه (الصدارة، التعريف، النوع،
    العدد، فقدُ التنوين) يلزمه ما ليس في الخانة وحدَها.
    """

    if not a or not b:
        raise ValueError("لا إعرابَ لخالية")
    return a[-1][1] == b[-1][1]
