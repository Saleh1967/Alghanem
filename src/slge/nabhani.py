"""تقسيماتُ النبهانيّ أنماطًا — مرآةُ `Slge.Nabhani` (ADR ٢٦): الدالُّ وحده (الدلالاتُ الثلاث، التراكيبُ
الثلاثة، المركّبُ الستّة)، المدلولُ وحده (الخمسة وفيها الهذيان)، الدالُّ والمدلول (السبعة)، النِّسَبُ الثلاث
(إسناديّة، تقييديّة، إضافيّة)، والترجيحُ عند تعارض ما يخلّ بالفهم: خمسةُ احتمالاتٍ بعشرة أوجه (التخصيصُ أولى
من الكلّ، المجازُ والإضمارُ سيّان، ثمّ النقل، ثمّ الاشتراك). كلُّ قائمةٍ هنا عباراتُ بحثها في المودَع المختوم
(`nabhani_table`)، لا من الذاكرة.
"""

from __future__ import annotations

from typing import Final

from slge.nabhani_table import SECTIONS, phrases

__all__ = ["DALALA", "DALL_MADLUL", "IHTIMAL", "MADLUL", "MURAKKAB", "NISBA", "RANK",
           "TARKIB", "awla", "tarjih"]

DALALA: Final[tuple[str, ...]] = phrases("الدال-وحده")[:3]
"""دلالاتُ الدالّ وحده: المطابقةُ والتضمّنُ (منطوق) والالتزامُ (مفهوم)."""
TARKIB: Final[tuple[str, ...]] = phrases("الدال-وحده")[4:7]
"""التراكيبُ الثلاثة: إسناد، مزج، إضافة."""
MURAKKAB: Final[tuple[str, ...]] = phrases("المركب")[1:7]
"""المركّبُ ستّةٌ بالوضع — «من أقسام الدالّ وحده»."""
MADLUL: Final[tuple[str, ...]] = phrases("المدلول-وحده")[:5]
"""المدلولُ وحده خمسة؛ الخامسُ الهذيان (مركّبٌ مهمل: مرخَّصٌ غيرُ موضوع)."""
DALL_MADLUL: Final[tuple[str, ...]] = phrases("الدال-والمدلول")[:7]
"""الدالُّ والمدلولُ سبعة."""
NISBA: Final[tuple[str, ...]] = ("الإسنادية", "التقييدية", "الإضافية")
"""النِّسَبُ الثلاث التي وُضع اللفظُ ليفيدها — لا «تضمينيّة» (ف393)."""
IHTIMAL: Final[tuple[str, ...]] = ("الاشتراك", "النقل", "المجاز", "الإضمار", "التخصيص")
RANK: Final[dict[str, int]] = {"الاشتراك": 0, "النقل": 1, "المجاز": 2, "الإضمار": 2, "التخصيص": 3}
"""رتبةُ الاحتمال: «كلُّ واحدٍ مرجوحٌ بالنسبة إلى كلّ ما بعده … إلّا الإضمارَ والمجازَ فهما سيّان»."""


def awla(a: str, b: str) -> bool:
    """`a` أولى من `b` (`awla`)."""

    return RANK[b] < RANK[a]


def tarjih(candidates: tuple[str, ...]) -> tuple[str, ...]:
    """الأولى أوّلًا، ولا يُسقَط احتمال؛ السيّانِ على ترتيبهما."""

    return tuple(sorted(candidates, key=lambda x: -RANK[x]))


def _check() -> None:
    assert len(SECTIONS) == 20
    assert DALALA == ("دلالة المطابقة", "دلالة التضمن", "دلالة الالتزام")
    assert TARKIB == ("تركيب إسناد", "تركيب مزج", "تركيب إضافة")
    assert MURAKKAB == ("الاستفهام", "الأمر", "الالتماس", "السؤال", "الخبر", "التنبيه")
    assert MADLUL[4] == "لفظاً مركباً مهملاً" and len(MADLUL) == 5
    assert DALL_MADLUL == ("المنفرد", "المتباين", "المترادف", "المشترك", "المنقول", "الحقيقة",
                           "المجاز")
    assert phrases("المركب")[0] == "من أقسام الدال وحده"
    assert "النسب الإسنادية، أو التقييدية، أو الإضافية" in phrases("الوضع-والنسب")
    # الأوجهُ العشرة بترتيب النصّ
    rules = phrases("الترجيح")[2:]
    assert len(rules) == 10
    assert awla("النقل", "الاشتراك") and awla("التخصيص", "الإضمار")
    assert not awla("المجاز", "الإضمار") and not awla("الإضمار", "المجاز")
    assert tarjih(("الاشتراك", "التخصيص", "النقل")) == ("التخصيص", "النقل", "الاشتراك")


_check()
