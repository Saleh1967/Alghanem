def _assert_the_witnesses_are_attested() -> None:
    """لا شاهدَ ههنا إلّا ما وقع في المُودَع بصورته؛ والمختلَقُ يُردّ لا يُقاس."""

    named = (
        tuple(witness.form for witness in THE_IBTIDA_WITNESSES)
        + THE_ILAL_WITNESSES
        + THE_SAKINAYN_WITNESSES
    )
    for form in named:
        if deposited_occurrences(form) < 1:
            raise AlgebraSuccessExamError(
                f"«{form}» غيرُ مشهودةٍ في المُودَع؛ لا تُمتحَن بها آلة."
            )


def _verify_the_pausal_faces_are_distinct() -> None:
    """أوجهُ الوقف تُعدّ بأسمائها المتمايزة؛ ووجهان باسمٍ واحدٍ عدٌّ مضاعَف."""

    names = [face.name for face in THE_PAUSAL_FACES]
    if len(set(names)) != len(names):
        raise AlgebraSuccessExamError("وجهان باسمٍ واحدٍ لا يُعدّان اثنين.")
