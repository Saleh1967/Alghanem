@dataclass(frozen=True, slots=True)
class CarrierReading:
    """حاملٌ مقروءٌ: رمزُه، وحرفُه مطويًّا، وحركتُه المُعلَنة، وعلاماتُه كلُّها."""

    raw: str
    letter: str | None
    haraka: str | None
    marks: str

    @property
    def standing(self) -> CellStanding:
        """منزلتُه في الجدول، مُشتَقّةً من حرفه وحركته لا مكتوبةً في حقل."""

        if self.letter is None:
            return CellStanding.OUTSIDE_THE_DECLARED_ALPHABET
        if self.haraka is None:
            return CellStanding.NO_DECLARED_HARAKA
        return CellStanding.A_CELL_IN_THE_TABLE

    @property
    def is_a_cell(self) -> bool:
        """أيقع هذا الحاملُ في خليّةٍ من الـ١١٢؟"""

        return self.standing is CellStanding.A_CELL_IN_THE_TABLE

    @property
    def cell(self) -> tuple[str, str] | None:
        """خليّتُه إن كانت له خليّة، وإلّا فلا شيءَ يُصطنَع له."""

        if self.letter is None or self.haraka is None:
            return None
        return (self.letter, self.haraka)


def carriers_of(form: str) -> tuple[CarrierReading, ...]:
    """حواملُ صورةٍ مكتوبة: كلُّ رمزٍ ليس علامةً، ومعه ما لصق به من علامات.

    والطيُّ مقروءٌ من `letter_fingerprint`، والحركةُ أوّلُ علامةٍ لاصقةٍ من
    الأربع المُعلَنة؛ فما خرج عن الأبجديّة المطويّة أو عن الحركات الأربع لم
    يُصطنَع له موضعٌ في الجدول.
    """

    declared = set(THE_DECLARED_LETTERS)
    marks = set(THE_DECLARED_HARAKAT)
    readings: list[CarrierReading] = []
    for index, raw in enumerate(form):
        if unicodedata.category(raw) == "Mn":
            continue
        run = ""
        for follower in form[index + 1 :]:
            if unicodedata.category(follower) != "Mn":
                break
            run += follower
        folded = fold_root(raw)
        readings.append(
            CarrierReading(
                raw=raw,
                letter=folded if folded in declared else None,
                haraka=next((mark for mark in run if mark in marks), None),
                marks=run,
            )
        )
    return tuple(readings)


@lru_cache(maxsize=1)
def _deposited_words() -> tuple[str, ...]:
    """كلماتُ المُودَع كما وقعت، مقروءةً من بابها الفاحصِ طولَه وبصمتَه."""

    return tuple(
        word for row in ayah_rows_of(THE_EXAMINED_DEPOSIT) for word in row.split()
    )


def deposited_occurrences(form: str) -> int:
    """عدّةُ وقوع صورةٍ بعينها في المُودَع؛ صفرٌ يعني أنّها غيرُ مشهودةٍ فيه."""

    return sum(1 for word in _deposited_words() if word == form)


