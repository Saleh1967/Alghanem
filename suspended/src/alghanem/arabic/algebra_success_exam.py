@dataclass(frozen=True, slots=True)
class IbtidaWitness:
    """شاهدٌ مشهودٌ في المُودَع، ومعه موضعُ الحكم فيه والمطلوبُ تفسيرُه."""

    form: str
    site_index: int
    required_outcome: str

    def __post_init__(self) -> None:
        if self.site_index < 0:
            raise AlgebraSuccessExamError("موضعُ حكمٍ سالبٌ لا يُقرأ.")
        if not self.required_outcome.strip():
            raise AlgebraSuccessExamError("شاهدٌ لا يُعلِن ما يجب تفسيرُه لا يمتحن شيئًا.")


THE_IBTIDA_WITNESSES: Final[tuple[IbtidaWitness, ...]] = (
    IbtidaWitness(
        form="اهْدِنَا",
        site_index=0,
        required_outcome="تحقُّقُ بدايةٍ همزيّةٍ مرخَّصة",
    ),
    IbtidaWitness(
        form="وَاسْتَعِينُوا",
        site_index=1,
        required_outcome="زوالُ إصلاح الابتداء وإعادةُ التقطيع",
    ),
    IbtidaWitness(
        form="وَأَقِيمُوا",
        site_index=1,
        required_outcome="حفظُ همزة القطع",
    ),
)
"""شواهدُ الابتداء والوصل، كلُّها مشهودةٌ في المُودَع، وموضعُ الحكم مُعلَنٌ فيها."""


@dataclass(frozen=True, slots=True)
class DecisionSite:
    """موضعُ الحكم مقروءًا: شاهدُه، وحاملُه، ومنزلتُه في الجدول."""

    witness: IbtidaWitness
    carrier: CarrierReading
    occurrences: int

    @property
    def standing(self) -> CellStanding:
        """منزلةُ الموضع، مُشتَقّةً من حامله."""

        return self.carrier.standing


def read_decision_sites() -> tuple[DecisionSite, ...]:
    """مواضعُ الحكم في الشواهد، مقروءةً من صورها بعد إثبات شهودها في المُودَع."""

    _assert_the_witnesses_are_attested()
    sites: list[DecisionSite] = []
    for witness in THE_IBTIDA_WITNESSES:
        carriers = carriers_of(witness.form)
        if witness.site_index >= len(carriers):
            raise AlgebraSuccessExamError(
                f"موضعُ الحكم خارجَ حوامل «{witness.form}»؛ وقفٌ لا تخمين."
            )
        sites.append(
            DecisionSite(
                witness=witness,
                carrier=carriers[witness.site_index],
                occurrences=deposited_occurrences(witness.form),
            )
        )
    return tuple(sites)


def ibtida_station() -> StationReading:
    """المحطّةُ الثانية: أيَقرأ الجبرُ موضعَ الحكم خليّةً، ثمّ أيُميّزُ بها؟

    والشرطُ مُعلَنٌ قبل القياس وهو شرطان متتاليان: أن يكون **كلُّ** موضعِ
    حكمٍ خليّةً في الجدول، ثمّ أن تبلغ الخلايا المتمايزةُ عددَ المطلوبات
    المتمايزة. فإن سقط الأوّلُ لم يُسأل عن الثاني، لأنّ غيابَ الحالة ليس
    جوابًا خاطئًا (`AN_UNREADABLE_SITE_IS_NOT_A_WRONG_ANSWER`).
    """

    sites = read_decision_sites()
    readable = sum(1 for site in sites if site.carrier.is_a_cell)
    outcomes = len({site.witness.required_outcome for site in sites})
    projections = len({site.carrier.cell for site in sites})
    if readable < len(sites):
        verdict = StationVerdict.UNREADABLE_AT_THE_DECISION_SITE
        detail = AN_UNREADABLE_SITE_IS_NOT_A_WRONG_ANSWER
    elif projections < outcomes:
        verdict = StationVerdict.DISCRIMINATION_IMPOSSIBLE_BY_COUNT
        detail = "صورتان في الجدول أقلُّ من مطلوبَين متمايزَين؛ فلا تمييزَ بها"
    else:
        verdict = StationVerdict.PASSED
        detail = "كلُّ موضعٍ خليّةٌ، والخلايا المتمايزةُ تبلغ المطلوبات"
    return StationReading(
        name="الابتداء والوصل",
        question="أللجبرِ حالةٌ في موضع الحكم، وأتُميّز بين المطلوبات؟",
        passing_condition="كلُّ موضعٍ خليّةٌ، ثمّ الخلايا المتمايزة ≥ المطلوبات",
        measured=(
            ("الشواهدُ المشهودة", len(sites)),
            ("المواضعُ التي تُقرأ خليّة", readable),
            ("المطلوباتُ المتمايزة", outcomes),
            ("الصورُ المتمايزة في الجدول", projections),
        ),
        verdict=verdict,
        detail=detail,
    )


