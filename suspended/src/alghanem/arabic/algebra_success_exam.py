@dataclass(frozen=True, slots=True)
class StationReading:
    """قراءةُ محطّةٍ: سؤالُها، وشرطُ اجتيازها، ومقدارُها، وحكمُها المُشتَقّ."""

    name: str
    question: str
    passing_condition: str
    measured: tuple[tuple[str, int], ...]
    verdict: StationVerdict
    detail: str

    def __post_init__(self) -> None:
        if not self.name.strip() or not self.question.strip():
            raise AlgebraSuccessExamError("محطّةٌ بلا اسمٍ أو بلا سؤالٍ لا تُقرأ.")
        if not self.passing_condition.strip():
            raise AlgebraSuccessExamError(
                "محطّةٌ لا تُعلِن شرطَ اجتيازها لا تُحسَب مجتازةً ولا مخفقة."
            )
        if not self.measured:
            raise AlgebraSuccessExamError("محطّةٌ بلا مقدارٍ مقيسٍ لا تُخرِج حكمًا.")

    @property
    def passed(self) -> bool:
        """أاجتازت؟ والاجتيازُ منزلةٌ واحدةٌ لا تُجمَع من غيرها."""

        return self.verdict is StationVerdict.PASSED


