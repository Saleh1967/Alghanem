"""امتحانُ نجاح الجبر: أربعُ محطّاتٍ تُشغَّل، والحكمُ يُشتَقّ ولا يُكتَب.

سُئل هذا السؤالُ وحدَه: **أينجح جبرُ الخليّة (الحرفُ وحركتُه) في المواضع التي
سمّاها البحثُ؟** والتوثيقُ — إيداعُ بايتاتِ بَطّوش والنشرِ والشافيةِ والكتابِ
وورقتَي Beesley وHulden — **دَينٌ مؤجَّلٌ بأسمائه**، لا يُقضى ههنا ولا يُدَّعى
قضاؤه (`THE_DOCUMENTATION_DEBT_IS_DEFERRED_AND_NAMED`). فما في هذه الوحدة من
حكمٍ فعلى **بايتاتٍ مُودَعةٍ مختومةٍ في هذه الشجرة** وحدَها.

**والامتحانُ يُشغَّل ولا يُوصَف.** كلُّ محطّةٍ تُعيد اشتقاقَ مقدارها عند كلّ
نداء، ثمّ يُشتَقُّ حكمُها من ذلك المقدار بشرطٍ مُعلَنٍ قبله. ولا حكمَ مكتوبًا
في حقلٍ يُنقَض، ولا نجاحَ يُفترَض لمحطّةٍ لم تُشغَّل
(`A_STATION_THAT_CANNOT_RUN_IS_NOT_A_STATION_THAT_PASSED`).

**المحطّةُ الأولى — الوقف: امتناعٌ عدًّا لا رأيًا.** أوجهُ الوقف المنقولةُ
ثلاثةٌ لا واحد: السكونُ، والرومُ (نطقٌ ببعض الحركة)، والإشمامُ (إشارةٌ إلى
الحركة دون تصويت). والحركاتُ المُعلَنةُ في `letter_haraka_partition` أربعٌ،
ولا يقبل منها قانونُ الوقف بالتسكين — وهو المقروءُ ههنا — إلّا واحدةً. فثلاثةٌ
مطلوبةٌ في واحدةٍ متاحة، وهذا امتناعٌ بالحمامة والبرج لا باختيار كلفة
(`THE_THREE_PAUSAL_FACES_ARE_NOT_ONE_STATE`).

**والمحطّةُ الثانية — الابتداءُ والوصل: موضعُ الحكم لا يُقرأ خليّةً أصلًا.**
شواهدُها ثلاثٌ مشهودةٌ في المُودَع: «اهْدِنَا» في الابتداء، و«وَاسْتَعِينُوا»
و«وَأَقِيمُوا» في الوصل. وموضعُ الحكم في كلٍّ مُعلَنٌ قبل القراءة. فإذا قُرِئ
وجِدَ أنّ همزةَ القطع تُطوى إلى «ء» وهي **خارج الثمانية والعشرين**، وأنّ ألفَ
الوصل **لا تحمل حركةً مُعلَنة**. فلا خليّةَ ههنا ولا هناك: ليس الجبرُ يُجيب
خطأً، بل **لا حالةَ له في موضع السؤال**
(`AN_UNREADABLE_SITE_IS_NOT_A_WRONG_ANSWER`).

**والمحطّةُ الثالثة — الإعلال: قاعدةٌ سطحيّةٌ تُشغَّل فتنقضها الصورُ المشهودة.**
تُصاغ القاعدةُ صياغةً قابلةً للتكذيب: *واوٌ أو ياءٌ تحمل حركةً غيرَ السكون،
قبلها حاملٌ عليه فتحةٌ ⇒ ألف*. ثمّ تُشغَّل على صفوف المُودَع. وكلُّ إيقادٍ لها
على **صورةٍ مشهودة** نقضٌ لها، لأنّ المشهودَ هو المخرَجُ لا المدخل
(`A_RULE_THAT_FIRES_ON_AN_ATTESTED_FORM_IS_FALSIFIED_BY_IT`). ومن شواهدها
المسمّاةِ في البحث «قَوِيٌّ» و«أَيَّامٍ»: تُوقِدان القاعدةَ ولا تنقلبان.

**ولا تُقرأ هذه المحطّةُ على مدخلٍ مقدَّر.** القاعدةُ الصرفيّةُ في أصلها نقلٌ
من مُقدَّرٍ إلى مشهود، والمقدَّرُ **تحليلُ مصدرٍ لا بايتاتٌ مُودَعة**، فلا
يُشغَّل ههنا ولا يُحتسَب نجاحًا ولا إخفاقًا
(`AN_UNDERLYING_FORM_IS_A_SOURCE_ANALYSIS_NOT_A_DEPOSITED_BYTE`).

**والمحطّةُ الرابعة — الساكنان: شكلٌ يُقاس صحيحًا ويُسمّى وكيلًا لا ظاهرة.**
يُقاس في المُودَع شكلُ «حاملٌ أخيرٌ عليه شدّةٌ قبلَه حاملٌ بلا حركةٍ مُعلَنة»،
وفيه «الدَّوَابِّ» و«صَوَافَّ» اللذان سمّاهما البحث. وهو **وكيل**: يجمع ألفَ
المدّ وغيرَها في حَدٍّ واحد، فلا يُقرأ عددُه عددَ الساكنَين الملتقيَين
(`THE_SHAPE_MIXES_A_MADD_WITH_AN_UNMARKED_CONSONANT`). والمقروءُ منه حكمٌ
واحدٌ فقط: منعٌ صوتيٌّ مطلقٌ لالتقاء الساكنين يردُّ صورًا **مشهودةً** في
البايتات، فهو مردودٌ بها.

**ولا سلطانَ لهذه الوحدة.** لا تُرخّص ولادةً، ولا ترفع حظرًا، ولا تفكّ
تجميدًا، ولا تُدخِل مصدرًا في قياس
(`NO_EXAM_HERE_LIFTS_A_BLOCK_OR_THAWS_A_FREEZE`).
"""

