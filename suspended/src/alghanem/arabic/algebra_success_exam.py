THE_SAKINAYN_WITNESSES: Final[tuple[str, ...]] = ("الدَّوَابِّ", "صَوَافَّ")
"""الشاهدان اللذان سمّاهما البحثُ، وكلاهما مشهودٌ في المُودَع."""


def _bears_the_shape(form: str) -> bool:
    """أفي الصورة شكلُ «شدّةٌ أخيرةٌ بعد حاملٍ بلا حركةٍ مُعلَنة»؟"""

    carriers = carriers_of(form)
    if len(carriers) < 2:
        return False
    return SHADDA in carriers[-1].marks and carriers[-2].haraka is None


def sakinayn_station() -> StationReading:
    """المحطّةُ الرابعة: أيردُّ المنعُ المطلقُ صورًا مشهودةً في البايتات؟

    والشرطُ مُعلَنٌ قبل القياس: يُقبَل المنعُ المطلقُ لالتقاء الساكنين إن لم
    يردَّ صورةً مشهودةً واحدة. والمقيسُ **شكلٌ وكيلٌ** يُسمّى وكيلًا ولا
    يُقرأ عددُه عددَ الظاهرة (`THE_SHAPE_MIXES_A_MADD_WITH_AN_UNMARKED_CONSONANT`).
    """

    _assert_the_witnesses_are_attested()
    occurrences = 0
    distinct: set[str] = set()
    for word in _deposited_words():
        if _bears_the_shape(word):
            occurrences += 1
            distinct.add(word)
    named = sum(1 for form in THE_SAKINAYN_WITNESSES if _bears_the_shape(form))
    verdict = (
        StationVerdict.PASSED
        if occurrences == 0
        else StationVerdict.FALSIFIED_BY_AN_ATTESTED_FORM
    )
    return StationReading(
        name="الساكنان",
        question="أيردُّ المنعُ المطلقُ صورًا مشهودةً في المُودَع؟",
        passing_condition="صفرُ وقوعٍ للشكل في الصور المشهودة",
        measured=(
            ("وقوعاتُ الشكل", occurrences),
            ("الصورُ المتمايزةُ الحاملةُ له", len(distinct)),
            ("الشاهدان المُسمَّيان الحاملان له", named),
        ),
        verdict=verdict,
        detail=THE_SHAPE_MIXES_A_MADD_WITH_AN_UNMARKED_CONSONANT,
    )


