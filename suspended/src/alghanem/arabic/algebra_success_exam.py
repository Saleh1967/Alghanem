THE_ILAL_WITNESSES: Final[tuple[str, ...]] = ("قَوِيٌّ", "أَيَّامٍ")
"""شاهدان سمّاهما البحثُ ووُجدا مشهودَين في المُودَع؛ وغيرُهما لم يُدخَل."""


def ilal_rule_fires_at(form: str) -> tuple[int, ...]:
    """مواضعُ إيقاد القاعدة السطحيّة في صورةٍ مكتوبة، بالدليل لا بالدعوى.

    والقاعدةُ مُعلَنةٌ بنصّها لتكون قابلةً للتكذيب: *واوٌ أو ياءٌ تحمل حركةً
    مُعلَنةً غيرَ السكون، وقبلها حاملٌ عليه فتحةٌ ⇒ ألف*.
    """

    carriers = carriers_of(form)
    return tuple(
        index
        for index in range(1, len(carriers))
        if carriers[index].letter in ("و", "ي")
        and carriers[index].haraka is not None
        and carriers[index].haraka != SUKUN
        and carriers[index - 1].haraka == FATHA
    )


def ilal_station() -> StationReading:
    """المحطّةُ الثالثة: أتصمُد القاعدةُ السطحيّةُ أمام الصور المشهودة؟

    والشرطُ مُعلَنٌ قبل القياس: تجتاز المحطّةُ إن لم توقِد القاعدةُ على صورةٍ
    مشهودةٍ واحدة. فكلُّ إيقادٍ نقضٌ، لأنّ المشهودَ مخرَجٌ لا مدخل.
    """

    _assert_the_witnesses_are_attested()
    firings = 0
    tokens = 0
    distinct: set[str] = set()
    for word in _deposited_words():
        hits = len(ilal_rule_fires_at(word))
        if hits:
            firings += hits
            tokens += 1
            distinct.add(word)
    on_named = sum(len(ilal_rule_fires_at(form)) for form in THE_ILAL_WITNESSES)
    verdict = (
        StationVerdict.PASSED
        if firings == 0
        else StationVerdict.FALSIFIED_BY_AN_ATTESTED_FORM
    )
    return StationReading(
        name="الإعلال",
        question="أتوقِد القاعدةُ السطحيّةُ على صورةٍ مشهودةٍ في المُودَع؟",
        passing_condition="صفرُ إيقادٍ على الصور المشهودة",
        measured=(
            ("الإيقاداتُ كلُّها", firings),
            ("الكلماتُ التي أوقدت", tokens),
            ("الصورُ المتمايزةُ التي أوقدت", len(distinct)),
            ("الإيقاداتُ على الشاهدَين المُسمَّيَين", on_named),
        ),
        verdict=verdict,
        detail=A_RULE_THAT_FIRES_ON_AN_ATTESTED_FORM_IS_FALSIFIED_BY_IT,
    )


