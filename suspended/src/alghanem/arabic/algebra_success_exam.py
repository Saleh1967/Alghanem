"""أوجهُ الوقف الثلاثةُ منقولةً بأسمائها؛ ولا يُولَّد منها عددٌ على مادّة."""


def waqf_station() -> StationReading:
    """المحطّةُ الأولى: أتسع الحالةُ الواحدةُ لثلاثة أوجهٍ متمايزة؟

    والشرطُ مُعلَنٌ قبل القياس: تجتاز المحطّةُ إن كانت الحالاتُ التي يقبلها
    قانونُ الوقف من الحركات المُعلَنة **لا تقلّ** عن عدد الأوجه المنقولة.
    وكلا الطرفين يُشتَقّ عند كلّ نداء: الأوجهُ من سجلّها، والحالاتُ من
    `THE_DECLARED_HARAKAT` بعد ترشيح قانون الوقف.
    """

    _verify_the_pausal_faces_are_distinct()
    faces = len(THE_PAUSAL_FACES)
    admitted = sum(1 for mark in THE_DECLARED_HARAKAT if mark in THE_PAUSAL_LAW_ADMITS)
    carried = sum(1 for face in THE_PAUSAL_FACES if face.declared_haraka is not None)
    verdict = (
        StationVerdict.PASSED
        if admitted >= faces
        else StationVerdict.DISCRIMINATION_IMPOSSIBLE_BY_COUNT
    )
    return StationReading(
        name="الوقف",
        question="أتُميّز الحالةُ الواحدةُ بين السكون والروم والإشمام؟",
        passing_condition="الحالاتُ المقبولةُ في الوقف ≥ الأوجهُ المنقولة",
        measured=(
            ("الأوجهُ المنقولة", faces),
            ("ما يقبله قانونُ الوقف من الحركات المُعلَنة", admitted),
            ("الأوجهُ التي تُحمَل على حركةٍ مُعلَنة", carried),
        ),
        verdict=verdict,
        detail=THE_THREE_PAUSAL_FACES_ARE_NOT_ONE_STATE,
    )


