def exam_stations() -> tuple[StationReading, ...]:
    """محطّاتُ الامتحان الأربع، مُعادًا تشغيلُها عند كلّ نداء بلا خزنٍ لحكم."""

    return (
        waqf_station(),
        ibtida_station(),
        ilal_station(),
        sakinayn_station(),
    )


def exam_standing(readings: tuple[StationReading, ...] | None = None) -> ExamStanding:
    """منزلةُ الامتحان: لا تُجمَع من أكثرِ المحطّات، ومحطّةٌ واحدةٌ تخرقه."""

    stations = exam_stations() if readings is None else readings
    if not stations:
        raise AlgebraSuccessExamError("امتحانٌ بلا محطّةٍ لا يُخرِج منزلة.")
    if all(station.passed for station in stations):
        return ExamStanding.PASSED_EVERY_STATION
    return ExamStanding.FAILED_AT_A_NAMED_STATION


def the_block_and_the_freeze_are_untouched() -> bool:
    """لا حظرَ يُرفَع ولا تجميدَ يُفكّ بهذا الامتحان؛ وتُعاد الجملةُ ليُحتَجّ بها."""

    return NO_EXAM_HERE_LIFTS_A_BLOCK_OR_THAWS_A_FREEZE.startswith(
        "NO_EXAM_HERE_LIFTS_A_BLOCK_OR_THAWS_A_FREEZE"
    )


