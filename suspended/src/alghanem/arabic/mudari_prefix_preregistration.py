class ClaimGenus(Enum):
    """جنسُ سندِ الدعوى؛ ولا تُرفَع دعوًى من جنسٍ إلى ما فوقه."""

    TEXTUALLY_IN_THE_SOURCE = "منصوصٌ_في_ج٣"
