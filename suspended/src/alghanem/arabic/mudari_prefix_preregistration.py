def specification_digest() -> str:
    """بصمةُ محتوى المواصفة؛ فتبديلُ حرفٍ في الشرط أو في الحدّ يُغيّرها."""

    return canonical_digest(
        canonical_bytes(
            {
                "standing": STANDING.value,
                "ancillary_letters": list(THE_ANCILLARY_LETTERS),
                "wide_carriers": list(THE_WIDE_HAMZA_CARRIERS),
                "carrier_keys": [key.value for key in CarrierKey],
                "noun_filters": [item.value for item in NounFilter],
                "condition": THE_COUNTING_CONDITION,
                "minimum_slots": THE_MINIMUM_SLOTS,
                "noun_mark_filter": THE_NOUN_MARK_FILTER,
                "declared_defect": THE_DECLARED_DEFECT,
                "expectation": THE_ENTAILED_EXPECTATION,
                "expectation_floor": THE_ENTAILED_EXPECTATION_FLOOR,
                "unpredicted": THE_UNPREDICTED_QUESTION,
                "claims": [
                    [
                        claim.name,
                        claim.statement,
                        claim.genus.value,
                        claim.surface_can_see_it,
                    ]
                    for claim in THE_DECLARED_CLAIMS
                ],
            }
        )
    )


