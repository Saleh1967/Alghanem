_FORBIDDEN_FIELD_MARKERS: Final[tuple[str, ...]] = (
    "outcome",
    "result",
    "observed",
    "measured",
    "count",
    "share",
    "verdict",
    "birth",
)


def _assert_no_outcome_field() -> None:
    """لا حقلَ نتيجةٍ في وحدة تجميد؛ والنتيجةُ تُقاس في موضعها لا تُودَع هنا."""

    for dataclass_type in (DeclaredClaim,):
        for field in fields(dataclass_type):
            for word in field.name.split("_"):
                if word in _FORBIDDEN_FIELD_MARKERS:
                    raise MudariPrefixSpecificationError(
                        f"`{field.name}` حقلُ نتيجةٍ في وحدةِ تجميد؛ والنتيجةُ "
                        "تُقاس في `mudari_prefix_census` لا تُودَع هنا."
                    )


def _assert_the_three_genera_are_all_used() -> None:
    """الفرزُ لا يكون فرزًا إن خلا من جنسٍ؛ فيُفحَص حضورُ الأجناس الثلاثة."""

    used = {claim.genus for claim in THE_DECLARED_CLAIMS}
    if used != set(ClaimGenus):
        raise MudariPrefixSpecificationError(
            "جنسٌ من أجناس السند لا دعوى له؛ والفرزُ الذي لا يفرز ليس فرزًا."
        )


def _assert_the_source_claims_are_the_three_quoted_ones() -> None:
    """المنصوصُ ثلاثٌ لا تزيد؛ فمن أضاف رابعةً أسند إلى المصدر ما لم ينصّ عليه."""

    quoted = [
        claim
        for claim in THE_DECLARED_CLAIMS
        if claim.genus is ClaimGenus.TEXTUALLY_IN_THE_SOURCE
    ]
    if len(quoted) != 3:
        raise MudariPrefixSpecificationError(
            "المنصوصُ في ج٣ ثلاثُ دعاوى؛ وزيادتُها إسنادٌ إلى المصدر بلا نصّ."
        )


def _assert_the_expectation_can_fail() -> None:
    """حدٌّ لا يُكذَّب ليس توقُّعًا؛ فيُفحَص أنّه دون الواحد وفوق المصادفة."""

    if not 0.5 < THE_ENTAILED_EXPECTATION_FLOOR < 1.0:
        raise MudariPrefixSpecificationError(
            "حدُّ التوقُّع بين النصف والواحد؛ وما دونه لا يُكذَّب وما فوقه محال."
        )


def _assert_the_specification_is_frozen() -> None:
    current = specification_digest()
    if current != MUDARI_PREFIX_SPECIFICATION_DIGEST:
        raise MudariPrefixSpecificationError(
            f"بصمةُ المواصفة الآن {current}، والمُجمَّدةُ "
            f"{MUDARI_PREFIX_SPECIFICATION_DIGEST}؛ فقد بُدِّل فيها شيءٌ بعد "
            "التجميد، ولا يُمرَّر التبديلُ بتحذير."
        )


_assert_no_outcome_field()
_assert_the_three_genera_are_all_used()
_assert_the_source_claims_are_the_three_quoted_ones()
_assert_the_expectation_can_fail()
_assert_the_specification_is_frozen()
