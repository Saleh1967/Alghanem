"""ختمُ شرطِ حروف المضارعة **قبل العدّ**: دعاوى بمنازل مصادرها، وشرطٌ مُجمَّد.

وصل كلامٌ في حروف المضارعة الأربعة «أنيت»: بحرفها تكشف المسندَ إليه، وبحركتها
تكشف الوزنَ والبناءَ للمجهول. وفيه تنبيهٌ نفيسٌ على المصادر: المنصوصُ عند
النبهاني جملةٌ واحدةٌ، وسائرُ التفصيل من علم الصرف، والربطُ بين البابين
استنتاجٌ من قائله. وهذه الوحدة تُودِع ذلك **كما فُرِز**، وتَختم فوقه شرطَ عدٍّ
واحدًا ببصمةٍ لا تُبدَّل، **قبل أن تُقرأ بايتةٌ واحدة**. ويفترق ههنا ثلاثةٌ
كانت تُقرأ «قاعدةً» واحدة::

    TextuallyInTheSource   != FromTheScienceOfSarf
    FromTheScienceOfSarf   != TheSpeakersOwnInference
    ADeclaredDefect        != AMeasuredOne

**أوّلًا: المنزلةُ `سابقةٌ للدليل`، وهذه دعوى عن التاريخ تُصدِّقها البايتات.**
أُودِع هذا الملفُّ في التزامٍ مستقلٍّ **لا عدَّ فيه ولا رقمَ مقيس**، ثمّ أُجري
العدُّ في `mudari_prefix_census` في التزامٍ بعده. فسبقُ الشرط للعدّ مسجَّلٌ في
تاريخ الشجرة لا مُدَّعًى في نثرها، وهو الفرقُ بين هذه المواصفة و`imperative_
wasla_specification` المُعلَنة `مُصاغة_بعد_الرقم` تصريحًا
(`A_PRIOR_SPECIFICATION_MUST_BE_PRIOR_IN_THE_RECORD`).

**وثانيًا: الدعاوى مفروزةٌ بمصادرها، والفرزُ حكمٌ على السند لا على الصحّة.**
المنصوصُ في ج٣ ثلاثةٌ: أنّ المضارع ما في أوّله إحدى الزوائد الأربع، وأنّ «تاء
التأنيث الساكنة» حرفٌ، وأنّ الإسناد إلى غير من قام بالفعل مجازٌ في التركيب.
وما سواه — حركةُ حرف المضارعة، وحركةُ العين، وإسنادُ الضمائر، وحالاتُ التاء
الأربع في الماضي — **من علم الصرف لا من النصّ**. والربطُ بين المجرّد والوضع
الشخصيّ، وبين المزيد والوضع النوعيّ، **استنتاجُ قائله** صرّح به. فلا يُنقَل
واحدٌ من الثلاثة بمنزلة الآخر (`A_SOURCE_GENUS_TRAVELS_WITH_ITS_CLAIM`).

**وثالثًا: ولا يُقاس ههنا إلّا ما للسطح عليه سلطان.** كشفُ المسند إليه، وكونُ
الإشارة إلى ما في الذهن لا إلى الواقع، ودلالةُ حركة العين على البناء —
دعاوى **لا تُقاس على رسمٍ مشكولٍ بلا وَسْمٍ نحويّ**، وبايتاتُ `MASAQ` ليست في
هذه الشجرة. فالمقيسُ شيءٌ واحدٌ ضيّقٌ: توزيعُ حركة ما قبل الآخر في صورةٍ
سطحيّةٍ مُعرَّفةٍ بالحركات وحدَها. وما عداه يُودَع دعوًى بمنزلتها ولا يُحمَّل
على العدّ (`WHAT_THE_SURFACE_CANNOT_SEE_IS_NOT_COUNTED_HERE`).

**ورابعًا: العيبُ مُعلَنٌ قبل الرقم، ويُلزَم القياسُ بقياسه لا بذكره.** السطحُ
لا يفرّق الفعلَ من الاسم، و«أُمّ» و«نُور» و«تُراب» تبتدئ بهذه الحروف مضمومةً.
وإعلانُ العيب وحدَه لا يكفي؛ فيُلزَم العدُّ بشيئين: مصفاةٌ مُعلَنةٌ ههنا
(**التنوينُ علامةُ اسمٍ**، فما حمله ليس فعلًا)، ونشرُ الرقم **تحت المصفاة
وبدونها** معًا، ثمّ مراجعةُ أكثرِ الصور تكرارًا واحدةً واحدة. فيصير العيبُ
مقدارًا يُقرأ لا تحفُّظًا يُكتَب (`A_DECLARED_DEFECT_MUST_BE_MEASURED_NOT_NAMED`).

**وخامسًا: حاملُ الهمزة اختيارٌ، فيُعلَن مفتاحان لا واحد.** همزةُ المضارعة
تُرسَم في هذه المدوّنة `أ`، وقد تقع صورُ ألفٍ أخرى في أوّل الكلمة. وقد عُلِّمنا
في `ending_release_deposit` أنّ توسيعَ صورة الألف يقلب الخانةَ من صفرٍ إلى
ألفٍ ومئتين؛ فلا يُنشَر ههنا رقمٌ تحت حاملٍ واحدٍ مسكوتٍ عن أخيه، بل تحت
المفتاحين معًا (`A_HAMZA_CARRIER_IS_A_CHOICE_AND_ITS_LADDER_TRAVELS_WITH_IT`).

**وسادسًا: التوقُّعُ واحدٌ، ومُقيَّدٌ بما تستلزمه القاعدة وحدَها.** قاعدةُ
الصرف تقول: عينُ المزيد مكسورةٌ في المعلوم مفتوحةٌ في المجهول. فالمتوقَّعُ
المُلزِم: أن تكون حركةُ ما قبل الآخر كسرةً أو فتحةً في **٩٠٪ فأكثر** من
المُطابِق بعد المصفاة. وأمّا قسمةُ الكسر على الفتح — أيّهما أكثر — فلا توقُّعَ
لها ههنا البتّة، فمهما خرجت **لا تُقرأ تنبّؤًا تحقّق**
(`AN_UNPREDICTED_SPLIT_IS_NOT_A_CONFIRMED_PREDICTION`).

**خمولٌ سلطويّ**: لا ولادةَ هنا ولا حكمَ ولادةٍ ولا تجميدَ `E0`، ولا استيرادَ
من `kernel/` ولا من `program/`، ولا رقمَ مقيسٌ في هذا الملفّ، ولا بايتةَ
مدوّنةٍ تُقرأ فيه.
"""

