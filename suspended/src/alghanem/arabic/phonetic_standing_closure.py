@dataclass(frozen=True, slots=True)
class PhoneticFileClosure:
    """إغلاقُ الملفّ: منزلةٌ مُشتَقّة، وجنسُ حجزٍ مُسمًّى، وشرطُ رفعٍ مكتوب."""

    standing_record: PhoneticStandingRecord
    promotion_condition: str
    findings: tuple[ClosedPhoneticFinding, ...]
    search_records: tuple[ExternalSourceSearchRecord, ...]

    def __post_init__(self) -> None:
        if not isinstance(self.standing_record, PhoneticStandingRecord):
            raise PhoneticStandingError("الإغلاقُ يحمل منزلةً مُصدَرةً من بوّابتها")
        if not self.promotion_condition.strip():
            raise PhoneticStandingError(
                "إغلاقٌ بلا شرطِ رفعٍ مكتوبٍ عصمةٌ لا منزلة؛ فما لا يُنقَض "
                "بشرطٍ مُسمًّى لا يُقرأ حجزًا"
            )
        if not self.findings:
            raise PhoneticStandingError("إغلاقُ ملفٍّ بلا نتيجةٍ واحدةٍ ليس إغلاقًا")
        if not self.search_records:
            raise PhoneticStandingError(
                "دعوى «لا يوجد مصدرٌ» بلا سجلِّ بحثٍ مُودَعٍ غيرُ قابلةٍ لإعادة "
                "الاشتقاق؛ فتُودَع بأسمائها ونتائجها أو لا تُدَّعى"
            )
        known = {finding.identifier for finding in self.findings}
        if len(known) != len(self.findings):
            raise PhoneticStandingError("مُعرِّفُ نتيجةٍ لا يتكرّر في إغلاقٍ واحد")
        for finding in self.findings:
            if (
                finding.depends_on_finding is not None
                and finding.depends_on_finding not in known
            ):
                raise PhoneticStandingError(
                    f"تبعيّةٌ إلى نتيجةٍ غيرِ مُسجَّلةٍ هنا: " f"{finding.depends_on_finding!r}"
                )

    @property
    def standing(self) -> PhoneticStanding:
        """منزلةُ الملفّ كلِّه، مُشتَقّةً من سجلّها لا مكتوبةً بجانبها."""

        return self.standing_record.standing

    @property
    def unconstructibility_genus(self) -> UnconstructibilityGenus:
        """جنسُ امتناع الترقية، مُشتَقًّا: حجزٌ لغياب سلطةٍ اليوم لا امتناعٌ فئويّ."""

        return self.standing_record.unconstructibility_genus

    @property
    def residue_defined_identifiers(self) -> tuple[str, ...]:
        """النتائجُ التي عُرِّفت فئتُها بالباقي، مُشتَقّةً لا مكتوبةً في حقل."""

        return tuple(
            finding.identifier
            for finding in self.findings
            if finding.is_residue_defined
        )

    def as_canonical_content(self) -> dict[str, object]:
        """محتوى الإغلاق للبصمة."""

        return {
            "standing": self.standing.name,
            "unconstructibility_genus": self.unconstructibility_genus.name,
            "tagging_source": self.standing_record.tagging_source.name,
            "source_deposit": self.standing_record.source_deposit.name,
            "rule_independence": self.standing_record.rule_independence.name,
            "promotion_condition": self.promotion_condition,
            "findings": [finding.as_canonical_content() for finding in self.findings],
            "search_records": [
                record.as_canonical_content() for record in self.search_records
            ],
        }


