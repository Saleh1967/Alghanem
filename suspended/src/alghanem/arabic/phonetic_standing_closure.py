def _refuse_an_incoherent_closure() -> None:
    """احرس الوحدةَ عند الاستيراد: منزلةٌ مُشتَقّة، ومدوّنةٌ لم تصل، وبواقٍ مرتّبة."""

    if PHONETIC_FILE_CLOSURE.standing is not (
        PhoneticStanding.RULE_DERIVED_BY_DECLARED_RULE
    ):
        raise PhoneticStandingError(
            "منزلةُ الملفّ اليوم `مُستنتَج_بقاعدة_مُعلَنة`؛ وغيرُها إصدارٌ لا "
            "سلطةَ لهذه الشجرة به"
        )
    if PHONETIC_FILE_CLOSURE.unconstructibility_genus is not (
        UnconstructibilityGenus.HELD_BY_MISSING_AUTHORITY_TODAY
    ):
        raise PhoneticStandingError(THE_CLOSURE_IS_HELD_NOT_REFUSED_BY_CATEGORY_NOTE)
    if MEASURED_SAKIN_CLASH_SOURCES:
        raise PhoneticStandingError(
            "وصلت مدوّنةٌ مقيسةٌ إلى الشجرة؛ وأسبابُ تعذّر الاشتقاق المكتوبةُ "
            "هنا تُراجَع معها ولا تبقى بحالها"
        )
    for declaring_type in (
        ClosedPhoneticFinding,
        ExternalSourceSearchRecord,
        PhoneticFileClosure,
    ):
        declared = {item.name for item in fields(declaring_type)}
        for marker in _FORBIDDEN_FIELD_MARKERS:
            if any(marker in name for name in declared):
                raise PhoneticStandingError(
                    f"حقلُ {marker!r} لا يكون في صنفٍ يُسجّل منزلةً مُشتَقّة"
                )
    if list(PHONETIC_CLOSURE_NAMED_RESIDUALS) != sorted(
        PHONETIC_CLOSURE_NAMED_RESIDUALS
    ):
        raise PhoneticStandingError("البواقي المُسمّاةُ تُرتَّب ترتيبًا ثابتًا")


_refuse_an_incoherent_closure()
