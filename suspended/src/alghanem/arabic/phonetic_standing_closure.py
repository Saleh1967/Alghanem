@dataclass(frozen=True, slots=True)
class PhoneticStandingRecord:
    """منزلةُ نتيجةٍ واحدة، مُشتَقّةً من حواملها ومُصدَرةً من البوّابة وحدها."""

    tagging_source: TaggingSource
    source_deposit: SourceDeposit
    rule_independence: RuleIndependence
    _token: object | None = field(default=None, repr=False, compare=False)

    def __post_init__(self) -> None:
        if self._token is not _GATE_TOKEN:
            raise PhoneticStandingError(
                "المنزلةُ لا تُنشَأ إلّا من `PhoneticStandingGate`؛ والكتابةُ "
                "المباشرة إعلانُ منزلةٍ لا اشتقاقُها"
            )
        for value, name in (
            (self.tagging_source, "مصدرُ الوسم"),
            (self.source_deposit, "حالُ الإيداع"),
            (self.rule_independence, "استقلالُ القاعدة"),
        ):
            if not isinstance(value, TaggingSource | SourceDeposit | RuleIndependence):
                raise PhoneticStandingError(f"{name} عضوٌ في مفردته المغلقة")

    @property
    def standing(self) -> PhoneticStanding:
        """المنزلةُ مُشتَقّةً من الحوامل الثلاثة، لا مكتوبةً بجانبها."""

        if (
            self.tagging_source is TaggingSource.HUMAN_LETTER_BY_LETTER
            and self.source_deposit is SourceDeposit.DIGESTED_AND_DEPOSITED
            and self.rule_independence
            is RuleIndependence.INDEPENDENT_OF_OUR_DERIVATION_RULE
        ):
            return PhoneticStanding.INDEPENDENTLY_VERIFIED
        return PhoneticStanding.RULE_DERIVED_BY_DECLARED_RULE

    @property
    def unconstructibility_genus(self) -> UnconstructibilityGenus:
        """جنسُ امتناع الترقية: حجزٌ لغياب سلطةٍ اليوم، لا امتناعٌ فئويّ."""

        return UnconstructibilityGenus.HELD_BY_MISSING_AUTHORITY_TODAY


class PhoneticStandingGate:
    """المُصدِر الوحيد لمنزلةٍ صوتيّة؛ ويردّ الترقيةَ بعلّتها المكتوبة."""

    @staticmethod
    def issue(
        tagging_source: TaggingSource,
        source_deposit: SourceDeposit,
        rule_independence: RuleIndependence,
    ) -> PhoneticStandingRecord:
        """اشتقّ المنزلةَ من الحوامل؛ ولا تُصدِر ما لا سلطةَ لهذه الشجرة به."""

        record = PhoneticStandingRecord(
            tagging_source=tagging_source,
            source_deposit=source_deposit,
            rule_independence=rule_independence,
            _token=_GATE_TOKEN,
        )
        if record.standing is PhoneticStanding.INDEPENDENTLY_VERIFIED:
            raise PhoneticStandingError(
                "`مُتحقَّق_منه_استقلاليًّا` مُعلَنةٌ وغيرُ قابلةٍ للإصدار اليوم: "
                "لم تصل إلى هذه الشجرة مدوّنةٌ موسومةٌ بشريًّا مُبصَّمةٌ مستقلّةٌ "
                f"عن قاعدة اشتقاقنا. وشرطُ الرفع مكتوب: {PROMOTION_CONDITION}"
            )
        return record


@dataclass(frozen=True, slots=True)
class ExternalSourceSearchRecord:
    """مصدرٌ خارجيٌّ فُحص: اسمُه، ورخصتُه، وطريقةُ وسمه، وسببُ ردّه.

    و`refusal_is_final` تفصل ردًّا باتًّا لبنية الصيغة عن ردٍّ يرفعه تغيُّرُ
    حالِ المصدر؛ ودمجُهما يجعل «مرفوض» يُقرأ انتظارًا حيث لا انتظار، أو
    يُقرأ باتًّا حيث لا بتّ.
    """

    source_id: str
    license_text: str
    tagging_method: str
    refusal_reasons: tuple[str, ...]
    refusal_is_final: bool
    why_the_refusal_stands_or_lifts: str

    def __post_init__(self) -> None:
        for value, name in (
            (self.source_id, "اسمُ المصدر"),
            (self.license_text, "الرخصة"),
            (self.tagging_method, "طريقةُ توليد الوسوم"),
            (self.why_the_refusal_stands_or_lifts, "حالُ الردّ"),
        ):
            if not isinstance(value, str) or not value.strip():
                raise PhoneticStandingError(f"{name} نصٌّ غير فارغ")
        if not self.refusal_reasons or any(
            not reason.strip() for reason in self.refusal_reasons
        ):
            raise PhoneticStandingError(
                "مصدرٌ مردودٌ بلا سببٍ مُسمًّى ردٌّ لا يُفحَص؛ ودعوى العدم "
                "تُودَع بأسبابها لا بدعواها"
            )

    def as_canonical_content(self) -> dict[str, object]:
        """محتوى سجلّ البحث للبصمة."""

        return {
            "source_id": self.source_id,
            "license_text": self.license_text,
            "tagging_method": self.tagging_method,
            "refusal_reasons": list(self.refusal_reasons),
            "refusal_is_final": self.refusal_is_final,
            "why_the_refusal_stands_or_lifts": self.why_the_refusal_stands_or_lifts,
        }


