"""جسرُ المعجم بأرجلٍ ثلاث: المدخل↔الكلمة · المادّة↔العائلة · الشاهد↔الآية.

**ما جاءت إليه هذه الوحدة**: كان المعجمُ يدخل هذه الشجرةَ من نافذة
الاستشهاد — «قال ابن فارس» و«في لسان العرب» — والاستشهادُ نقلٌ لا يُكذَّب.
وههنا يدخل من بابه: **قائمةٌ مغلقةٌ معلنةُ التعداد + قاعدةُ عدٍّ معلنةٌ قبل
القياس + عددٌ مقفلٌ يُعاد اشتقاقُه**. فلا مدخلَ ولا مادّةَ ولا شاهدَ يدخل
إلّا بهذا الثلاثيّ، وكلُّ رقمٍ يخرج من هنا قابلٌ للتكذيب ببايتاته.

`A_CITATION_IS_NOT_A_MEASUREMENT`: «قال المعجمُ كذا» خبرٌ لا مقامَ له، فلا
يُصدَّق ولا يُكذَّب. و«هذه المادّةُ حضورُها كذا واتّساعُها كذا» عددٌ تحت قاعدةٍ
على بايتاتٍ مبصومة، فيُردّ بإعادة القياس. والفرقُ بينهما بابُ هذه الوحدة كلِّه.

`A_CLOSED_LIST_IS_THE_UNIT_OF_ADMISSION`: لا يدخل شيءٌ فردًا. الداخلُ قائمةٌ
مُعلَنٌ تعدادُها قبل فتحها، ويُمسَك تعدادُها بحارسٍ عند الاستيراد؛ فزيادةُ مادّةٍ
صامتةً أو حذفُها تُوقِف الوحدةَ ولا تُزحزح رقمًا في صمت.

`A_FRAME_PROXY_IS_NOT_A_ROOT_ANALYSIS`: قاعدةُ المطابقة ههنا **وكيلُ إطار**:
حروفُ المادّة الثلاثةُ متتاليةً في رمزٍ واحد على ترتيبها لا على تجاورها. وليست
تحليلًا صرفيًّا ولا اشتقاقًا: تُصيب ما ليس من المادّة (`proxy_false_admissions`
تُخرِج أعيانَه من البايتات)، وتُخطئ ما هو منها إذا سقط حرفٌ من حروفه في الرسم.
فمن قرأ عددَها «عددَ مشتقّات المادّة» قرأ غيرَ ما قيس، وهو الصنفُ نفسُه الذي
سُجِّل في `tawlid_algebra_ledger`: بصمةٌ تُقاس صحيحةً ثمّ تُسمّى باسم ظاهرةٍ
ليست هي.

`A_SURFACE_FORM_IS_NOT_A_MORPHOLOGICAL_FAMILY`: «العائلة» ههنا صورةٌ سطحيّةٌ
متمايزةٌ تحت القاعدة، لا عائلةٌ صرفيّة. فـ«كتاب» و«كتابا» عائلتان بهذا العدّ
وهما من وزنٍ واحد، و«الكتاب» ثالثةٌ بلامها. والاسمُ مُعلَنٌ كذلك كيلا يُقرأ
اتّساعًا صرفيًّا وهو تعدادُ رسوم.

`PRESENCE_IN_THE_TEXT_IS_NOT_PRESENCE_IN_THE_LEXICON`: رجلان مختلفان، ولكلٍّ
عددُه. حضورُ المادّة في المدوّنة يُقاس بوكيل الإطار، وحضورُها مدخلًا في المعجم
يُقاس بمطابقة خانة الجذر في جدولٍ مُودَع. والعشرون تحضر كلُّها في المدوّنة
ولا تحضر كلُّها في المعجم المُودَع؛ ولو طُويا في رقمٍ واحدٍ لضاع الفرق.

`THE_GEMINATE_COLLAPSE_IS_A_REFUSED_RULE_NOT_A_SECOND_COUNT`: ردُّ المضاعف
«حبب» إلى «حب» قاعدةٌ **مرفوضةٌ باسمها** في `root_orthography_bridge`
(`حذف_التضعيف`): تُبدِّل المعدودَ لا رسمَه، و`root_type` في «مقاييس» يفصل
المضاعفَ من الثلاثيّ بنصّه. فلا تُخرَج ههنا عدًّا ثانيًا مُرخَّصًا؛ تُخرَج
**ثمنًا** في `price_of_the_refused_collapse` ليُرى ما تصنعه، ومنزلتُها مرفوضةٌ
لا مختارة.

`THE_QUOTED_TOTALS_ARE_NOT_REPRODUCED_ON_THESE_BYTES`: وردت أرقامٌ منقولةٌ
للعرض الأوّل — حضورٌ 20/20، واتّساعٌ 1,132 عائلة، وورودٌ 5,450 موضعًا، وصدرٌ
«علم 1,448» وتاليه «حب 399»، وصفٌّ «قرأ: 4 عائلات في 8 مواضع». وهي محفوظةٌ
بحروفها في `THE_QUOTED_FIRST_EXHIBIT`، وحفظُها ليس تصديقَها: تُصادَم كلُّها
في `quoted_figures_reading`. والمصادمةُ تُخرِج ثلاثةَ أحكامٍ لا حكمين —
موافقٌ، ومخالفٌ، وموافقٌ **تحت قاعدةٍ مرفوضة** — إذ «حب 399» لا يبلغه إلّا
حذفُ التضعيف، فموافقتُه شهادةٌ على قاعدةِ الناقل لا على بايتاتنا.

`THE_WITNESS_LEG_IS_VACANT_AND_ITS_VACANCY_IS_MEASURED`: رجلُ الشاهد نصفُها
مبنيٌّ ونصفُها خالٍ، والخلوُّ **مقيسٌ لا مقول**. فجانبُ المدوّنة مبنيٌّ: شبكةُ
(مادّة × آية) تُخرَج بأعدادها. وجانبُ المعجم غيرُ موصولٍ بها: شواهدُ الجدول
المُودَع مقاطعُ شعرٍ لا آياتٍ — تُقاس حضورًا في `witness_leg_reading` ولا
يُلتمَس فيها إسنادٌ إلى آية — وخاناتُ الجدول المُعلَنةُ ليس فيها خانةُ آية.
ولو نزلت نسخةٌ مفرَّغةٌ بختمها تحمل إسنادَ الشواهد إلى الآيات لانقلب هذا
الحكمُ من نفسه بلا تحرير حرفٍ ههنا.

`AN_ABSENCE_IS_CLAIMED_ONLY_AFTER_A_POSITIVE_WITNESS`: كلُّ نفيٍ ههنا يجتاز
شاهدًا موجِبًا أوّلًا: يُعَدُّ ما يُقارِب المطلوب فيوجد كثيرًا — مداخلُ الجدول
بالآلاف، ومقاطعُ شواهده بالآلاف — فالأداةُ تقرأ، وما لم تجده غائبٌ لا مُغفَل.

**ولا سلطةَ لهذه الوحدة**: لا ولادةَ فيها، ولا حكمَ ولادة، ولا تجميدَ `E0`،
ولا تستورد من `kernel/` ولا من `program/`، ولا تقرؤها بوّابةٌ فيهما.

المصادر: «معجم مقاييس اللغة» لابن فارس، مفرَّغًا في `maqayis_by_root_csv_999.csv`
المُبصَّم في هذه الشجرة؛ ونصُّ تنزيل `quran-simple-enhanced.txt` المُبصَّم في
`corpora/`. والإسنادُ إليهما شرطُ رخصةٍ لا لطفَ عبارة.
"""

