THE_WITHHELD_LEXICON: Final[str] = "لسان العرب — نسخةٌ مفرَّغةٌ بختمها"
"""المعجمُ الذي يسدّ رجلَ الشاهد؛ ولا بايتَ منه في هذه الشجرة."""

THE_REFUSED_COLLAPSE_RULE: Final[str] = "حذف_التضعيف"
"""اسمُ القاعدة المرفوضة في `root_orthography_bridge`، منقولًا ليُقابَل بها."""


class EntryStage(Enum):
    """مقاماتُ مطابقة المدخل: الرسمُ كما هو، ثمّ التطبيعُ بقاعدتَي الهمزة."""

    AS_WRITTEN = "الرسمُ كما هو"
    HAMZA_TO_BARE_ALIF = "همزة_إلى_ألف_عارية"
    HAMZA_TO_CARRIED_ALIF = "همزة_إلى_ألف_حاملة"


class QuotedStanding(Enum):
    """حكمُ رقمٍ منقولٍ بعد مصادمته؛ ثلاثةٌ لا اثنان."""

    REPRODUCED = "صمد"
    REFUTED = "سقط"
    REACHED_ONLY_BY_A_REFUSED_RULE = "لا يُبلَغ إلّا بقاعدةٍ مرفوضة"


_ARABIC_COMBINING_MARKS: Final[frozenset[str]] = frozenset(
    chr(codepoint)
    for codepoint in range(0x0600, 0x0700)
    if unicodedata.category(chr(codepoint)) == "Mn"
)


def _bare(token: str) -> str:
    """صورةُ الرمز مجرّدةً من علامات الكتلة العربيّة، بلا مساسٍ بحرف."""

    return "".join(char for char in token if char not in _ARABIC_COMBINING_MARKS)


def _corpus_text() -> str:
    return read_quran_corpus_bytes().decode("utf-8")


@lru_cache(maxsize=1)
def corpus_ayahs() -> tuple[tuple[str, ...], ...]:
    """آياتُ المدوّنة، كلُّ آيةٍ رموزُها مجرّدةً بعد طرح مِرماز الناشر.

    والخزنُ خزنُ أداءٍ لا خزنُ حكم: البايتاتُ تُطابَق طولًا وبصمةً في
    `read_quran_corpus_bytes` قبل أن تصل إلى هنا، فلا يدخل الخزنَ ما لم
    يجتز البوّابة.
    """

    collected: list[tuple[str, ...]] = []
    for line in _corpus_text().split("\n"):
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        collected.append(
            tuple(
                _bare(token)
                for token in stripped.split()
                if not token.startswith(THE_MARKUP_TOKEN_PREFIX)
            )
        )
    return tuple(collected)


def corpus_tokens() -> tuple[str, ...]:
    """رموزُ المدوّنة كلُّها تحت `TOKEN_COUNTING_RULE`، مرتَّبةً كما وردت."""

    return tuple(token for ayah in corpus_ayahs() for token in ayah)


def _material_hits_token(material: str, token: str) -> bool:
    """أتُصيب المادّةُ هذا الرمزَ بوكيل الإطار؟ ترتيبًا لا تجاورًا."""

    position = 0
    for char in token:
        if char == material[position]:
            position += 1
            if position == len(material):
                return True
    return False


@dataclass(frozen=True)
class MaterialReading:
    """قراءةُ مادّةٍ واحدة: عائلاتُها وورودُها وآياتُها، كلُّها مقيسة."""

    material: str
    families: int
    occurrences: int
    ayahs: int

    def __post_init__(self) -> None:
        if self.families > self.occurrences:
            raise LexiconBridgeError(
                f"«{self.material}»: عائلاتٌ أكثرُ من ورودٍ — قاعدةٌ منكسرة."
            )
        if self.ayahs > self.occurrences:
            raise LexiconBridgeError(
                f"«{self.material}»: آياتٌ أكثرُ من ورودٍ — قاعدةٌ منكسرة."
            )

    @property
    def is_present(self) -> bool:
        """الحضورُ ورودٌ واحدٌ فأكثر؛ ولا حضورَ بصفر."""

        return self.occurrences > 0


def _readings_for(materials: Iterable[str]) -> tuple[MaterialReading, ...]:
    ayahs = corpus_ayahs()
    readings: list[MaterialReading] = []
    for material in materials:
        forms: set[str] = set()
        occurrences = 0
        touched = 0
        for ayah in ayahs:
            hit_here = False
            for token in ayah:
                if _material_hits_token(material, token):
                    forms.add(token)
                    occurrences += 1
                    hit_here = True
            if hit_here:
                touched += 1
        readings.append(
            MaterialReading(
                material=material,
                families=len(forms),
                occurrences=occurrences,
                ayahs=touched,
            )
        )
    return tuple(readings)


@lru_cache(maxsize=1)
def material_readings() -> tuple[MaterialReading, ...]:
    """قراءاتُ العشرين بترتيب القائمة، تحت القاعدة المُعلَنة وحدَها."""

    return _readings_for(THE_TWENTY_MATERIALS)


@dataclass(frozen=True)
class FamilyLegCensus:
    """تعدادُ رجل المادّة: حضورٌ واتّساعٌ وورودٌ ومتصدِّر، بلا رقمٍ منقول."""

    declared: int
    present: int
    families: int
    occurrences: int
    leader: str
    leader_occurrences: int

    @property
    def presence_is_complete(self) -> bool:
        """أحضرت العشرون كلُّها؟ وهو سؤالٌ يُجاب بالعدّ لا بالدعوى."""

        return self.present == self.declared


def family_leg_census() -> FamilyLegCensus:
    """رجلُ المادّة مقيسةً: العشرون على بايتاتٍ مُبصَّمةٍ بقاعدةٍ مُعلَنة."""

    readings = material_readings()
    leader = max(readings, key=lambda reading: reading.occurrences)
    return FamilyLegCensus(
        declared=DECLARED_CARDINALITY,
        present=sum(1 for reading in readings if reading.is_present),
        families=sum(reading.families for reading in readings),
        occurrences=sum(reading.occurrences for reading in readings),
        leader=leader.material,
        leader_occurrences=leader.occurrences,
    )


def _stage_rules(stage: EntryStage) -> tuple[NormalisationRule, ...]:
    if stage is EntryStage.AS_WRITTEN:
        return ()
    by_name = {rule.name: rule for rule in NORMALISATION_RULES}
    hamza = by_name[stage.value]
    return (
        hamza,
        by_name["ألف_مقصورة_إلى_ياء"],
        by_name["تاء_مربوطة_إلى_تاء"],
    )


def _normalised(form: str, rules: tuple[NormalisationRule, ...]) -> str:
    if not rules:
        return form
    return normalise_root(form, rules).after


@lru_cache(maxsize=1)
def _deposited_entries() -> tuple[str, ...]:
    return tuple(row[THE_ENTRY_COLUMN] for row in root_table_rows())


@dataclass(frozen=True)
class EntryLegCensus:
    """تعدادُ رجل المدخل عند مقامٍ واحد؛ والمقامُ وسيطٌ إلزاميٌّ لا افتراضيّ."""

    stage: EntryStage
    declared: int
    entries_in_the_lexicon: int
    absent: tuple[str, ...]
    deposited_entries: int

    def __post_init__(self) -> None:
        if self.entries_in_the_lexicon + len(self.absent) != self.declared:
            raise LexiconBridgeError(
                "الحاضرُ والغائبُ لا يُكمِلان التعدادَ المُعلَن؛ قاعدةٌ منكسرة."
            )


def entry_leg_census(stage: EntryStage) -> EntryLegCensus:
    """حضورُ العشرين مداخلَ في الجدول المُودَع، عند مقامٍ مُصرَّحٍ به.

    والمقامُ لا يُختار ههنا نيابةً عن أحد: قاعدتا الهمزة مسنونتان كلتاهما في
    `root_orthography_bridge`، فيُطلَب المقامُ وسيطًا ويُخرَج العددُ باسمه.
    """

    if not isinstance(stage, EntryStage):
        raise LexiconBridgeError("مقامُ المطابقة وسيطٌ إلزاميٌّ من `EntryStage`.")
    rules = _stage_rules(stage)
    deposited = _deposited_entries()
    normalised_side = {_normalised(entry, rules) for entry in deposited}
    absent = tuple(
        material
        for material in THE_TWENTY_MATERIALS
        if _normalised(material, rules) not in normalised_side
    )
    return EntryLegCensus(
        stage=stage,
        declared=DECLARED_CARDINALITY,
        entries_in_the_lexicon=DECLARED_CARDINALITY - len(absent),
        absent=absent,
        deposited_entries=len(set(deposited)),
    )


@dataclass(frozen=True)
class WitnessLegReading:
    """رجلُ الشاهد: شبكتُنا مقيسةً، وجانبُ المعجم مقيسَ الخلوّ لا مقولَه."""

    edges: int
    ayahs_touched: int
    ayahs_in_the_corpus: int
    lexicon_witness_segments: int
    lexicon_has_an_ayah_column: bool
    withheld_lexicon: str

    @property
    def the_join_is_readable(self) -> bool:
        """أيُقرأ وصلُ شاهدِ المعجم بآيةٍ؟ لا يُقرأ إلّا بخانةِ إسنادٍ إليها."""

        return self.lexicon_has_an_ayah_column


def witness_leg_reading() -> WitnessLegReading:
    """الشبكةُ عندنا بأعدادها، وخلوُّ جانب المعجم بشاهدٍ موجِبٍ قبله.

    والشاهدُ الموجِبُ مقيسٌ في الحقلين: مقاطعُ شواهد الجدول تُعَدُّ فتكون
    بالآلاف، ومداخلُه تُعَدُّ فتكون بالآلاف؛ فالأداةُ تقرأ، وانتفاءُ خانة
    الآية انتفاءٌ في البايتات لا في القراءة.
    """

    readings = material_readings()
    columns = frozenset(root_table_rows()[0])
    return WitnessLegReading(
        edges=sum(reading.ayahs for reading in readings),
        ayahs_touched=len(
            {
                index
                for index, ayah in enumerate(corpus_ayahs())
                for material in THE_TWENTY_MATERIALS
                if any(_material_hits_token(material, token) for token in ayah)
            }
        ),
        ayahs_in_the_corpus=len(corpus_ayahs()),
        lexicon_witness_segments=count_witness_segments(),
        lexicon_has_an_ayah_column=any("ayah" in column for column in columns),
        withheld_lexicon=THE_WITHHELD_LEXICON,
    )


def proxy_false_admissions(material: str, limit: int = 8) -> tuple[str, ...]:
    """صورٌ أصابها الوكيلُ في المدوّنة، تُعرَض ليُرى أنّه وكيلٌ لا تحليل.

    ولا يحكم هذا الجسرُ على صورةٍ بأنّها من المادّة أو ليست منها: يُخرِج
    أطولَ ما أصابه الوكيلُ، وحكمُ الاشتقاق لصاحبه لا لهذه الوحدة.
    """

    if material not in THE_TWENTY_MATERIALS:
        raise LexiconBridgeError(f"«{material}» ليست من القائمة المغلقة المُعلَنة.")
    if limit < 1:
        raise LexiconBridgeError("حدُّ العرض لا يكون دون واحد.")
    hits = {
        token
        for ayah in corpus_ayahs()
        for token in ayah
        if _material_hits_token(material, token)
    }
    return tuple(sorted(hits, key=lambda token: (-len(token), token))[:limit])


@dataclass(frozen=True)
class RefusedRulePrice:
    """ثمنُ القاعدة المرفوضة: ما كانت تصنعه لو أُعمِلت، ومنزلتُها مرفوضة."""

    rule_name: str
    why_it_is_refused: str
    families: int
    occurrences: int
    families_added: int
    occurrences_added: int

    @property
    def is_licensed(self) -> bool:
        """أمُرخَّصةٌ؟ لا. والحقلُ مكتوبٌ ليُقرأ الجوابُ ولا يُفترَض."""

        return False


def price_of_the_refused_collapse() -> RefusedRulePrice:
    """ما يصنعه حذفُ التضعيف بالعددين، معروضًا ثمنًا لا عدًّا مُرخَّصًا."""

    refused = next(
        rule for rule in REFUSED_RULES if rule.name == THE_REFUSED_COLLAPSE_RULE
    )
    collapsed = _readings_for(
        material[:2] if material[1] == material[2] else material
        for material in THE_TWENTY_MATERIALS
    )
    licensed = family_leg_census()
    families = sum(reading.families for reading in collapsed)
    occurrences = sum(reading.occurrences for reading in collapsed)
    return RefusedRulePrice(
        rule_name=refused.name,
        why_it_is_refused=refused.why_it_is_refused,
        families=families,
        occurrences=occurrences,
        families_added=families - licensed.families,
        occurrences_added=occurrences - licensed.occurrences,
    )


@dataclass(frozen=True)
class QuotedFigure:
    """رقمٌ منقولٌ بحروفه، بإزاء ما قِيس، بحكمٍ مشتقٍّ لا مكتوب."""

    name: str
    quoted: int
    measured: int
    standing: QuotedStanding


THE_QUOTED_FIRST_EXHIBIT: Final[dict[str, int]] = {
    "الحضورُ في المدوّنة": 20,
    "الاتّساع: عائلات": 1_132,
    "الورود: مواضع": 5_450,
    "صدرُ الورود: علم": 1_448,
    "تاليه: حب": 399,
    "قرأ: عائلات": 4,
    "قرأ: مواضع": 8,
}
"""أرقامُ العرض الأوّل الواردةُ نقلًا، محفوظةً بحروفها ومُصادَمةٌ كلُّها."""


def quoted_figures_reading() -> tuple[QuotedFigure, ...]:
    """مصادمةُ كلِّ رقمٍ منقولٍ بما تُخرِجه البايتاتُ تحت القاعدة المُعلَنة."""

    census = family_leg_census()
    readings = {reading.material: reading for reading in material_readings()}
    price = price_of_the_refused_collapse()
    collapsed_hab = _readings_for(("حب",))[0]
    figures = (
        ("الحضورُ في المدوّنة", census.present),
        ("الاتّساع: عائلات", census.families),
        ("الورود: مواضع", census.occurrences),
        ("صدرُ الورود: علم", readings["علم"].occurrences),
        ("قرأ: عائلات", readings["قرأ"].families),
        ("قرأ: مواضع", readings["قرأ"].occurrences),
    )
    collided = [
        QuotedFigure(
            name=name,
            quoted=THE_QUOTED_FIRST_EXHIBIT[name],
            measured=measured,
            standing=(
                QuotedStanding.REPRODUCED
                if measured == THE_QUOTED_FIRST_EXHIBIT[name]
                else QuotedStanding.REFUTED
            ),
        )
        for name, measured in figures
    ]
    collided.append(
        QuotedFigure(
            name="تاليه: حب",
            quoted=THE_QUOTED_FIRST_EXHIBIT["تاليه: حب"],
            measured=readings["حبب"].occurrences,
            standing=(
                QuotedStanding.REACHED_ONLY_BY_A_REFUSED_RULE
                if collapsed_hab.occurrences == THE_QUOTED_FIRST_EXHIBIT["تاليه: حب"]
                and readings["حبب"].occurrences != THE_QUOTED_FIRST_EXHIBIT["تاليه: حب"]
                else QuotedStanding.REFUTED
            ),
        )
    )
    if price.occurrences_added <= 0:
        raise LexiconBridgeError("القاعدةُ المرفوضةُ لم تُغيّر عددًا؛ فعرضُ ثمنها بلا معنًى.")
    return tuple(collided)


