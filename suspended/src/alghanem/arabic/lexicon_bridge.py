@dataclass(frozen=True)
class LegDeclaration:
    """إعلانُ رجلٍ قبل قياسها: مقابلُها عندنا، وما يُقاس فيها، ومنزلتُها."""

    leg: BridgeLeg
    our_side: str
    what_is_measured: str
    standing: LegStanding

    def __post_init__(self) -> None:
        if not self.our_side.strip():
            raise LexiconBridgeError("رجلٌ بلا مقابلٍ عندنا لا تُقاس.")
        if not self.what_is_measured.strip():
            raise LexiconBridgeError("رجلٌ بلا معدودٍ مُعلَنٍ ليست رجلًا.")


