def locked_counts_have_drifted() -> tuple[str, ...]:
    """أسماءُ ما انزاح من الأعداد المقفلة؛ وفراغُها شهادةُ ثباتٍ لا دعواه."""

    regenerated = _regenerated_counts()
    return tuple(
        locked.name
        for locked in THE_LOCKED_COUNTS
        if regenerated[locked.name] != locked.value
    )


def _assert_the_closed_list_matches_its_declaration() -> None:
    """حارسُ القائمة المغلقة: تعدادُها المُعلَنُ يُمسَك عند الاستيراد."""

    if len(THE_TWENTY_MATERIALS) != DECLARED_CARDINALITY:
        raise LexiconBridgeError(
            "تعدادُ القائمة خالفَ المُعلَن؛ ولا تُفتَح قائمةٌ بلا تعدادٍ يسبقها."
        )
    if len(set(THE_TWENTY_MATERIALS)) != DECLARED_CARDINALITY:
        raise LexiconBridgeError("مادّةٌ مكرّرةٌ في القائمة المغلقة؛ فالتعدادُ كاذب.")
    for material in THE_TWENTY_MATERIALS:
        if len(material) != 3:
            raise LexiconBridgeError(
                f"«{material}» ليست ثلاثيّةً، وقاعدةُ الوكيل مسنونةٌ على ثلاثة."
            )


def _assert_the_legs_are_three_and_distinct() -> None:
    """حارسُ الأرجل: ثلاثٌ بأعيانها، لا تُطوى واحدةٌ في أخرى."""

    if len(THE_THREE_LEGS) != len(BridgeLeg):
        raise LexiconBridgeError("أرجلُ الجسر ثلاثٌ مُعلَنةٌ، ولا يُعلَن غيرُها.")
    if len({declaration.leg for declaration in THE_THREE_LEGS}) != len(BridgeLeg):
        raise LexiconBridgeError("رجلٌ مُعلَنةٌ مرّتين؛ فالثلاثيّةُ مكسورة.")


def _assert_the_withheld_lexicon_is_absent_from_this_tree() -> None:
    """حارسُ الخلوّ: لو نزلت النسخةُ المفرَّغةُ لانقلب الحكمُ بلا تحرير حرف."""

    root = Path(__file__).resolve().parents[3]
