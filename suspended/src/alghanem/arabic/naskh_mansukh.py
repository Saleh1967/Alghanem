def _require_member(value: object, kind: type[Enum], label: str) -> None:
    if not isinstance(value, kind):
        raise NaskhMansukhError(f"{label} عضوٌ في مفردته المغلقة لا نصٌّ حرّ.")


def derive_rank_admission(
    mansukh_standing: TransmissionStanding,
    nasikh_standing: TransmissionStanding,
) -> RankAdmission:
    """اشتقّ حالَ الرتبة: أيبلغ الناسخُ رتبةَ المنسوخ أم ينزل عنها؟

    والسلَّمُ مقروءٌ من `TransmissionStanding` المستورَد لا من ترتيبٍ يُكتَب
    هنا. و`فرض` يُردّ بعلّته الخاصّة في أيّ موضعٍ وقع، ناسخًا كان أو منسوخًا:
    فهو ليس رتبةً في سلَّم النقل أصلًا حتى تُقارَن.
    """

    _require_member(mansukh_standing, TransmissionStanding, "رتبةُ المنسوخ")
    _require_member(nasikh_standing, TransmissionStanding, "رتبةُ الناسخ")

    if TransmissionStanding.FARD in (mansukh_standing, nasikh_standing):
        return RankAdmission.مردود_بأن_الفرض_ليس_مقيسا
    if (
        mansukh_standing is TransmissionStanding.MUTAWATIR
        and nasikh_standing is TransmissionStanding.AHAD
    ):
        return RankAdmission.مردود_بنزول_الرتبة
    return RankAdmission.الرتبة_قائمة


