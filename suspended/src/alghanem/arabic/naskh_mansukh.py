class NaskhCandidate:
    """دعوى نسخٍ معروضةٌ على الشروط؛ ولا حقلَ نتيجةٍ فيها البتّة.

    تحمل ما تُعرَض به الدعوى: جنسَ الحكم المرفوع، وموقعَ الرافع منه، وتقييدَ
    الخطاب بوقت، ومحلَّ النسخ، ورتبتَي المنسوخ والناسخ. والنتيجةُ تُشتَقّ
    بـ`derive_naskh` ولا تُكتَب، فلا يُخالَف المكتوبُ المُشتَقَّ.
    """

    ruling_genus: RulingGenus
    taraakhi: Taraakhi
    time_binding: TimeBinding
    venue: NaskhVenue
    mansukh_standing: TransmissionStanding
    nasikh_standing: TransmissionStanding

    def __post_init__(self) -> None:
        _require_member(self.ruling_genus, RulingGenus, "جنسُ الحكم")
        _require_member(self.taraakhi, Taraakhi, "موقعُ الدليل الرافع")
        _require_member(self.time_binding, TimeBinding, "تقييدُ الخطاب بوقت")
        _require_member(self.venue, NaskhVenue, "محلُّ النسخ")
        _require_member(self.mansukh_standing, TransmissionStanding, "رتبةُ المنسوخ")
        _require_member(self.nasikh_standing, TransmissionStanding, "رتبةُ الناسخ")

    @property
    def rank_admission(self) -> RankAdmission:
        """حالُ الرتبة، مُشتَقّةٌ من رتبتَي الطرفين لا مكتوبةً في حقل."""

        return derive_rank_admission(self.mansukh_standing, self.nasikh_standing)


def derive_naskh(candidate: NaskhCandidate) -> NaskhOutcome:
    """اشتقّ وقوعَ النسخ من الشروط الثلاثة والرتبة معًا؛ مُشتَقٌّ لا مكتوب.

    وترتيبُ الفحص ليس اعتباطًا: التقييدُ بوقتٍ يُقرأ **أوّلًا** لأنّه يُخرِج
    الخطابَ من الباب رأسًا، فلا يُقال فيه «لم تستوفِ دعواه شروطَها» وهو ممّا
    لا تُعرَض عليه الشروطُ أصلًا (`ExpiryIsNotNaskh`).
    """

    if not isinstance(candidate, NaskhCandidate):
        raise NaskhMansukhError("النتيجةُ تُشتَقّ من مرشَّحٍ مُجمَّد لا من حقولٍ مُمرَّرة.")

    if candidate.time_binding is TimeBinding.مقيد_بوقت_معين:
        return NaskhOutcome.انتهاء_وقت_لا_نسخ
    if candidate.ruling_genus is not RulingGenus.شرعي:
        return NaskhOutcome.لا_نسخ
    if candidate.taraakhi is not Taraakhi.متراخ:
        return NaskhOutcome.لا_نسخ
    if candidate.rank_admission is not RankAdmission.الرتبة_قائمة:
        return NaskhOutcome.لا_نسخ
    return NaskhOutcome.ينسخ


TILAWA_ABROGATION_AS_TRANSMITTED: Final[TilawaAbrogationStanding] = (
    TilawaAbrogationStanding.لم_يثبت_بالقطعي
)


_FORBIDDEN_FIELD_MARKERS: Final[tuple[str, ...]] = (
    "result",
    "outcome",
    "verdict",
    "birth",
    "freeze",
    "certificate",
    "invalid",
    "corrupt",
    "weak",
    "batil",
)


def _assert_no_written_result_or_defect_field() -> None:
    """احرسْ خلوَّ المرشَّح من حقلِ نتيجةٍ ومن وصفِ المنسوخ بفسادٍ أو ضعف.

    الأوّلُ لئلّا يُخالَف المكتوبُ المُشتَقَّ، والثاني لأنّ `IbtalIsNotButlan`:
    المنسوخُ حكمٌ صحيحٌ انتهى أمدُه، لا حكمٌ فاسدٌ كُشِف فسادُه.
    """

    for field in fields(NaskhCandidate):
        lowered = field.name.lower()
        for marker in _FORBIDDEN_FIELD_MARKERS:
            if marker in lowered:
                raise RuntimeError(
                    f"NaskhCandidate.{field.name} حقلٌ ممنوع: "
                    + IBTAL_IS_NOT_BUTLAN_NOTE
                )


_assert_no_written_result_or_defect_field()
