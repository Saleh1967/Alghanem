"""الناسخُ والمنسوخ: شروطٌ ثلاثةٌ مجتمعةٌ، ورتبةٌ لا يَنزِل عنها الناسخ.

هذا القسمُ الخامسُ من `usul_dalala_sections`، وكان وحدَه `غير_مُرمَّز` بعلّةٍ
مُسمّاة: `NASKH_TEXT_NOT_EXTRACTED_RESIDUAL` — «لم يُستخرَج له نصٌّ واحد».
وهذه الوحدةُ ترفع تلك العلّةَ بعينها ولا ترفع غيرها: زُوِّد اللفظُ، فبُنيت
المفردةُ **منه** لا قبله.

**والنسخُ إبطالُ الحكم المستفاد من نصٍّ سابقٍ بنصٍّ لاحق**، وشروطُه المنقولةُ
ثلاثةٌ **مجتمعة**: أن يكون الحكمُ المنسوخ شرعيًّا، وأن يكون الدليلُ الرافعُ
شرعيًّا **متراخيًا** عن الخطاب المنسوخ حكمُه، وأن لا يكون الخطابُ المرفوعُ حكمُه
**مقيَّدًا بوقتٍ معيَّن**.

**والثلاثةُ تُشتَقّ ولا تُكتَب** (`ThreeConditionsOrNoNaskh`)، على منوال
`BothUnitiesOrNoCarrying` في `mutlaq_muqayyad` حرفًا بحرف: من اكتفى باثنين
أبطل أحكامًا لا تُبطَل. وتُردّ عند الإنشاء كلُّ قراءةٍ مكتوبةٍ تخالف المُشتَقّ.

**والشرطُ الثالثُ سالبٌ، ومخالفتُه ليست نسخًا فاسدًا بل جنسًا آخر**
(`ExpiryIsNotNaskh`): الخطابُ المقيَّدُ بوقتٍ ينتهي حكمُه بانتهاء وقته **بنفسه**،
ولا يحتاج رافعًا أصلًا؛ فقراءةُ انتهائه نسخًا تُدخِل في باب النسخ ما ليس منه،
وتجعل للنسخ شواهدَ كاذبةً تُقوّيه بما ليس له. ولذلك له عضوٌ في المُخرَجات
مستقلٌّ عن `لا_نسخ`، لا رسالةٌ نثريّةٌ ولا سكوت.

**ورتبةُ الناسخ لا تنزل عن رتبة المنسوخ** (`NoNaskhOfTheCertainByTheProbable`):
«لا يجوز أن يَنسخ المتواترَ إلا المتواتر، فلا يُنسخ المتواتر بالآحاد». وهذا
يربط البابَ بسلَّم `TransmissionStanding` القائم في الشجرة — **استيرادًا لا
نسخًا**، على سابقة `mutlaq_muqayyad` في استيرادها `DalilScope`. فلا تُعاد هنا
مفردةُ درجاتٍ ثانية تُغيَّر في موضعٍ وتبقى في الآخر.

**و`فرض` ليس رتبةً أضعفَ في هذا السلَّم بل خارجَ السلَّم**
(`FardIsNotAWeakerRankButNoRankAtAll`): هو «تقديرٌ لم يقع عليه حسٌّ مستقلٌّ بعد»
بنصّ `transmission_standing`؛ فردُّ نسخٍ ادُّعي به ليس من جنس ردِّ الآحاد على
المتواتر — ذاك مقيسٌ قصُرت رتبتُه، وهذا لم يُقَس أصلًا. وجمعُهما في علّةٍ واحدة
يُوهِم أنّ الفرضَ يُرقّى بالقياس إلى ناسخٍ وهو لا يُرقّى إلا بأن يصير مقيسًا
أوّلًا. فلكلٍّ عضوُ رفضٍ مستقلّ.

**ونسخُ الحكم غيرُ نسخ التلاوة** (`AbrogationOfRulingIsNotAbrogationOfWording`):
الأوّلُ هو موضوعُ هذا الباب كلِّه، والثاني رفعُ اللفظ نفسه من القرآن. والمنقولُ
فيه: «لم يثبت وقوعه بالدليل القطعيّ». **وهذه سالبةُ ثبوتٍ لا سالبةُ إمكان**،
وتُكتَب كما وردت: `لم_يثبت_بالقطعي` عضوًا مُسمًّى، لا `ممتنع` ولا `واقع`؛ فمن
قرأ «لم يثبت» امتناعًا قرأ عدمَ العلم علمًا بالعدم، وهو عينُ ما يمنعه ردُّ
`AbsentRelation != DeclaredIncomparability` في النواة.

**والإبطالُ غيرُ الباطل** (`IbtalIsNotButlan`): «الإبطالُ هو نسخُ الحكم، وأمّا
الباطلُ فهو ضدُّ الحقّ». فالنسخُ إجراءٌ مشروعٌ يرفع حكمًا **صحيحًا** انتهى
أمدُه، لا قدحٌ في المنسوخ ولا تخطئةٌ له. ولذلك لا حقلَ في هذه الوحدة يصف المنسوخَ
بفسادٍ ولا بضعف، ويُفحَص ذلك عند الاستيراد.

**ومفردةُ هذه الوحدة مطلوبةٌ لا مُثبَتة**: اللفظُ منقولٌ في **طلبٍ** يُحيل إلى
الشخصية الإسلامية ج٣ بأسطرٍ من ملفٍّ مستخرَج، ولم يُقابَل بطبعةٍ ورقيةٍ مُسمّاة؛
فالمُخرَجُ «تسجيل» لا «شهادة»، وبقيّتاه في `NASKH_WORDING_IS_SUPPLIED_NOT_COLLATED`
و`EXTRACTED_LINE_NUMBERS_ARE_NOT_PRINT_PAGINATION`.

**ولا شاهدَ مُطبَّقًا هنا**: لا آيةَ ولا حديثَ يُحكَم عليه بنسخٍ في هذه الوحدة،
ولا يُقرأ منها حكمٌ فقهيٌّ في مسألةٍ بعينها (`NoRulingIsIssuedOnAnyText`).
فالمُشتَقُّ شروطٌ ورتبةٌ، والتطبيقُ على نصٍّ بعينه بابٌ لم يُفتَح.

**وهذه الوحدة تسجيلٌ لا سلطة**: لا ولادة، ولا حكمَ ولادة، ولا تجميد، ولا `E0`،
ولا تستورد من `kernel/` شيئًا، ولا تقرؤها وحدةٌ فيه.
"""

