"""إحصاءُ جذورٍ متنافسةٍ في مدوَّنةٍ مُوسَّمةٍ مُبصَّمة: أعدادٌ بقواعد عدِّها.

**الحدُّ الذي جاءت هذه الوحدةُ إليه**: سجَّلت
`hollow_root_levels_deposit` تعارضًا مرتبتُه `THE_TREE_CANNOT_TEST_IT`: حسمُ
هويّة العلّة (و/ي) بمطابقة الهيكل الساكن بجدول الجذور **دوريّ**، لأنّ `خيف`
و`نيم` و`هوب` و`قيل` مُدرَجةٌ في «مقاييس اللغة» مداخلَ مستقلّةً كما `خوف` و`نوم`
و`هيب` و`قول`، فالهيكلُ يُرجِع الاحتمالين معًا. وشرطُ الحسم المكتوبُ هناك قبل
هذه الوحدة: «شاهدٌ خارجَ الصورة السطحية يُسنِد هويّةَ العلّة إسنادًا مُبصَّمًا».
وخانةُ `ROOT` في مدوَّنة `QURANIC_ARABIC_CORPUS_WITNESS` شاهدٌ من هذا الجنس:
مُوسَّمةٌ كلمةً كلمةً بأيدي غيرنا قبل أن يُطرَح سؤالُنا.

`THE_NUMBERS_ARRIVED_BEFORE_THE_RUN`: الأعدادُ المُودَعةُ هنا وصلت مُصرَّحًا بها
في نصٍّ خارجيّ **قبل** أن يُشغَّل على البايتات في هذه الشجرة شيء، ثمّ شُغِّل
العدُّ فخرجت مطابقةً حرفًا بحرف. وهذا مطابقةٌ تنبّؤيةٌ لا ملاءمةٌ بعد النظر،
وهو أقوى ما في هذه الوحدة. ولو لم تُطابق لوجب تسجيلُ الفرق لا تعديلُ القاعدة
حتى تُطابق — على منوال `TUNED_ON_DEV_REPORTED_ON_HELD_OUT` في
`irab_case_readout`.

`A_COUNT_IS_RELATIVE_TO_ITS_COUNTING_RULE`: «تردُّد ١٢٤» بلا قاعدةٍ ليس عددًا:
المقاطعُ الصرفية غيرُ الكلمات غيرُ الآيات. فكلُّ عددٍ هنا يحمل قاعدتَه الثلاثيةَ
معًا (`RootCountingRule`)، على منوال `maqayis_root_table_deposit`.

`A_TAGGED_ROOT_IS_A_HUMAN_JUDGEMENT_NOT_A_MEASUREMENT`: خانةُ `ROOT` تبويبُ
مُوسِّمين، لا خاصّيّةٌ تُقاس من البايتات. فصفرُ `xyf` معناه **«لم يُوسَم في هذه
المدوَّنة»**، لا «لا وجودَ لخيف في العربية» ولا «أخطأ من أثبته في المعجم».

`ANNOTATOR_AGREEMENT_IS_NOT_TRUTH`: دعوى «ثلاثةُ لغويّين بوَّبوا كلَّ كلمةٍ على
حدة» **غيرُ قابلةٍ لإعادة الاشتقاق من هذه البايتات**: ليس في الملفّ حقلُ مُوسِّمٍ
ولا حقلُ اتّفاق. فتُنقَل عن توثيق المدوَّنة نقلًا، ولا تُقرأ شاهدًا مُبصَّمًا.

`THE_CENSUS_IS_NOT_A_ROOT_EXTRACTOR`: ما تُثبته هذه الوحدةُ أنّ أحد طرفَي كلّ
زوجٍ متنافسٍ **غيرُ مُوسَّمٍ في هذه المدوَّنة البتّة**، فلا مُنازعَ للطرف الآخر
فيها. وليست فيها دالّةٌ تأخذ صورةً سطحيةً فتُرجِع جذرَها؛ فالدوريّةُ ترتفع
**داخل هذه المدوَّنة بعينها** بانتفاء المُنازِع، لا بانكشاف قاعدةِ استخراج. ومن
قرأها مستخرِجَ جذورٍ قرأ ما ليس فيها.

`A_COUNT_IN_A_CORPUS_IS_NOT_A_COUNT_IN_ARABIC`: الأعدادُ دالّةٌ في هذه
المدوَّنة وفي إصدارها وفي قاعدة العدّ معًا؛ واستنفادُ مدوَّنةٍ ليس استنفادَ لغة،
على منوال `CompleteInductionIsCorpusBounded`.

`ZERO_IS_NOT_A_REFUTATION_OF_A_HAND_BUILT_EXAMPLE`: صفرُ `hwb` و`hyb` معًا
يُخرِج `يَهَابُ` من نطاق هذه المدوَّنة، وهو **موافقٌ** لما صُرِّح به سلفًا في
`hollow_root_levels_preregistration`: جنسُ إسنادها `MANUALLY_CONSTRUCTED_EXAMPLE`
لا صورةٌ مرصودة. فلا تُحذَف الصورةُ ولا تُرقّى؛ والزوجُ الأدنى يبقى مثالًا
صرفيًّا صحيحًا خارج هذه المدوَّنة، ويبقى الحدُّ الذي أظهره قائمًا.

`WITNESS_BYTES_ARE_STILL_NOT_VENDORED`: لم تُنسَخ بايتاتُ المدوَّنة إلى الشجرة
ولن تُنسَخ: رخصتُها ورخصةُ النصّ المُضمَّن فيها تمنعان التغيير وليستا رخصةَ هذا
المستودع. فالعدُّ يقع عند حائز البايتات بـ
`examples/irab/measure_hollow_root_census.py`، ولا يمرّ رقمٌ قبل مطابقة البصمة
والطول.

`THIS_IS_REGISTRATION_NOT_AUTHORITY`: لا ولادةَ هنا، ولا حكمَ ولادة، ولا تجميدَ
`E0`، ولا استيرادَ من `kernel/`؛ ولا تُبدَّل بهذه الوحدة مرتبةُ تعارضٍ مُسجَّلٍ
في `hollow_root_levels_deposit`: تبديلُ المرتبة قرارٌ مستقلّ لا أثرٌ جانبيٌّ
لإيداع أرقام.

المصدر: مدوَّنة القرآن الصرفية، http://corpus.quran.com — مبنيّةٌ على نصّ
تنزيل، http://tanzil.info. والإسنادُ إليهما شرطُ رخصةٍ لا لطفَ عبارة.
"""

