def _require_text(value: str, label: str) -> str:
    if not isinstance(value, str) or not value.strip():
        raise HollowRootCensusError(f"{label} نصٌّ غير فارغ؛ ولا يُترَك صمتًا.")
    return value


@dataclass(frozen=True, slots=True)
class SegmentRecord:
    """سطرُ مقطعٍ صرفيٍّ مقروءًا بأعمدته الأربعة، بلا تحويلٍ ولا تطبيع.

    الصورةُ تبقى بترميز Buckwalter كما هي في الملفّ: تحويلُها إلى العربية
    يُدخِل جدولَ تحويلٍ وترتيبَ شدّةٍ وحركة، وهو بابُ أخطاءٍ مُسجَّلٌ في
    `irab_case_readout`، ولا حاجةَ إليه لعدِّ خانةٍ نصُّها ASCII.

    `AN_EMPTY_FORM_IS_A_SEGMENT_NOT_A_MALFORMED_LINE`: عمودُ الصورة يقع
    فارغًا في هذه المدوَّنة فعلًا، ومواضعُه ٢٠٨ مقاطعَ كلُّها لاحقةُ ضميرِ
    المتكلّم المحذوفةِ الياء («رَبِّ»، «ٱتَّقُونِ»). ورفضُ هذه الأسطر ظنَّ
    الرفضُ صونًا وهو حذفُ مقاطعَ موسومةٍ بأيدي أهلها، فيُنقِص العدَّ ٢٠٨.
    وقد ظهرت الواقعةُ عند أوّل تشغيلٍ على البايتات لا عند النظر، فتُسجَّل
    كما ظهرت: الصورةُ وحدَها تقبل الفراغَ، والوَسْمُ والسماتُ لا تقبلانه.
    """

    sura: int
    aya: int
    word: int
    segment: int
    form: str
    tag: str
    features: str

    def __post_init__(self) -> None:
        for number, label in (
            (self.sura, "رقمُ السورة"),
            (self.aya, "رقمُ الآية"),
            (self.word, "رقمُ الكلمة"),
            (self.segment, "رقمُ المقطع"),
        ):
            if not isinstance(number, int) or number < 1:
                raise HollowRootCensusError(f"{label} عددٌ صحيحٌ موجب.")
        if not isinstance(self.form, str):
            raise HollowRootCensusError("صورةُ المقطع نصٌّ، وقد تقع فارغةً فعلًا.")
        _require_text(self.tag, "وَسْمُ المقطع")
        _require_text(self.features, "سماتُ المقطع")

    @property
    def location(self) -> str:
        """الموضعُ بصيغته في الملفّ، لا مُعادَ تنسيقه بصيغةٍ من عندنا."""

        return f"({self.sura}:{self.aya}:{self.word}:{self.segment})"


def parse_segment_line(line: str) -> SegmentRecord | None:
    """يقرأ سطرًا واحدًا: `None` لترويسةٍ أو تعليقٍ أو فراغ، ورفضٌ للمشوَّه.

    والسطرُ المشوَّه يُرفَع به خطأٌ ولا يُتخطّى صامتًا: تخطّي سطرٍ لا يُقرأ
    يُنقِص العددَ بلا أثرٍ يُتتبَّع، فيصير النقصُ خاصّيّةً في اللغة عند من
    قرأ الرقم.
    """

    if not line.strip():
        return None
    if line.startswith(COMMENT_PREFIX):
        return None
    columns = line.split(COLUMN_SEPARATOR)
    if columns and columns[0] == HEADER_FIRST_COLUMN:
        return None
    if len(columns) != DECLARED_COLUMN_COUNT:
        raise HollowRootCensusError(
            f"سطرٌ بأعمدةٍ عددُها {len(columns)} والمُعلَن "
            f"{DECLARED_COLUMN_COUNT}؛ ولا يُحمَل على أقرب صيغة."
        )
    location, form, tag, features = columns
    if not location.startswith("(") or not location.endswith(")"):
        raise HollowRootCensusError(f"موضعٌ خارج صيغة الأقواس المُعلَنة: {location}")
    parts = location[1:-1].split(":")
    if len(parts) != 4:
        raise HollowRootCensusError(f"موضعٌ ليس رباعيَّ الأجزاء: {location}")
    try:
        sura, aya, word, segment = (int(part) for part in parts)
    except ValueError as error:
        raise HollowRootCensusError(f"موضعٌ بجزءٍ غيرِ عدديّ: {location}") from error
    return SegmentRecord(
        sura=sura,
        aya=aya,
        word=word,
        segment=segment,
        form=form,
        tag=tag,
        features=features,
    )


def root_of_features(features: str) -> str | None:
    """قيمةُ `ROOT` في سمات المقطع، أو `None` إن لم تُوسَم سمةُ جذرٍ أصلًا.

    والمطابقةُ على سمةٍ كاملةٍ بين الفواصل، لا على ورودِ النصّ في أيّ موضع:
    المطابقةُ الجزئيةُ تجعل `ROOT:xwfr` يُعَدّ `xwf`.
    """

    for feature in features.split(FEATURE_SEPARATOR):
        if feature.startswith(ROOT_FEATURE_PREFIX):
            value = feature[len(ROOT_FEATURE_PREFIX) :]
            return value or None
    return None


