@dataclass(frozen=True, slots=True)
class RootCensusRow:
    """عددُ جذرٍ واحدٍ تحت القواعد الثلاث معًا، ومواضعُه إن كان نادرًا."""

    root_buckwalter: str
    root_arabic: str
    segment_count: int
    word_count: int
    verse_count: int
    locations: tuple[str, ...]

    def __post_init__(self) -> None:
        _require_text(self.root_buckwalter, "الجذرُ بترميز Buckwalter")
        _require_text(self.root_arabic, "الجذرُ بالعربية")
        for count, label in (
            (self.segment_count, "عددُ المقاطع"),
            (self.word_count, "عددُ الكلمات"),
            (self.verse_count, "عددُ الآيات"),
        ):
            if not isinstance(count, int) or count < 0:
                raise HollowRootCensusError(f"{label} عددٌ صحيحٌ غيرُ سالب.")
        if not self.word_count <= self.segment_count:
            raise HollowRootCensusError(
                "عددُ الكلمات لا يزيد على عدد المقاطع؛ فالكلمةُ تجمع مقاطعَها."
            )
        if not self.verse_count <= self.word_count:
            raise HollowRootCensusError(
                "عددُ الآيات لا يزيد على عدد الكلمات؛ فالآيةُ تجمع كلماتِها."
            )
        if self.segment_count <= RARE_ROOT_LOCATION_LIMIT:
            if len(self.locations) != self.segment_count:
                raise HollowRootCensusError(
                    "جذرٌ نادرٌ تُودَع مواضعُه كاملةً؛ وبعضُها يُوهِم استيفاءً."
                )
        elif self.locations:
            raise HollowRootCensusError(
                "جذرٌ فوق حدّ الندرة لا تُودَع له مواضعُ منتقاة؛ "
                "والمنتقى يُقرأ عيّنةً مُصمَّمة."
            )

    def count_under(self, rule: RootCountingRule) -> int:
        """العددُ تحت قاعدةٍ مُسمّاة؛ ولا عددَ يُقرأ من هذه الوحدة بلا قاعدة."""

        if rule is RootCountingRule.SEGMENTS:
            return self.segment_count
        if rule is RootCountingRule.WORDS:
            return self.word_count
        return self.verse_count


def census_rows(
    records: Iterable[SegmentRecord],
    roots: Iterable[tuple[str, str]],
) -> tuple[RootCensusRow, ...]:
    """يُحصي جذورًا مُسمّاةً على مقاطعَ مقروءة، بالقواعد الثلاث معًا.

    والجذورُ تُمرَّر أزواجًا (Buckwalter، عربية) مُعلَنةً قبل القراءة، فلا
    يُختار المعدودُ بعد رؤية الأعداد.
    """

    wanted = tuple(roots)
    segments: dict[str, list[SegmentRecord]] = {root: [] for root, _ in wanted}
    if len(segments) != len(wanted):
        raise HollowRootCensusError("جذرٌ مكرَّرٌ في المطلوب؛ والتكرارُ يُضاعف عدَّه.")
    for record in records:
        root = root_of_features(record.features)
        if root is not None and root in segments:
            segments[root].append(record)
    rows: list[RootCensusRow] = []
    for root, arabic in wanted:
        found = segments[root]
        words = {(item.sura, item.aya, item.word) for item in found}
        verses = {(item.sura, item.aya) for item in found}
        locations = tuple(item.location for item in found)
        rows.append(
            RootCensusRow(
                root_buckwalter=root,
                root_arabic=arabic,
                segment_count=len(found),
                word_count=len(words),
                verse_count=len(verses),
                locations=(locations if len(found) <= RARE_ROOT_LOCATION_LIMIT else ()),
            )
        )
    return tuple(rows)


def verified_corpus_bytes(path: Path) -> bytes:
    """بايتاتُ المدوَّنة مرفوضةً إن خالفت طولَ الشاهد أو بصمتَه.

    ولا يمرّ رقمٌ من هذه الوحدة قبل هذه المطابقة: ملفٌّ آخرُ بالاسم نفسه
    يُعطي أعدادًا تُقرأ أعدادَ هذا الشاهد وهي أعدادُ سواه.
    """

    if not path.is_file():
        raise HollowRootCensusError(f"ملفُّ المدوَّنة غيرُ موجودٍ في المسار: {path}")
    data = path.read_bytes()
    witness = QURANIC_ARABIC_CORPUS_WITNESS
    if len(data) != witness.byte_length:
        raise HollowRootCensusError(
            f"طولُ البايتات {len(data)} لا يطابق الشاهد {witness.byte_length}"
        )
    digest = hashlib.sha256(data).hexdigest()
    if digest != witness.sha256:
        raise HollowRootCensusError(
            f"بصمةُ البايتات {digest} لا تطابق الشاهد {witness.sha256}"
        )
    return data


def corpus_lines(path: Path) -> tuple[str, ...]:
    """أسطرُ المدوَّنة المُبصَّمة مفصولةً بفاصلها هي، بلا تطبيعٍ ولا تجريد."""

    data = verified_corpus_bytes(path)
    return tuple(data.decode("utf-8").split(CORPUS_LINE_SEPARATOR))


def rederive_segment_count(lines: Iterable[str]) -> int:
    """عددُ المقاطع الصرفية تحت `RootCountingRule.SEGMENTS`، من الأسطر نفسِها."""

    return sum(1 for line in lines if parse_segment_line(line) is not None)


