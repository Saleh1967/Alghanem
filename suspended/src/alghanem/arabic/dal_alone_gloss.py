class ProfileAxis(Enum):
    """محاورُ الصورة، مُعلَنةٌ قبل القياس؛ وكلُّها نصيبٌ يُشتَقّ بالعدّ."""

    SHARE_MUDAAF = "نصيبُ_المضاعف"
    SHARE_THULATHI = "نصيبُ_الثلاثيّ"
    SHARE_THULATHI_MUTALL = "نصيبُ_الثلاثيّ_المعتلّ"
    SHARE_WITH_POETRY = "نصيبُ_حاملِ_الشاهد_الشعريّ"
    SHARE_WITH_ANY_AXIS = "نصيبُ_الموسومِ_بمحورٍ"


THE_PROFILE_AXES: Final[tuple[ProfileAxis, ...]] = tuple(ProfileAxis)
"""المحاورُ الخمسةُ مُعلَنةً قبل القياس؛ ولا يُزاد محورٌ بعد رؤية النتيجة."""

DECLARED_TOLERANCE: Final[float] = 0.05
"""السماحيّةُ المُطلَقةُ مُعلَنةٌ قبل القياس: خمسُ نقاطٍ مئويّة، لا مُلائَمةٌ بعدَه."""

_TYPE_MUDAAF: Final[str] = "مضاعف"
_TYPE_THULATHI: Final[str] = "ثلاثي"
_TYPE_THULATHI_MUTALL: Final[str] = "ثلاثي معتل"


@dataclass(frozen=True, slots=True)
class StructuralProfile:
    """صورةُ مجموعةٍ من المداخل: أنصبةٌ تُحسَب عند كلّ قراءةٍ ولا تُكتَب."""

    label: str
    entries: tuple[DalGlossEntry, ...]

    def __post_init__(self) -> None:
        if not self.entries:
            raise DalAloneGlossError(
                "صورةُ مجموعةٍ خاليةٍ نِسَبُها قسمةٌ على صفر؛ ولا تُقرَأ صفرًا"
            )
        if not self.label.strip():
            raise DalAloneGlossError("صورةٌ بلا اسمٍ لا تُقابَل بأخرى")

    @property
    def size(self) -> int:
        """عددُ المداخل، مُشتقًّا بالعدّ."""

        return len(self.entries)

    def share(self, axis: ProfileAxis) -> float:
        """نصيبُ محورٍ واحد، محسوبًا الآن من المداخل لا مقروءًا من حقل."""

        if axis is ProfileAxis.SHARE_MUDAAF:
            hits = sum(1 for e in self.entries if e.root_type == _TYPE_MUDAAF)
        elif axis is ProfileAxis.SHARE_THULATHI:
            hits = sum(1 for e in self.entries if e.root_type == _TYPE_THULATHI)
        elif axis is ProfileAxis.SHARE_THULATHI_MUTALL:
            hits = sum(1 for e in self.entries if e.root_type == _TYPE_THULATHI_MUTALL)
        elif axis is ProfileAxis.SHARE_WITH_POETRY:
            hits = sum(1 for e in self.entries if e.carries_poetry_evidence)
        else:
            hits = sum(1 for e in self.entries if e.carries_any_axis)
        return hits / self.size


def profile_of(label: str, entries: Iterable[DalGlossEntry]) -> StructuralProfile:
    """صوِّر مجموعةً من المداخل باسمها المُعلَن."""

    return StructuralProfile(label=label, entries=tuple(entries))


@dataclass(frozen=True, slots=True)
class AxisComparison:
    """مقابلةُ محورٍ واحد: النصيبان، وفرقُهما، وحكمُه داخل السماحيّة."""

    axis: ProfileAxis
    part_share: float
    whole_share: float
    tolerance: float

    @property
    def gap(self) -> float:
        """فرقُ النصيبين مُطلَقًا، مُشتقًّا لا مكتوبًا."""

        return abs(self.part_share - self.whole_share)

    @property
    def is_within_band(self) -> bool:
        """أيقع الفرقُ داخل السماحيّة المُعلَنة قبل القياس؟"""

        return self.gap <= self.tolerance


class SelfSimilarityStanding(Enum):
    """منزلةُ دعوى «الجزءُ بنيةُ الكلّ»، ثلاثيّةً لا ثنائيّة."""

    MIRRORS_THE_WHOLE_ON_EVERY_DECLARED_AXIS = "يُشبه_الكلَّ_في_كلّ_محورٍ_مُعلَن"
    DIVERGES_ON_A_NAMED_AXIS = "يخالف_في_محورٍ_مُسمًّى"
    DEFERRED_FOR_WANT_OF_A_SECOND_SOURCE = "مُرجأةٌ_لانعدام_مصدرٍ_ثانٍ"


@dataclass(frozen=True, slots=True)
class SelfSimilarityVerdict:
    """حكمُ الدعوى، مُشتقًّا من مقابلات المحاور لا مكتوبًا بجانبها."""

    comparisons: tuple[AxisComparison, ...]
    second_source_corroborates: bool

    def __post_init__(self) -> None:
        if len(self.comparisons) != len(THE_PROFILE_AXES):
            raise DalAloneGlossError(
                "المحاورُ تُقابَل كلُّها أو لا تُقابَل؛ وإسقاطُ محورٍ تشابهٌ صامت"
            )
        if len({item.axis for item in self.comparisons}) != len(self.comparisons):
            raise DalAloneGlossError("محورٌ تكرّر في المقابلة؛ والتكرارُ يُخفي نقصًا")

    @property
    def diverging_axes(self) -> tuple[ProfileAxis, ...]:
        """المحاورُ الخارجةُ عن السماحيّة، مُسمّاةً لا مُبتلَعةً في متوسّط."""

        return tuple(item.axis for item in self.comparisons if not item.is_within_band)

    @property
    def standing(self) -> SelfSimilarityStanding:
        """المنزلةُ خاصّيّةٌ تُشتَقّ عند كلّ قراءة؛ ولا حقلَ منزلةٍ ههنا.

        والنقضُ أرخصُ من التصديق: محورٌ واحدٌ خارجَ السماحيّة ينقض الدعوى
        بمصدرٍ واحد، أمّا قيامُها على المحاور كلِّها فلا يُقرَأ إثباتًا ما لم
        يُقابله مصدرٌ ثانٍ مستقلّ؛ وانعدامُه إرجاءٌ لا موافقة.
        """

        if self.diverging_axes:
            return SelfSimilarityStanding.DIVERGES_ON_A_NAMED_AXIS
        if not self.second_source_corroborates:
            return SelfSimilarityStanding.DEFERRED_FOR_WANT_OF_A_SECOND_SOURCE
        return SelfSimilarityStanding.MIRRORS_THE_WHOLE_ON_EVERY_DECLARED_AXIS


def assess_self_similarity(
    part: StructuralProfile,
    whole: StructuralProfile,
    tolerance: float = DECLARED_TOLERANCE,
    second_source_corroborates: bool | None = None,
) -> SelfSimilarityVerdict:
    """قابِل صورةَ الجزء بصورة الكلّ على المحاور الخمسة بسماحيّةٍ مُعلَنة.

    و`second_source_corroborates` يُقرَأ حيًّا من شقّ MASAQ إن لم يُمرَّر؛
    فلا يُكتَب «قام مصدرٌ ثانٍ» في نداءٍ ولا يُفترَض قيامُه.
    """

    if tolerance < 0.0:
        raise DalAloneGlossError("سماحيّةٌ سالبةٌ ليست سماحيّة")
    corroborates = (
        assess_masaq_side().a_root_gloss_can_be_extracted
        if second_source_corroborates is None
        else second_source_corroborates
    )
    return SelfSimilarityVerdict(
        comparisons=tuple(
            AxisComparison(
                axis=axis,
                part_share=part.share(axis),
                whole_share=whole.share(axis),
                tolerance=tolerance,
            )
            for axis in THE_PROFILE_AXES
        ),
        second_source_corroborates=corroborates,
    )


# --- شقُّ MASAQ ومانعاه -----------------------------------------------------------


class MasaqBlocker(Enum):
    """ما يمنع استخراجَ وسمِ الدال من MASAQ اليوم؛ مانعان لا مانعٌ واحد."""

    BYTES_ARE_NOT_IN_THIS_TREE = "بايتاتُ_MASAQ_ليست_مُودَعةً_ولا_مُصرَّحًا_بمسارها"
    NO_ROOT_COLUMN_SO_DAL_IS_A_SURFACE_NOT_A_ROOT = "لا_عمودَ_جذرٍ_في_MASAQ"


@dataclass(frozen=True, slots=True)
class MasaqDalExtraction:
    """حالُ شقّ MASAQ: مانعُه العارضُ مقروءٌ حيًّا، والباقي مكتوبٌ في بنيتها."""

    bytes_are_resolvable: bool

    @property
    def blockers(self) -> tuple[MasaqBlocker, ...]:
        """الموانعُ القائمةُ الآن، مُشتقّةً لا مكتوبة.

        ومانعُ انعدامِ عمود الجذر قائمٌ على كلّ حال، فحضورُ البايتات يرفع
        الأوّلَ وحدَه ولا يرفع الثاني.
        """

        found: list[MasaqBlocker] = []
        if not self.bytes_are_resolvable:
            found.append(MasaqBlocker.BYTES_ARE_NOT_IN_THIS_TREE)
        found.append(MasaqBlocker.NO_ROOT_COLUMN_SO_DAL_IS_A_SURFACE_NOT_A_ROOT)
        return tuple(found)

    @property
    def a_root_gloss_can_be_extracted(self) -> bool:
        """أيُستخرَج من MASAQ وسمُ **جذرٍ** للدال؟ لا، ولو حضرت البايتات."""

        return False


def assess_masaq_side() -> MasaqDalExtraction:
    """اقرأ حالَ شقّ MASAQ الآن؛ وحضورُ البايتات يُفحَص ولا يُفترَض."""

    return MasaqDalExtraction(bytes_are_resolvable=masaq_bytes_are_resolvable())


