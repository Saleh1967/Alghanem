"""وسمُ الدال وحدَه، ودعوى أنّه بنيةُ البنية الكليّة مُختبَرةً لا مكتوبة.

الطلبُ كان: «اعمل وسمًا للدال وحدَه ليكون بنيةَ البنية الكليّة، واستخرج الوسمَ
من MASAQ ومن مقاييس اللغة». وهذه الوحدة تفعل منه ما تكفيه البايتاتُ المُودَعة،
وتُسمّي ما لا تكفيه::

    SourceGivenPartition != DesignedSubset
    DerivedAxisCount     != WrittenAxisCount
    PartResemblesWhole   != PartIsTheWhole
    MaqayisGloss         != MasaqGloss

**التقسيمُ يُعطيه المصدرُ ولا يُصمَّم ههنا.** «الدالُ وحدَه» ليس مرشِّحًا
نكتبه نحن على عمود الجذر، بل بابٌ قائمٌ في بنية المعجم نفسِه يحمل ترويسةً
مكتوبةً في البايتات: `كتاب الدّال`. فالمقطوعُ مقطوعٌ **بيد ابن فارس** لا بيد
القارئ، وذلك فرقٌ في السند لا في النتيجة وحدَها
(`THE_PARTITION_IS_GIVEN_BY_THE_SOURCE_NOT_CUT_BY_THE_READER`). ويُتحقَّق منه
هنا: كلُّ صفٍّ تحت هذه الترويسة جذرُه مبدوءٌ بالدال، ولا جذرَ مبدوءٌ بالدال
خارجَها؛ فالتطابقُ مُشتَقٌّ لا مُدَّعًى.

**عددُ المحاور يُعاد اشتقاقُه من نصّ المحاور، ولا يُقرأ من عمود العدّ.** في
الجدول عمودُ `axes_count` مكتوبٌ بيد المُدخِل؛ وفي `semantic_axes` نصُّ المحاور
مفصولًا بـ`|`. فالعددُ ههنا **خاصّيّةٌ تُحسَب** من النصّ، والعمودُ المكتوب
يُقابَل به ولا يُصدَّق: يُحصى الموافقُ والمخالفُ والساكتُ ثلاثةً متمايزة
(`DeclaredAxisCountAudit`). ودمجُ «سكتَ العمود» في «خالفَ العمود» يُسقط فرقًا
قائمًا: الساكتُ لم يُدلِ بشيءٍ يُخالَف به (`SILENCE_IS_NOT_DISAGREEMENT`).

**«بنيةُ البنية الكليّة» دعوى قابلةٌ للنقض، فتُختبَر ولا تُكتَب في حقل.** تُقرأ
هنا على أضيق معانيها وأقبلِها للقياس: أن تكون صورةُ باب الدال على محاورَ
مُعلَنةٍ قبل القياس مطابقةً لصورة الجدول كلِّه داخل سماحيّةٍ مُعلَنةٍ قبله
(`DECLARED_TOLERANCE`). والمحاورُ خمسةُ أنصبةٍ مُشتَقّةٍ بالعدّ، والحكمُ
يُجمَع من محاورها فيُسمّي المخالفَ باسمه ولا يُبتلَع في متوسّط
(`SelfSimilarityStanding`).

**والنتيجةُ نقضٌ جزئيٌّ مسجَّلٌ لا مُهندَسٌ حولَه**: تتطابق أنصبةُ أنواع الجذر
داخل السماحيّة، ويخالف نصيبُ الشاهد الشعريّ خارجَها. فالجزءُ يُشبه الكلَّ في
تركيبه ولا يُشبهه في كثافة استشهاده؛ ومن قرأ الشبهَ في محورٍ شبهًا في البنية
فقد عمّم من محورٍ لم يُقَس
(`RESEMBLANCE_ON_ONE_AXIS_IS_NOT_RESEMBLANCE_IN_STRUCTURE`).

**وشقُّ MASAQ لا يقوم اليوم، ومانعاه اثنان لا واحد.** الأوّلُ عارضٌ: بايتاتُ
MASAQ ليست في هذه الشجرة ولا صُرِّح بمسارها، فلا يُشتَقّ منها رقم. والثاني
باقٍ ولو حضرت البايتات: **ليس في MASAQ عمودُ جذر**
(`NO_ROOT_COLUMN_SO_NO_CROSS_CORPUS_FIGURE` في `masaq_corpus_deposit`)، فـ«الدالُ
وحدَه» فيها سطحٌ في مقطعٍ لا جذرٌ في باب. ومقابلةُ بابِ جذرٍ بمجموعةِ مقاطعَ
سطحيّةٍ مقابلةٌ بين جنسين، لا بين وسمَين لشيءٍ واحد
(`A_SURFACE_SEGMENT_IS_NOT_A_ROOT_ENTRY`). فالشقّان لا يُدمَجان في وسمٍ واحد،
ولا يُقرأ سكوتُ MASAQ موافقةً.

**وليس هذا إيداعًا في `gloss_registry`.** ذلك السجلُّ يَسِم **مواضعَ** في نصٍّ
مُسجَّلٍ بمحدِّد سطرٍ ومجال، وجهتُه تُقابَل بمُعلِن المجال فتُردّ إن اتّحدت به.
والوسمُ ههنا وسمُ **جذرٍ** في معجمٍ مُبصَّم، لا وسمُ وقوعٍ في مدوّنة؛ وحملُه
إلى ذلك السجلّ خلطُ جنسٍ يفتح بوّابةً لم تُستوفَ شروطُها
(`THIS_IS_NOT_A_DEPOSIT_INTO_THE_OCCURRENCE_GLOSS_REGISTRY`).

**خمولٌ سلطويّ**: لا ولادةَ هنا ولا حكمَ ولادةٍ ولا تجميدَ `E0`، ولا استيرادَ
من `kernel/`، ولا تُرفَع بهذه الوحدة منزلةٌ محجوزة.
"""

