@dataclass(frozen=True, slots=True)
class DalGlossEntry:
    """وسمُ جذرٍ واحد: نصُّه من البايتات، وأعدادُه خاصّيّاتٌ تُحسَب لا حقول."""

    root_full: str
    root_type: str
    root_display: str
    axes_text: str
    poetry_text: str
    chapter_header: str
    written_axis_count: str

    def __post_init__(self) -> None:
        if not self.root_full.strip():
            raise DalAloneGlossError("وسمٌ بلا جذرٍ مكتوبٍ لا يُنسَب إلى شيء")

    @property
    def belongs_to_a_named_chapter(self) -> bool:
        """أيقع الجذرُ تحت بابٍ مُسمًّى؟ يُقرَأ من البايتات لا يُفترَض.

        وفي الجدول صفوفٌ لا ترويسةَ لها، فالتقسيمُ بالترويسة **غيرُ شاملٍ**
        للجدول كلِّه؛ ورفضُها عند الإنشاء كان يُخفي ذلك خلف خطأٍ عامّ
        (`THE_CHAPTER_PARTITION_DOES_NOT_COVER_THE_WHOLE_TABLE`).
        """

        return bool(self.chapter_header)

    @property
    def axes(self) -> tuple[str, ...]:
        """المحاورُ الدلاليّة مفصولةً بقاعدتها المُعلَنة، بلا فارغٍ ولا فراغ."""

        parts = self.axes_text.split(THE_AXIS_SEPARATOR)
        return tuple(part.strip() for part in parts if part.strip())

    @property
    def derived_axis_count(self) -> int:
        """عددُ المحاور مُشتَقًّا من نصّها؛ ولا يُقرَأ من عمود العدّ البتّة."""

        return len(self.axes)

    @property
    def carries_poetry_evidence(self) -> bool:
        """أفي الصفّ شاهدٌ شعريٌّ منصوص؟ يُقرَأ من خلوّ الحقل لا من دعوى."""

        return bool(self.poetry_text.strip())

    @property
    def carries_any_axis(self) -> bool:
        """أوُسِم الجذرُ بمحورٍ واحدٍ على الأقلّ؟"""

        return self.derived_axis_count > 0

    @property
    def opens_with_dal(self) -> bool:
        """أيبدأ الجذرُ بالدال؟ تُفحَص به دعوى انطباق البابِ على حرفه."""

        return self.root_full[0] == "د"


def _entry_from_row(row: Mapping[str, str]) -> DalGlossEntry:
    return DalGlossEntry(
        root_full=row["root_full"],
        root_type=row["root_type"],
        root_display=row["root_display"],
        axes_text=row["semantic_axes"],
        poetry_text=row["poetry_evidence"],
        chapter_header=row["chapter_header"].strip(),
        written_axis_count=row["axes_count"].strip(),
    )


def whole_table_entries() -> tuple[DalGlossEntry, ...]:
    """الجدولُ كلُّه مداخلَ وسمٍ، مقروءًا من البايتات المُبصَّمة عند كلّ قراءة."""

    return tuple(_entry_from_row(row) for row in root_table_rows())


def entries_outside_any_chapter() -> tuple[DalGlossEntry, ...]:
    """صفوفُ الجدول التي لا ترويسةَ بابٍ لها؛ تُعَدّ ولا تُطوى."""

    return tuple(
        entry for entry in whole_table_entries() if not entry.belongs_to_a_named_chapter
    )


def dal_gloss_from_maqayis() -> tuple[DalGlossEntry, ...]:
    """وسمُ الدال وحدَه: صفوفُ `كتاب الدّال` من «مقاييس اللغة» المُبصَّم.

    والانتقاءُ بالترويسة لا بالحرف؛ فانطباقُ البابِ على حرفه يُفحَص بعدُ في
    `test_the_chapter_and_the_letter_coincide` ولا يُفترَض ههنا.
    """

    entries = tuple(
        entry
        for entry in whole_table_entries()
        if entry.chapter_header == THE_DAL_CHAPTER_HEADER
    )
    if not entries:
        raise DalAloneGlossError(
            f"لم يُعثَر على بابٍ بترويسة «{THE_DAL_CHAPTER_HEADER}»؛ "
            "وبابٌ خالٍ لا يُقرَأ وسمًا فارغًا بل يُوقِف القراءة"
        )
    return entries


# --- تدقيقُ العمود المكتوب بالعدد المُشتَقّ ---------------------------------------


@dataclass(frozen=True, slots=True)
class DeclaredAxisCountAudit:
    """مقابلةُ عمود `axes_count` المكتوب بالعدد المُشتَقّ من نصّ المحاور."""

    entries: tuple[DalGlossEntry, ...]

    @property
    def silent_count(self) -> int:
        """صفوفٌ لم يُكتَب فيها عددٌ البتّة؛ سكوتٌ لا خلاف."""

        return sum(1 for entry in self.entries if not entry.written_axis_count)

    @property
    def agreeing_count(self) -> int:
        """صفوفٌ وافق عمودُها المكتوبُ العددَ المُشتَقّ."""

        return sum(
            1
            for entry in self.entries
            if entry.written_axis_count.isdigit()
            and int(entry.written_axis_count) == entry.derived_axis_count
        )

    @property
    def disagreeing_count(self) -> int:
        """صفوفٌ خالف فيها العمودُ المكتوبُ العددَ المُشتَقّ."""

        return sum(
            1
            for entry in self.entries
            if entry.written_axis_count.isdigit()
            and int(entry.written_axis_count) != entry.derived_axis_count
        )

    @property
    def unreadable_count(self) -> int:
        """صفوفٌ فيها عمودٌ غيرُ خالٍ ولا يُقرَأ عددًا؛ لا يُصمَت عنه."""

        return sum(
            1
            for entry in self.entries
            if entry.written_axis_count and not entry.written_axis_count.isdigit()
        )

    @property
    def is_a_complete_partition(self) -> bool:
        """أاستوعبت الأصنافُ الأربعةُ كلَّ صفّ؟ جردٌ يمنع صفًّا بلا حساب."""

        total = (
            self.silent_count
            + self.agreeing_count
            + self.disagreeing_count
            + self.unreadable_count
        )
        return total == len(self.entries)


def audit_declared_axis_counts(
    entries: Iterable[DalGlossEntry],
) -> DeclaredAxisCountAudit:
    """دقِّق العمودَ المكتوبَ بالعدد المُشتَقّ، بأربعة أصنافٍ لا صنفين."""

    return DeclaredAxisCountAudit(entries=tuple(entries))


