class DalAloneGlossError(ValueError):
    """خطأٌ في قراءة وسم الدال أو في مقابلة صورته بصورة الجدول."""


THE_DAL_CHAPTER_HEADER: Final[str] = "كتاب الدّال"
"""ترويسةُ باب الدال كما وردت في بايتات المعجم؛ مقروءةٌ لا مُنشأةٌ ههنا."""

THE_AXIS_SEPARATOR: Final[str] = "|"
"""فاصلُ المحاور في عمود `semantic_axes`؛ قاعدةُ عدٍّ تُعلَن قبل الرقم."""


