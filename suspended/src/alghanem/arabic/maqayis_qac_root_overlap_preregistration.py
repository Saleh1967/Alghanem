@dataclass(frozen=True, slots=True)
class OverlapStage:
    """مقامُ تطبيعٍ واحد: اسمُه، وهل يُحوَّل فيه الترميز، وسلسلةُ قواعده.

    والمقاماتُ **ستّةٌ لا أربعة**: عمودُ «بعد الهمزة» انقسم عمودين لأنّ صاحبَ
    الطلب لم يُجب أيَّ صورةٍ تُوحَّد إليها الهمزةُ، فسُنّت القاعدتان معًا كما
    في `THE_HAMZA_TARGET_WAS_NOT_CHOSEN_HERE`.
    """

    name: str
    statement: str
    transliterates_qac: bool
    rules: tuple[NormalisationRule, ...]

    def __post_init__(self) -> None:
        for value, label in ((self.name, "اسمُ المقام"), (self.statement, "نصُّه")):
            if not isinstance(value, str) or not value.strip():
                raise OverlapPreregistrationError(f"{label} نصٌّ غيرُ فارغ.")
        if not isinstance(self.transliterates_qac, bool):
            raise OverlapPreregistrationError(
                "تحويلُ الترميز في المقام مُصرَّحٌ به صراحةً؛ فمقامٌ لا يقول "
                "أيُحوِّل أم لا يُقابِل ASCII بالعربية ويُخرِج صفرًا بلا سبب."
            )
        names = [rule.name for rule in self.rules]
        if len(set(names)) != len(names):
            raise OverlapPreregistrationError("قاعدةٌ مكرَّرةٌ في مقامٍ واحد.")
        if not self.transliterates_qac and self.rules:
            raise OverlapPreregistrationError(
                "مقامٌ يُطبِّع بلا تحويلٍ يُعمِل قواعدَ عربيةً على ASCII؛ "
                "وذلك تطبيعُ جانبٍ واحدٍ يُقرأ تطبيعَ الجانبين."
            )

    @property
    def rule_names(self) -> tuple[str, ...]:
        """أسماءُ قواعد المقام بترتيبها؛ فترتيبُ الإعمال جزءٌ من القاعدة."""

        return tuple(rule.name for rule in self.rules)


