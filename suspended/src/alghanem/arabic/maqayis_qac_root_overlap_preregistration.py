def _preregistration_content() -> dict[str, object]:
    return {
        "standing": STANDING.value,
        "stages": [
            {
                "name": stage.name,
                "statement": stage.statement,
                "transliterates_qac": stage.transliterates_qac,
                "rules": list(stage.rule_names),
            }
            for stage in OVERLAP_STAGES
        ],
        "figures": [
            {
                "label": figure.label,
                "claimed_value": figure.claimed_value,
                "counting_rule": figure.counting_rule.name,
                "declared_stage": figure.declared_stage,
                "standing": figure.standing.value,
            }
            for figure in ARRIVING_OVERLAP_FIGURES
        ],
        "hypotheses": [hypothesis.label for hypothesis in HAMZA_DIAGNOSIS_HYPOTHESES],
        "unanswered": [decision.question for decision in UNANSWERED_COUNTING_DECISIONS],
    }


def preregistration_digest() -> str:
    """بصمةُ هذا التجميد؛ بها يُعرَف أنّ التوقّعَ لم يُبدَّل بعد رؤية النتيجة."""

    return canonical_digest(canonical_bytes(_preregistration_content()))


