"""سجلُّ ترخيصِ الجبر: توقيعٌ على مرجعَين، وسُلَّمٌ من الـ١١٢، ودَينٌ توثيقيّ.

**أوّلًا: والتوقيعُ على ما فُتِح، ولا يمتدّ إلى ثالثٍ لم يُفتَح.** رخَّص المالكُ
المرجعَين المُودَعَين في `corpora/` — `quran-simple-enhanced.txt` و
`globalquran-simple-enhanced.txt` — فصارا مرجعَي المقابلة بإذنٍ مُسمًّى. وشرطُ
هذه الرخصة مكتوبٌ معها: **بايتاتُها هي المحكومُ عليها**، فمن جاء بنسخةٍ ثالثةٍ
لم تُفتَح لم يدخل تحت التوقيع ألبتّة، ولا يُقاس عليه بالقياس
(`AN_OWNERS_SIGNATURE_COVERS_THE_BYTES_IT_NAMES_AND_NOT_A_THIRD_COPY`).
والرخصةُ جهةٌ لا احتواء، كما في `ontology.linguistic`: رخصةٌ بلا شرطٍ دعوى
احتواءٍ في ثوب ترخيص.

**وثانيًا: والـ١١٢ رخصةٌ تدريجيّةٌ لا رخصةٌ دفعةً واحدة.** الجدولُ مئةٌ واثنتا
عشرةَ خليّةً مُعلَنةً قبل العدّ (٢٨ × ٤)، ثمّ امتلأ على ثلاث مراتبَ بتوسيع
المادّة وحدَها:

| المرتبة | الخلايا المرخَّصة | الوقوعات | ما لم تُرخِّصه |
|---|---|---|---|
| الفاتحة | 41/112 | 100 | 71 خليّةً لا شاهدَ لها |
| + الفتح ٢٩ | 74/112 | 270 | 38 خليّةً لا شاهدَ لها |
| + نثر الشجرة | 108/112 | 90,373 | 4 خلايا لا شاهدَ لها |

**فالترخيصُ ههنا شهادةُ وقوعٍ لا إذنُ نحويّ**: خليّةٌ رُخِّصت يعني أنّ
بايتاتٍ مفتوحةً أرَتْها، وخليّةٌ لم تُرخَّص **ليست ممنوعةً** بل غيرَ مشهودة
(`A_LICENCE_GRANTED_RUNG_BY_RUNG_IS_NOT_A_LICENCE_GRANTED_WHOLE`).
والأربعُ الباقياتُ مُسمَّياتٌ بهوامشها في `letter_haraka_partition`، لا
تُقرَأ منعًا ولا تُستكمَل بالتخمين.

**وثالثًا: وسُلَّمُ الجبر من تلك الخليّة إلى هذه النقطة.** كلُّ درجةٍ ههنا
تُستدعى حيًّا من وحدتها فتُعاد أرقامُها عند كلّ قراءة، ولا يُنقَل منها رقمٌ
منسوخًا. والدرجةُ تُسجِّل **ما رخَّصته وما امتنعت عنه معًا**، لأنّ سُلَّمًا
يذكر مكاسبَه وحدَها سُلَّمُ دعاية لا سُلَّمُ حساب.

**ورابعًا: والدَّينُ دَينان، فلا يُخلَطان.** سأل المالكُ أن يُنجَز الجبرُ
ويُوقَّع، وأن يبقى ما يلزم للتوثيق **دَينًا معلَّقًا** — وصرَّح بأنّ «الدَّينَ
التوثيقُ وليس العدّ». فيُفصَل ههنا:

* **دَينُ العدّ** — عددٌ ادُّعي ولم يُعَد اشتقاقُه. وهذا يُبرهَن صفرًا لا
  يُقال صفرًا: كلُّ درجةٍ في السُّلَّم تُشغَّل عند القراءة، فإن امتنع تشغيلُها
  سقطت الدرجةُ بعلّتها ولم تُطوَ.
* **دَينُ التوثيق** — بايتاتٌ أو شهادةٌ غائبةٌ عن الشجرة، يتوقّف عليها حكمٌ
  موسومٌ باسمها. وهذا **ليس صفرًا**، ويُعرَض بأسمائه ومحالِّ حلِّه.

فمن سدَّد دَينَ العدّ لم يسدِّد دَينَ التوثيق، ومن عدَّ الثاني الأوّلَ فقد
خلط بابَين (`THE_SUSPENDED_DEBT_IS_DOCUMENTATION_AND_NEVER_A_COUNT`).
وصفرُ دَينِ العدّ ههنا **ليس صفرًا مُعلَنًا بل صفرٌ قابلٌ للانتقاض**: يكفي
أن تمتنع درجةٌ واحدةٌ عن التشغيل حتّى يصير غيرَ صفر، فهو صفرٌ يُمكن أن يخرج
على غيرِ ما خرج (`A_ZERO_THAT_COULD_NOT_HAVE_BEEN_OTHERWISE_IS_NOT_REPORTED`).

**وخامسًا: وتوقيعُ الجبر لا يرفع حظرًا ولا يفكّ تجميدًا.** ما كان معلَّقًا
في وحدةٍ يبقى معلَّقًا بعد هذا السجلّ، وما كان مجمَّدًا يبقى مجمَّدًا. وسقفُ
هذه الوحدة: أن تُسمّيَ الرخصةَ وشرطَها، والدَّينَ وجنسَه. وليس لها أن تُنشئ
عددًا جديدًا في اللغة.
"""

