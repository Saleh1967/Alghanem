BLIND_SAMPLE_RANGE: Final[tuple[int, int]] = (0x0621, 0x064F)

THE_DEPOSITS_READ: Final[tuple[str, ...]] = (AMIRI, SCHEHERAZADE, NOTO_KUFI)


class BlindSkeletonError(ValueError):
    """رفضٌ عند القياس: عيّنةٌ لا تُشتقّ، أو فئةٌ تُدَّعى بلا هندسة."""


def blind_sample_of(filename: str) -> tuple[int, ...]:
    """أرقامُ رسومِ الحروف المنفصلة، مرتَّبةً ومجرَّدةً من كلّ هُويّة.

    تُستعمَل الهُويّةُ ههنا في **الاختيار** وحدَه ثمّ تُحجَب: لا يخرج من
    هذه الدالّة إلّا أرقامٌ معتمة، فلا سبيلَ للتجميع إلى الأسماء.
    """

    font = load_font(filename)
    low, high = BLIND_SAMPLE_RANGE
    found = {
        glyph
        for code in range(low, high + 1)
        if (glyph := font.glyph_for(chr(code))) != 0
    }
    if not found:
        raise BlindSkeletonError(f"لا رسمَ عربيًّا في {filename}؛ ولا عيّنةَ تُقاس.")
    return tuple(sorted(found))


def the_whole_font_sample_of(filename: str) -> tuple[int, ...]:
    """كلُّ رسمٍ في الوديعة؛ وبه تُختبَر استقرارُ الفئة باتّساع العيّنة."""

    return tuple(range(load_font(filename).glyph_count))


def _readable_outline(font: FontBits, glyph: int) -> tuple[Contour, ...] | None:
    try:
        return font.outline_of(glyph)
    except FontDepositError:
        return None


def group_blindly(filename: str, glyphs: tuple[int, ...]) -> tuple[frozenset[int], ...]:
    """يجمع الرسومَ بهندستها وحدَها: تقاسُمُ كنتورٍ مطابقٍ يجمع.

    لا اسمَ ولا نقطةَ ترميزٍ تدخل ههنا؛ إنّما أرقامٌ معتمةٌ وإحداثيّات.
    والعلاقةُ تُغلَق تعدّيًا، وهذا الإغلاقُ مقيسُ الأثر لا مُغفَل.
    """

    font = load_font(filename)
    unique = tuple(sorted(set(glyphs)))
    owners: dict[Contour, list[int]] = defaultdict(list)
    for glyph in unique:
        outline = _readable_outline(font, glyph)
        if outline is None:
            continue
        for contour in outline:
            owners[contour].append(glyph)
    parent = {glyph: glyph for glyph in unique}

    def find(node: int) -> int:
        while parent[node] != node:
            parent[node] = parent[parent[node]]
            node = parent[node]
        return node

    for sharers in owners.values():
        first = sharers[0]
        for other in sharers[1:]:
            left, right = find(first), find(other)
            if left != right:
                parent[left] = right
    grouped: dict[int, set[int]] = defaultdict(set)
    for glyph in unique:
        grouped[find(glyph)].add(glyph)
    return tuple(
        sorted(
            (frozenset(members) for members in grouped.values()),
            key=lambda members: (-len(members), min(members)),
        )
    )


def open_identities(
    filename: str, grouped: tuple[frozenset[int], ...]
) -> tuple[frozenset[str], ...]:
    """يفتح الهُويّاتِ **بعد** التجميد: أيُّ حروفٍ وقعت في كلّ فئة.

    ولا تُذكَر إلّا الفئاتُ التي فيها أكثرُ من حرفٍ واحد، إذ الفئةُ المفردةُ
    لا تقول شيئًا عن تقاسم.
    """

    font = load_font(filename)
    low, high = BLIND_SAMPLE_RANGE
    by_glyph: dict[int, set[str]] = defaultdict(set)
    for code in range(low, high + 1):
        glyph = font.glyph_for(chr(code))
        if glyph:
            by_glyph[glyph].add(chr(code))
    opened = []
    for members in grouped:
        letters = {
            letter for glyph in members for letter in by_glyph.get(glyph, frozenset())
        }
        if len(letters) > 1:
            opened.append(frozenset(letters))
    return tuple(sorted(opened, key=lambda letters: (-len(letters), sorted(letters))))


@cache
def geometric_classes_of(
    filename: str, whole_font: bool = False
) -> tuple[frozenset[str], ...]:
    """الفئاتُ **المقيسة**: مشتقّةٌ من الهندسة المبسوطة لا من إعلان الخطّ."""

    sample = (
        the_whole_font_sample_of(filename) if whole_font else blind_sample_of(filename)
    )
    return open_identities(filename, group_blindly(filename, sample))


@cache
def declared_classes_of(filename: str) -> tuple[frozenset[str], ...]:
    """الفئاتُ **المُعلَنة**: ما يقوله الخطّ في بتاته عن تركيب رسومه.

    والجسمُ ههنا هو المكوّنُ الذي إزاحتُه صفرٌ؛ فإن تعدّد لم يُرجَّح واحدٌ
    على آخر، بل تُفرَد تلك الرسومُ فئةً لا تُجمَع.
    """

    font = load_font(filename)
    grouped: dict[object, set[int]] = defaultdict(set)
    sample = blind_sample_of(filename)
    for glyph in sample:
        if not font.is_composite(glyph):
            grouped[glyph].add(glyph)
            continue
        try:
            components = font.components_of(glyph)
        except FontDepositError:
            grouped[("refused", glyph)].add(glyph)
            continue
        anchored = [part for part in components if (part[1], part[2]) == (0, 0)]
        key: object = anchored[0][0] if len(anchored) == 1 else ("odd", glyph)
        grouped[key].add(glyph)
    for glyph in sample:
        if glyph in grouped:
            grouped[glyph].add(glyph)
    return open_identities(
        filename,
        tuple(frozenset(members) for members in grouped.values()),
    )


def classes_that_transport(
    filenames: tuple[str, ...] = THE_DEPOSITS_READ, declared: bool = False
) -> tuple[frozenset[str], ...]:
    """الفئاتُ الثابتةُ في كلّ وديعةٍ من المذكورات، وهي شرطُ «ليست خطًّا واحدًا»."""

    if len(filenames) < 2:
        raise BlindSkeletonError("لا نقلَ يُقاس على وديعةٍ واحدة.")
    reader = declared_classes_of if declared else geometric_classes_of
    surviving = set(reader(filenames[0]))
    for filename in filenames[1:]:
        surviving &= set(reader(filename))
    return tuple(
        sorted(surviving, key=lambda letters: (-len(letters), sorted(letters)))
    )


@dataclass(frozen=True)
class DescriptionLength:
    """طولا الوصف بوحدةٍ مُعلَنة: نقاطُ النموذجين، ولا ترجيحَ بينهما."""

    scope: str
    independent_points: int
    shared_points: int
    references: int

    def __post_init__(self) -> None:
        if not self.scope.strip():
            raise BlindSkeletonError("لا بدّ للنطاق من اسمٍ يُنسَب إليه القياس.")
        for value in (self.independent_points, self.shared_points, self.references):
            if value < 1:
                raise BlindSkeletonError("طولُ وصفٍ خالٍ لا يُقاس.")
        if self.shared_points > self.independent_points:
            raise BlindSkeletonError("المتقاسَمُ أطولُ من المستقلّ؛ وهذا محال.")

    @property
    def saving(self) -> float:
        """وفرُ النموذج البنيويّ نسبةً مئويّة، محسوبًا عند القراءة."""

        return (
            100.0
            * (self.independent_points - self.shared_points)
            / self.independent_points
        )


def description_length_of(filename: str) -> DescriptionLength:
    r"""يقيس \(M_0\) و\(M_1\) على عيّنة الوديعة العمياء، بعدّ النقاط."""

    font = load_font(filename)
    sample = blind_sample_of(filename)
    independent = 0
    references = 0
    distinct: set[Contour] = set()
    for glyph in sample:
        outline = _readable_outline(font, glyph)
        if outline is None:
            continue
        for contour in outline:
            independent += len(contour)
            references += 1
            distinct.add(contour)
    return DescriptionLength(
        scope=filename,
        independent_points=independent,
        shared_points=sum(len(contour) for contour in distinct),
        references=references,
    )


def _arabic_fused_alefs() -> frozenset[str]:
    return frozenset(
        {"\u0627"}
        | {
            letter
            for letter in fused_letters()
            if unicodedata.normalize("NFD", letter)[0] == "\u0627"
        }
    )


def fused_alef_class_in(filename: str) -> frozenset[str]:
    """الفئةُ المقيسةُ التي وقعت فيها الألفُ في هذه الوديعة."""

    for letters in geometric_classes_of(filename):
        if "\u0627" in letters:
            return letters
    return frozenset({"\u0627"})


def the_canonical_fusion_is_realized_in(filename: str) -> bool:
    """أتجمع هندسةُ هذه الوديعةِ ألفَ يونيكود وملحَماتِها في فئةٍ واحدة؟"""

    return _arabic_fused_alefs() <= fused_alef_class_in(filename)


