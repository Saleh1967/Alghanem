r"""ولادةُ الجسم المشترك من الهندسة عمياءَ: المُعلَنُ ينقطع، والمقيسُ ينتقل.

يونيكود لا يعرف أنّ **ب ت ث** ثلاثةٌ على رسمٍ واحد، لأنّه لا يخزّن هذه
العلاقة. فلمّا أُضيف المصدرُ الثاني من البتات — وديعةُ الخطّ — صار السؤالُ
قابلًا للقياس. وهذه الوحدةُ تقيسه، ولا تستورد «الإعجامَ» ولا «النقطة».

**أوّلًا: والقياسُ أعمى ثمّ تُفتَح الهُويّات.** تُجمَع الرسومُ بهندستها وحدَها:
رسمان في فئةٍ واحدةٍ إن تقاسما كنتورًا **مطابقًا بالإحداثيّات**. ولا تدخل
هُويّةُ يونيكود في التجميع ألبتّة؛ إنّما تُستعمَل في **اختيار العيّنة** ثمّ
تُحجَب، ولا تُفتَح إلّا بعد أن تُجمَّد الفئات. وهذا الترتيبُ نفسُه هو الحُجّة
على أنّ الفئةَ لم تُبنَ على الاسم
(`IDENTITY_SELECTS_THE_SAMPLE_AND_IS_WITHHELD_FROM_THE_GROUPING`).

**وثانيًا: وفصلُ المُعلَن عن المقيس هو المِلْستون كلُّه.** للخطّ أن **يعلن**
تفكيكَه: أن يكون الرسمُ مركّبًا من جسمٍ وزيادةٍ مُزاحة. وله ألّا يعلن شيئًا:
أن يرسم كلَّ حرفٍ رسمًا بسيطًا. والمقيسُ شيءٌ آخر: أن نأخذ الهندسةَ مبسوطةً
ونبحث عن التطابق. والنتيجةُ على المُودَع الثلاثة قاطعةٌ في الفرق:

| الخطّ | المُعلَن | المقيس |
|---|---|---|
| أميري (نسخيّ) | 12 | 13 |
| شهرزاد (نسخيّ) | 14 | 14 |
| كوفيُّ نوتو | **4** | **14** |

فالكوفيُّ لا يعلن من الرسم شيئًا: أربعتُه كلُّها أسرُ الهمزة — آأ وإا وؤو
وئى — وهي **عينُ ما يعلنه يونيكود** في الحروف المُلحَمة، لا زيادةَ عليه.
ومع ذلك تُخرِج هندستُه أربعَ عشرةَ فئة.

**وثالثًا: والنقلُ ينقلب بانقلاب السؤال.** نُقِلت الفئاتُ بين الثلاثة:

| النقل | المُعلَن | المقيس |
|---|---|---|
| أميري ∩ شهرزاد | 11 | 12 |
| أميري ∩ كوفيّ | **0** | 10 |
| شهرزاد ∩ كوفيّ | 1 | 11 |
| **الثلاثة جميعًا** | **0** | **10** |

فالتفكيكُ **المُعلَن** لا ينتقل ألبتّة إلى خطٍّ لا يعلنه — وهذا متوقَّع، إذ
هو خبرٌ عن بناء الخطّ. والتفكيكُ **المقيس** ينتقل: عشرُ فئاتٍ تصحّ في نسخيَّين
من صانعَين مستقلَّين وفي كوفيٍّ من أسرةِ خطٍّ أخرى. وهي:
**بتث، جحخ، دذ، رز، سش، صض، طظ، عغ، ةه، ؤو**
(`A_DECLARED_DECOMPOSITION_IS_FONT_BUILD_A_MEASURED_ONE_TRANSPORTS`).

**ورابعًا: ولا يُقرأ من هذا حكمٌ لغويّ.** أن تتقاسم **ب ت ث** كنتورًا واحدًا
في ثلاثة خطوطٍ خبرٌ عن **الرسم**، لا عن صوتٍ ولا صرفٍ ولا أصلٍ تاريخيّ. ولم
يُسمَّ ما زاد «نقطةً» ولا ما بقي «جسمًا» إلّا تسميةً إجرائيّة: \(G=K\sqcup R\)
حيث \(K\) المتقاسَمُ و\(R\) الباقي، لا غير
(`SHARED_GEOMETRY_IS_NOT_A_LINGUISTIC_IDENTITY`).

**وخامسًا: وطولُ الوصف يُنشَر رقمًا لا حكمًا.** النموذجُ الأضعفُ \(M_0\) أن
يُوصَف كلُّ حرفٍ بنقاطه كاملةً. والنموذجُ البنيويُّ \(M_1\) أن تُوصَف
الكنتوراتُ المتمايزةُ مرّةً وتُحال إليها. والوفرُ مقيسٌ عند القراءة: **32.463%**
في أميري، و**34.660%** في شهرزاد، و**30.416%** في الكوفيّ. وهو وفرٌ **متقاربٌ
في الثلاثة** مع اختلاف تصاميمها. **ولا يُقرأ منه ترجيحٌ لنموذجٍ على نموذج**:
عدُّ النقاط وحدةُ وصفٍ مُعلَنةٌ اختِيرت، وغيرُها يُعطي غيرَه، ولا بروتوكولَ
ترجيحٍ ههنا (`THE_DESCRIPTION_LENGTH_IS_A_NUMBER_NOT_A_SELECTION`).

**وسادسًا: والاكتشافُ غيرُ مستقرٍّ باتّساع ما يُسأل عنه.** وُسِّعت العيّنةُ
العمياءُ من رسوم الحروف المنفصلة إلى **كلّ** رسمٍ في الخطّ. فثبت النسخيّان
(13 و14 كما هما)، **وانهار الكوفيُّ من 14 إلى 10**: التحمت أسرٌ لا تجمعها إلّا
سلسلةُ تقاسمٍ عابرةٌ عبر أشكال السياق — فصارت ؤ و ة و ع و غ و ه و و فئةً
واحدة. والسببُ أنّ «تقاسمَ كنتورٍ» علاقةٌ **تُغلَق تعدّيًا** فتَسري. فالفئةُ
المقيسةُ مشروطةٌ بعيّنتها العمياء، وشرطُها منشورٌ لا مطويّ
(`THE_SHARED_CONTOUR_RELATION_CHAINS_WHEN_THE_BLIND_SAMPLE_WIDENS`).

**وسابعًا: والجسرُ إلى الحروف المُلحَمة، وعنده وحدَه تختلف الثلاثة.** قرّر
`hidden_mark_population` أنّ آ وأ وإ حواملُ ألفٍ مُلحَمةٌ بعلامة. فهل تظهر هذه
البنيةُ **هندسيًّا**؟ الجوابُ مقيسٌ: شهرزادُ وحدَها تجمع الأربعةَ آ أ إ ا في
فئةٍ واحدة؛ وأميري يجمع آ إ ا **ويُخرِج أ** لأنّ جسمَ ألفها مُزاحٌ اثنتي عشرة
وحدةً فلا يُطابق؛ والكوفيُّ يقسمها قسمين: آأ وإا. فبنيةُ يونيكود **تتحقّق
هندسيًّا في واحدٍ من ثلاثة**. وموضعُ اختلاف الخطوط هو بعينه موضعُ الالتحام
الذي قِيس من قبلُ في الجدول — لا مصادفةَ في ذلك ولا برهان
(`THE_CANONICAL_FUSION_IS_REALIZED_BY_ONE_DEPOSIT_OF_THREE`).
"""

