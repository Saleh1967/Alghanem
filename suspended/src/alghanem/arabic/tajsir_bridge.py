"""جسرُ الطبقات الثلاث: ترميزٌ وإملاءٌ وصوت، مفكوكةً ثمّ ملحومةً بقرينتها.

**العدُّ لا يسبق الجسر، والجسرُ شرطُ إمكانٍ لا شرطٌ لازمٌ وحدَه.** قيل في هذه
الشجرة إنّ «العدَّ صحيحٌ دائمًا عن مصفاته»، فسقط هذا القولُ بالقياس: إن قُرئ
الموضعُ العاري حالًا خامسةً مستقلّةً فاضت خلايا (حامل × حال) إلى **140** في
وعاءٍ سعتُه **112**، فلا جدولَ يُقرأ فيه العدُّ أصلًا. فالفيضُ ليس «عدًّا
آخرَ صحيحًا»، بل **لا وعاءَ قبل القرار**
(`THE_BRIDGE_IS_A_PRECONDITION_OF_COUNTING_NOT_A_REFINEMENT_OF_IT`).

**والطبقاتُ ثلاثٌ لا تُخلَط، ولكلّ موضعٍ معرِّفٌ في كلٍّ منها معًا:**

| الطبقة | الهويّة | المصدر |
|---|---|---|
| الترميز | نقطةُ يونيكود كما هي، بلا طيّ | `encoding_carrier` و`encoding_marks` |
| الإملاء | الحاملُ بعد طيٍّ مُعلَنِ البنود | `orthographic_carrier` |
| الصوت | حالٌ من إحدى عشرةَ، منها ثلاثٌ غيرُ مرسومة | `state` |

واللحامُ **دالّةٌ تُسجَّل مع قرينتها** لا استبدالٌ صامت: كلُّ موضعٍ يحمل
`warrant` يسمّي البوّابة التي أخرجت حالَه، فيُراجَع القرارُ ولا يُبتلَع
(`A_WELD_WITHOUT_ITS_WARRANT_IS_A_SILENT_SUBSTITUTION`).

**والعُريُ لا يُحسَم بقرارٍ واحدٍ بل بثلاث بواباتٍ ورابعةٍ تمتنع.** الموضعُ
العاري من كلّ علامةٍ ليس سكونًا بالضرورة — وهو ما قرّرته
`written_haraka_mark.THE_NEGATIVE_IS_AN_ABSENT_MARK_NOT_A_SUKUN` — فيُعرَض على:
مدٍّ (حاملُه ا/و/ي بعد حركةٍ مجانسة)، فهمزةِ وصلٍ ساقطةٍ (أوّلُ الكلمة ألفًا
يتلوها ساكن)، فسكونٍ مقدَّر. وما لم تُصبه بوّابةٌ **يُعلَّق ولا يُخمَّن**:
أوّلُ كلمةٍ عارٍ ليس همزةَ وصلٍ لا يكون ساكنًا (لا يُبتدأ بساكن)، وحرفُ مدٍّ
بلا حركةٍ مجانسةٍ قبله لا يُقطَع فيه. فالمعلَّقُ صنفٌ أوّلُ لا بقيّةٌ
(`THE_SUSPENDED_IS_A_CLASS_NOT_A_REMAINDER`).

**والشدّةُ تُعدّ بمصدرها لا بعلامتها.** علامةٌ واحدةٌ تجمع ظواهرَ شتّى، كما
سمّت `tawlid_algebra_ledger.A_MARK_HAS_MANY_SOURCES_SO_COUNTING_IT_DOES_NOT_`
`COUNT_ONE`؛ فلا يُخرَج «عدُّ المشدَّد» رقمًا واحدًا، بل جدولًا بأعمدةٍ
مُسمّاة. وعمودُ «تضعيفِ الصيغة» **مُسمًّى بلا بوّابةٍ تُدخله على هذه
البيّنة**، وبقاؤه فارغًا مُصرَّحٌ به لا مطويّ
(`THE_PATTERN_COLUMN_IS_NAMED_WITHOUT_AN_ADMITTING_RULE`). وعمودُ «تضعيفِ
الأصل» يُدخَل بشاهدِ جذرٍ مضاعفٍ مُصرَّحٍ به من جدول المقاييس، وهو **وكيلٌ
سطحيٌّ لا تحليلٌ صرفيّ** على منوال `lexicon_bridge.A_SURFACE_FORM_IS_NOT_A_`
`MORPHOLOGICAL_FAMILY` (`A_ROOT_WITNESS_HERE_IS_A_PROXY_NOT_AN_ANALYSIS`).

**والتنوينُ نونٌ ساكنةٌ غيرُ مرسومة، فللنون عدّان مُعلَنان لا عددٌ واحد.**
يُردُّ التنوينُ إلى مقطعٍ زائدٍ موسومٍ بمصدره (`SegmentSource.FROM_TANWIN`)،
فتنفصل «النونُ المرسومة» عن «النونِ المنطوقة»، ولا تُقرأ إحداهما مكانَ
الأخرى (`THE_TWO_NUN_COUNTS_ARE_BOTH_DECLARED_AND_NEITHER_REPLACES_THE_OTHER`).

**و«ة» لا تُطوى بقرارٍ واحدٍ بل تُقرأ بدالّتَين.** وصلًا تاءٌ، ووقفًا هاءٌ؛
فإن لم يُعرف موضعُ الكلمة من حدّ الوقف خرج الموضعُ **معلَّقًا** ولم يُحتسب في
أيٍّ من العدَّين (`A_SYMBOL_WITH_TWO_READINGS_IS_NOT_FOLDED_INTO_EITHER`).

**والقوانينُ الثلاثةُ تُصاغ قابلةً للسقوط، وما لا يمكن أن يُخالَف لا يُقبَل.**
قانونُ الوقف **لا يُبنى على هذه الوديعة**: علاماتُ الوقف مطروحةٌ منها كما
قرّرت `fath_ayah_source_text.THE_WAQF_MARKS_ARE_DROPPED_SO_NO_PAUSE_IS_READABLE`،
فيُخرَج مُعلَّقًا بلا رقم (`THE_WAQF_LAW_IS_SUSPENDED_FOR_WANT_OF_ITS_MARKS`).
وقانونُ الابتداء يُقاس على **مواضعِ ابتداءٍ محقَّقة** — أوائلِ الأسطر — لا على
كلّ رمز؛ وقانونُ الوصل يُقاس على ما ثبت وصلُه. وهذا أخذٌ بما سبق إليه
`carrier_projection_deposit.the_edges_only_the_space_rule_makes`: حدُّ الرمز
غيرُ حدّ النطق.

**وكلُّ نسبةٍ تخرج صفرًا أو تامّةً تُحجَز حتّى يُبرَز شاهدُ إمكانِ خلافها.**
سقط في هذه الشجرة رقمٌ «100.00%» لأنّ القسمةَ عُرِّفت بالدعوى نفسِها، فلم يكن
ممكنًا أن يخرج غيرَها. فالنسبةُ ههنا `Ratio` لا عددًا عائمًا، ولا تُقرأ قيمتُها
عند الطرفين إلّا بشاهدٍ **يُشغَّل** فيُظهِر أنّ القاعدة تنقدح على نصٍّ آخر
(`A_RATIO_AT_THE_EXTREMES_IS_WITHHELD_UNTIL_IT_COULD_HAVE_BEEN_OTHERWISE`).

**وثمنُ كلّ طيٍّ مقيسٌ لا مُقدَّر**: `fold_price_over` تُخرج لكلّ بندٍ من بنود
الطيّ كم موضعًا حرّك، فيُقابَل العدُّ بالطيّ وبدونه في جدولٍ واحد.

**والمادّةُ الناقصة مُسمّاة**: وديعةٌ مختومةٌ فيها علاماتُ الوقف. وبدونها
ثلاثةٌ من المطلوب — قانونُ الوقف، وفصلُ «ة»، وتحقيقُ مواضع الابتداء بعد الوقف
اللازم — تُعلَّق ولا تُخمَّن (`THE_MISSING_MATERIAL_IS_NAMED_NOT_SUBSTITUTED`).

**خمولٌ سلطويّ**: لا ولادةَ ولا حكمَ ولا تجميد، ولا استيرادَ من `kernel/`.
"""

