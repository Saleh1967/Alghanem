@dataclass(frozen=True)
class FoldRule:
    """بندُ طيٍّ واحد: صورةٌ مكتوبةٌ تُردّ إلى حاملٍ، ومعها قرينةُ ردِّها."""

    written: str
    folded: str
    warrant: str

    def __post_init__(self) -> None:
        if len(self.written) != 1 or len(self.folded) != 1:
            raise TajsirError("بندُ الطيّ نقطتان مفردتان لا سلسلتان.")
        if self.written == self.folded:
            raise TajsirError("بندٌ لا يحرّك شيئًا ليس بندَ طيّ.")
        if not self.warrant:
            raise TajsirError("طيٌّ بلا قرينةٍ استبدالٌ صامت.")


THE_DECLARED_FOLD: Final[tuple[FoldRule, ...]] = (
    FoldRule("\u0623", _ALIF, "صورةُ همزةٍ على ألف"),
    FoldRule("\u0625", _ALIF, "صورةُ همزةٍ تحت ألف"),
    FoldRule("\u0622", _ALIF, "ألفٌ عليها مدّة"),
    FoldRule("\u0671", _ALIF, "ألفُ وصلٍ مرسومةٌ بعلامتها"),
    FoldRule("\u0621", _ALIF, "همزةٌ مفردةٌ بلا كرسيّ"),
    FoldRule("\u0624", _WAW, "همزةٌ على واو"),
    FoldRule("\u0626", _YA, "همزةٌ على ياء"),
    FoldRule("\u0649", _YA, "ألفٌ مقصورة"),
)
"""بنودُ الطيّ المُعلَنة؛ و«ة» ليست فيها عمدًا، وعلّتُها في `A_SYMBOL_WITH_...`."""


def fold_map() -> Mapping[str, str]:
    """جدولُ الطيّ مشتقًّا من بنوده، لا مكتوبًا مرّتين."""

    return MappingProxyType({rule.written: rule.folded for rule in THE_DECLARED_FOLD})


def words_of(text: str) -> tuple[str, ...]:
    """الرموزُ التي فيها حرفٌ عربيٌّ واحدٌ فأكثر؛ وما سواها ليس كلمة."""

    return tuple(
        token
        for token in text.split()
        if any(_LETTER_RANGE[0] <= ord(ch) <= _LETTER_RANGE[1] for ch in token)
    )


