class TajsirError(ValueError):
    """رفضٌ في الجسر: علامةٌ بلا موضعٍ قبلها، أو نسبةٌ بمقامٍ صفر."""


# --- الطبقةُ الأولى: الترميز، بلا طيٍّ ولا حكم ------------------------------

NORMALIZATION_FORM: Final[Literal["NFC"]] = "NFC"
"""الصورةُ القانونيّةُ التي يُقرأ عليها الترميز، مُسجَّلةً لا مطويّة."""

_COMBINING: Final[str] = "Mn"

FATHA: Final[str] = "\u064e"
DAMMA: Final[str] = "\u064f"
KASRA: Final[str] = "\u0650"
SUKUN: Final[str] = "\u0652"
TANWIN_FATH: Final[str] = "\u064b"
TANWIN_DAMM: Final[str] = "\u064c"
TANWIN_KASR: Final[str] = "\u064d"
SHADDA: Final[str] = "\u0651"

THE_TA_MARBUTA: Final[str] = "\u0629"
"""«ة»: رمزٌ واحدٌ بمدلولَين، لا يُطوى إلى أحدهما."""

_ALIF: Final[str] = "\u0627"
_LAM: Final[str] = "\u0644"
_WAW: Final[str] = "\u0648"
_YA: Final[str] = "\u064a"
_NUN: Final[str] = "\u0646"

_LETTER_RANGE: Final[tuple[int, int]] = (0x0621, 0x064A)


def encoding_positions(word: str) -> tuple[tuple[str, tuple[str, ...]], ...]:
    """الطبقةُ الأولى: مواضعُ الترميز كما هي، حاملًا وما لصق به بترتيبه."""

    built: list[tuple[str, list[str]]] = []
    for character in unicodedata.normalize(NORMALIZATION_FORM, word):
        code = ord(character)
        if unicodedata.category(character) == _COMBINING:
            if not built:
                raise TajsirError(
                    "علامةٌ لاصقةٌ بلا موضعٍ قبلها؛ ولا يُفتَح لها موضعٌ "
                    "لأنّ ذلك حكمٌ لا قراءة."
                )
            built[-1][1].append(character)
        elif _LETTER_RANGE[0] <= code <= _LETTER_RANGE[1]:
            built.append((character, []))
    return tuple((carrier, tuple(marks)) for carrier, marks in built)


